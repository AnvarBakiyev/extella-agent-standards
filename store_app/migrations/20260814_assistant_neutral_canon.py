#!/usr/bin/env python3
"""Поставить единый канон выше конкретного ассистента."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
CONTENT = ROOT / "store_app" / "content.json"
OLD_VERSION = "2026-08-14.3"
NEW_VERSION = "2026-08-14.4"


def replace_once(text: str, old: str, new: str, label: str) -> str:
    if text.count(old) != 1:
        raise SystemExit(f"миграция не применена: ожидался один якорь {label}")
    return text.replace(old, new, 1)


def main() -> None:
    data = json.loads(CONTENT.read_text(encoding="utf-8"))
    if data.get("версия_содержимого") != OLD_VERSION:
        raise SystemExit("миграция не применена: неожиданная версия содержимого")

    data["шапка"]["вступление"] = replace_once(
        data["шапка"].get("вступление", ""),
        "Быстрее всего — отдать это своему Claude Code или Codex со словами",
        "Быстрее всего — отдать это своему ассистенту со словами",
        "нейтральное вступление",
    )

    by_number = {section.get("номер"): section for section in data.get("разделы") or []}
    section_07 = by_number.get("07") or {}
    section_09 = by_number.get("09") or {}

    section_07["тело"] = replace_once(
        section_07.get("тело", ""),
        "<p>Скопируй и отдай своему Claude Code или Codex. Дальше он сделает сам.</p>",
        "<p>Скопируй и отдай своему ассистенту. Дальше он сделает сам.</p>",
        "нейтральное описание промпта",
    )
    section_07["тело"] = replace_once(
        section_07.get("тело", ""),
        "6. Доведи до предрелиза сам: права объявлены, покупка себе, установка, первый запуск чистым состоянием. Остановись перед публикацией — эту кнопку нажму я.",
        "6. Доведи новый листинг до предрелиза сам: права объявлены, покупка себе, установка, первый запуск чистым состоянием. Остановись перед публичным действием — Publish нового листинга или add-version уже опубликованного. Решение приму я.",
        "граница H20 в готовом промпте",
    )

    section_09["заголовок"] = "Один канон для любого ассистента"
    body = section_09.get("тело", "")
    body = replace_once(
        body,
        "<p><strong>Кнопка «Подключить Codex» находится над руководством.</strong> Она вызывает один\nзакреплённый Expert на устройстве: проверяет Codex, ставит подписанный локальный мост, связывает\nтекущий аккаунт Extella и перечитывает health. Setup не запускает модель и не расходует план.</p>",
        "<p><strong>Любой ассистент подключается к одному канону:</strong> README.md и\nstore_app/content.json в публичном репозитории. Codex, Claude Code и другие инструменты —\nне отдельные стандарты, а разные способы прочитать одни и те же правила.</p>\n<p>Для Codex над руководством есть готовая кнопка. Она вызывает один закреплённый Expert на\nустройстве: проверяет Codex, ставит подписанный локальный мост, связывает текущий аккаунт\nExtella и перечитывает health. Setup не запускает модель и не расходует план.</p>",
        "единый канон перед маршрутом Codex",
    )
    body = replace_once(
        body,
        "<p>Реальный запрос в Codex — отдельное действие по явной просьбе пользователя. Он может\nрасходовать план Codex/ChatGPT или API. Обратный мост запускает Codex, не Claude: Claude Code\nпользуется тем же каноном через Extella MCP.</p>",
        "<p>Маршрут выбирается по задаче: Codex ставит локальный подписанный мост, Claude Code\nподключается через Extella MCP, а другой ассистент может читать публичный канон напрямую.\nОбратный мост технически запускает Codex, не Claude. Любой реальный вызов модели — отдельное\nдействие по явной просьбе пользователя и может расходовать план или API.</p>",
        "нейтральное описание маршрутов",
    )
    body = replace_once(
        body,
        "<h3>Готовый промпт для моста</h3>\n<div class=\"cmd\"><button class=\"copy\">Копировать</button><code>Настрой мост Codex ↔ Claude ↔ Extella по единому публичному гиду.",
        "<h3>Готовый промпт для подключения</h3>\n<div class=\"cmd\"><button class=\"copy\">Копировать</button><code>Подключи моего ассистента к Extella по единому публичному гиду.",
        "нейтральный заголовок и промпт",
    )
    body = replace_once(
        body,
        "5. Перед реальным вызовом Codex предупреди о возможном расходе плана или API.\n6. В Extella используй прямой глобальный Expert, не run_agent. Не ослабляй loopback, HMAC, freshness, replay-защиту и account binding.",
        "5. Перед реальным вызовом модели предупреди о возможном расходе плана или API.\n6. Для локального моста Codex в Extella используй прямой глобальный Expert, не run_agent. Не ослабляй loopback, HMAC, freshness, replay-защиту и account binding.",
        "общая модель и конкретный маршрут Codex",
    )
    section_09["тело"] = body

    data["версия_содержимого"] = NEW_VERSION
    data["что_нового"].insert(0, {
        "версия": NEW_VERSION,
        "строки": [
            "Любой ассистент подключается к одному публичному канону",
            "Codex, Claude Code и другие инструменты описаны как маршруты, а не отдельные стандарты",
        ],
    })
    CONTENT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
