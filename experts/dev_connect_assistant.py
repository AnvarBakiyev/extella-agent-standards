# expert: dev_connect_assistant
# description: Готовит ключ Extella на ЭТОМ компьютере для Claude Code или Codex: выпускает его через прокси окна, кладёт в ~/.extella/api_token.txt и проверяет. Называет устройство и сверяет его с ожидаемым; у лежащего ключа сверяет аккаунт. Ключ никуда не печатает. Параметры: app_token, проверить_только, проба, ожидаемое_устройство, заменить_чужой.

def dev_connect_assistant(app_token: str = "", проверить_только: str = "", проба: str = "",
                          ожидаемое_устройство: str = "", заменить_чужой: str = "") -> str:
    """Кнопка «Подключить мой редактор» целиком, без модели посередине.

    ЗАЧЕМ. Приложение Extella не кладёт ключ на диск, и на каждом новом компьютере
    Claude Code или Codex упираются в «подключите Extella». Человеку остаётся пять
    шагов руками или агент, который печатает ключ в чат (разговор 29.09.2026).

    КАК. Платформа ключ эксперту не передаёт (замер 28–29.09.2026, Mac и VPS). Зато
    окно приложения получает пропуск `{{app_token}}`, а с правом `api.full` пропуск
    открывает прокси ядра `/api/ext/core/…` (H15): ОС подставляет настоящий ключ на
    своей стороне. Эксперт на этом компьютере через тот же прокси выпускает ключ и
    сразу пишет в файл. Ключ не проходит ни через страницу, ни через модель.

    НЕ ПЛОДИТЬ КЛЮЧИ. Список токенов отдаёт только имена и даты, без значений (замер
    29.09.2026), — прежний ключ по имени не переиспользовать. Поэтому единственная
    защита — рабочий ключ на диске: есть и принимается ядром — новый не выпускается.

    К КАКОМУ АГЕНТУ. Ключ в ядре привязан к агенту (`/api/token/validate` отдаёт
    agent_id), и выпуск без `X-Agent-Id` ядро отклоняет 422. Привязываем к основному
    агенту аккаунта `agent_extella_default` — к нему привязан и рабочий ключ, с которым
    строятся приложения. Агент самого приложения не годится: всё, что создаст
    редактор, уехало бы в агента справочника.

    БЕЗОПАСНОСТЬ. Значение ключа не возвращается и не пишется в журнал: наружу идут
    путь, права, имя ключа в списке токенов и отпечаток (первые 8 символов sha256).
    Имя ключа — «Extella Guide · <компьютер>»: по нему человек найдёт и отзовёт ключ
    этого компьютера в Library → System → Tokens.

    КОНТРАКТ С ОКНОМ. Каждый ответ несёт `код` исхода — окно двуязычное и строит
    фразу из своей таблицы строк по коду; русское `message` — для журнала и для
    вызова без окна.

    РЕЖИМ ПРОБЫ (`проба`). Для замера на чужой или общей машине: ключ выпускается,
    проверяется рукопожатием и тут же отзывается, на диск не пишется ничего.

    УСТРОЙСТВО И АККАУНТ (версия 2, аудит Guide 26.10.2026, F06). Вызов без `targets`
    уходит на устройство по умолчанию, и успех с чужого компьютера горел зелёным.
    Теперь каждый ответ несёт `устройство` — номер из ~/.extella/device.txt, — а с
    `ожидаемое_устройство` эксперт отказывает ДО любых изменений, если номер другой.
    Лежащий рабочий ключ сверяется с аккаунтом окна по агентам аккаунта: ключ другого
    аккаунта не выдаётся за готовый и без `заменить_чужой` не перезаписывается — его
    может использовать другой инструмент человека.
    """
    import hashlib
    import json
    import os
    import platform
    import urllib.error
    import urllib.request

    ПРОКСИ = "https://os.extella.ai/api/ext/core"
    ЯДРО = "https://api.extella.ai"

    # Окно не знает своего устройства (H106), поэтому каждый ответ называет машину:
    # иначе ключ, легший не туда, выглядел бы успехом.
    машина = {"компьютер": platform.node(), "система": platform.system(), "версия_эксперта": 2}
    на_windows = platform.system() == "Windows"
    имя_ключа = ("Extella Guide · " + (platform.node() or "компьютер"))[:80]

    папка = os.path.join(os.path.expanduser("~"), ".extella")
    файл = os.path.join(папка, "api_token.txt")

    import re
    устройство = ""
    try:
        with open(os.path.join(папка, "device.txt"), encoding="utf-8") as f:
            кандидат = f.read().strip()
        if re.fullmatch(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}", кандидат):
            устройство = кандидат.lower()
    except OSError:
        pass
    машина["устройство"] = устройство

    def ответ(подключено: bool, **поля) -> str:
        return json.dumps({"status": "success" if подключено else "error",
                           "подключено": подключено, **машина, **поля}, ensure_ascii=False)

    def отпечаток(значение: str) -> str:
        return hashlib.sha256(значение.encode("utf-8")).hexdigest()[:8]

    def вызов(адрес: str, тело: dict, заголовки: dict) -> tuple:
        запрос = urllib.request.Request(
            адрес, data=json.dumps(тело).encode("utf-8"),
            headers={"Content-Type": "application/json", "X-Profile-Id": "default", **заголовки},
            method="POST")
        try:
            with urllib.request.urlopen(запрос, timeout=60) as о:
                return о.status, о.read().decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            return e.code, e.read().decode("utf-8", "replace")[:300]
        except Exception as e:                                   # noqa: BLE001
            return 0, type(e).__name__

    def рукопожатие(ключ: str) -> tuple:
        """Живой вызов, а не наличие файла: мёртвый ключ в файле выглядит как подключение."""
        код, _ = вызов(ЯДРО + "/api/agent/list", {}, {"X-Auth-Token": ключ})
        return код == 200, f"HTTP {код}"

    def через_прокси(путь: str, тело: dict, агент: str = "") -> tuple:
        заголовки = {"X-App-Token": пропуск}
        if агент:
            заголовки["X-Agent-Id"] = агент
        код, текст = вызов(ПРОКСИ + путь, тело, заголовки)
        try:
            return код, json.loads(текст)
        except ValueError:
            return код, {"сырой_ответ": текст[:200]}

    # Не то устройство — отказ до любых изменений: ни чтения ключа, ни выпуска.
    ожидаемое = (ожидаемое_устройство or "").strip().lower()
    if ожидаемое and устройство and ожидаемое != устройство:
        return ответ(False, ожидалось=ожидаемое, код="не_то_устройство",
                     message="Ответило другое устройство, не то, что выбрано. Ключ не трогал.",
                     что_сделать="Выбрать нужное устройство и повторить.")

    def агенты_аккаунта(заголовки_или_ключ) -> set:
        """Номера агентов аккаунта без платформенных общих (agent_extella_*): у разных
        аккаунтов их имена совпадают, у своих агентов номера уникальны."""
        if isinstance(заголовки_или_ключ, str):
            код, текст = вызов(ЯДРО + "/api/agent/list", {}, {"X-Auth-Token": заголовки_или_ключ})
            try:
                данные = json.loads(текст)
            except ValueError:
                return set()
        else:
            код, данные = через_прокси("/api/agent/list", {})
        if код != 200 or not isinstance(данные, dict):
            return set()
        return {str(а.get("id")) for а in (данные.get("agents") or [])
                if isinstance(а, dict) and а.get("id") and not str(а.get("id")).startswith("agent_extella_")}

    def тот_же_аккаунт(ключ: str):
        """True / False / None (сверить не по чему: своих агентов нет хотя бы у одной стороны)."""
        if not пропуск or пропуск.startswith("{{"):
            return None
        у_окна, у_ключа = агенты_аккаунта(None), агенты_аккаунта(ключ)
        if not у_окна or not у_ключа:
            return None
        return bool(у_окна & у_ключа)

    пропуск = (app_token or "").strip()

    существующий = ""
    try:
        with open(файл, encoding="utf-8") as f:
            существующий = f.read().strip()
    except OSError:
        pass

    # Рабочий ключ на месте — ничего не выпускаем: каждое нажатие не должно
    # плодить ключи в списке токенов.
    if существующий and not проба:
        живой, как = рукопожатие(существующий)
        аккаунт = тот_же_аккаунт(существующий) if живой else None
        if живой and аккаунт is False and not заменить_чужой:
            return ответ(False, файл=файл, отпечаток=отпечаток(существующий), аккаунт_сверен=True,
                         код="чужой_аккаунт",
                         message="На компьютере лежит рабочий ключ ДРУГОГО аккаунта Extella. Не трогал его.",
                         что_сделать="Заменить его ключом этого аккаунта — или открыть Guide в том аккаунте, "
                                     "для которого нужен редактор.")
        if живой and аккаунт is not False:
            return ответ(True, файл=файл, отпечаток=отпечаток(существующий), ключ_выпущен=False,
                         аккаунт_сверен=аккаунт is True,
                         код="уже_подключено", message="Ключ уже на месте и работает. Новый не выпускал.")
        if проверить_только:
            return ответ(False, файл=файл, ответ_ядра=как,
                         код="ключ_мёртв", message="В файле лежит ключ, но платформа его больше не принимает.",
                         что_сделать="Нажать «Подключить редактор» — ключ заменится рабочим.")

    if проверить_только and not существующий:
        return ответ(False, код="нет_ключа", message="Ключа на этом компьютере нет.",
                     что_сделать="Нажать «Подключить редактор».")

    # Облачный контейнер — не компьютер человека: ключ, выпущенный туда, остался бы
    # живым в чужой песочнице. Признаков два, и нужны оба: device.txt ненадёжен сам
    # по себе (H91: на VPS его нет при работающем листенере).
    if not os.path.exists(os.path.join(папка, "device.txt")) and os.path.exists("/.dockerenv"):
        return ответ(False, похоже_на_контейнер=True,
                     код="контейнер", message="Вызов выполнился в облачном контейнере, а не на твоём компьютере. "
                             "Ключ туда не выпускаю.",
                     что_сделать="Открыть приложение в Extella на своём компьютере: внизу окна "
                                 "должно быть «Running».")

    if not пропуск or пропуск.startswith("{{"):
        return ответ(False, код="нет_пропуска", message="Окно приложения не передало пропуск.",
                     что_сделать="Закрыть окно приложения и открыть снова: пропуск живёт два часа.")

    # 1. Основной агент аккаунта: к нему привяжется ключ.
    код, агенты = через_прокси("/api/agent/list", {})
    if код == 403:
        return ответ(False, ответ_платформы=f"HTTP {код}",
                     код="нет_права", message="Приложению не выдано право «Full Extella API access».",
                     что_сделать="Открыть карточку приложения и разрешить это право, "
                                 "затем нажать кнопку ещё раз.")
    if код != 200:
        return ответ(False, ответ_платформы=f"HTTP {код}",
                     код="платформа_молчит", message="Платформа не ответила на запрос списка агентов.",
                     что_сделать="Повторить через минуту; если не проходит — закрыть и открыть окно.")
    все = [а for а in (агенты.get("agents") or []) if isinstance(а, dict)] if isinstance(агенты, dict) else []
    основной = next((а for а in все if а.get("id") == "agent_extella_default"), None)
    if not основной:
        return ответ(False, код="нет_основного_агента", message="В аккаунте не нашёлся основной агент Extella.",
                     что_сделать="Создать ключ руками: Library → System → Tokens.")

    # 2. Новый ключ с именем этого компьютера — по имени его найдут и отзовут.
    код, выпуск = через_прокси("/api/token/create", {"name": имя_ключа}, основной["id"])
    ключ = str((выпуск or {}).get("token") or "") if код == 200 else ""
    if not ключ:
        return ответ(False, ответ_платформы=f"HTTP {код}",
                     код="не_выдан", message="Платформа не выдала ключ.",
                     что_сделать="Повторить; если не проходит — создать ключ руками: "
                                 "Library → System → Tokens.")

    живой, как = рукопожатие(ключ)

    if проба:
        # Замер без следа: ключ выпущен ради проверки цепочки — сразу отзываем.
        # Ключ уходит платформе в теле отзыва — это единственное место, куда он
        # передаётся, и в ответ окну он не попадает.
        код_отзыва, _ = через_прокси("/api/token/revoke", dict(token=ключ), основной["id"])
        return ответ(живой, проба=True, ключ_выпущен=True, рукопожатие=как,
                     отозван=код_отзыва == 200, записано_на_диск=False,
                     код="проба", message="Цепочка работает: ключ выпущен, принят и отозван."
                             if живой else f"Ключ выпущен, но не принят ({как}).")

    if not живой:
        return ответ(False, рукопожатие=как, код="не_принят", message=f"Ключ получен, но платформа его не приняла ({как}).",
                     что_сделать="Повторить через минуту.")

    try:
        os.makedirs(папка, exist_ok=True)
        # Через временный файл: половина ключа на диске хуже, чем его отсутствие.
        временный = файл + ".tmp"
        with open(временный, "w", encoding="utf-8") as f:
            f.write(ключ + "\n")
        os.chmod(временный, 0o600)
        os.replace(временный, файл)
        os.chmod(файл, 0o600)
    except OSError as e:
        return ответ(False, код="не_записан", message=f"Не удалось записать ключ: {type(e).__name__}",
                     что_сделать="Проверить права на папку ~/.extella")

    return ответ(
        True, файл=файл,
        # На Windows chmod 0o600 доступа не ограничивает: файл защищён только
        # профилем пользователя. Писать там «600» — докладывать неправду (28.09.2026).
        права="профиль пользователя Windows" if на_windows else "600",
        имя_ключа=имя_ключа, агент=основной.get("name") or "", отпечаток=отпечаток(ключ),
        ключ_выпущен=True, заменён_прежний=bool(существующий and существующий != ключ),
        код="подключено", message="Ключ на месте и проверен. Настройка Claude Code или Codex — следующий шаг.")
