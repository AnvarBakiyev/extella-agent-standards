# description: Голосовой ввод для окна приложения: устройство пишет микрофон и возвращает распознанный текст, звук не покидает машину
def mic_record(
    seconds: int = 10,
    mode: str = "text",
    language: str = "ru",
    device: str = "",
    keep_file: bool = False,
    model: str = "small",
):
    """Записывает микрофон НА УСТРОЙСТВЕ и отдаёт текст в окно приложения.

    Зачем существует. Окно приложения живёт в песочнице без своего
    происхождения и без разрешения на микрофон, поэтому `getUserMedia` в нём
    отклоняется — записать голос со страницы нельзя в принципе (замер
    24.08.2026, жалоба на отсутствие голосового ввода в витрине). Но у окна
    есть законный путь наружу: попросить устройство. Микрофон открывает
    listener на машине пользователя, а окно получает уже готовый текст.

    Звук остаётся на устройстве: файл пишется во временный каталог,
    распознаётся локально и удаляется. Никуда не отправляется и не
    сохраняется, если явно не попросили `keep_file`.

    Параметры:
      seconds  — сколько писать (ограничено 60: синхронный вызов из окна
                 столько не ждёт, длинную диктовку собирают из отрезков);
      mode     — "text" вернуть распознанное, "file" вернуть путь к записи;
      language — язык распознавания;
      device   — имя или номер входа, пусто — вход по умолчанию;
      model    — размер распознавателя. Замер 25.08.2026 на живой машине:
                 «base» расшифровывает 0,8 с, но русский разбирает грязно
                 («вводовок не приложения»); «small» — 1,1 с и почти чисто.
                 Поэтому по умолчанию «small»; первая загрузка модели на
                 устройстве качает файл и занимает полминуты, дальше она
                 лежит в кэше;
      keep_file — не удалять запись (по умолчанию удаляется).

    Возвращает готовое значение сразу, без внутренней задачи: окно ждёт
    ответа синхронно.
    """
    import os
    import sys
    import tempfile
    import time
    import wave

    начало = time.time()
    seconds = max(1, min(int(seconds or 10), 60))
    язык = (language or "ru").strip() or "ru"
    временный = os.path.join(tempfile.gettempdir(), f"extella_mic_{int(начало)}.wav")

    def прибрать():
        if not keep_file:
            try:
                os.remove(временный)
            except OSError:
                pass

    # ── запись ───────────────────────────────────────────────────────────────
    частота = 16000                      # распознавание всё равно сводит к 16 кГц
    записано = False
    чем = ""
    try:
        import sounddevice
        if device:
            try:
                sounddevice.default.device = int(device)
            except ValueError:
                sounddevice.default.device = device
        поток = sounddevice.rec(int(seconds * частота), samplerate=частота,
                                channels=1, dtype="int16")
        sounddevice.wait()
        with wave.open(временный, "wb") as ф:
            ф.setnchannels(1)
            ф.setsampwidth(2)
            ф.setframerate(частота)
            ф.writeframes(поток.tobytes())
        записано, чем = True, "sounddevice"
    except Exception as беда:                                     # noqa: BLE001
        причина_sd = str(беда)[:160]
        # Запасной путь — ffmpeg со штатным входом каждой системы.
        import subprocess
        вход = {"darwin": ("avfoundation", device or ":default"),
                "win32": ("dshow", f"audio={device}" if device else "audio=default"),
                }.get(sys.platform, ("alsa", device or "default"))
        try:
            subprocess.run(
                ["ffmpeg", "-y", "-f", вход[0], "-i", вход[1], "-t", str(seconds),
                 "-ac", "1", "-ar", str(частота), временный],
                capture_output=True, timeout=seconds + 30, check=True)
            записано, чем = True, "ffmpeg"
        except Exception as беда2:                                # noqa: BLE001
            return {"ok": False,
                    "почему": "микрофон не открылся на устройстве",
                    "подробности": {"sounddevice": причина_sd,
                                    "ffmpeg": str(беда2)[:160]},
                    "что делать": "Проверить, что устройству разрешён доступ к "
                                  "микрофону в настройках системы: службе, которая "
                                  "исполняет задания Extella, разрешение выдаётся "
                                  "отдельно и молча не запрашивается."}

    размер = os.path.getsize(временный) if os.path.exists(временный) else 0
    if not записано or размер < 1000:
        прибрать()
        return {"ok": False, "почему": "запись вышла пустой",
                "что делать": "Проверить, что выбран нужный вход и он не занят "
                              "другой программой."}

    if mode == "file":
        return {"ok": True, "файл": временный, "секунд": seconds,
                "чем записано": чем, "байт": размер}

    # ── распознавание на этом же устройстве ──────────────────────────────────
    try:
        import whisper
    except Exception:                                             # noqa: BLE001
        прибрать()
        return {"ok": False, "почему": "распознавание недоступно",
                "что делать": "Поставить локальное распознавание на устройстве "
                              "или запрашивать mode='file' и разбирать запись "
                              "своими средствами.",
                "секунд": seconds}
    try:
        # Модель держим в кэше процесса: между вызовами listener переиспользует
        # его, и повторная загрузка съедала бы больше, чем сама расшифровка.
        глобальные = globals()
        ключ = f"__whisper_{model}"
        модель = глобальные.get(ключ)
        if модель is None:
            модель = whisper.load_model(model)
            глобальные[ключ] = модель
        итог = модель.transcribe(временный, language=язык, fp16=False)
        текст = (итог.get("text") or "").strip()
    except Exception as беда:                                     # noqa: BLE001
        прибрать()
        return {"ok": False, "почему": "распознавание не справилось",
                "подробности": str(беда)[:200]}
    прибрать()
    return {"ok": True, "текст": текст, "секунд": seconds,
            "чем записано": чем, "заняло_сек": round(time.time() - начало, 1)}
