#!/usr/bin/env python3
"""Вставить пробу хранилища в страницу приложения — и уметь снять её обратно.

ЗАЧЕМ. Окно ОС обязано знать, дали ли приложению хранилище: без него drawio
показывает английскую ошибку, а excalidraw молча теряет рисунки. Ответить может
только сама страница приложения — снаружи чужое происхождение не прочитать, а
отдельный файл-разведчик не доезжает: excalidraw ставит service worker на весь
порт и любой адрес отдаёт саму доску.

    python3 tools/inject_probe.py ~/extella-cabinet/board/index.html
    python3 tools/inject_probe.py --снять ~/extella-cabinet/board/index.html
    python3 tools/inject_probe.py --selftest

Правка чужого файла подчиняется трём правилам:
  * вставка помечена, поэтому её видно и можно снять;
  * повтор ничего не дублирует;
  * рядом остаётся копия «.до_пробы» — если приложение обновится, будет с чем сверить.
"""

import pathlib
import shutil
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
НАЧАЛО = "<!-- extella-проба: начало"
КОНЕЦ = "<!-- extella-проба: конец -->"


def кусок() -> str:
    return (КОРЕНЬ / "templates" / "probe_snippet.html").read_text()


def вставить(файл: pathlib.Path, текст_куска: str = None) -> str:
    текст_куска = текст_куска if текст_куска is not None else кусок()
    т = файл.read_text()
    if НАЧАЛО in т:
        return "уже вставлено"
    # В <head> как можно раньше: у drawio доступ к хранилищу случается на старте,
    # и проба обязана успеть ответить до того, как приложение упадёт.
    # Перевод строки ставим ТОЛЬКО после куска. Если добавить его и перед, снятие
    # оставит лишнюю пустую строку, и файл перестанет совпадать с исходным —
    # мелочь, из-за которой не докажешь, что правку сняли начисто.
    кусок_ = текст_куска.rstrip("\n") + "\n"
    место = т.lower().find("<head>")
    if место >= 0:
        т = т[:место + 6] + кусок_ + т[место + 6:]
    else:
        т = кусок_ + т
    копия = файл.with_suffix(файл.suffix + ".до_пробы")
    if not копия.exists():
        shutil.copy2(файл, копия)
    файл.write_text(т)
    return "вставлено"


def снять(файл: pathlib.Path) -> str:
    т = файл.read_text()
    a = т.find(НАЧАЛО)
    if a < 0:
        return "пробы нет"
    b = т.find(КОНЕЦ)
    if b < 0:
        return "метка конца потеряна — снимать вслепую нельзя, поправь руками"
    файл.write_text(т[:a] + т[b + len(КОНЕЦ):].lstrip("\n"))
    return "снято"


def _selftest() -> int:
    import tempfile
    провалы = []
    # Образец обязан нести МЕТКИ: на них держится и «не дублировать», и «снять».
    # Первый вариант теста подсовывал кусок без меток и «проваливал» исправный код.
    ОБРАЗЕЦ = НАЧАЛО + " -->\n<script>console.log('проба')</script>\n" + КОНЕЦ + "\n"

    def проверить(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    print("Самопроверка inject_probe:")
    with tempfile.TemporaryDirectory() as d:
        ф = pathlib.Path(d) / "index.html"
        ф.write_text("<html><head><title>Приложение</title></head><body>тело</body></html>")
        исходник = ф.read_text()

        проверить("вставка проходит", вставить(ф, ОБРАЗЕЦ) == "вставлено")
        после = ф.read_text()
        проверить("проба попала в head", после.index(ОБРАЗЕЦ) < после.index("<title>"))
        проверить("тело приложения цело", "тело" in после and "<title>Приложение</title>" in после)
        проверить("копия сохранена", (ф.with_suffix(".html.до_пробы")).exists())

        проверить("повтор не дублирует", вставить(ф, ОБРАЗЕЦ) == "уже вставлено")
        проверить("после повтора проба одна", ф.read_text().count(ОБРАЗЕЦ) == 1)

        проверить("снятие проходит", снять(ф) == "снято")
        проверить("файл вернулся к исходному", ф.read_text() == исходник)
        проверить("снятие дважды честно молчит", снять(ф) == "пробы нет")

        # Потерянная метка конца — не повод резать файл наугад.
        ф.write_text(НАЧАЛО + " ...\n<html></html>")
        проверить("без метки конца не режем",
                  снять(ф).startswith("метка конца потеряна"))

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not аргументы:
        print(__doc__)
        sys.exit(2)
    for путь in аргументы:
        ф = pathlib.Path(путь).expanduser()
        итог = снять(ф) if "--снять" in sys.argv else вставить(ф)
        print(f"  {ф}: {итог}")
