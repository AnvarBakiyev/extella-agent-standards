#!/usr/bin/env python3
"""Отбор агентом: фраза сверх словаря → модель возвращает ФОРМУ, а не болтовню.

ЗАЧЕМ. Тупой разбор «скажи» понимает источник, получателя и «первые N» — и на
этом честно останавливается. Фразу «возьми все тарифы, которые снимали
пользователи» он выполнял как «возьми всё»: уверенно выгружал НЕ ТО, что
спрошено. Замер 20.08.2026, фраза Анвара в окне Таблицы. Это хуже отказа.

УСТРОЙСТВО — эскалация, а не замена. Быстрые фразы остаются коду: секунда,
ноль токенов, полная воспроизводимость. К агенту уезжает только фраза со
смыслом сверх словаря («которые», «где», вопрос) — вместе с данными источника.
Агент обязан вернуть форму ИЗ НАШЕГО ЖЕ СЛОВАРЯ (см. КОНТРАКТ_ПЯТИ_ФОРМ.md):
он ещё один источник форм, а не новый способ рисовать. Ответ проверяется
контролёром форм; невалидное или выдуманное — отказ, на холст не попадает.

ЧЕСТНОСТЬ. Нет в данных того, что спросили, — агент говорит «нет», и это
доносится человеку дословно. Подпись на результате всегда сообщает, что отбор
делал агент по фразе: интерпретация не выдаёт себя за механику.

    python3 tools/отбор_агентом.py --selftest
"""

import json
import pathlib
import re
import sys
import urllib.request

СЮДА = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(СЮДА))
from формы import Отказ, ФОРМЫ, пример, проверить  # noqa: E402
import паспорт as П                                 # noqa: E402

# Данных больше — честный отказ, а не молчаливый срез: модель, получившая
# половину данных, вернёт уверенный ответ по половине, и это неправда.
ПРЕДЕЛ_ДАННЫХ = 120_000

# Смысл сверх словаря узнаём по словам-условиям. Список нарочно короткий:
# ложное срабатывание уводит быструю фразу на медленный путь (десятки секунд
# и токены), поэтому вежливые слова вроде «пожалуйста» сюда не входят.
УСЛОВНЫЕ = ("котор", "где ", "кроме", "можешь", "сколько", "?")


def сверх_словаря(фраза: str) -> bool:
    ф = " " + фраза.lower() + " "
    return any(с in ф for с in УСЛОВНЫЕ)


ЗАДАНИЕ = """Ты отбираешь данные по запросу человека. Отвечай СТРОГО одним JSON, без пояснений и текста вокруг.

ЗАПРОС: {фраза}

Верни одну форму из словаря ({формы}) с данными, отвечающими запросу.
Образцы форм (структуру повторять точно):
list: {обр_list}
number: {обр_number}
steps: {обр_steps}
links: {обр_links}
document: {обр_document}

Правила:
- бери значения ТОЛЬКО из данных ниже, ничего не вычисляй «из головы»;
  проценты и суммы можно складывать/считать по данным честно;
- в "подпись" напиши, по какому признаку отобрано;
- если в данных НЕТ того, что спрошено, верни {{"отказ": "<одна честная фраза, чего именно нет>"}} — это правильный ответ, не сочиняй.

ДАННЫЕ приложения «{имя}»:
{данные}"""


def _спросить(запрос: str) -> dict:
    """Тот же канал, что у паспорта: поле input, ответ в output без reasoning."""
    тело = {"agent_id": П.АГЕНТ, "input": запрос}
    з = urllib.request.Request(
        f"{П.ЯДРО}/api/agent/run", data=json.dumps(тело, ensure_ascii=False).encode(),
        headers={"X-Auth-Token": П.токен(), "X-Profile-Id": "default",
                 "X-Agent-Id": П.АГЕНТ, "Content-Type": "application/json"},
        method="POST")
    try:
        with urllib.request.urlopen(з, timeout=180) as о:
            ответ = json.loads(о.read().decode())
    except urllib.error.HTTPError as е:
        raise Отказ(f"платформа отказала ({е.code}): {е.read().decode()[:200]}")
    except (urllib.error.URLError, OSError) as е:
        raise Отказ(f"платформа недоступна: {е}")
    текст = П.ответ_словами(ответ)
    м = re.search(r"\{.*\}", текст, re.S)
    if not м:
        raise Отказ(f"агент ответил не формой: {текст[:200]}")
    try:
        return json.loads(м.group(0))
    except json.JSONDecodeError as е:
        raise Отказ(f"агент вернул испорченный JSON ({е}): {м.group(0)[:200]}")


ЗАДАНИЕ_СОЧИНЕНИЯ = """Ты сочиняешь СТРУКТУРУ по замыслу человека — схему процесса, путь, разбивку. Отвечай СТРОГО одним JSON, без пояснений и текста вокруг.

ЗАМЫСЕЛ: {фраза}

Верни одну форму из словаря ({формы}). Для процессов и путей — «шаги»,
для систем со стрелками — «связи», для перечней — «список».
Образцы форм (структуру повторять точно):
steps: {обр_steps}
links: {обр_links}
list: {обр_list}

Правила:
- 5–12 узлов: схему читают глазами, а не листают;
- имена узлов короткие, на языке человека, без нумерации в тексте;
- если замысел не разложить в структуру, верни {{"отказ": "<одна честная фраза почему>"}}."""


def сочинить(фраза: str, спроси=None) -> dict:
    """Замысел без источника → структура от агента. Доска — единственное окно,
    где ценнее не перенос данных, а сочинение: схема процесса, путь клиента,
    структура отдела. Слово Анвара 20.08.2026: доска без этого «не вызывает
    восторгов». Честность та же, что у отбора: подпись говорит, что это
    сочинение, контролёр форм не пускает мусор."""
    запрос = ЗАДАНИЕ_СОЧИНЕНИЯ.format(
        фраза=" ".join(фраза.split())[:300], формы=", ".join(ФОРМЫ),
        **{f"обр_{ф}": json.dumps(пример(ф), ensure_ascii=False)
           for ф in ("steps", "links", "list")})
    ответ = (спроси or _спросить)(запрос)
    if "отказ" in ответ:
        raise Отказ(f"агент честно отказал: {ответ['отказ']}")
    д = проверить(ответ)
    д["caption"] = (f"{д.get('caption') or ''} · сочинено агентом по фразе, "
                    f"проверьте глазами").strip(" ·")
    return д


def отобрать(фраза: str, имя: str, файл: pathlib.Path, спроси=None) -> dict:
    """Фраза + данные источника → проверенная форма (или честный Отказ)."""
    данные = файл.read_text()
    if len(данные) > ПРЕДЕЛ_ДАННЫХ:
        raise Отказ(f"данных «{имя}» слишком много для агентского отбора "
                    f"({len(данные) // 1024} КБ при пределе "
                    f"{ПРЕДЕЛ_ДАННЫХ // 1024} КБ) — скажите точнее или «первые N»")
    запрос = ЗАДАНИЕ.format(
        фраза=" ".join(фраза.split())[:300], формы=", ".join(ФОРМЫ), имя=имя,
        данные=данные,
        **{f"обр_{ф}": json.dumps(пример(ф), ensure_ascii=False) for ф in ФОРМЫ})
    ответ = (спроси or _спросить)(запрос)
    if "отказ" in ответ:
        raise Отказ(f"агент честно отказал: {ответ['отказ']}")
    д = проверить(ответ)          # невалидная форма — отказ, не рисуем неправду
    # Интерпретация не выдаёт себя за механику: подпись говорит, кто отбирал.
    д["caption"] = (f"{д.get('caption') or ''} · отбор агентом по фразе, "
                    f"проверьте глазами").strip(" ·")
    return д


def selftest() -> int:
    ошибки = []

    for фраза, ждём in (("Можешь взять из Астры все тарифы, которые снимали "
                         "пользователи, и положить сюда в таблицу?", True),
                        ("возьми тех, у которых отток выше 20", True),
                        ("сколько всего городов в астре", True),
                        ("возьми из астры первые 8", False),
                        ("возьми из таблицы и нарисуй на доске", False),
                        ("новая доска", False),
                        ("возьми из астры и положи в таблицу", False)):
        if сверх_словаря(фраза) != ждём:
            ошибки.append(f"сверх_словаря({фраза!r}) = {not ждём}, ждали {ждём}")
    if not ошибки:
        print("  ✓ условные фразы уходят агенту, механические остаются коду")

    файл = pathlib.Path("/tmp/отбор_проба.json")
    файл.write_text(json.dumps({"записи": [{"город": "Алматы", "отток": 21}]}))

    годная = {"form": "number", "title": "Городов", "value": "1",
              "caption": "посчитано по записям"}
    д = отобрать("сколько городов?", "проба", файл, спроси=lambda з: dict(годная))
    if "отбор агентом" not in (д.get("caption") or ""):
        ошибки.append("подпись не говорит, что отбирал агент, — интерпретация "
                      "выдаёт себя за механику")
    else:
        print("  ✓ годная форма проходит и подписывается «отбор агентом»")

    try:
        отобрать("сколько?", "проба", файл,
                 спроси=lambda з: {"отказ": "в данных нет тарифов"})
        ошибки.append("отказ агента не донесён человеку")
    except Отказ as о:
        if "нет тарифов" in str(о):
            print("  ✓ честный отказ агента доносится дословно")
        else:
            ошибки.append(f"отказ агента искажён: {о}")

    try:
        отобрать("сколько?", "проба", файл,
                 спроси=lambda з: {"форма": "список", "строки": "не список"})
        ошибки.append("невалидная форма прошла контролёра — на холст поедет "
                      "неправда")
    except Отказ:
        print("  ✓ невалидную форму агента контролёр не пропускает")

    файл.write_text("х" * (ПРЕДЕЛ_ДАННЫХ + 1))
    try:
        отобрать("сколько?", "проба", файл, спроси=lambda з: dict(годная))
        ошибки.append("огромные данные молча уехали модели — ответ был бы по "
                      "обрезку")
    except Отказ:
        print("  ✓ слишком большие данные — честный отказ, а не молчаливый срез")
    файл.unlink(missing_ok=True)

    print("\n" + ("ИТОГ САМОПРОВЕРКИ: все проверки прошли" if not ошибки
                  else "ОТКАЗ:\n  " + "\n  ".join(ошибки)))
    return 1 if ошибки else 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    print(__doc__)
    sys.exit(2)
