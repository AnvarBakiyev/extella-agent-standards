#!/usr/bin/env python3
"""Размер файла, названный в тексте, обязан быть правдой (H112-бис).

ЗАЧЕМ. В тот же день, когда вход для внешнего агента был написан, две цифры в нём
устарели: `rules/INDEX.md` назван «около 10 КБ» при настоящих 16, а вход — «9 КБ»
при 6,7. Это тот же класс, что «116 правил» через час после 118: число в тексте
живёт своей жизнью и тихо становится ложью, а внешний агент по ней решает, тянуть
файл или нет.

ЧТО ПРОВЕРЯЕТСЯ. В строке одновременно названы файл репозитория и размер в
килобайтах — значит это утверждение о файле, и оно сверяется с диском. Допуск 25%:
текст не обязан меняться от каждой правки, но и врать вдвое не должен.

ЧЕГО НЕ ТРОГАЕТ. Размеры без имени файла (лимиты канала «тело до 64 КБ»),
размеры чужих страниц (страница GitHub), файлы, которых нет в репозитории.

    python3 tools/check_file_size_claims.py
    python3 tools/check_file_size_claims.py --selftest

Коды выхода: 0 — все названные размеры правдивы, 1 — есть расхождение.

ПРИЁМКА 25.09.2026: прогон по живым текстам поймал две ошибки самого гейта —
число привязывалось к соседнему файлу и не распознавалось кириллическое имя.
Обе стали пробами; после починки на живом дереве ложных тревог нет.
"""

from __future__ import annotations

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ДОКУМЕНТЫ = ("AGENT_START.md", "PROMPT_FOR_EXTERNAL_AGENT.md", "README.md")
ДОПУСК = 0.25

РАЗМЕР = re.compile(r"(\d+(?:[.,]\d+)?)\s*КБ")
ФАЙЛ = re.compile(r"[`\[]?([A-Za-z0-9_./-]+\.(?:md|py|json|html|js|sh))[`\]]?")


def утверждения(строка: str):
    """(имя файла, названный размер) для строки, где есть и файл, и килобайты.

    Число привязывается к БЛИЖАЙШЕМУ имени файла, а не к первому: в строке их
    бывает несколько, и пары «по порядку» дали ложный красный на первой же строке
    настоящего текста.
    """
    размеры = [(m.start(), float(m.group(1).replace(",", "."))) for m in РАЗМЕР.finditer(строка)]
    файлы = [(m.start(1), m.group(1)) for m in ФАЙЛ.finditer(строка)]
    if not размеры or not файлы:
        return []
    пары = []
    for место, имя in файлы:
        # Размер относится к файлу, если стоит ПОСЛЕ него: «файл — N КБ».
        после = [р for р in размеры if 0 <= р[0] - место <= 60]
        if после:
            пары.append((имя, после[0][1]))
    return пары


def беды(корень: pathlib.Path, документы=ДОКУМЕНТЫ) -> list[str]:
    найдено = []
    for имя in документы:
        путь = корень / имя
        if not путь.exists():
            continue
        for н, строка in enumerate(путь.read_text(encoding="utf-8").splitlines(), 1):
            for файл, названо in утверждения(строка):
                цель = корень / файл
                if not цель.is_file():
                    continue                      # чужая страница или пример пути
                настоящий = цель.stat().st_size / 1024
                if abs(настоящий - названо) > ДОПУСК * настоящий:
                    найдено.append(
                        f"{имя}:{н}: про {файл} сказано {названо:g} КБ, на диске "
                        f"{настоящий:.1f} КБ — поправь или убери размер")
    return найдено


def проверить() -> int:
    список = беды(КОРЕНЬ)
    for б in список:
        print("  ✗ " + б)
    if список:
        print("\nНЕ УСПЕХ: размер в тексте разошёлся с файлом. Размеры устаревают молча — "
              "надёжнее не называть их вовсе.")
        return 1
    print("Все названные размеры файлов совпадают с диском.")
    return 0


def _selftest() -> int:
    import tempfile
    провалы = []

    def проба(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    print("Самопроверка check_file_size_claims:")
    проба("строка без файла не считается утверждением",
          утверждения("тело запроса до 64 КБ") == [])
    проба("строка без размера не считается утверждением",
          утверждения("читай `AGENT_START.md` целиком") == [])
    проба("файл и размер в одной строке — это утверждение",
          утверждения("вход `AGENT_START.md` — 9 КБ") == [("AGENT_START.md", 9.0)])
    проба("дробный размер распознаётся",
          утверждения("`rules/INDEX.md` — 16,0 КБ")[0][1] == 16.0)
    проба("число перед файлом к нему не относится",
          утверждения("сырой README — 31 КБ. Свод `DEPLOY_REQUIREMENTS.md` — 369 КБ")
          == [("DEPLOY_REQUIREMENTS.md", 369.0)])

    with tempfile.TemporaryDirectory() as вр:
        к = pathlib.Path(вр)
        (к / "target.md").write_text("x" * 10240, encoding="utf-8")       # 10 КБ
        (к / "AGENT_START.md").write_text("файл `target.md` — 10 КБ\n", encoding="utf-8")
        проба("верный размер претензий не вызывает", беды(к) == [])
        (к / "AGENT_START.md").write_text("файл `target.md` — 4 КБ\n", encoding="utf-8")
        проба("враньё вдвое ловится", len(беды(к)) == 1)
        (к / "AGENT_START.md").write_text("файл `target.md` — 11 КБ\n", encoding="utf-8")
        проба("отклонение в пределах допуска пропускается", беды(к) == [])
        (к / "AGENT_START.md").write_text("страница GitHub — 497 КБ\n", encoding="utf-8")
        проба("чужая страница без файла не проверяется", беды(к) == [])

        # Кириллица весит два байта на знак: размер, посчитанный ЗНАКАМИ, занижен
        # примерно в 1,6 раза. Именно так неверные числа и попали в тексты — их
        # печатал split_rules. Гейт обязан мерить байты, иначе благословит занижение.
        (к / "ru.md").write_text("я" * 6000, encoding="utf-8")        # 6000 знаков = 11,7 КБ
        (к / "AGENT_START.md").write_text("файл `ru.md` — 5,9 КБ\n", encoding="utf-8")
        проба("размер, посчитанный знаками вместо байтов, ловится", len(беды(к)) == 1)
        (к / "AGENT_START.md").write_text("файл `ru.md` — 11,7 КБ\n", encoding="utf-8")
        проба("правильный размер в байтах проходит", беды(к) == [])

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы — " + "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    sys.exit(_selftest() if "--selftest" in sys.argv else проверить())
