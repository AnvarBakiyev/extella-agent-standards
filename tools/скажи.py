def реестр() -> dict:
    if not РЕЕСТР.exists():
        return {}
    return json.loads(РЕЕСТР.read_text())


def записать_реестр(д: dict) -> None:
    РЕЕСТР.parent.mkdir(parents=True, exist_ok=True)
    РЕЕСТР.write_text(json.dumps(д, ensure_ascii=False, indent=2))


def основа(слово: str) -> str:
    """Отрезать русское окончание: «астры», «астре», «астрой» → «астр».

    Это не морфология, а грубое усечение — и этого достаточно, потому что мы не
    угадываем значение, а лишь сопоставляем с коротким списком известных имён.
    Ошибиться тут можно только в сторону «не нашёл», и тогда мы честно спросим.
    """
    с = слово.lower().strip(".,!?;:«»\"'()")
    for окончание in ("ами", "ями", "ой", "ей", "ах", "ях", "ов", "ам", "ям",
                      "ы", "и", "е", "у", "ю", "а", "я", "ой"):
        if len(с) > 4 and с.endswith(окончание):
            return с[:-len(окончание)]
    return с


def сколько(фраза: str) -> int | None:
    """«первые 9», «топ 8», «9 первых» → 9. Не назвали числа — не режем.

    Зачем вообще: слепой показ всего разваливает картину. Сто три карточки — это
    выгрузка, а не схема, и человек в ней не видит ничего. Но отбор НЕ делается
    втихую по умолчанию: молча показать часть и не сказать об этом — обман.
    Не назвали число — рисуем всё и пишем сколько.
    """
    for i, с in enumerate(слова := фраза.lower().split()):
        ч = "".join(з for з in с if з.isdigit())
        if not ч:
            continue
        рядом = " ".join(слова[max(0, i - 2):i + 3])
        if any(к in рядом for к in ("перв", "топ", "верх", "главн")):
            return int(ч)
    return None


def обрезать(д: dict, сколько_нужно: int | None) -> dict:
    поле = СПИСОЧНЫЕ.get(д["форма"])
    if not поле or not сколько_нужно or len(д[поле]) <= сколько_нужно:
        return д
    было = len(д[поле])
    д[поле] = д[поле][:сколько_нужно]
    # Отбор обязан быть виден НА рисунке, а не только в терминале: подпись едет
    # вместе с формой, терминал закрывается.
    д["подпись"] = (f"{д.get('подпись') or ''} · показаны первые "
                    f"{сколько_нужно} из {было}").strip(" ·")
    print(f"  отбор: показываю {сколько_нужно} из {было}")
    return д


def найти_и_слово(фраза: str, имена) -> tuple:
    """Как найти(), но возвращает и совпавшее слово фразы.

    Зачем: таблица теперь И источник, И получатель. Во фразе «возьми из таблицы
    и положи в таблицу» одно и то же слово нельзя отдать обоим: сначала находим
    источник, вычёркиваем его слово, в остатке ищем получателя. Без вычёркивания
    «возьми из таблицы и нарисуй на доске» уносило рисунок в таблицу.
    """
    слова = [(с, основа(с)) for с in фраза.split()]
    for имя in имена:
        кандидаты = [имя]
        if isinstance(имена, dict) and isinstance(имена.get(имя), dict):
            человеческое = имена[имя].get("имя")
            if человеческое:
                кандидаты.append(str(человеческое))
        for к in кандидаты:
            о = основа(к)
            for слово, ос in слова:
                if ос == о or (len(ос) > 3 and (ос.startswith(о) or о.startswith(ос))):
                    return имя, слово
    return None, None


def найти(фраза: str, имена) -> str | None:
    слова = {основа(с) for с in фраза.split()}
    for имя in имена:
        # Установщик регистрирует латинский slug, а человек говорит по-русски:
        # «возьми из таблицы» должно найти источник «tablica» по его
        # человеческому имени «Таблица». Ключ и имя равноправны в поиске.
        кандидаты = [имя]
        if isinstance(имена, dict) and isinstance(имена.get(имя), dict):
            человеческое = имена[имя].get("имя")
            if человеческое:
                кандидаты.append(str(человеческое))
        for к in кандидаты:
            о = основа(к)
            if о in слова or any(с.startswith(о) or о.startswith(с)
                                 for с in слова if len(с) > 3):
                return имя
    return None


def особая_доска(фраза: str) -> str | None:
    """«новая доска» / «верни доску» — команды самой доске, без источника.

    Узнаются НАРОЧНО узко: любое слово переноса («возьми», «нарисуй»,
    «положи»…) выключает разбор, потому что «нарисуй новую схему на доске» —
    это про данные, а не про чистый холст. Ошибиться здесь можно только в
    сторону «не понял» — стереть доску, когда просили рисунок, много дороже.
    """
    слова = [с.lower().strip(".,!?;:«»\"'()") for с in фраза.split()]
    if any(с == "из" or с.startswith(("возьм", "полож", "нарис", "собер",
                                      "покаж", "экспорт")) for с in слова):
        return None
    if not any(с.startswith("доск") for с in слова):
        return None
    if any(с.startswith(("нов", "чист")) for с in слова):
        return "новая"
    if any(с.startswith("верн") for с in слова):
        return "верни"
    return None


def новая_доска() -> int:
    """Текущая доска целиком уходит в архив, холст остаётся чистым.

    Ничего не удаляется: «новая» здесь значит «прежняя отложена файлом».
    Пишем ЧЕРЕЗ сервер доски, а не в файл напрямую: каждая запись двигает
    счётчик версий, и открытое окно перечитывает работу само — человеку не
    нужно ничего нажимать (тот же механизм, каким доска узнаёт о рисунке
    агента, см. cabinet_server.py про ВЕРСИЯ).
    """
    было = Д.хранилище(Д.ПОРТ)
    было.pop("_версия", None)
    элементов = len([e for e in json.loads(было.get("excalidraw") or "[]")
                     if not e.get("isDeleted")])
    АРХИВ_ДОСКИ.mkdir(parents=True, exist_ok=True)
    снимок = АРХИВ_ДОСКИ / f"доска_{datetime.datetime.now():%Y-%m-%d_%H%M%S}.json"
    снимок.write_text(json.dumps(было, ensure_ascii=False))
    for ключ in было:
        if ключ == "excalidraw":
            Д.хранилище(Д.ПОРТ, {"ключ": "excalidraw", "значение": "[]"})
        elif ключ not in ОБСТАНОВКА:
            Д.хранилище(Д.ПОРТ, {"ключ": ключ, "значение": None})
    print(f"✓ прежняя доска отложена в архив: {снимок.name} "
          f"({элементов} элементов, ничего не потеряно)")
    print("  Холст чистый. Открытое окно доски обновится само за пару секунд.")
    print("  Вернуть прежнюю доску: скажите «верни доску».")
    return 0


def верни_доску() -> int:
    """Последний снимок из архива обратно на холст.

    Нынешняя доска перед возвратом тоже уходит в архив: возврат не имеет права
    уметь терять. Из-за этого повторное «верни доску» честно качает между двумя
    последними снимками — это задуманное «передумал обратно», а не дефект.
    """
    снимки = sorted(АРХИВ_ДОСКИ.glob("доска_*.json")) if АРХИВ_ДОСКИ.exists() else []
    if not снимки:
        raise Отказ("архив досок пуст — «новая доска» ещё не произносилась, "
                    "возвращать нечего")
    цель = снимки[-1]
    хочу = json.loads(цель.read_text())
    сейчас = Д.хранилище(Д.ПОРТ)
    сейчас.pop("_версия", None)
    запас = АРХИВ_ДОСКИ / f"доска_{datetime.datetime.now():%Y-%m-%d_%H%M%S}.json"
    запас.write_text(json.dumps(сейчас, ensure_ascii=False))
    for ключ in сейчас:
        if ключ not in хочу:
            Д.хранилище(Д.ПОРТ, {"ключ": ключ, "значение": None})
    for ключ, значение in хочу.items():
        Д.хранилище(Д.ПОРТ, {"ключ": ключ, "значение": значение})
    элементов = len([e for e in json.loads(хочу.get("excalidraw") or "[]")
                     if not e.get("isDeleted")])
    print(f"✓ доска возвращена из снимка {цель.name}: {элементов} элементов")
    print(f"  Прежний холст тоже сохранён ({запас.name}) — возврат ничего не теряет.")
    print("  Открытое окно доски обновится само за пару секунд.")
    return 0


def работа(фраза: str, учись: bool, всё_равно: bool, окно: str = "") -> int:
    спец = особая_доска(фраза)
    if спец == "новая":
        return новая_доска()
    if спец == "верни":
        return верни_доску()

    источники = реестр()
    if not источники:
        raise Отказ(f"реестр источников пуст ({РЕЕСТР}). Добавить: "
                    f"python3 tools/скажи.py --добавить астра --файл <файл>")

    имя, слово_источника = найти_и_слово(фраза, источники)
    if not имя:
        raise Отказ(f"не понял, из какого приложения брать. Знаю: "
                    f"{', '.join(источники)}. Назовите одно из них — "
                    f"угадывать не буду, ошибка тут дороже переспроса. "
                    f"Ещё умею: «новая доска» и «верни доску»")
    остаток = " ".join(с for с in фраза.split() if с != слово_источника)
    # Получатель по умолчанию — окно, из которого сказана фраза: «возьми из
    # астры первые 8» в окне Таблицы кладёт СЮДА. Это не угадывание: контекст
    # назван самим местом, где человек стоит. Явное «на доску» / «в отчёт»
    # сильнее контекста. Без окна (терминал, чат) по-старому — доска.
    кому = найти(остаток, ПОЛУЧАТЕЛИ)
    if not кому and окно:
        кому = найти(окно, ПОЛУЧАТЕЛИ)
        if not кому:
            raise Отказ(f"скажите, куда положить — «на доску», «в таблицу» или "
                        f"«в отчёт»: окно «{окно}» данные не принимает")
    кому = кому or "доска"
    файл = pathlib.Path(источники[имя]["файл"]).expanduser()
    if not файл.exists():
        raise Отказ(f"у источника «{имя}» нет файла {файл} — приложение ни разу "
                    f"не сохраняло работу или было удалено")

    print(f"\n  источник: {имя} · получатель: {кому}")

    try:
        п = П.прочитать(имя)
    except Отказ:
        if not учись:
            raise Отказ(f"у «{имя}» нет паспорта — я не знаю, что означают его данные. "
                        f"Прочитать формат моделью: добавьте --учись")
        print("  паспорта нет — читаю формат моделью, это один раз")
        if П.написать(имя, файл) != 0:
            return 1
        п = П.прочитать(имя)

    if not п.get("подтверждён") and not всё_равно:
        raise Отказ(f"паспорт «{имя}» не подтверждён человеком. Посмотрите, верно ли "
                    f"модель поняла формат:\n    python3 tools/паспорт.py --имя {имя} "
                    f"--достать\n  и подтвердите:\n    python3 tools/паспорт.py --имя "
                    f"{имя} --подтвердить")

    д = обрезать(П.применить(п, json.loads(файл.read_text())), сколько(фраза))
    сколько_всего = len(д.get(СПИСОЧНЫЕ.get(д["форма"], ""), []) or [1])
    if not сколько(фраза) and сколько_всего > 20:
        print(f"  показываю ВСЕ {сколько_всего} пунктов — это выгрузка, а не картина. "
              f"Скажите «первые 9», если нужна картина")
    временный = pathlib.Path(f"/tmp/форма_{имя}.json")
    временный.write_text(json.dumps(д, ensure_ascii=False))
    итог = subprocess.run([sys.executable, str(СЮДА / ПОЛУЧАТЕЛИ[кому]),
                           "--файл", str(временный), "--источник", имя],
                          capture_output=True, text=True)
    print(итог.stdout.strip() or итог.stderr.strip())
    временный.unlink(missing_ok=True)
    return итог.returncode


def selftest() -> int:
    ошибки = []

    for фраза, ждём in (("возьми первые 9", 9), ("топ 8 по потерям", 8),
                        ("нарисуй всё", None), ("возьми из 1с", None)):
        if сколько(фраза) != ждём:
            ошибки.append(f"сколько({фраза}) = {сколько(фраза)}, ждали {ждём}")
    if not ошибки:
        print("  ✓ «первые 9» и «топ 8» понимаются, случайное число — нет")

    д = обрезать({"форма": "список", "заголовок": "х", "подпись": "",
                  "строки": [{"имя": str(i)} for i in range(50)]}, 5)
    if len(д["строки"]) != 5:
        ошибки.append("отбор не режет")
    elif "из 50" not in д["подпись"]:
        ошибки.append("отбор молчит о том, что показана часть — это обман")
    else:
        print("  ✓ отбор режет и ЧЕСТНО подписывает: «первые 5 из 50»")

    ист, слово = найти_и_слово("возьми из таблицы и нарисуй на доске",
                               {"tablica": {"файл": "х", "имя": "Таблица"}})
    остаток = " ".join(с for с in "возьми из таблицы и нарисуй на доске".split()
                       if с != слово)
    if ист != "tablica" or найти(остаток, ПОЛУЧАТЕЛИ) != "доска":
        ошибки.append("«из таблицы на доску»: слово источника не вычеркнуто — "
                      "рисунок уехал бы обратно в таблицу")
    else:
        print("  ✓ «из таблицы → на доску»: источник и получатель не путаются")

    if найти("возьми из астры и положи в таблицу", ПОЛУЧАТЕЛИ) != "таблица":
        ошибки.append("получатель-таблица не находится")
    else:
        print("  ✓ «положи в таблицу»: таблица работает и получателем")

    if найти("собери отчёт", ПОЛУЧАТЕЛИ) != "отчёт":
        ошибки.append("второй получатель не находится по фразе")
    else:
        print("  ✓ получателей два, и оба выбираются словом")

    for слово, ждём in (("астры", "астр"), ("астре", "астр"), ("доске", "доск"),
                        ("Астра,", "астр")):
        if основа(слово) != ждём:
            ошибки.append(f"основа({слово}) = {основа(слово)}, ждали {ждём}")
    if not ошибки:
        print("  ✓ склонения имён приложений узнаются: «из астры» = «астра»")

    if найти("возьми из астры и нарисуй на доске", {"астра": 1, "юрист": 1}) != "астра":
        ошибки.append("источник во фразе не найден")
    elif найти("нарисуй мне что-нибудь красивое", {"астра": 1}) is not None:
        ошибки.append("источник УГАДАН там, где его не называли — это опаснее отказа")
    else:
        print("  ✓ названный источник находится, неназванный не выдумывается")

    if найти("возьми из таблицы", {"tablica": {"файл": "х", "имя": "Таблица"}}) != "tablica":
        ошибки.append("русское имя источника из реестра не находится — slug не выговорить")
    else:
        print("  ✓ «из таблицы» находит источник tablica по человеческому имени")

    if найти("нарисуй на доске", ПОЛУЧАТЕЛИ) != "доска":
        ошибки.append("получатель не найден")
    else:
        print("  ✓ получатель определяется по фразе")

    # Контекст «здесь»: имя окна разрешается в получателя тем же поиском, что
    # и слова фразы. Окно без роли получателя (Сторож) не угадывается.
    for окно, ждём in (("Доска схем", "доска"), ("Таблица", "таблица"),
                       ("Сторож", None)):
        if найти(окно, ПОЛУЧАТЕЛИ) != ждём:
            ошибки.append(f"окно {окно!r} → {найти(окно, ПОЛУЧАТЕЛИ)!r}, ждали {ждём!r}")
    if not any("окно" in о for о in ошибки):
        print("  ✓ окно «Доска схем»/«Таблица» становится получателем, «Сторож» — нет")

    плохие = []
    for фраза, ждём in (("новая доска", "новая"), ("заведи новую доску", "новая"),
                        ("Чистую доску, пожалуйста", "новая"),
                        ("верни доску", "верни"), ("верни старую доску", "верни"),
                        ("возьми из таблицы и нарисуй на доске", None),
                        ("нарисуй новую схему на доске", None),
                        ("возьми из астры первые 8 и положи в таблицу", None)):
        if особая_доска(фраза) != ждём:
            плохие.append(f"особая_доска({фраза!r}) = {особая_доска(фраза)!r}, "
                          f"ждали {ждём!r}")
    if плохие:
        ошибки.extend(плохие)
    else:
        print("  ✓ «новая доска»/«верни доску» узнаются, фразы переноса не задеты")

    print("\n" + ("ИТОГ САМОПРОВЕРКИ: все проверки прошли" if not ошибки
                  else "ОТКАЗ:\n  " + "\n  ".join(ошибки)))
    return 1 if ошибки else 0


def main() -> int:
    р = argparse.ArgumentParser(description="Одна строка: возьми из X, нарисуй на Y")
    р.add_argument("фраза", nargs="?")
    р.add_argument("--учись", action="store_true",
                   help="если паспорта нет — прочитать формат моделью")
    р.add_argument("--всё-равно", dest="всё_равно", action="store_true",
                   help="рисовать по неподтверждённому паспорту")
    р.add_argument("--окно", default="",
                   help="имя окна, из которого сказана фраза; получатель по умолчанию")
    р.add_argument("--реестр", action="store_true")
    р.add_argument("--добавить", metavar="ИМЯ")
    р.add_argument("--файл")
    р.add_argument("--selftest", action="store_true")
    а = р.parse_args()
    if а.selftest:
        return selftest()
    try:
        if а.добавить:
            if not а.файл:
                raise Отказ("нужен --файл: где приложение хранит свою работу")
            д = реестр()
            д[а.добавить.lower()] = {"файл": str(pathlib.Path(а.файл).expanduser())}
            записать_реестр(д)
            print(f"✓ источник «{а.добавить}» зарегистрирован")
            return 0
        if а.реестр:
            д = реестр()
            print(f"\nИсточники ({len(д)}):")
            for имя, з in д.items():
                try:
                    п = П.прочитать(имя)
                    состояние = (f"паспорт: {п['форма']}"
                                 + ("" if п.get("подтверждён") else ", НЕ подтверждён"))
                except Отказ:
                    состояние = "паспорта нет — добавьте --учись при первом вызове"
                print(f"  {имя:14} {состояние}")
            print(f"\nПолучатели: {', '.join(ПОЛУЧАТЕЛИ)}")
            return 0
        if а.фраза:
            return работа(а.фраза, а.учись, а.всё_равно, а.окно)
    except Отказ as о:
        print(f"ОТКАЗ: {о}", file=sys.stderr)
        return 1
    р.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
