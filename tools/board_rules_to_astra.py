#!/usr/bin/env python3
"""Доска схем → правило Астры: нарисованная стрелка становится решением.

ЗАЧЕМ. Обратное направление сильнее прямого. Когда агент рисует данные на доске —
это живой отчёт. Когда человек рисует на доске условие и действие, а агент читает
это как ПРАВИЛО и применяет к данным, — схема перестаёт быть картинкой и становится
способом управлять приложением. Развитие правилами и концептами вместо кода.

Как человек пишет правило: две фигуры и стрелка между ними.

    ┌────────────────────┐        ┌─────────────────────────┐
    │ отток выше 20%     │ ─────► │ предложить скидку 15%   │
    └────────────────────┘        └─────────────────────────┘
       условие (читает машина)       действие (читает человек)

Условие разбирается ДЕТЕРМИНИРОВАННО, по маленькому словарю: у чисел не должно
быть двух версий. Что не разобрано — честно называется, а не угадывается.
Действие машина не толкует: она показывает, к кому его применить, а решает человек.

    python3 tools/board_rules_to_astra.py                 # прочитать и применить
    python3 tools/board_rules_to_astra.py --пример        # нарисовать образец правила
    python3 tools/board_rules_to_astra.py --сухой         # не писать ответ на доску
    python3 tools/board_rules_to_astra.py --selftest

Коды выхода: 0 — прочитано, 1 — отказ с причиной.
"""

import argparse
import json
import pathlib
import re
import sys

СЮДА = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(СЮДА))
from astra_churn_to_board import (  # noqa: E402
    ОЗЕРО, ПОРТ, Отказ, деньги, хранилище, _основа)

МЕТКА_ОТВЕТА = "ответ_"      # чем помечены наши ответы: повтор их заменяет
МЕТКА_ПРИМЕРА = "пример_"

# Словарь метрик: что человек пишет словом → что лежит в витрине Астры.
# Список короткий намеренно: лучше честно не понять, чем угадать неверно.
МЕТРИКИ = {
    "отток": "доля", "churn": "доля",
    "nps": "nps",
    "ушло": "ушло", "ушедших": "ушло",
    "абонентов": "всего", "абоненты": "всего",
}
ОПЕРАТОРЫ = [
    (r"выше|больше|более|>=|>", ">"),
    (r"ниже|меньше|менее|<=|<", "<"),
]
ЕДИНИЦЫ = {"доля": "%", "nps": "", "ушло": " абонентов", "всего": " абонентов"}


def разобрать_условие(текст: str) -> dict | None:
    """«отток выше 20%» → {метрика: доля, оператор: >, значение: 20.0}."""
    т = " ".join(текст.lower().split())
    метрика = next((поле for слово, поле in МЕТРИКИ.items() if слово in т), None)
    if not метрика:
        return None
    оператор = next((зн for образец, зн in ОПЕРАТОРЫ if re.search(образец, т)), None)
    if not оператор:
        return None
    число = re.search(r"(\d+(?:[.,]\d+)?)", т)
    if not число:
        return None
    return {"метрика": метрика, "оператор": оператор,
            "значение": float(число.group(1).replace(",", "."))}


def подпись_фигуры(фигура: dict, элементы: list) -> str:
    """Текст фигуры: либо привязанный, либо лежащий внутри её границ."""
    ид = фигура.get("id")
    for э in элементы:
        if э.get("type") == "text" and э.get("containerId") == ид:
            return (э.get("text") or "").strip()
    x, y = фигура.get("x", 0), фигура.get("y", 0)
    ш, в = фигура.get("width", 0), фигура.get("height", 0)
    внутри = [э for э in элементы
              if э.get("type") == "text" and not э.get("isDeleted")
              and x - 4 <= э.get("x", 0) <= x + ш and y - 4 <= э.get("y", 0) <= y + в]
    return " ".join((э.get("text") or "").strip() for э in внутри).strip()


def найти_правила(элементы: list) -> tuple[list, list]:
    """Правило = стрелка, привязанная с обеих сторон. Ищем только такие."""
    живые = [э for э in элементы if not э.get("isDeleted")]
    по_ид = {э.get("id"): э for э in живые}
    правила, непонятые = [], []
    for стрелка in [э for э in живые if э.get("type") == "arrow"]:
        нач = (стрелка.get("startBinding") or {}).get("elementId")
        кон = (стрелка.get("endBinding") or {}).get("elementId")
        if not (нач and кон and нач in по_ид and кон in по_ид):
            continue
        слева = подпись_фигуры(по_ид[нач], живые)
        справа = подпись_фигуры(по_ид[кон], живые)
        if not (слева and справа):
            continue
        условие = разобрать_условие(слева)
        if условие:
            правила.append({"условие_текст": слева, "действие": справа, **условие})
        else:
            непонятые.append({"слева": слева, "справа": справа})
    return правила, непонятые


def применить(правило: dict, города: list) -> list:
    з, о, м = правило["значение"], правило["оператор"], правило["метрика"]
    подошли = [г for г in города
               if (г[м] > з if о == ">" else г[м] < з)]
    return sorted(подошли, key=lambda г: -г["потеряно_тыс"])


def ответ_на_доску(правила: list, эл: list, порт: int) -> int:
    живые = [э for э in эл if not э.get("isDeleted")
             and not str(э.get("id", "")).startswith(МЕТКА_ОТВЕТА)]
    фигура = next((э for э in живые if э.get("type") == "rectangle"), None)
    текст = next((э for э in живые if э.get("type") == "text"), None)
    if not (фигура and текст):
        raise Отказ("на доске нет образца фигуры и подписи")
    низ = max(э.get("y", 0) + (э.get("height") or 0) for э in живые)
    лев = min(э.get("x", 0) for э in живые)

    новые = []
    y = низ + 200
    шапка = "Ответ агента на правила с доски"
    новые.append(_основа(текст, x=лев, y=y, width=760, height=34, fontSize=24,
                         strokeColor="#1a1a1a", text=шапка, originalText=шапка))
    новые[-1]["id"] = МЕТКА_ОТВЕТА + новые[-1]["id"].split("_", 1)[1]
    y += 50
    for п in правила:
        строки = (f"{п['условие_текст']}  →  {п['действие']}\n"
                  f"подошло городов: {len(п['подошли'])}"
                  + (f" · {', '.join(г['город'] for г in п['подошли'][:6])}"
                     if п["подошли"] else " — ни одного")
                  + (f"\nна кону: {деньги(sum(г['потеряно_тыс'] for г in п['подошли']))}"
                     if п["подошли"] else ""))
        э = _основа(фигура, x=лев, y=y, width=760, height=110,
                    strokeColor="#1971c2", backgroundColor="#d0ebff")
        э["id"] = МЕТКА_ОТВЕТА + э["id"].split("_", 1)[1]
        новые.append(э)
        т = _основа(текст, x=лев + 18, y=y + 16, width=724, height=80, fontSize=16,
                    strokeColor="#1a1a1a", text=строки, originalText=строки)
        т["id"] = МЕТКА_ОТВЕТА + т["id"].split("_", 1)[1]
        новые.append(т)
        y += 140

    прочие = [э for э in эл if not str(э.get("id", "")).startswith(МЕТКА_ОТВЕТА)]
    хранилище(порт, {"ключ": "excalidraw",
                     "значение": json.dumps(прочие + новые, ensure_ascii=False)})
    return len(новые)


def нарисовать_пример(эл: list, порт: int) -> int:
    """Образец правила: чтобы человеку было что переписать своими словами."""
    живые = [э for э in эл if not э.get("isDeleted")]
    фигура = next((э for э in живые if э.get("type") == "rectangle"), None)
    текст = next((э for э in живые if э.get("type") == "text"), None)
    стрелка_обр = next((э for э in живые if э.get("type") == "arrow"), None)
    if not (фигура and текст and стрелка_обр):
        raise Отказ("на доске нет прямоугольника, подписи и стрелки — "
                    "с них берётся форма, чтобы не выдумывать схему")
    низ = max(э.get("y", 0) + (э.get("height") or 0) for э in живые)
    лев = min(э.get("x", 0) for э in живые)
    y = низ + 200

    усл = _основа(фигура, x=лев, y=y, width=300, height=90,
                  strokeColor="#e03131", backgroundColor="#ffc9c9")
    дей = _основа(фигура, x=лев + 460, y=y, width=340, height=90,
                  strokeColor="#2f9e44", backgroundColor="#b2f2bb")
    for э, слова in ((усл, "отток выше 20%"), (дей, "предложить скидку 15%")):
        э["id"] = МЕТКА_ПРИМЕРА + э["id"].split("_", 1)[1]
        т = _основа(текст, x=э["x"] + 20, y=э["y"] + 32, width=э["width"] - 40,
                    height=28, fontSize=18, strokeColor="#1a1a1a",
                    text=слова, originalText=слова)
        т["id"] = МЕТКА_ПРИМЕРА + т["id"].split("_", 1)[1]
        э["_подпись"] = т

    стр = _основа(стрелка_обр, x=лев + 310, y=y + 45, width=140, height=0,
                  strokeColor="#1a1a1a", points=[[0, 0], [140, 0]],
                  startBinding={"elementId": усл["id"], "focus": 0, "gap": 8},
                  endBinding={"elementId": дей["id"], "focus": 0, "gap": 8})
    стр["id"] = МЕТКА_ПРИМЕРА + стр["id"].split("_", 1)[1]
    усл["boundElements"] = [{"id": стр["id"], "type": "arrow"}]
    дей["boundElements"] = [{"id": стр["id"], "type": "arrow"}]

    подпись = "образец правила: перепишите своими словами — агент прочитает"
    п = _основа(текст, x=лев, y=y - 34, width=700, height=22, fontSize=14,
                strokeColor="#868e96", text=подпись, originalText=подпись)
    п["id"] = МЕТКА_ПРИМЕРА + п["id"].split("_", 1)[1]

    новые = [п, усл, усл.pop("_подпись"), дей, дей.pop("_подпись"), стр]
    прочие = [э for э in эл if not str(э.get("id", "")).startswith(МЕТКА_ПРИМЕРА)]
    хранилище(порт, {"ключ": "excalidraw",
                     "значение": json.dumps(прочие + новые, ensure_ascii=False)})
    return len(новые)


def работа(порт: int, озеро: pathlib.Path, сухой: bool, пример: bool) -> int:
    д = хранилище(порт)
    эл = json.loads(д.get("excalidraw") or "[]")

    if пример:
        n = нарисовать_пример(эл, порт)
        print(f"  ✓ образец правила нарисован ({n} элементов)")
        print("  Откройте доску, перепишите условие и действие своими словами,")
        print("  затем запустите без --пример.")
        return 0

    правила, непонятые = найти_правила(эл)
    print(f"\nЧТО АГЕНТ ПРОЧИТАЛ НА ДОСКЕ")
    print(f"  элементов: {len(эл)} · правил (стрелка с двумя концами): {len(правила)}")
    if непонятые:
        print(f"\n  Связи, которые НЕ понял ({len(непонятые)}) — не угадываю:")
        for н in непонятые[:5]:
            print(f"    «{н['слева'][:38]}» → «{н['справа'][:38]}»")
        print("    словарь условий: отток, NPS, ушло, абонентов + выше/ниже + число")
    if not правила:
        print("\n  Правил не нашёл. Нарисовать образец: --пример")
        return 0

    from astra_churn_to_board import взять_данные
    города = взять_данные(озеро, 100)["города"]
    print(f"\n  Применяю к Астре ({len(города)} городов):")
    for п in правила:
        п["подошли"] = применить(п, города)
        деньги_ = sum(г["потеряно_тыс"] for г in п["подошли"])
        print(f"\n    ПРАВИЛО: {п['условие_текст']}  →  {п['действие']}")
        print(f"      разобрано как: {п['метрика']} {п['оператор']} {п['значение']}"
              f"{ЕДИНИЦЫ.get(п['метрика'],'')}")
        if п["подошли"]:
            print(f"      подошло городов: {len(п['подошли'])} · на кону {деньги(деньги_)}")
            for г in п["подошли"][:6]:
                print(f"        {г['город']:14} отток {г['доля']}% · {деньги(г['потеряно_тыс'])}")
        else:
            print("      не подошёл ни один город")

    if сухой:
        print("\n  СУХОЙ ПРОГОН: ответ на доску не писал")
        return 0
    n = ответ_на_доску(правила, эл, порт)
    print(f"\n  ✓ ответ нарисован на доске ({n} элементов). Откройте доску заново.")
    return 0


def selftest() -> int:
    ошибки = []
    for текст, ждём in (
        ("отток выше 20%", {"метрика": "доля", "оператор": ">", "значение": 20.0}),
        ("NPS ниже 40", {"метрика": "nps", "оператор": "<", "значение": 40.0}),
        ("ушло больше 1000 абонентов", {"метрика": "ушло", "оператор": ">", "значение": 1000.0}),
    ):
        и = разобрать_условие(текст)
        if и != ждём:
            ошибки.append(f"«{текст}» разобрано как {и}")
    if not ошибки:
        print("  ✓ условия разбираются по словарю")

    for текст in ("предложить скидку", "отток растёт", "выше 20%", ""):
        if разобрать_условие(текст) is not None:
            ошибки.append(f"«{текст}» не должно было разобраться")
    if not any("не должно" in о for о in ошибки):
        print("  ✓ непонятное честно не разбирается, а не угадывается")

    города = [{"город": "А", "доля": 25.0, "nps": 50, "ушло": 100, "всего": 400, "потеряно_тыс": 900},
              {"город": "Б", "доля": 12.0, "nps": 30, "ушло": 20, "всего": 500, "потеряно_тыс": 100}]
    п = {"метрика": "доля", "оператор": ">", "значение": 20.0}
    if [г["город"] for г in применить(п, города)] != ["А"]:
        ошибки.append("фильтр по доле сработал неверно")
    else:
        print("  ✓ правило применяется к данным детерминированно")

    эл = [
        {"id": "у", "type": "rectangle", "x": 0, "y": 0, "width": 100, "height": 50},
        {"id": "ту", "type": "text", "containerId": "у", "text": "отток выше 20%", "x": 5, "y": 5},
        {"id": "д", "type": "rectangle", "x": 200, "y": 0, "width": 100, "height": 50},
        {"id": "тд", "type": "text", "containerId": "д", "text": "дать скидку", "x": 205, "y": 5},
        {"id": "с", "type": "arrow", "startBinding": {"elementId": "у"},
         "endBinding": {"elementId": "д"}},
        {"id": "с2", "type": "arrow"},
    ]
    пр, неп = найти_правила(эл)
    if len(пр) != 1 or пр[0]["действие"] != "дать скидку":
        ошибки.append(f"правило со стрелкой не найдено: {пр}")
    else:
        print("  ✓ правило читается из стрелки с двумя привязками")
    if неп:
        ошибки.append(f"непривязанная стрелка попала в непонятые: {неп}")
    else:
        print("  ✓ стрелка без привязок правилом не считается")

    if ошибки:
        for о in ошибки:
            print(f"  ✕ {о}")
        print("ИТОГ САМОПРОВЕРКИ: есть отказы")
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


def main() -> int:
    р = argparse.ArgumentParser(add_help=True)
    р.add_argument("--порт", type=int, default=ПОРТ)
    р.add_argument("--озеро", default=str(ОЗЕРО))
    р.add_argument("--сухой", action="store_true")
    р.add_argument("--пример", action="store_true")
    р.add_argument("--selftest", action="store_true")
    а = р.parse_args()
    if а.selftest:
        return selftest()
    try:
        return работа(а.порт, pathlib.Path(а.озеро).expanduser(), а.сухой, а.пример)
    except Отказ as о:
        print(f"\nНе смог: {о}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
