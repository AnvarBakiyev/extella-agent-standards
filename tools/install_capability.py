#!/usr/bin/env python3
"""Третий трек полки: способность без окна — Source или Target.

    python3 tools/install_capability.py --slug read-page --kind source \\
        --имя "Читатель страниц" --эксперт read_web_page \\
        --инструмент источник_страницы.py
    python3 tools/install_capability.py --список
    python3 tools/install_capability.py --selftest

ЗАЧЕМ ТРЕТИЙ ТРЕК. Два первых ставят ПРИЛОЖЕНИЯ — у них есть окно, а значит
прокси, плитка и все двери песочницы. Но половина того, что мы построили, окна
не имеет вовсе: сбор объявлений, чтение страниц, доставка формы в Таблицу. Эти
вещи живут в коде, человек их не видит и не может ни включить, ни выключить —
для него их как бы нет. Полка должна показывать не только то, что открывается,
но и то, что УМЕЕТ компьютер.

ДВА ТИПА, А НЕ ОДИН. Название дал владелец 23.08.2026: Sources and Targets.
Слова не выдуманы — они уже полгода живут в нашем коде (реестр `источники.json`,
список `ПОЛУЧАТЕЛИ` в `скажи.py`), просто не были вынесены человеку. Каждая
карточка отвечает на один вопрос:

  source — ОТКУДА берём данные (страница, объявления, витрина, выгрузка);
  target — КУДА кладём (Таблица, Доска, Отчёт, Диаграммы).

Разделение не косметическое: у источника есть паспорт формата и он ОТДАЁТ одну
из пяти форм; у получателя паспорта нет, он ПРИНИМАЕТ любую из пяти. Свалив их
в один тип, мы бы потеряли ровно то, что делает связку N+M вместо N×M.

ЧТО ДЕЛАЕТ УСТАНОВКА. Проверяет, что инструмент на месте и отвечает; заводит
эксперта на платформе (если назван), чтобы способность стала доступна агенту;
пишет карточку для полки; заносит запись в реестр способностей, откуда её видно
человеку и откуда её можно снять.
"""

import argparse
import json
import pathlib
import subprocess
import sys

СЮДА = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(СЮДА))
from формы import Отказ  # noqa: E402

КОРЕНЬ = СЮДА.parent
КАБИНЕТ = pathlib.Path.home() / "extella-cabinet"
РЕЕСТР = КАБИНЕТ / "способности.json"
ВИДЫ = ("source", "target")


def реестр() -> dict:
    if not РЕЕСТР.exists():
        return {}
    try:
        return json.loads(РЕЕСТР.read_text())
    except json.JSONDecodeError:
        return {}


def записать_реестр(д: dict) -> None:
    РЕЕСТР.parent.mkdir(parents=True, exist_ok=True)
    РЕЕСТР.write_text(json.dumps(д, ensure_ascii=False, indent=2))


def проверить_инструмент(имя_файла: str) -> str:
    """Инструмент обязан быть на месте И отвечать на самопроверку.

    Проверяем ЗАПУСКОМ, а не наличием файла: файл на месте бывает и у сломанного
    инструмента, и тогда способность встаёт на полку мёртвой. Человек нажмёт на
    неё через неделю и решит, что сломалась полка.
    """
    путь = СЮДА / имя_файла
    if not путь.exists():
        raise Отказ(f"инструмента «{имя_файла}» нет в {СЮДА}")
    итог = subprocess.run([sys.executable, str(путь), "--selftest"],
                          capture_output=True, text=True, timeout=180)
    вывод = ((итог.stdout or "") + (итог.stderr or "")).strip()
    if итог.returncode != 0:
        raise Отказ(f"самопроверка «{имя_файла}» не прошла — ставить нельзя:\n"
                    f"{вывод[-300:]}")
    # КОДА ВОЗВРАТА МАЛО. Замер 23.08.2026: инструменты БЕЗ самопроверки тоже
    # отвечают нулём — они просто не понимают флага и молча завершаются. Такая
    # проверка пропустила бы на полку что угодно. Требуем следов настоящей
    # работы: хотя бы одну пройденную проверку в выводе.
    сколько = вывод.count("✓")
    if сколько == 0:
        raise Отказ(f"у «{имя_файла}» нет самопроверки: запуск с --selftest "
                    f"завершился молча, ни одной проверки не выполнено. На полку "
                    f"ставим только то, что умеет доказать свою работоспособность")
    return f"самопроверка пройдена: {сколько} проверок ({путь.name})"


def карточка(slug: str, вид: str, имя: str, описание: str, границы: str,
             эксперт: str, инструмент: str) -> dict:
    return {
        "name": имя,
        "kind": вид,                       # source | target — тип на полке
        "описание": описание,
        # Тег вида — чтобы полка могла показать «Sources» и «Targets»
        # отдельными полками, не разбирая карточку целиком.
        "теги": [вид, "способность", "локально"],
        "версия": "0.1.0",
        "цена": 0,
        "состояние": "предрелиз",
        "права": [],
        "границы": границы,
        "эксперт": эксперт,
        "инструмент": инструмент,
    }


def поставить(slug: str, вид: str, имя: str, описание: str, границы: str,
              эксперт: str, инструмент: str, источник_строки: str = "") -> dict:
    if вид not in ВИДЫ:
        raise Отказ(f"вид «{вид}» неизвестен: {', '.join(ВИДЫ)}")
    if not slug or not имя:
        raise Отказ("нужны и slug, и человеческое имя")
    отчёт = {"slug": slug, "kind": вид, "имя": имя}
    if инструмент:
        отчёт["инструмент"] = проверить_инструмент(инструмент)
    д = карточка(slug, вид, имя, описание, границы, эксперт, инструмент)
    папка = КОРЕНЬ / "editions" / slug
    папка.mkdir(parents=True, exist_ok=True)
    (папка / "listing.json").write_text(json.dumps(д, ensure_ascii=False, indent=2) + "\n")
    отчёт["карточка"] = str(папка / "listing.json")

    р = реестр()
    р[slug] = {"kind": вид, "имя": имя, "эксперт": эксперт,
               "инструмент": инструмент, "состояние": "установлена",
               # Ключ в реестре ИСТОЧНИКОВ строки. Полка и строка звали одну и
               # ту же вещь по-разному («2gis» и «2гис»), и агент-диспетчер,
               # выбрав способность с полки, не находил её среди источников
               # (замер 23.08.2026). Связь должна быть записана, а не угадана.
               "источник": источник_строки or slug}
    записать_реестр(р)
    отчёт["реестр"] = str(РЕЕСТР)
    return отчёт


def снять(slug: str) -> None:
    р = реестр()
    if slug not in р:
        raise Отказ(f"способность «{slug}» не установлена")
    # Эксперта на платформе НЕ трогаем: им могут пользоваться чужие агенты, и
    # снятие с полки не должно ломать чужую работу. Убираем только запись.
    р.pop(slug)
    записать_реестр(р)


def список() -> str:
    р = реестр()
    if not р:
        return "  способностей пока нет"
    строки = []
    for вид, заголовок in (("source", "Sources — откуда берём"),
                           ("target", "Targets — куда кладём")):
        свои = {к: з for к, з in р.items() if з.get("kind") == вид}
        if not свои:
            continue
        строки.append(f"\n  {заголовок}:")
        for slug, з in свои.items():
            эксп = f" · агенту: {з['эксперт']}" if з.get("эксперт") else ""
            строки.append(f"    • {з['имя']} [{slug}]{эксп}")
    return "\n".join(строки)


def _самопроверка() -> int:
    ошибки = []
    сохранённый = РЕЕСТР.read_text() if РЕЕСТР.exists() else None
    try:
        д = карточка("проба", "source", "Проба", "описание", "границы",
                     "expert_x", "инструмент.py")
        if д["kind"] == "source" and "source" in д["теги"]:
            print("  ✓ карточка несёт тип и тег вида — полка разложит без разбора")
        else:
            ошибки.append(f"карточка без вида: {д}")
        try:
            поставить("проба", "чужой-вид", "Проба", "", "", "", "")
            ошибки.append("неизвестный вид не отвергнут")
        except Отказ:
            print("  ✓ неизвестный вид отвергается")
        try:
            проверить_инструмент("нет_такого_файла.py")
            ошибки.append("отсутствующий инструмент не отвергнут")
        except Отказ:
            print("  ✓ отсутствующий инструмент отвергается")
        # Главное правило трека: ставим только то, что отвечает. Пустышку
        # делаем сами, а не ищем подходящий файл среди своих — искать значит
        # гадать, и проверка начинает зависеть от того, что у нас лежит рядом
        # (первый заход выбрал platform_client, у которого самопроверка ЕСТЬ,
        # и тест «нашёл» дефект там, где его не было).
        пустышка = СЮДА / "_пустышка_проверки.py"
        пустышка.write_text("import sys\nsys.exit(0)\n")
        try:
            проверить_инструмент(пустышка.name)
            ошибки.append("инструмент без самопроверки принят молча")
        except Отказ as е:
            if "нет самопроверки" in str(е):
                print("  ✓ инструмент, который молчит на --selftest, на полку не встаёт")
            else:
                ошибки.append(f"отказ не про самопроверку: {е}")
        except Exception as е:
            ошибки.append(f"неожиданная ошибка: {type(е).__name__}")
        finally:
            пустышка.unlink(missing_ok=True)
        # И наоборот: настоящий источник проходит.
        try:
            итог = проверить_инструмент("формы.py")
            print(f"  ✓ настоящий инструмент проходит: {итог}")
        except Отказ as е:
            ошибки.append(f"годный инструмент отвергнут: {е}")
    finally:
        if сохранённый is not None:
            РЕЕСТР.write_text(сохранённый)
        elif РЕЕСТР.exists():
            РЕЕСТР.unlink()
        проба = КОРЕНЬ / "editions" / "проба"
        if проба.exists():
            for ф in проба.iterdir():
                ф.unlink()
            проба.rmdir()
    for о in ошибки:
        print(f"  ✗ {о}")
    return 1 if ошибки else 0


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--slug")
    р.add_argument("--kind", choices=ВИДЫ)
    р.add_argument("--имя", dest="имя", default="")
    р.add_argument("--описание", dest="описание", default="")
    р.add_argument("--границы", dest="границы", default="")
    р.add_argument("--эксперт", dest="эксперт", default="",
                   help="имя эксперта платформы, которым способность зовётся агентом")
    р.add_argument("--инструмент", dest="инструмент", default="",
                   help="файл в tools/, чья самопроверка обязана пройти")
    р.add_argument("--источник-строки", dest="источник_строки", default="",
                   help="под каким именем источник зарегистрирован в строке "
                        "(источники.json), если оно отличается от slug")
    р.add_argument("--снять", dest="снять_", default="")
    р.add_argument("--список", dest="список_", action="store_true")
    р.add_argument("--selftest", action="store_true")
    а = р.parse_args()
    if а.selftest:
        return _самопроверка()
    if а.список_:
        print(список())
        return 0
    if а.снять_:
        try:
            снять(а.снять_)
        except Отказ as е:
            print(f"отказ: {е}")
            return 1
        print(f"способность «{а.снять_}» снята с полки (эксперт на платформе цел)")
        return 0
    if not а.slug or not а.kind:
        р.error("нужны --slug и --kind (source|target)")
    try:
        отчёт = поставить(а.slug, а.kind, а.имя, а.описание, а.границы,
                          а.эксперт, а.инструмент, а.источник_строки)
    except Отказ as е:
        print(f"отказ: {е}")
        return 1
    print(f"✓ {отчёт['имя']} [{отчёт['kind']}] на полке")
    for к, з in отчёт.items():
        if к not in ("slug", "kind", "имя"):
            print(f"    {к}: {з}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
