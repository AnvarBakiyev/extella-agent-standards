#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Гейт правила по дизайну: копия в гиде не должна разъехаться с источником.

Правило пишет дизайн-владелец, а работает оно в промпте генерации — значит абзац обязан лежать прямо
в `AGENT_BUILD_GUIDE.md`, иначе Codex его не увидит. Копия и источник — два места, а два места
неизбежно разъезжаются: сегодня это наш самый частый класс аварий (описания экспертов разошлись
с аккаунтом, документ архитектуры за час разошёлся с шаблоном паспорта).

Поэтому проверяем два свойства:

1. **Абзац на месте и полон.** Все токены палитры и все запреты присутствуют. Это работает
   везде, даже если репозитория витрины рядом нет — а его нет у коллеги и у любого, кому
   правило отдали одним файлом.
2. **Источника для сверки слово в слово больше нет.** Он жил в `extella-toolbar-src`; репозиторий
   закрыт (метка `toolbar-final-2026-08`), `DESIGN_CODE.md` с 04.09.2026 лежит в корне этого репозитория, но это
   канон окон OS без абзаца-цитаты — сверять с ним нечего. Канонической копией для авторов стал
   сам абзац в гиде (и его зеркало в скилле). Гейт говорит «не сверялись», а не делает вид.

Как пользоваться:
  python3 check_design_rule.py --selftest
  python3 check_design_rule.py                  # проверить гид рядом с собой

Коды выхода: 0 — совпадает, 1 — расхождение.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GUIDE = os.path.join(ROOT, "AGENT_BUILD_GUIDE.md")
# Скилл несёт ТУ ЖЕ цитату: его читают чаты, которые строят интерфейсы, и копия
# в нём обязана совпадать с гидом слово в слово. Две копии одного правила — наш
# самый частый класс аварий, и здесь он закрывается по построению.
SKILL = os.path.join(ROOT, "skills", "extella-ui", "SKILL.md")
# ИСТОЧНИКА ДЛЯ СВЕРКИ НЕТ. `extella-toolbar-src` закрыт (метка toolbar-final-2026-08);
# DESIGN_CODE.md с 04.09.2026 лежит в корне этого репозитория, но абзаца-цитаты в нём нет — это канон
# окон OS, а не выжимка для генерации. Канонической копией стал сам абзац в гиде.
# Путь к удалённому репозиторию убран: гейт честно говорит «не сверялись».
# Замер 04.09.2026: из 28 токенов REQUIRED дословно в DESIGN_CODE.md есть 16 —
# сверка по токенам потребует сначала согласовать формулировки, см. описание PR.
SOURCE = None

# Обязательное содержимое абзаца. Не косметика: без токена цвет уедет мимо палитры,
# без запрета вернутся эмодзи и капс, без контракта темы окно заведёт свой тумблер.
REQUIRED = [
    # ШРИФТЫ. Nunito пришёл 31.07.2026 вместе с дизайн-кодом и отменил Source Sans 3.
    # Гейт полгода требовал отменённый шрифт: правило поменяли, проверку не тронули,
    # и никто не увидел, потому что общий прогон спрашивал у неё только селфтест.
    # Замер 19.08.2026 — отсюда и правило «канон проверяется по-настоящему».
    "Nunito", "Source Serif 4", "JetBrains Mono",
    # ПАЛИТРА. Без токена цвет уедет мимо и продукт провалит гейт бренда.
    "#FAF9F5", "#FFFFFF", "#F5F3EC", "#0A0A0A", "#C57E33", "#2F6B66", "#D7E0DC",
    "#141414", "#181818", "#F5F3EE", "#D4944A",
    # ШКАЛЫ. Кегль, отступы и радиусы — то, по чему интерфейс опознаётся как наш.
    "11 / 13 / 15 / 20 / 26", "кратны четырём", "мелкие контролы 8",
    # БЕЗ ЭТОГО браузер наберёт кнопки Arial — самая заметная поломка вида.
    "font-family:inherit",
    # ЗАПРЕТЫ. Без них возвращаются эмодзи, капс и градиенты.
    "без градиентов", "без эмодзи", "без капса",
    # Добавлено Эллой 29.07 после разбора живых экранов: жирный гротеск в заголовке —
    # то, что рисует любая генерация, и именно от него интерфейс выглядит сгенерированным.
    "серифом Source Serif 4", "без отрицательной разрядки", "гротеск в заголовке запрещён",
    # ОДНО ГЛАВНОЕ ДЕЙСТВИЕ — про понятность экрана, а не про цвет.
    "главное действие на экране ровно одно",
    # КОНТРАКТ С ХОСТОМ: своя тема и свой язык в окне запрещены.
    "etb_theme", "etb_init", "data-lm",
]


def _quote(text):
    """Абзац-цитата: строки, начинающиеся с '>'. В обоих файлах он оформлен одинаково."""
    lines = [l.strip()[1:].strip() for l in text.splitlines() if l.strip().startswith(">")]
    return re.sub(r"\s+", " ", " ".join(lines)).strip()


МЕТКА_АБЗАЦА = "Интерфейс — часть Extella"


def _design_quote(text):
    """Только абзац дизайн-кода, а не все цитаты файла подряд.

    Первая редакция склеивала ВСЕ строки, начинающиеся с «>», и сравнивала их
    целиком. В гиде есть другие цитаты — например про эксперта, — поэтому
    сравнение падало на чужом тексте и показывало расхождение там, где его нет.
    Проверка, которая краснеет не на том, обесценивает себя так же, как та,
    которая молчит.
    """
    блок = []
    собираем = False
    for строка in text.splitlines():
        это_цитата = строка.strip().startswith(">")
        if это_цитата:
            содержимое = строка.strip()[1:].strip()
            if МЕТКА_АБЗАЦА in содержимое:
                собираем, блок = True, [содержимое]
                continue
            if собираем:
                блок.append(содержимое)
        elif собираем and not строка.strip():
            continue
        elif собираем:
            break
    return re.sub(r"\s+", " ", " ".join(блок)).strip()


def check_skill(guide_text, skill_text):
    """Цитата в скилле совпадает с цитатой в гиде. Иначе скилл учит отменённому."""
    в_гиде, в_скилле = _design_quote(guide_text), _design_quote(skill_text)
    if not в_скилле:
        return ["в скилле extella-ui нет абзаца дизайн-кода: чат, строящий интерфейс, "
                "останется без правила"]
    if в_гиде != в_скилле:
        # Показываем ПЕРВОЕ расхождение: список различий целиком никто не читает.
        for i, (а, б) in enumerate(zip(в_гиде, в_скилле)):
            if а != б:
                срез = slice(max(0, i - 60), i + 60)
                return [f"копия дизайн-кода в скилле разошлась с гидом:\n"
                        f"      гид:    …{в_гиде[срез]}…\n"
                        f"      скилл:  …{в_скилле[срез]}…"]
        короче = "скилле" if len(в_скилле) < len(в_гиде) else "гиде"
        return [f"копия дизайн-кода в скилле разошлась с гидом: в {короче} текст обрывается"]
    return []


def check(guide_text, source_text=None):
    """Возвращает (список проблем, сверялись ли с источником)."""
    problems = []
    quote = _quote(guide_text)
    if not quote:
        return (["в гиде нет абзаца-цитаты с правилом по дизайну"], False)
    for token in REQUIRED:
        if token not in quote:
            problems.append("в абзаце нет обязательного «%s»" % token)
    if source_text is None:
        return (problems, False)
    src = _quote(source_text)
    if not src:
        problems.append("в источнике не нашёлся абзац-цитата — сверять не с чем")
    elif src != quote:
        problems.append("копия в гиде разошлась с источником "
                        "(SOURCE) — перенеси текст заново")
    return (problems, bool(src))


def selftest():
    print("Самопроверка правила по дизайну:")
    ok = True
    good = "> Используй только эти токены: " + ", ".join(REQUIRED)
    cases = [
        ("полный абзац проходит", good, None, 0),
        ("нет абзаца вовсе — поймано", "просто текст без цитаты", None, 1),
        ("пропал токен палитры — поймано", good.replace("#C57E33", ""), None, 1),
        ("пропал запрет — поймано", good.replace("без эмодзи", ""), None, 1),
        ("совпадение с источником проходит", good, good, 0),
        ("расхождение с источником — поймано", good, good + " и ещё кое-что", 1),
    ]
    for label, guide, source, expect_problems in cases:
        problems, _ = check(guide, source)
        got = (len(problems) > 0) == (expect_problems > 0)
        print(("PASS: " if got else "FAIL: ") + label)
        ok = ok and got

    # Отсутствие витрины рядом не должно выглядеть как успешная сверка.
    _, compared = check(good, None)
    if not compared:
        print("PASS: без репозитория витрины честно говорим, что не сверяли")
    else:
        ok = False
        print("FAIL: сверка без источника выдана за успешную")

    print("ИТОГ САМОПРОВЕРКИ: " + ("все проверки прошли" if ok else "есть провалы"))
    return 0 if ok else 1


def _selftest_skill():
    """Расхождение копии в скилле обязано ловиться, совпадение — проходить."""
    гид = "> Интерфейс — часть Extella.\n> Шрифт Nunito.\n"
    свои = [
        ("совпадает", гид, False),
        ("разошлось", "> Интерфейс — часть Extella.\n> Шрифт Source Sans 3.\n", True),
        ("оборвано", "> Интерфейс — часть Extella.\n", True),
        ("нет цитаты", "просто текст без цитаты", True),
        # Чужая цитата рядом не должна считаться частью абзаца дизайна.
        ("чужая цитата рядом",
         "> Эксперт — это не кнопка.\n\n> Интерфейс — часть Extella.\n> Шрифт Nunito.\n",
         False),
    ]
    for имя, текст, ждём_проблему in свои:
        есть = bool(check_skill(гид, текст))
        if есть != ждём_проблему:
            print("FAIL: копия в скилле «%s» оценена как %s" % (имя, есть))
            return False
    return True


def main(argv):
    if "--selftest" in argv:
        код = selftest()
        if not _selftest_skill():
            return 1
        return код
    if not os.path.exists(GUIDE):
        print("ОШИБКА: не найден %s" % GUIDE)
        return 1
    with open(GUIDE, encoding="utf-8") as fh:
        guide = fh.read()
    source = None
    if SOURCE and os.path.exists(SOURCE):
        with open(SOURCE, encoding="utf-8") as fh:
            source = fh.read()
    problems, compared = check(guide, source)
    if os.path.exists(SKILL):
        with open(SKILL, encoding="utf-8") as fh:
            problems += check_skill(guide, fh.read())
        со_скиллом = True
    else:
        со_скиллом = False
    for p in problems:
        print("ОШИБКА: " + p)
    if problems:
        return 1
    print("правило по дизайну: абзац полон, "
          + ("совпадает с источником" if compared else "источника рядом нет — не сверял")
          + (", копия в скилле совпадает" if со_скиллом else ", скилла рядом нет"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
