#!/usr/bin/env python3
"""Гейт издания: паспорт заполнен, данные на месте, тема не трогает чужие окна.

Издание собирает человек, который не программист, и ошибки у него будут тихие:
чувствительные данные уедут в облако, тема покрасит чужие приложения, прав
запрошено больше нужного. Всё это выглядит как работающий продукт — поэтому
проверяет машина, а не глаз.

Использование:
    python3 tools/check_edition.py путь/к/изданию
    python3 tools/check_edition.py --selftest
"""

import pathlib
import re
import sys

ОПАСНЫЕ_ПРАВА = {"api.full", "kv.write", "rules.write", "concept.write"}


def отказ(беды: list) -> int:
    print("ИЗДАНИЕ НЕ ГОТОВО:")
    for b in беды:
        print("  ✗", b)
    return 1


def разобрать_yaml(текст: str) -> dict:
    """Мини-разбор: только то, что нужно гейту. Без внешних зависимостей."""
    d = {}
    стек = [(-1, d)]
    строки = текст.split("\n")
    i = 0
    while i < len(строки):
        строка = строки[i]
        i += 1
        if not строка.strip() or строка.lstrip().startswith("#"):
            continue
        отступ = len(строка) - len(строка.lstrip())
        # Комментарий в конце строки — обычное дело в паспорте, который правит человек.
        # Без его отсечения значение «устройство   # пояснение» не совпадёт ни с чем.
        без_кавычек = строка.split('"')
        for н in range(0, len(без_кавычек), 2):
            if "#" in без_кавычек[н]:
                без_кавычек[н] = без_кавычек[н].split("#")[0]
                без_кавычек = без_кавычек[:н + 1]
                break
        строка_ = '"'.join(без_кавычек).strip()
        if not строка_:
            continue
        while len(стек) > 1 and отступ <= стек[-1][0]:
            стек.pop()
        узел = стек[-1][1]

        if строка_.startswith("- "):
            узел.setdefault("_список", []).append(строка_[2:].strip().strip('"'))
            continue

        if ":" not in строка_:
            continue
        ключ, _, знач = строка_.partition(":")
        ключ, знач = ключ.strip(), знач.strip().strip('"')

        # Блочный текст (> или |): собираем все более отступленные строки в одну.
        if знач in (">", "|"):
            куски = []
            while i < len(строки):
                следующая = строки[i]
                if not следующая.strip():
                    i += 1
                    continue
                if len(следующая) - len(следующая.lstrip()) <= отступ:
                    break
                куски.append(следующая.strip())
                i += 1
            узел[ключ] = " ".join(куски)
            continue

        if знач == "":
            новый = {}
            узел[ключ] = новый
            стек.append((отступ, новый))
        else:
            узел[ключ] = знач
    return d


def значение(узел, *путь, умолчание=None):
    for к in путь:
        if not isinstance(узел, dict):
            return умолчание
        узел = узел.get(к)
    return узел if узел is not None else умолчание


def проверить(папка: pathlib.Path) -> int:
    беды = []

    паспорт = папка / "edition.yaml"
    if not паспорт.exists():
        return отказ([f"нет паспорта {паспорт.name} — с него начинается издание"])
    d = разобрать_yaml(паспорт.read_text())

    # 1. Издание должно быть придумано, а не названо.
    для_кого = значение(d, "для_кого") or ""
    почему = значение(d, "почему_бросит") or ""
    if isinstance(для_кого, dict) or len(str(для_кого).strip()) < 20:
        беды.append("поле «для_кого» пустое или в одну строку — издание не придумано")
    if isinstance(почему, dict) or len(str(почему).strip()) < 20:
        беды.append("поле «почему_бросит» пустое — непонятно, ради чего человек это поставит")

    контекст = str(значение(d, "издание", "контекст") or "")
    if re.search(r"^(женщин|мужчин|девушк|парн)", контекст.strip(), re.I):
        беды.append(f"контекст «{контекст}» задан полом, а не жизненной ситуацией — "
                    "продаёт содержание (беременность, спорт, уход), а не ярлык")

    # 2. Данные. Самое дорогое правило: чувствительное живёт только на машине.
    чувств = str(значение(d, "данные", "чувствительные", умолчание="false")).lower() == "true"
    где = str(значение(d, "данные", "где_живут") or "")
    if чувств and где != "устройство":
        беды.append("чувствительные данные объявлены, а «где_живут» не «устройство» — "
                    "здоровье, цикл и документы клиента не покидают его машину")
    if где not in ("устройство", "облако"):
        беды.append(f"«где_живут» = «{где}»: ожидается «устройство» или «облако»")

    # 3. Права: минимум, и опасное — только с написанной причиной.
    права = set(значение(d, "права_приложения", "_список", умолчание=[]))
    if not права and not str(значение(d, "не_ходит_к_платформе") or "").lower().startswith("да"):
        # Пустые права почти всегда означают «продукт откроется и молча умрёт».
        # Но бывает честное исключение: страница, которая никуда не ходит — ни к
        # агенту, ни к эксперту (например, доска, живущая целиком на машине). Такому
        # продукту права не нужны, и требовать их — значит просить лишнего доступа.
        # Исключение объявляется словом в паспорте, а не молчанием.
        беды.append("права приложения не объявлены — продукт откроется целым и не "
                    "заработает: каждый вызов агента вернёт 403. Если продукт и правда "
                    "никуда не ходит, объяви это: «не_ходит_к_платформе: да»")
    лишние = права & ОПАСНЫЕ_ПРАВА
    if лишние and "причина_прав" not in d:
        беды.append(f"запрошены сильные права {sorted(лишние)} без поля «причина_прав» — "
                    "покупатель видит их до покупки")

    # 4. Тема не обязательна, но если объявлена — не трогает чужие окна.
    #
    # ПОПРАВКА 14.08.2026: раньше гейт ТРЕБОВАЛ файл темы у каждого издания. Требование
    # неверное: расширения подмешиваются в страницы, которые ОС открывает, а в саму
    # оболочку ОС — нет (H19-секста, проверено установкой темы, которая ничего не
    # изменила). Требуя тему, гейт заставлял класть в издание декоративный файл,
    # который заведомо ничего не делает, — а зелёный гейт при этом обещал обратное.
    # Теперь тема проверяется, только если издание её объявило.
    объявлена = значение(d, "состав", "тема")
    тема = папка / str(объявлена or "theme.js")
    if объявлена and not тема.exists():
        беды.append(f"в паспорте объявлена тема {тема.name}, а файла нет")
    elif тема.exists():
        код = тема.read_text()
        if "/app-page/" not in код:
            беды.append("тема не проверяет, в каком окне оказалась: расширение "
                        "подмешивается во ВСЕ окна ОС и покрасит чужие приложения")
        if re.search(r"localStorage\s*\.\s*getItem\s*\(\s*[\"']etk", код):
            беды.append("тема читает токен аккаунта — теме он не нужен ни при каких условиях")
        if re.search(r"fetch\s*\(\s*[\"']https?://(?!os\.extella\.ai)", код):
            беды.append("тема ходит на посторонний адрес — тема красит, а не передаёт данные")

    if беды:
        return отказ(беды)
    print(f"Издание «{значение(d, 'издание', 'имя')}» готово к сборке:")
    print(f"  контекст: {контекст} · данные: {где} · права: {sorted(права) or 'нет'}")
    return 0


def _selftest() -> int:
    import tempfile
    провалы = []

    ХОРОШЕЕ = """издание:
  имя: "Издание для беременных"
  контекст: "беременность, первый ребёнок"
для_кого: >
  Женщина в ожидании ребёнка, у которой анализы, приёмы и сроки лежат в трёх разных местах.
почему_бросит: >
  Всё в одном месте и ничего не уезжает с её компьютера, в отличие от облачных приложений.
состав:
  тема: theme.js
данные:
  где_живут: устройство
  чувствительные: true
права_приложения:
  - expert.run
"""
    ТЕМА = "if (location.pathname.indexOf('/app-page/') !== 0) {}"

    def случай(имя, паспорт, тема, ждём_провал):
        with tempfile.TemporaryDirectory() as d:
            p = pathlib.Path(d)
            (p / "edition.yaml").write_text(паспорт)
            if тема is not None:          # None = издание без темы, файла нет вовсе
                (p / "theme.js").write_text(тема)
            код = проверить(p)
            ок = (код != 0) if ждём_провал else (код == 0)
            if not ок:
                провалы.append(имя)
                print(f"  ✗ {имя}")
            else:
                print(f"  ✓ {имя}")

    print("Самопроверка check_edition:")
    случай("правильное издание проходит", ХОРОШЕЕ, ТЕМА, False)
    случай("чувствительные данные в облаке ловятся",
           ХОРОШЕЕ.replace("где_живут: устройство", "где_живут: облако"), ТЕМА, True)
    случай("пустые права ловятся",
           ХОРОШЕЕ.replace("  - expert.run", ""), ТЕМА, True)
    случай("контекст по полу ловится",
           ХОРОШЕЕ.replace('"беременность, первый ребёнок"', '"женщины"'), ТЕМА, True)
    случай("тема без проверки окна ловится", ХОРОШЕЕ, "// красим всё подряд", True)
    случай("тема, читающая токен, ловится", ХОРОШЕЕ,
           ТЕМА + "\nlocalStorage.getItem('etk_v3')", True)
    # Тема необязательна: облик ОС расширением не меняется, требовать её — значит
    # требовать заведомо мёртвый файл. Но объявленная и отсутствующая — ошибка.
    случай("продукт, который никуда не ходит, проходит без прав",
           ХОРОШЕЕ.replace("права_приложения:\n  - expert.run",
                           "не_ходит_к_платформе: да\nправа_приложения:"), ТЕМА, False)
    случай("издание без темы проходит", ХОРОШЕЕ.replace("  тема: theme.js\n", ""), None, False)
    случай("объявленная, но отсутствующая тема ловится", ХОРОШЕЕ, None, True)
    случай("пустое «для_кого» ловится",
           ХОРОШЕЕ.replace("Женщина в ожидании ребёнка, у которой анализы, приёмы и сроки лежат в трёх разных местах.", "-"),
           ТЕМА, True)

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    sys.exit(проверить(pathlib.Path(sys.argv[1])))
