#!/usr/bin/env python3
"""Перевод не отстал от оригинала. Иначе английский тихо станет неправдой.

ЗАЧЕМ. Русский текст правят каждый день, английский — когда вспомнят. Через месяц
получаются два разных руководства под одним именем, и человек, читающий
английское, следует правилам, которых больше нет. Проверка ловит это машиной, а
не памятью автора.

КАК. Рядом с переводом хранятся ДВА отпечатка: русского текста, с которого он
сделан, и самого перевода. Изменился русский — перевод объявляется отставшим;
изменился английский без пересборки отпечатков — объявляется ушедшим вперёд.

Второй отпечаток появился 24.09.2026 после живой поломки (H111): правку про то, откуда
берётся ключ, я внёс только в английское тело, русское осталось с прежним
неверным обещанием. Отпечаток русского при этом совпадал, гейт был зелёным, и в
собранную страницу ушли два разных руководства под одним именем — русское лгало,
английское говорило правду. Проверка свежести в одну сторону такое не видит. Английский ОБЯЗАТЕЛЕН — двуязычие RU+EN сразу (канон:
«Русский и английский сразу», H95). Раздел без английского — нарушение; начатый
перевод обязан быть полным и не отставать от русского.

ПРИЁМКА 25.09.2026: прогон по content.json ложных тревог не дал; настоящих
находок 2 — английский текст ушёл вперёд русского и эксперт был переименован
в переводе (dev_connect_agent вместо dev_connect_assistant).

    python3 tools/check_translation.py store_app/content.json
    python3 tools/check_translation.py --selftest
    python3 tools/check_translation.py --отпечатки store_app/content.json  # проставить
"""

import hashlib
import json
import pathlib
import re
import sys

ПОЛЯ = (("заголовок", "заголовок_en"), ("тело", "тело_en"))


def отпечаток(текст: str) -> str:
    """Короткий отпечаток русского текста. Пробелы по краям не считаются: правка
    отступов не должна объявлять перевод отставшим."""
    return hashlib.sha256(текст.strip().encode("utf-8")).hexdigest()[:16]


ЯКОРЯ = re.compile(
    r"\b[A-Za-z_][A-Za-z0-9_-]*\.(?:md|json|py|mjs|sh|html)\b"   # имена файлов
    r"|github\.com/[A-Za-z0-9._/-]+"                              # адреса репозиториев
    r"|https?://[A-Za-z0-9._~:/?#@!$&'()*+,;=%-]+"                 # ссылки
    # Имена экспертов и модулей. Замер 25.09.2026: русский текст звал
    # dev_connect_assistant, английский — dev_connect_agent, эксперта с таким
    # именем не существует. Отпечаток совпадал, имена файлов совпадали, и
    # читатель по-английски получал «Expert not found».
    r"|\b(?:dev|toolkit|wz|lc|bf)_[a-z][a-z0-9_]*"
)


def якоря(текст: str) -> set:
    """Имена файлов, адреса и ссылки. Они обязаны совпадать в обоих языках:
    перевод может звучать иначе, но вести должен туда же.

    Замер 20.08.2026: русский пункт велел читать README.md, а его перевод —
    START_HERE.md, устаревший файл. Отпечаток при этом совпадал, потому что
    русский текст никто не менял: проверка свежести не видит неверный перевод.
    """
    return set(m.group(0).rstrip('.,;:') for m in ЯКОРЯ.finditer(текст or ""))


def проверить(данные: dict) -> list:
    ошибки = []
    разделы = данные.get("разделы") or []
    переведённые = [r for r in разделы if str(r.get("тело_en") or "").strip()]
    if разделы and not переведённые:
        return ["английского перевода нет вовсе — двуязычие обязательно: русский и "
                "английский сразу (канон «Русский и английский сразу», H95). "
                "Перевести все разделы и проставить отпечатки: --отпечатки"]
    if not переведённые:
        return []                      # разделов нет — переводить нечего

    if len(переведённые) != len(разделы):
        нет = [r.get("номер", "?") for r in разделы if not str(r.get("тело_en") or "").strip()]
        ошибки.append("перевод начат, но не у всех разделов: нет у " + ", ".join(нет))

    for r in разделы:
        номер = r.get("номер", "?")
        for русское, английское in ПОЛЯ:
            есть_en = str(r.get(английское) or "").strip()
            if not есть_en:
                continue
            слепки = r.get("перевод_от") if isinstance(r.get("перевод_от"), dict) else {}

            ожидалось = отпечаток(str(r.get(русское) or ""))
            записано = str(слепки.get(русское, ""))
            if not записано:
                ошибки.append(f"раздел {номер}: у перевода поля «{русское}» нет отпечатка оригинала")
            elif записано != ожидалось:
                ошибки.append(f"раздел {номер}: перевод поля «{русское}» отстал от русского текста")

            # Отпечаток самого перевода. Без него английский можно править в
            # одиночку, и языки тихо расходятся в содержании.
            ждём_en = отпечаток(есть_en)
            есть_слепок = str(слепки.get(английское, ""))
            if not есть_слепок:
                ошибки.append(f"раздел {номер}: у поля «{английское}» нет отпечатка самого "
                              f"перевода — английский можно править в одиночку")
            elif есть_слепок != ждём_en:
                ошибки.append(f"раздел {номер}: английский текст поля «{английское}» ушёл "
                              f"вперёд русского — правка внесена только в перевод")
            ру, ан = якоря(str(r.get(русское) or "")), якоря(есть_en)
            пропало, лишнее = sorted(ру - ан), sorted(ан - ру)
            if пропало or лишнее:
                части = []
                if пропало:
                    части.append("в переводе нет: " + ", ".join(пропало))
                if лишнее:
                    части.append("в переводе лишнее: " + ", ".join(лишнее))
                ошибки.append(f"раздел {номер}: перевод поля «{русское}» ведёт не туда — "
                              + "; ".join(части))

    шапка = данные.get("шапка") or {}
    if any(k.endswith("_en") for k in шапка):
        для_шапки = [k for k in шапка if not k.endswith("_en") and not k.endswith("_от")]
        нет = [k for k in для_шапки if not str(шапка.get(k + "_en") or "").strip()]
        if нет:
            ошибки.append("в шапке нет перевода полей: " + ", ".join(нет))
    return ошибки


def проставить(путь: pathlib.Path) -> int:
    """Записать отпечатки для тех переводов, что уже есть. Ставится после
    перевода раздела, а не заранее: отпечаток без перевода ничего не охраняет."""
    данные = json.loads(путь.read_text(encoding="utf-8"))
    сделано = 0
    for r in данные.get("разделы") or []:
        для = {}
        for русское, английское in ПОЛЯ:
            перевод = str(r.get(английское) or "").strip()
            if перевод:
                для[русское] = отпечаток(str(r.get(русское) or ""))
                для[английское] = отпечаток(перевод)
        if для:
            r["перевод_от"] = для
            сделано += 1
    путь.write_text(json.dumps(данные, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"отпечатки проставлены разделам: {сделано}")
    return 0


def _selftest() -> int:
    ошибки = []

    # Двуязычие обязательно: раздел без английского — нарушение.
    if any("двуязычие обязательно" in о for о in
           проверить({"разделы": [{"номер": "01", "тело": "русский"}]})):
        print("  ✓ отсутствие английского объявлено нарушением")
    else:
        ошибки.append("отсутствие английского не объявлено нарушением")

    # Начатый перевод обязан быть полным.
    частичный = {"разделы": [
        {"номер": "01", "тело": "а", "тело_en": "a",
         "перевод_от": {"тело": отпечаток("а"), "тело_en": отпечаток("a")}},
        {"номер": "02", "тело": "б"},
    ]}
    if any("не у всех" in о for о in проверить(частичный)):
        print("  ✓ неполный перевод пойман")
    else:
        ошибки.append("неполный перевод не пойман")

    # Отставший перевод пойман: русский поменяли, отпечаток остался старым.
    отставший = {"разделы": [
        {"номер": "01", "тело": "новый русский", "тело_en": "english",
         "перевод_от": {"тело": отпечаток("старый русский"),
                        "тело_en": отпечаток("english")}},
    ]}
    if any("отстал" in о for о in проверить(отставший)):
        print("  ✓ отставший перевод пойман")
    else:
        ошибки.append("отставший перевод не пойман")

    # Свежий перевод проходит.
    свежий = {"разделы": [
        {"номер": "01", "тело": "текст", "тело_en": "text",
         "перевод_от": {"тело": отпечаток("текст"), "тело_en": отпечаток("text")}},
    ]}
    if проверить(свежий):
        ошибки.append("свежий перевод объявлен отставшим")
    else:
        print("  ✓ свежий перевод проходит")

    # Правка отступов не считается изменением смысла.
    if отпечаток("  текст  ") != отпечаток("текст"):
        ошибки.append("отпечаток зависит от пробелов по краям")
    else:
        print("  ✓ правка отступов не объявляет перевод отставшим")

    # Имя эксперта, переведённое «по смыслу», поймано: такого эксперта нет.
    переименовал = {"разделы": [
        {"номер": "01", "тело": "зови dev_connect_assistant",
         "тело_en": "call dev_connect_agent",
         "перевод_от": {"тело": отпечаток("зови dev_connect_assistant"),
                        "тело_en": отпечаток("call dev_connect_agent")}},
    ]}
    if any("ведёт не туда" in о for о in проверить(переименовал)):
        print("  ✓ переименованный в переводе эксперт пойман")
    else:
        ошибки.append("переименованный в переводе эксперт не пойман")

    # Перевод, ведущий в другой файл, пойман — даже когда отпечаток свеж.
    увёл = {"разделы": [
        {"номер": "01", "тело": "читай README.md", "тело_en": "read START_HERE.md",
         "перевод_от": {"тело": отпечаток("читай README.md"),
                        "тело_en": отпечаток("read START_HERE.md")}},
    ]}
    if any("ведёт не туда" in о for о in проверить(увёл)):
        print("  ✓ перевод, уводящий в другой файл, пойман")
    else:
        ошибки.append("перевод в другой файл не пойман")

    # Живая поломка 24.09.2026: правка внесена только в английский. Русский не
    # менялся, его отпечаток совпадал, и прежний гейт был зелёным.
    ушёл_вперёд = {"разделы": [
        {"номер": "01", "тело": "прежний русский",
         "тело_en": "the corrected english",
         "перевод_от": {"тело": отпечаток("прежний русский"),
                        "тело_en": отпечаток("the stale english")}},
    ]}
    if any("ушёл" in о for о in проверить(ушёл_вперёд)):
        print("  ✓ английский, ушедший вперёд русского, пойман")
    else:
        ошибки.append("английский, ушедший вперёд русского, не пойман")

    # Перевод без своего отпечатка объявляется незащищённым.
    без_слепка = {"разделы": [
        {"номер": "01", "тело": "текст", "тело_en": "text",
         "перевод_от": {"тело": отпечаток("текст")}},
    ]}
    if any("в одиночку" in о for о in проверить(без_слепка)):
        print("  ✓ перевод без своего отпечатка объявлен незащищённым")
    else:
        ошибки.append("перевод без своего отпечатка не объявлен незащищённым")

    if ошибки:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(ошибки))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


def main() -> int:
    аргументы = sys.argv[1:]
    if "--selftest" in аргументы:
        return _selftest()
    if "--отпечатки" in аргументы:
        цели = [a for a in аргументы if not a.startswith("--")]
        return проставить(pathlib.Path(цели[0]))
    цели = [pathlib.Path(a) for a in аргументы if not a.startswith("--")]
    if not цели:
        print(__doc__)
        return 2
    плохо = 0
    for путь in цели:
        ошибки = проверить(json.loads(путь.read_text(encoding="utf-8")))
        if ошибки:
            плохо = 1
            print(f"{путь}: нарушений {len(ошибки)}")
            for о in ошибки:
                print("  ·", о)
        else:
            print(f"{путь}: перевод в согласии с оригиналом")
    return плохо


if __name__ == "__main__":
    sys.exit(main())
