#!/usr/bin/env python3
"""Гейт состава издания: что поставится человеку и можно ли это снять.

Издание ставит на машину человека чужой код: наши приложения, скиллы ассистента,
репозитории, иногда модели на гигабайты. Ошибки здесь тихие и дорогие:

* плавающая ветка вместо тега — приедет что угодно, что в неё запушили;
* правка конфига ассистента без копии — сломали чужие настройки;
* секрет в архиве — уехал всем покупателям;
* поставили то, что нечем снять — человек живёт с этим навсегда;
* состав, который нельзя показать до покупки, — сюрприз вместо удобства.

    python3 tools/check_compose.py editions/fde
    python3 tools/check_compose.py --selftest
"""

import pathlib
import re
import sys

ПЛАВАЮЩИЕ = {"main", "master", "HEAD", "latest", "dev"}


def отказ(беды):
    print("СОСТАВ ИЗДАНИЯ НЕ ГОТОВ:")
    for b in беды:
        print("  ✗", b)
    return 1


def значение(узел, *путь, умолчание=None):
    for к in путь:
        if not isinstance(узел, dict):
            return умолчание
        узел = узел.get(к)
    return узел if узел is not None else умолчание


def проверить(папка: pathlib.Path) -> int:
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    import check_edition

    файл = папка / "compose.yaml"
    if not файл.exists():
        print("состава нет — издание из одного приложения, проверять нечего")
        return 0
    d = check_edition.разобрать_yaml(файл.read_text())
    беды = []

    # 1. Человек должен прочитать состав ДО покупки.
    словами = значение(d, "что_поставится_словами", умолчание="")
    if isinstance(словами, dict) or len(str(словами).strip()) < 30:
        беды.append("нет поля «что_поставится_словами» — покупатель узнаёт состав "
                    "постфактум, а это сюрприз, а не удобство")

    сырой = файл.read_text()

    # 2. Репозитории — только по тегу. Проверяем сырой текст: разбор списков
    #    объектов нам не нужен, а пропустить ветку нельзя.
    for м in re.finditer(r"^\s*-?\s*тег:\s*[\"']?([^\"'\n#]+)", сырой, re.M):
        тег = м.group(1).strip()
        if тег in ПЛАВАЮЩИЕ:
            беды.append(f"репозиторий берётся по ветке «{тег}» — из ветки приедет что "
                        f"угодно, что в неё запушили. Только тег релиза")
    # Строка списка начинается с дефиса: «  - откуда: …». Без учёта дефиса
    # проверка не находила ни одного репозитория и молча пропускала отсутствие тега.
    if re.search(r"^\s*-?\s*откуда:\s*[\"']?[\w.-]+/[\w.-]+", сырой, re.M) \
            and not re.search(r"^\s*-?\s*тег:", сырой, re.M):
        беды.append("репозиторий указан без тега — версия не зафиксирована")

    # 3. Правка чужого конфига — только с копией и без перезаписи.
    if re.search(r"^\s*mcp:", сырой, re.M) and "mcp: []" not in сырой:
        правило = " ".join(re.findall(r"правило:.*?(?=\n\s*\w+:|\Z)", сырой, re.S))
        if "не перезапис" not in правило.replace("ы", "").replace("ь", "") \
                and "дополняется" not in правило:
            беды.append("есть подключения MCP, но не сказано, что конфиг ассистента "
                        "дополняется, а не перезаписывается — чужие настройки сломаются")
        if "копи" not in правило:
            беды.append("правка конфига ассистента без сохранения прежнего файла копией")

    # 4. Секреты не едут в архиве.
    if re.search(r"(токен|token|api[_-]?key|секрет)\s*:\s*[\"']?[A-Za-z0-9_\-]{16,}", сырой):
        беды.append("в составе похоже на секрет — архив уезжает покупателю целиком; "
                    "ключи спрашиваются при первом запуске")

    # 5. Обещания, которые человек прочитает.
    минут = значение(d, "обещания", "время_установки_минут")
    try:
        минут = int(str(минут))
    except (TypeError, ValueError):
        минут = None
    if минут is None:
        беды.append("не объявлено «время_установки_минут» — установка без обещания "
                    "срока читается как зависание")
    elif минут > 15:
        беды.append(f"обещано {минут} минут установки — режь состав, а не терпи: "
                    f"дольше пятнадцати минут установку бросают")
    if str(значение(d, "обещания", "снимается_полностью", умолчание="")).lower() != "да":
        беды.append("не обещано «снимается_полностью: да» — ставить то, что нечем "
                    "снять, человеку нельзя (у нас так было с расширением)")

    # 6. Модели не ставятся молча.
    if re.search(r"^\s*размер_гб:", сырой, re.M) and "спросить_отдельно: да" not in сырой:
        беды.append("модель в составе без «спросить_отдельно: да» — гигабайты не "
                    "качают без явного согласия")

    if беды:
        return отказ(беды)
    print(f"Состав «{значение(d, 'издание', 'имя')}» готов:")
    print(f"  роль: {значение(d, 'издание', 'роль')}")
    print(f"  обещано установки: {минут} мин · снимается полностью: да")
    return 0


def _selftest() -> int:
    import tempfile
    провалы = []

    ХОРОШИЙ = """издание:
  имя: "Издание для внедренца"
  роль: "тот, кто приносит ИИ в компанию"
что_поставится_словами: >
  Гид, мост к ассистенту, подключение к платформе и шаблон приложения.
репозитории:
  - откуда: "AnvarBakiyev/extella-agent-standards"
    тег: "v0.1.0"
mcp:
  - имя: "extella"
    правило: >
      конфиг дополняется, а не перезаписывается; прежний файл сохраняется копией
обещания:
  время_установки_минут: 5
  данные_наружу: нет
  снимается_полностью: да
"""

    def случай(имя, текст, ждём_провал):
        with tempfile.TemporaryDirectory() as d:
            p = pathlib.Path(d)
            (p / "compose.yaml").write_text(текст)
            код = проверить(p)
            ок = (код != 0) if ждём_провал else (код == 0)
            print(("  ✓ " if ок else "  ✗ ") + имя)
            if not ок:
                провалы.append(имя)

    print("Самопроверка check_compose:")
    случай("правильный состав проходит", ХОРОШИЙ, False)
    случай("плавающая ветка ловится", ХОРОШИЙ.replace('тег: "v0.1.0"', 'тег: "main"'), True)
    случай("репозиторий без тега ловится",
           ХОРОШИЙ.replace('    тег: "v0.1.0"\n', ""), True)
    случай("правка конфига без копии ловится",
           ХОРОШИЙ.replace("; прежний файл сохраняется копией", ""), True)
    случай("секрет в составе ловится",
           ХОРОШИЙ.replace('  время_установки_минут: 5',
                           '  время_установки_минут: 5\n  token: "abcdefgh12345678ijkl"'), True)
    случай("долгая установка ловится",
           ХОРОШИЙ.replace("время_установки_минут: 5", "время_установки_минут: 40"), True)
    случай("нет обещания снятия — ловится",
           ХОРОШИЙ.replace("снимается_полностью: да", "снимается_полностью: нет"), True)
    случай("модель без согласия ловится",
           ХОРОШИЙ + "модели:\n  - имя: \"m\"\n    размер_гб: 4\n", True)

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    sys.exit(проверить(pathlib.Path(sys.argv[1])))
