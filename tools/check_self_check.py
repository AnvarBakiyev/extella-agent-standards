def main(аргументы: list) -> int:
    if "--selftest" in аргументы:
        return selftest()
    пути = [pathlib.Path(а) for а in аргументы if not а.startswith("-")]
    if not пути:
        print("укажи корень продукта")
        return 2
    всего = 0
    for корень in пути:
        if not корень.is_dir():
            print(f"нет папки {корень}")
            return 2
        беды = проверить(корень)
        всего += len(беды)
        print(f"\n{корень}: " + ("самопроверка есть и честна" if not беды
                                 else f"замечаний {len(беды)}"))
        for б in беды:
            print(f"  · {б}")
    return 1 if всего else 0


