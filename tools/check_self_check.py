#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Самопроверка продукта: есть ли она, работает ли и УМЕЕТ ЛИ ПАДАТЬ.

ЗАЧЕМ. Продукт проверяет человек, и это самое дорогое звено: у покупателя мы не
стоим за плечом, а своими руками проверять каждый продукт после каждой правки
некому. Значит проверять должен сам продукт — одной командой, которая отвечает
«готов» или «не готов и вот что именно».

Замеры, из которых выросло правило:
* Рекрутёр, 30.07.2026: интерфейс звал 45 методов, существовало 26. Проверка была
  зелёной, потому что список методов автор писал РУКАМИ. Отсутствующий метод не
  падает — он даёт пустой экран без слова об ошибке;
* Рекрутёр, 02.08.2026: 19 кнопок не работали при зелёных гейтах;
* окна ОС, 15–16.08.2026: отчёт «окно ✓ программа ✓ служба ✓» был правдой про
  каждое звено и ложью про целое.

ЧТО ПРОВЕРЯЕТСЯ ЗДЕСЬ. Не качество продукта, а качество его самопроверки:

  1. точка входа объявлена и запускается;
  2. на целом продукте отвечает успехом;
  3. **на испорченном отвечает провалом** — гейт сам портит копию продукта;
  4. отчёт написан словами, а не одним кодом выхода;
  5. список проверяемого не зашит в код руками.

Пункт 3 — главный. Самопроверка, которая не может провалиться, хуже отсутствия
самопроверки: она даёт ложную уверенность и её ставят в приёмку.

    python3 check_self_check.py путь/к/продукту
    python3 check_self_check.py --selftest

Коды выхода: 0 — самопроверка есть и честна, 1 — нет или бесполезна, 2 — не прочитан.
"""
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

# Где искать объявление самопроверки. Порядок — от явного к неявному.
ИСТОЧНИКИ_ОБЪЯВЛЕНИЯ = ("MANIFEST.yaml", "manifest.yaml", "package.json", "README.md")
КЛЮЧИ = ("самопроверка", "self_check", "selfcheck", "selftest")

# Признаки того, что список проверяемого зашит руками. Замер: именно так и была
# написана зелёная проверка на 26 методов при 45 в интерфейсе.
РУЧНОЙ_СПИСОК = re.compile(
    r"(МЕТОДЫ|METHODS|EXPECTED|ОЖИДАЕМЫЕ)\s*[:=]\s*[\(\[\{]", re.IGNORECASE)
# Признаки того, что список берётся из интерфейса — так и надо.
ИЗ_ИНТЕРФЕЙСА = re.compile(
    r"(read_text|readFileSync|open\s*\(|findall|finditer|querySelector)", re.IGNORECASE)

ПРЕДЕЛ_СЕКУНД = 180


def найти_точку_входа(корень: pathlib.Path) -> tuple[list[str], str]:
    """Команда самопроверки и то, откуда она взялась."""
    for имя in ИСТОЧНИКИ_ОБЪЯВЛЕНИЯ:
        файл = корень / имя
        if not файл.is_file():
            continue
        текст = файл.read_text(encoding="utf-8", errors="replace")
        for строка in текст.split("\n"):
            # Комментарии — не объявление. Замер 20.08.2026: строка
            # «# Запускается БЕЗ PYTHONPATH: самопроверка…» была принята за команду,
            # и гейт пытался запустить файл с именем «самопроверка,».
            if строка.lstrip().startswith("#"):
                continue
            низ = строка.lower()
            if any(к in низ for к in КЛЮЧИ) and ("python" in низ or "node" in низ or "--" in низ):
                команда = строка.split(":", 1)[-1].strip().strip("\"'`- ")
                if команда:
                    return команда.split(), имя
    # Соглашение по умолчанию: app/main.py --selftest. Оно уже живёт в продуктах.
    for путь in (корень / "app" / "main.py", корень / "main.py"):
        if путь.is_file():
            return [sys.executable, str(путь), "--selftest"], f"соглашение ({путь.name})"
    return [], ""


def прогнать(команда: list[str], корень: pathlib.Path) -> tuple[int, str]:
    try:
        итог = subprocess.run(команда, cwd=корень, capture_output=True, text=True,
                              timeout=ПРЕДЕЛ_СЕКУНД)
    except subprocess.TimeoutExpired:
        return 124, "самопроверка не уложилась в три минуты"
    except OSError as отказ:
        return 127, f"самопроверку не удалось запустить: {отказ}"
    return итог.returncode, ((итог.stdout or "") + (итог.stderr or "")).strip()


def имена_из_интерфейса(корень: pathlib.Path) -> set:
    """Что интерфейс реально зовёт. Портить надо именно это.

    Иначе гейт убирает метод, которым никто не пользуется, и обвиняет честную
    самопроверку в том, что она промолчала. Замер 19.08.2026 на Рекрутёре:
    первая редакция убрала forget_binding, которого в разметке нет вовсе.
    """
    имена: set = set()
    for путь in list(корень.rglob("*.html")) + list(корень.rglob("*.js")):
        if "__pycache__" in str(путь) or "node_modules" in str(путь):
            continue
        текст = путь.read_text(encoding="utf-8", errors="replace")
        for шаблон in (r"api\s*\(\s*['\"`]([\w.]+)", r"pywebview\.api\.([\w]+)",
                       r"вызов\s*\(\s*['\"`]([\w.]+)"):
            имена |= set(re.findall(шаблон, текст))
    return {и.split(".")[-1] for и in имена}


def адреса_из_интерфейса(корень: pathlib.Path) -> set:
    """Адреса вида /api/…, которые зовёт интерфейс.

    Продукт может звать сервер не по имени метода, а по адресу. Тогда честная
    порча — убрать АДРЕС, а не любую функцию: замер 20.08.2026 на коннекторах
    Composio — гейт убрал метод, которого интерфейс не зовёт, и обвинил
    исправную самопроверку в молчании.
    """
    адреса: set = set()
    for путь in list(корень.rglob("*.html")) + list(корень.rglob("*.js")):
        if "__pycache__" in str(путь) or "node_modules" in str(путь):
            continue
        текст = путь.read_text(encoding="utf-8", errors="replace")
        адреса |= set(re.findall(r"['\"`](/api/[a-zA-Z0-9_/-]+)", текст))
    return адреса


def сломать(копия: pathlib.Path) -> str | None:
    """Испортить одну вещь так, как ломается в жизни: пропавший метод.

    Не случайный символ и не синтаксис: синтаксическую ошибку заметит и запуск.
    Пропавший метод — это именно тот отказ, который даёт пустой экран и который
    самопроверка обязана поймать.

    Убираем метод, который ЗОВЁТ ИНТЕРФЕЙС. Если разметка не нашлась — берём
    любой, но тогда вывод гейта слабее, и он об этом говорит.
    """
    нужные = имена_из_интерфейса(копия)

    # Сначала пробуем убрать АДРЕС, который зовёт интерфейс: для продуктов,
    # общающихся с сервером по путям, это и есть пропавшая способность.
    адреса = адреса_из_интерфейса(копия)
    кандидаты = []
    for путь in sorted(копия.rglob("*.py")):
        if "test" in путь.name or "__pycache__" in str(путь):
            continue
        текст = путь.read_text(encoding="utf-8", errors="replace")
        общие = sorted(а for а in адреса if f'"{а}"' in текст)
        if общие:
            кандидаты.append((len(общие), путь, текст, общие))
    if кандидаты:
        # Цель выбираем по файлу, где адресов больше всего — это маршрутизатор.
        _, главный, _, общие = max(кандидаты, key=lambda к: к[0])
        цель = общие[len(общие) // 2]
        # Убираем адрес ВО ВСЕХ файлах, где он встречается. У продукта может быть
        # вторая копия сервера (замер 20.08.2026 на коннекторах: копия лежит в
        # os_product/runtime), и порча одной копии ничего не доказывает: пропавшая
        # способность пропадает везде, а не в одном файле.
        где = []
        for _, путь, текст, свои in кандидаты:
            if цель in свои:
                путь.write_text(текст.replace(f'"{цель}"', f'"{цель}_УБРАН"'),
                                encoding="utf-8")
                где.append(str(путь.relative_to(копия)))
        сколько = f" (копий: {len(где)})" if len(где) > 1 else ""
        return (f"{главный.relative_to(копия)}:{цель} "
                f"(адрес, который зовёт интерфейс){сколько}")

    for путь in sorted(копия.rglob("*.py")):
        if "test" in путь.name or "__pycache__" in str(путь):
            continue
        текст = путь.read_text(encoding="utf-8", errors="replace")
        м = list(re.finditer(r"^(\s*)def ([a-zA-Zа-яА-Я_][\w]*)\(", текст, re.M))
        подходящие = [x for x in м if not x.group(2).startswith("_")
                      and x.group(2) not in ("main", "selftest", "самопроверка")]
        если_из_интерфейса = [x for x in подходящие if x.group(2) in нужные]
        цели = если_из_интерфейса or ([] if нужные else подходящие)
        if not цели:
            continue
        цель = цели[len(цели) // 2]
        новое = текст[:цель.start(2)] + цель.group(2) + "_УБРАН" + текст[цель.end(2):]
        путь.write_text(новое, encoding="utf-8")
        метка = "зовётся интерфейсом" if если_из_интерфейса else "интерфейс не найден"
        return f"{путь.relative_to(копия)}:{цель.group(2)} ({метка})"
    return None


def проверить(корень: pathlib.Path, факты: dict | None = None) -> list[str]:
    беды: list[str] = []
    факты = факты if факты is not None else {}
    команда, откуда = найти_точку_входа(корень)
    # Путь машины автора наружу не уходит: в магазине его увидит покупатель, а
    # домашний каталог — это имя человека. Оставляем команду относительной.
    факты["команда"] = " ".join(
        а.replace(str(корень.resolve()) + "/", "").replace(str(корень) + "/", "")
         .replace(sys.executable, "python3")
        for а in команда) if команда else ""
    факты["откуда"] = откуда
    if not команда:
        return ["самопроверки нет вовсе: объяви её в MANIFEST.yaml или положи "
                "app/main.py --selftest. Без неё продукт проверяет только человек"]

    код, вывод = прогнать(команда, корень)
    факты["код"] = код
    факты["отчёт"] = " ".join(вывод.split())[:400]
    if код != 0:
        беды.append(f"самопроверка ({откуда}) на целом продукте отвечает провалом: "
                    f"код {код} · {' '.join(вывод.split())[:200]}")
        return беды

    if len(вывод.strip()) < 40:
        беды.append("самопроверка молчит: отчёт короче сорока знаков. Человеку нужен "
                    "не код выхода, а слова — что работает и что нет")

    # ГЛАВНОЕ: портим копию и требуем красноты.
    with tempfile.TemporaryDirectory() as врем:
        копия = pathlib.Path(врем) / корень.name
        shutil.copytree(корень, копия, symlinks=True,
                        ignore=shutil.ignore_patterns("__pycache__", ".git", ".venv",
                                                      "node_modules", "*.pyc"))
        что = сломать(копия)
        факты["мутация"] = что
        if что is None:
            беды.append("нечего испортить: в продукте не нашлось ни одного метода — "
                        "проверить честность самопроверки нечем")
        else:
            # Точку входа ИЩЕМ В КОПИИ, а не переписываем пути в команде.
            # Переписывание ломалось молча: на macOS /var — ссылка на /private/var,
            # приставка не совпадала, аргумент оставался прежним, и гейт запускал
            # ЦЕЛЫЙ продукт вместо испорченного. Ответ был «успех», и гейт делал
            # вывод «самопроверка честна» — ровно та ложь, которую он ищет.
            команда_копии, _ = найти_точку_входа(копия)
            код2, вывод2 = прогнать(команда_копии, копия)
            факты["покраснела"] = код2 != 0
            факты["негативный_контроль"] = True
            if код2 == 0:
                беды.append(
                    f"самопроверка НЕ УМЕЕТ ПАДАТЬ: убран метод {что}, а она всё равно "
                    f"отвечает успехом. Такая проверка даёт ложную уверенность — "
                    f"замер 30.07.2026: интерфейс звал 45 методов, было 26, "
                    f"проверка была зелёной")

    # Список проверяемого не должен быть переписан руками.
    ручные = []
    for путь in sorted(корень.rglob("*.py")):
        if "__pycache__" in str(путь):
            continue
        текст = путь.read_text(encoding="utf-8", errors="replace")
        if "selftest" not in текст and "самопроверка" not in текст:
            continue
        if РУЧНОЙ_СПИСОК.search(текст) and not ИЗ_ИНТЕРФЕЙСА.search(текст):
            ручные.append(str(путь.relative_to(корень)))
    if ручные:
        беды.append(f"список проверяемого зашит руками ({', '.join(ручные[:3])}): "
                    f"он разойдётся с интерфейсом и проверка станет зелёной впустую. "
                    f"Вычитывай список из интерфейса")
    return беды


