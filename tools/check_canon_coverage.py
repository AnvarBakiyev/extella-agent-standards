#!/usr/bin/env python3
"""Сколько правил канона охраняет машина, а сколько держится на памяти.

ЗАЧЕМ. Замер 22.09.2026: в DEPLOY_REQUIREMENTS.md 101 правило, и только 19 из
них упоминаются хоть в одном гейте. Остальные — памятка: их соблюдают, только
если прочли и запомнили. Чат Агента 1С сформулировал цену точно: «памятки
забываются в первый же спешный выпуск» — у него голос интерфейса, форма кода и
состав поставки стерегутся тестами именно поэтому.

Этот гейт превращает «канон жив или мёртв» в число и не даёт ему падать.

ЧТО СЧИТАЕТСЯ ОХРАНОЙ. Правило охраняется, если его номер (H12, H99…) упомянут в
исполняемой проверке: tools/*.py или templates/**/check*.py. Документы и
комментарии в markdown охраной не считаются — это ровно та памятка, от которой
уходим.

ХРАПОВИК. Доля охраняемых правил записывается в tools/canon_coverage.json.
Гейт падает, если доля стала МЕНЬШЕ записанной: покрытие может только расти.
Новое правило без проверки не запрещено, но оно опускает долю — и это видно
сразу, а не через месяц.

Дополнительно отчёт называет правила-обходы дефектов платформы без ссылки на
пункт письма Тимуру: такие правила переживают починку платформы и становятся
вредными (H96 пролежал неверным месяц).

    python3 tools/check_canon_coverage.py              # отчёт + храповик
    python3 tools/check_canon_coverage.py --обновить   # записать новый уровень
    python3 tools/check_canon_coverage.py --selftest

Коды выхода: 0 — покрытие не упало, 1 — упало, 2 — нечего проверять.

ПРИЁМКА 25.09.2026: прогон по своду зелёный, ложных тревог нет; падение доли
проверено искусственным понижением — ловится.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
КАНОН = КОРЕНЬ / "DEPLOY_REQUIREMENTS.md"
УРОВЕНЬ = КОРЕНЬ / "tools" / "canon_coverage.json"

ПРАВИЛО = re.compile(r"^### (H\d+)\.(.*?)(?=^### H\d+\.|\Z)", re.M | re.S)
# Признаки того, что правило компенсирует дефект платформы.
ОБХОД = re.compile(r"дефект платформы|платформ[аы]\s+(молча|игнорир|не умеет|не даёт)|обход",
                   re.I)
# Ссылка на пункт письма платформе: «§45», «К_ТИМУРУ».
ССЫЛКА_НА_ПИСЬМО = re.compile(r"§\s?\d+|К_ТИМУРУ", re.I)


def правила(текст: str) -> dict[str, str]:
    return {m.group(1): m.group(2) for m in ПРАВИЛО.finditer(текст)}


def проверки(корень: pathlib.Path) -> str:
    файлы = list((корень / "tools").glob("*.py"))
    файлы += list((корень / "templates").rglob("check*.py"))
    сам = pathlib.Path(__file__).resolve()
    return "\n".join(ф.read_text(encoding="utf-8", errors="replace")
                     for ф in файлы if ф.resolve() != сам)


def замер(канон: str, код: str) -> dict:
    все = правила(канон)
    охраняемые = sorted((h for h in все if re.search(rf"\b{h}\b", код)),
                        key=lambda x: int(x[1:]))
    обходы_без_ссылки = sorted((h for h, тело in все.items()
                                if ОБХОД.search(тело) and not ССЫЛКА_НА_ПИСЬМО.search(тело)),
                               key=lambda x: int(x[1:]))
    доля = round(len(охраняемые) / len(все), 4) if все else 0.0
    return {"всего": len(все), "охраняемых": len(охраняемые), "доля": доля,
            "охраняемые": охраняемые, "обходы_без_ссылки": обходы_без_ссылки}


def проверить(обновить: bool = False) -> int:
    if not КАНОН.exists():
        print(f"нет канона: {КАНОН}")
        return 2
    итог = замер(КАНОН.read_text(encoding="utf-8"), проверки(КОРЕНЬ))
    if not итог["всего"]:
        print("в каноне не найдено ни одного правила — проверять нечего")
        return 2

    print(f"Правил в каноне: {итог['всего']}")
    print(f"Охраняет машина: {итог['охраняемых']} ({итог['доля']:.1%})")
    print(f"Держится на памяти: {итог['всего'] - итог['охраняемых']}")
    print("Охраняемые: " + " ".join(итог["охраняемые"]))
    if итог["обходы_без_ссылки"]:
        print(f"\nОбходы дефектов платформы без ссылки на письмо ({len(итог['обходы_без_ссылки'])}) — "
              "починят платформу, правило останется и станет вредным:")
        print("  " + " ".join(итог["обходы_без_ссылки"]))

    прежний = None
    if УРОВЕНЬ.exists():
        try:
            прежний = json.loads(УРОВЕНЬ.read_text(encoding="utf-8")).get("доля")
        except Exception:                                   # noqa: BLE001
            прежний = None

    if обновить or прежний is None:
        УРОВЕНЬ.write_text(json.dumps({"доля": итог["доля"], "охраняемых": итог["охраняемых"],
                                       "всего": итог["всего"]}, ensure_ascii=False, indent=2) + "\n",
                           encoding="utf-8")
        print(f"\nУровень записан: {итог['доля']:.1%}")
        return 0

    if итог["доля"] + 1e-9 < прежний:
        print(f"\nНЕ УСПЕХ: покрытие упало с {прежний:.1%} до {итог['доля']:.1%}. "
              "Добавлено правило без проверки — дайте ему гейт или тест, "
              "либо осознанно опустите планку флагом --обновить.")
        return 1
    print(f"\nИТОГ: покрытие не упало ({прежний:.1%} → {итог['доля']:.1%})")
    return 0


def _selftest() -> int:
    провалы = []

    def проба(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    канон = ("### H1. Первое\nтекст\n"
             "### H2. Второе\nобход: дефект платформы\n"
             "### H3. Третье\nобход, дефект платформы, см. §45\n")
    print("Самопроверка check_canon_coverage:")
    з = замер(канон, "проверка ссылается на H1 и H3")
    проба("находит все правила", з["всего"] == 3)
    проба("охрана по номеру в коде", з["охраняемые"] == ["H1", "H3"])
    проба("доля считается", abs(з["доля"] - 2 / 3) < 1e-3)
    проба("H12 не засчитывается за H1 (граница слова)",
          замер("### H1. а\n### H12. б\n", "только H12")["охраняемые"] == ["H12"])
    проба("обход без ссылки на письмо ловится", з["обходы_без_ссылки"] == ["H2"])
    проба("обход со ссылкой на §45 не ловится", "H3" not in з["обходы_без_ссылки"])
    проба("пустой код — ноль охраны", замер(канон, "")["охраняемых"] == 0)

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы — " + "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    sys.exit(проверить(обновить="--обновить" in sys.argv))
