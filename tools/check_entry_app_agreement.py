#!/usr/bin/env python3
"""Вход для агента и приложение для человека не расходятся (H112).

ЗАЧЕМ. Один и тот же порядок работы описан дважды и для двух читателей:
`AGENT_START.md` читает чат-агент, приложение «Разработка на Extella» читает
человек. Расходятся такие пары молча и всегда в одну сторону — правят то, что
под рукой. Цена известна по разбору 25.09.2026: внешние чаты остановили
оплаченную работу клиента на фактах, которые в одном месте были, а в другом нет.

ЧТО ПРОВЕРЯЕТСЯ. Раздел приложения с ролью «ловушки» объявляет список правил,
которые он покрывает (`правила_входа`). Каждое правило, названное во входе
в разделе про ловушки, обязано быть в этом списке. Обратное не требуется:
приложение вправе рассказывать больше.

Дополнительно: промпт для внешнего агента и приложение обязаны вести в один и
тот же вход и одинаково говорить про публичную справку. А раздел, который
пересказывает вход, обязан дать сырой адрес входа: пересказ устаревает раньше
источника, и читатель должен уходить к источнику одним шагом (просьба хранителя
канона 25.09.2026 — чем меньше копий, тем меньше работы этой проверке).

    python3 tools/check_entry_app_agreement.py
    python3 tools/check_entry_app_agreement.py --selftest

Коды выхода: 0 — согласны, 1 — разошлись.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ВХОД = КОРЕНЬ / "AGENT_START.md"
ПРОМПТ = КОРЕНЬ / "PROMPT_FOR_EXTERNAL_AGENT.md"
СОДЕРЖИМОЕ = КОРЕНЬ / "store_app" / "content.json"

ЗАГОЛОВОК_ЛОВУШЕК = re.compile(r"^##+\s*.*ловуш", re.IGNORECASE | re.MULTILINE)


def ловушки_входа(текст: str) -> set[str]:
    """Номера правил, названные в разделе входа про ловушки.

    Читается только этот раздел: маршрутная таблица называет правила по другому
    поводу, и требовать их все от приложения значило бы требовать пересказ свода.
    """
    м = ЗАГОЛОВОК_ЛОВУШЕК.search(текст)
    if not м:
        return set()
    хвост = текст[м.end():]
    след = re.search(r"^##\s", хвост, re.MULTILINE)
    кусок = хвост[: след.start()] if след else хвост
    return set(re.findall(r"\bH(\d{1,3})\b", кусок))


СЫРОЙ_ВХОД = ("raw.githubusercontent.com/AnvarBakiyev/extella-agent-standards/"
              "main/AGENT_START.md")


def не_ведёт_во_вход(текст: str) -> bool:
    """Текст пересказывает вход, но не даёт сырого адреса входа."""
    return bool(текст.strip()) and СЫРОЙ_ВХОД not in текст


def беды() -> list[str]:
    плохо: list[str] = []

    if not ВХОД.exists():
        return ["нет AGENT_START.md — вход для агента пропал"]
    вход = ВХОД.read_text(encoding="utf-8")

    if not СОДЕРЖИМОЕ.exists():
        return ["нет store_app/content.json"]
    данные = json.loads(СОДЕРЖИМОЕ.read_text(encoding="utf-8"))
    разделы = данные.get("разделы") or []

    ловушки = [р for р in разделы if р.get("роль") == "ловушки"]
    if not ловушки:
        плохо.append("в приложении нет раздела с ролью «ловушки» — человеку "
                     "сентябрьские факты взять негде")
    else:
        объявлено = {str(н).lstrip("Hh") for н in (ловушки[0].get("правила_входа") or [])}
        нужно = ловушки_входа(вход)
        if not нужно:
            плохо.append("во входе не нашёлся раздел про ловушки — проверять нечем")
        пропало = sorted(нужно - объявлено, key=int)
        if пропало:
            плохо.append("вход называет правила, которых нет в разделе ловушек "
                         "приложения: " + ", ".join("H" + н for н in пропало))

        # Пересказ обязан вести к источнику: он устаревает раньше входа.
        for язык in ("тело", "тело_en"):
            if не_ведёт_во_вход(ловушки[0].get(язык) or ""):
                плохо.append(f"раздел ловушек ({язык}) пересказывает вход, но не даёт "
                             f"сырого адреса AGENT_START.md")

    промпты = [р for р in разделы if р.get("роль") == "промпт-агенту"]
    if not промпты:
        плохо.append("в приложении нет раздела с ролью «промпт-агенту» — кнопке "
                     "нечего копировать")
    else:
        тело = промпты[0].get("тело") or ""
        if "AGENT_START.md" not in тело:
            плохо.append("промпт приложения не ведёт во вход AGENT_START.md")
        if "api.html" not in тело:
            плохо.append("промпт приложения не говорит, что публичная справка "
                         "не источник правды")
        if "raw.githubusercontent.com" not in тело:
            плохо.append("промпт приложения не даёт сырых ссылок — веб-чтение "
                         "обрежет свод, и агент не прочитает правил")

    if ПРОМПТ.exists():
        текст = ПРОМПТ.read_text(encoding="utf-8")
        if "AGENT_START.md" not in текст:
            плохо.append("PROMPT_FOR_EXTERNAL_AGENT.md не ведёт во вход")
    return плохо


def проверить() -> int:
    плохо = беды()
    for б in плохо:
        print("  ✗ " + б)
    if плохо:
        print("\nНЕ УСПЕХ (H112): вход для агента и приложение для человека "
              "разошлись.")
        return 1
    print("H112 цел: вход и приложение называют одни ловушки и один вход.")
    return 0


def _selftest() -> int:
    провалы = []

    def проба(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    print("Самопроверка check_entry_app_agreement:")

    образец = (
        "# Старт\n\n## Маршрут по задачам\n\n| x | `rules/H999.md` |\n\n"
        "## Десять ловушек, на которых встают все\n\n"
        "1. Ключ один. → `rules/H109.md`\n2. Окно. → `rules/H106.md`\n\n"
        "## Первые действия\n\nничего\n")
    найдено = ловушки_входа(образец)
    проба("номера из раздела ловушек прочитаны", найдено == {"109", "106"})
    проба("номера из маршрутной таблицы не требуются", "999" not in найдено)
    проба("без раздела ловушек возвращается пусто",
          ловушки_входа("# Старт\n\n## Маршрут\n\n`rules/H1.md`\n") == set())

    проба("пересказ без адреса входа ловится",
          не_ведёт_во_вход("Ключ один, заголовки разные."))
    проба("пересказ с сырым адресом входа проходит",
          not не_ведёт_во_вход("Читай " + СЫРОЙ_ВХОД))
    проба("пустой текст претензий не вызывает", not не_ведёт_во_вход(""))

    проба("H112 назван в тексте проверки",
          "H112" in pathlib.Path(__file__).read_text(encoding="utf-8"))
    проба("живой репозиторий согласен", беды() == [])

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы — " + "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    sys.exit(_selftest() if "--selftest" in sys.argv else проверить())
