#!/usr/bin/env python3
"""Форма агента → диаграмма в окне «Диаграммы» (draw.io).

ЗАЧЕМ. У Доски схем канал агента был, у Диаграмм — нет: на фразу «сделай
диаграмму орг структуры» строка честно отказывала. Замер 21.08.2026, окно
Диаграмм. При этом сам draw.io в окне ещё и НЕ СОХРАНЯЛСЯ («Изменения не
сохранены» в его шапке) — работа жила только в памяти окна.

Здесь оба вопроса решает одна вещь: диаграмма лежит в хранилище приложения
файлом (`~/extella-cabinet/данные/drawio.json`, ключ `extella_диаграмма`),
как чертёж на столе. Агент кладёт туда свой чертёж, окно его подхватывает и
возвращает обратно каждую правку человека.

Принимает общий язык пяти форм (см. docs/FIVE_FORMS.md): «связи» рисуются
графом, «шаги» — цепочкой, «список» — колонкой карточек.

    python3 tools/в_диаграммы.py --файл форма.json
    python3 tools/в_диаграммы.py --selftest
"""

import argparse
import html
import json
import pathlib
import sys

ХРАНИЛИЩЕ = pathlib.Path.home() / "extella-cabinet" / "данные" / "drawio.json"
КЛЮЧ = "extella_диаграмма"
# Подпись — обязательство перед человеком: рисунок агента видно и его можно
# отличить от своего. Тот же уговор, что на Доске схем.
ПОДПИСЬ = "нарисовано агентом"

ШИРИНА, ВЫСОТА = 200, 60
ЗАЗОР_X, ЗАЗОР_Y = 90, 50


class Отказ(Exception):
    pass


def _клетка(ид: str, текст: str, x: int, y: int, стиль: str) -> str:
    т = html.escape(str(текст or "")[:120], quote=True)
    return (f'<mxCell id="{ид}" value="{т}" style="{стиль}" vertex="1" parent="1">'
            f'<mxGeometry x="{x}" y="{y}" width="{ШИРИНА}" height="{ВЫСОТА}" as="geometry"/>'
            f'</mxCell>')


def _стрелка(ид: str, откуда: str, куда: str, подпись: str = "") -> str:
    т = html.escape(str(подпись or "")[:60], quote=True)
    return (f'<mxCell id="{ид}" value="{т}" style="edgeStyle=orthogonalEdgeStyle;'
            f'rounded=1;html=1;" edge="1" parent="1" source="{откуда}" target="{куда}">'
            f'<mxGeometry relative="1" as="geometry"/></mxCell>')


def связи_в_xml(узлы: list, рёбра: list, название: str) -> str:
    """Граф: узлы по ярусам, рёбра стрелками.

    Ярус узла — глубина от корня. Без раскладки по ярусам орг-структура
    выглядит кучей коробок, и человек не видит подчинения.
    """
    имена = [str(у)[:120] for у in узлы]
    номер = {и: f"n{к}" for к, и in enumerate(имена)}
    родитель = {}
    for р in рёбра:
        а, б = (р.get("от"), р.get("к")) if isinstance(р, dict) else (р[0], р[1])
        if б in номер and а in номер:
            родитель.setdefault(б, а)

    def ярус(и, глубина=0):
        if глубина > 12 or и not in родитель:
            return глубина
        return ярус(родитель[и], глубина + 1)

    по_ярусам = {}
    for и in имена:
        по_ярусам.setdefault(ярус(и), []).append(и)

    клетки = []
    стиль = ("rounded=1;whiteSpace=wrap;html=1;fillColor=#FAF6EF;"
             "strokeColor=#C57E33;fontColor=#2A2A2A;")
    for у, ряд in sorted(по_ярусам.items()):
        for i, и in enumerate(ряд):
            x = i * (ШИРИНА + ЗАЗОР_X) + 40
            y = у * (ВЫСОТА + ЗАЗОР_Y) + 40
            клетки.append(_клетка(номер[и], и, x, y, стиль))
    for к, р in enumerate(рёбра):
        if isinstance(р, dict):
            а, б, п = р.get("от"), р.get("к"), р.get("подпись", "")
        else:
            а, б, п = (list(р) + ["", "", ""])[:3]
        if а in номер and б in номер:
            клетки.append(_стрелка(f"e{к}", номер[а], номер[б], п))
    return _обернуть(клетки, название)


def шаги_в_xml(шаги: list, название: str) -> str:
    клетки = []
    стиль = ("rounded=1;whiteSpace=wrap;html=1;fillColor=#F3EEE5;"
             "strokeColor=#5FA8A0;fontColor=#2A2A2A;")
    предыдущий = None
    for к, ш in enumerate(шаги):
        текст = ш.get("текст") if isinstance(ш, dict) else ш
        ид = f"s{к}"
        клетки.append(_клетка(ид, текст, 40, к * (ВЫСОТА + ЗАЗОР_Y) + 40, стиль))
        if предыдущий:
            клетки.append(_стрелка(f"se{к}", предыдущий, ид))
        предыдущий = ид
    return _обернуть(клетки, название)


def _обернуть(клетки: list, название: str) -> str:
    подпись = _клетка("подпись", f"{название} · {ПОДПИСЬ}", 40, -60,
                      "text;html=1;align=left;fontSize=12;fontColor=#8C8C8C;")
    тело = "".join([подпись] + клетки)
    return ('<mxfile host="extella"><diagram name="Схема">'
            '<mxGraphModel dx="800" dy="600" grid="1" gridSize="10" page="1" '
            'pageWidth="850" pageHeight="1100"><root>'
            '<mxCell id="0"/><mxCell id="1" parent="0"/>'
            f'{тело}</root></mxGraphModel></diagram></mxfile>')


def форма_в_xml(форма: dict) -> str:
    название = str(форма.get("название") or форма.get("заголовок")
                   or форма.get("имя") or "Схема")[:80]
    вид = форма.get("форма") or форма.get("вид")
    if вид == "связи" or ("узлы" in форма) or ("связи" in форма):
        рёбра = форма.get("рёбра") or форма.get("связи") or []
        узлы = форма.get("узлы") or []
        if not узлы:
            # Живой формат агента: он присылает ТОЛЬКО связи, узлы
            # подразумеваются (замер 21.08.2026, «сделай диаграмму орг
            # структуры» — восемь связей, ни одного узла). Собираем сами,
            # в порядке появления: начальник встречается раньше подчинённого,
            # и ярусы получаются правильные.
            for р in рёбра:
                а, б = ((р.get("от"), р.get("к")) if isinstance(р, dict)
                        else (р[0], р[1]) if len(р) > 1 else (None, None))
                for имя in (а, б):
                    if имя and имя not in узлы:
                        узлы.append(имя)
        if not узлы:
            raise Отказ("в форме «связи» нет ни узлов, ни связей — рисовать нечего")
        return связи_в_xml(узлы, рёбра, название)
    if вид == "шаги" or "шаги" in форма:
        шаги = форма.get("шаги") or []
        if not шаги:
            raise Отказ("в форме «шаги» нет ни одного шага")
        return шаги_в_xml(шаги, название)
    if вид == "список" or "строки" in форма:
        строки = форма.get("строки") or []
        if not строки:
            raise Отказ("в форме «список» нет ни одной строки")
        return шаги_в_xml([{"текст": с if isinstance(с, str) else
                            " · ".join(str(з) for з in (с.values() if isinstance(с, dict) else с))}
                           for с in строки], название)
    raise Отказ("не понял форму: жду «связи» (узлы + рёбра), «шаги» или «список»")


def положить(xml: str) -> int:
    """Положить чертёж в хранилище приложения и поднять счётчик версии.

    Счётчик — это сигнал открытому окну «работу поменял кто-то другой»: по
    нему окно предложит обновиться кнопкой (или обновится само при простое).
    """
    ХРАНИЛИЩЕ.parent.mkdir(parents=True, exist_ok=True)
    данные = json.loads(ХРАНИЛИЩЕ.read_text()) if ХРАНИЛИЩЕ.exists() else {}
    данные[КЛЮЧ] = xml
    данные["_версия"] = int(данные.get("_версия") or 0) + 1
    ХРАНИЛИЩЕ.write_text(json.dumps(данные, ensure_ascii=False))
    return len(xml)


def selftest() -> int:
    ошибки = []
    xml = форма_в_xml({"форма": "связи", "название": "Орг-структура",
                       "узлы": ["CEO", "Продажи", "Разработка"],
                       "рёбра": [{"от": "CEO", "к": "Продажи"},
                                 {"от": "CEO", "к": "Разработка"}]})
    if xml.count("<mxCell") < 6:
        ошибки.append("узлы и стрелки не собрались")
    else:
        print("  ✓ связи рисуются графом")
    # Подчинённые обязаны лежать НИЖЕ начальника: без ярусов орг-структура
    # превращается в кучу коробок, и смысл теряется.
    import re as _re
    y = {м.group(1): int(м.group(2)) for м in
         _re.finditer(r'value="([^"]+)"[^>]*>\s*<mxGeometry x="\d+" y="(\d+)"', xml)}
    if y.get("CEO", 0) >= y.get("Продажи", 0):
        ошибки.append("ярусы не расставлены: подчинённый не ниже начальника")
    else:
        print("  ✓ подчинённые лежат ярусом ниже")
    if ПОДПИСЬ not in xml:
        ошибки.append("подпись агента потерялась")
    else:
        print("  ✓ рисунок подписан «нарисовано агентом»")
    # ЖИВОЙ ФОРМАТ АГЕНТА: только связи, без списка узлов.
    живая = форма_в_xml({"форма": "связи", "заголовок": "Орг-структура",
                         "связи": [{"от": "Гендиректор", "к": "Техдиректор"},
                                   {"от": "Техдиректор", "к": "Разработка"}]})
    if живая.count("<mxCell") < 5 or "Разработка" not in живая:
        ошибки.append("форма агента (связи без узлов) не нарисовалась")
    else:
        print("  ✓ форма агента без списка узлов рисуется")
    try:
        форма_в_xml({"форма": "связи", "узлы": [], "связи": []})
        ошибки.append("пустая форма не отказала")
    except Отказ:
        print("  ✓ пустая форма отказывает словами")
    # Текст человека не должен ломать разметку — иначе окно покажет пустоту.
    опасный = форма_в_xml({"форма": "шаги", "шаги": ['<b>"взлом"</b> & прочее']})
    if "<b>" in опасный.split('value="')[2]:
        ошибки.append("разметка из текста не экранирована")
    else:
        print("  ✓ текст экранируется, разметку не ломает")
    print("ИТОГ САМОПРОВЕРКИ:", "все проверки прошли" if not ошибки else "; ".join(ошибки))
    return 1 if ошибки else 0


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    # Имена аргументов общие для всех получателей (см. скажи.py::_доставить):
    # диспетчер зовёт всех одинаково, иначе канал молча не работает.
    р.add_argument("--файл", "--форма", dest="файл",
                   help="json-файл с формой (связи | шаги | список)")
    р.add_argument("--источник", default="", help="откуда пришла форма (для подписи)")
    р.add_argument("--selftest", action="store_true")
    а = р.parse_args()
    if а.selftest:
        return selftest()
    if not а.файл:
        print("ОТКАЗ: нечего рисовать — дайте --файл форма.json", file=sys.stderr)
        return 1
    форма = json.loads(pathlib.Path(а.файл).expanduser().read_text())
    # Заголовок, сочинённый агентом, важнее служебного слова диспетчера
    # («замысел»): человек должен увидеть «Организационная структура», а не
    # внутреннее имя канала.
    if а.источник and not (форма.get("название") or форма.get("заголовок")):
        форма["название"] = а.источник
    try:
        xml = форма_в_xml(форма)
    except Отказ as о:
        print(f"ОТКАЗ: {о}", file=sys.stderr)
        return 1
    знаков = положить(xml)
    print(f"✓ диаграмма положена в окно «Диаграммы» ({знаков} знаков разметки)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
