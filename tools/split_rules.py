#!/usr/bin/env python3
"""Канон по одному правилу на файл — чтобы его мог прочитать внешний агент.

ЗАЧЕМ. Замер 25.09.2026: `DEPLOY_REQUIREMENTS.md` — 369 КБ и 117 правил. Веб-чтение
такой страницы обрезается, и внешний агент до правил просто не доезжает: два чата
оплаченного клиента прочитали ранбук на 10 КБ и применили его, а свод не читали
вовсе. Читают то, что помещается.

ЧТО ДЕЛАЕТ. Разбирает свод и раскладывает каждое правило отдельным файлом
`rules/H<номер>.md` (единицы килобайт), плюс `rules/INDEX.md` — оглавление из одной
строки на правило. Адресация становится поштучной: агент берёт `rules/H106.md`
сырой ссылкой и читает целиком.

    python3 tools/split_rules.py            # разложить
    python3 tools/split_rules.py --check    # проверить, что разложенное не отстало
    python3 tools/split_rules.py --selftest

Коды выхода: 0 — в порядке, 1 — отстало или пусто.
"""

from __future__ import annotations

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
СВОД = КОРЕНЬ / "DEPLOY_REQUIREMENTS.md"
ПАПКА = КОРЕНЬ / "rules"
СЫРАЯ = "https://raw.githubusercontent.com/AnvarBakiyev/extella-agent-standards/main"

ЗАГОЛОВОК = re.compile(r"^### (H\d+(?:-[А-Яа-яЁёA-Za-z]+)?)\.\s*(.+)$", re.M)


def правила(текст: str) -> list[tuple[str, str, str]]:
    """(номер, заголовок, тело) для каждого правила свода."""
    метки = list(ЗАГОЛОВОК.finditer(текст))
    собрано = []
    for i, м in enumerate(метки):
        конец = метки[i + 1].start() if i + 1 < len(метки) else len(текст)
        собрано.append((м.group(1), м.group(2).strip(), текст[м.start():конец].rstrip() + "\n"))
    return собрано


def шапка(номер: str, заголовок: str) -> str:
    return (f"<!-- Файл собран из DEPLOY_REQUIREMENTS.md автоматически: "
            f"python3 tools/split_rules.py. Правится свод, а не этот файл. -->\n\n"
            f"# {номер}. {заголовок}\n\n"
            f"Свод целиком — `DEPLOY_REQUIREMENTS.md`; оглавление правил — "
            f"[rules/INDEX.md]({СЫРАЯ}/rules/INDEX.md).\n\n")


def оглавление(собрано: list[tuple[str, str, str]]) -> str:
    строки = ["<!-- Собрано автоматически: python3 tools/split_rules.py -->",
              "",
              "# Правила канона: оглавление",
              "",
              "Каждое правило лежит отдельным файлом на несколько килобайт — бери по одному, "
              "а не свод целиком (369 КБ веб-чтение обрезает).",
              "",
              f"Сырая ссылка на правило: `{СЫРАЯ}/rules/H<номер>.md`",
              "",
              "| правило | о чём |",
              "|---|---|"]
    for номер, заголовок, _ in sorted(собрано, key=lambda т: (int(re.sub(r"\D", "", т[0])), т[0])):
        строки.append(f"| [{номер}](H{re.sub(r'^H', '', номер)}.md) | {заголовок} |")
    строки.append("")
    return "\n".join(строки)


def собрать() -> dict[str, str]:
    текст = СВОД.read_text(encoding="utf-8")
    собрано = правила(текст)
    файлы = {f"H{re.sub(r'^H', '', номер)}.md": шапка(номер, заголовок) + тело
             for номер, заголовок, тело in собрано}
    файлы["INDEX.md"] = оглавление(собрано)
    return файлы


def разложить(проверить: bool = False) -> int:
    if not СВОД.exists():
        print(f"нет свода: {СВОД}")
        return 1
    файлы = собрать()
    if len(файлы) < 2:
        print("в своде не найдено ни одного правила")
        return 1

    if проверить:
        отставшие = []
        существующие = {п.name for п in ПАПКА.glob("*.md")} if ПАПКА.exists() else set()
        for имя, содержимое in файлы.items():
            путь = ПАПКА / имя
            if not путь.exists() or путь.read_text(encoding="utf-8") != содержимое:
                отставшие.append(имя)
        лишние = sorted(существующие - set(файлы))
        if отставшие or лишние:
            print(f"разложенные правила отстали от свода: обновить {len(отставшие)}, "
                  f"удалить {len(лишние)} — запусти python3 tools/split_rules.py")
            for имя in (отставшие[:5] + лишние[:5]):
                print("   ·", имя)
            return 1
        print(f"правил разложено: {len(файлы) - 1}, всё совпадает со сводом")
        return 0

    ПАПКА.mkdir(exist_ok=True)
    for имя in {п.name for п in ПАПКА.glob("*.md")} - set(файлы):
        (ПАПКА / имя).unlink()
    for имя, содержимое in файлы.items():
        (ПАПКА / имя).write_text(содержимое, encoding="utf-8")
    самый_большой = max(файлы.items(), key=lambda п: len(п[1]))
    print(f"разложено правил: {len(файлы) - 1}; самый крупный файл — "
          f"{самый_большой[0]}, {len(самый_большой[1]) // 1024} КБ")
    return 0


def _selftest() -> int:
    провалы = []

    def проба(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    print("Самопроверка split_rules:")
    образец = ("вступление\n"
               "### H1. ПЕРВОЕ ПРАВИЛО\nтело первого\n\n"
               "### H5-бис. ПОПРАВКА\nтело поправки\n\n"
               "### H106. ОКНО ОС\nтело окна\n")
    р = правила(образец)
    проба("находит все правила, включая H5-бис", [н for н, _, _ in р] == ["H1", "H5-бис", "H106"])
    проба("тело правила не захватывает следующее", "тело поправки" not in р[0][2])
    проба("заголовок отделён от номера", р[2][1] == "ОКНО ОС")
    огл = оглавление(р)
    проба("оглавление содержит все правила", all(н in огл for н, _, _ in р))
    проба("в шапке сказано, что правится свод", "Правится свод" in шапка("H1", "х"))

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы — " + "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    sys.exit(разложить(проверить="--check" in sys.argv))
