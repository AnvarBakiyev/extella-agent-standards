"""Доктор среды — одна самопроверка для ЛЮБОГО приложения Extella.

Решение Гульжан 01.09.2026: доктор должен быть универсальным и проверять каждое
приложение. Поэтому этот файл сознательно НЕ знает ничего про Рекрутёра: что
проверять, приложение описывает словарём-паспортом, а доктор умеет проверять.
Файл целиком переносится в другой продукт без правок.

Два режима, и это продуктовое решение, а не техническое:
  быстрый  — при каждом открытии продукта, < полсекунды, только локальное:
             ОС, Python, библиотеки, место, права, своя ли панель на порту;
  полный   — по кнопке «Проверить и починить» в момент отказа: плюс сеть до
             платформы и живость устройства-исполнителя (это секунды и десятки
             секунд — при каждом открытии они наказывали бы здоровых).

Каждая беда возвращается тройкой: что случилось · чем грозит · что нажать/сделать.
Доктор не чинит систему сам (установщик уже починил всё, что можно без человека) —
он превращает «ничего не работает» в одно конкретное действие.
"""

from __future__ import annotations

import json
import os
import shutil
import sys
import urllib.error
import urllib.request
from pathlib import Path

# Паспорт проверки — то, что приложение говорит о себе. Всё необязательно.
# {
#   "product_ru":  "Рекрутёр",          — как продукт называет себя в /api/health
#   "min_python":  (3, 10),
#   "modules":     ["fitz", "docx"],    — без чего возможности молча откажут
#   "data_dir":    "~/extella_recruiting",
#   "min_free_mb": 300,
#   "panel_port":  8794,
#   "platform":    "https://api.extella.ai/health",
#   "executor":    callable() -> None   — бросает исключение, если исполнитель спит
# }


def _беда(имя: str, что: str, чинить: str, важно: bool = True) -> dict:
    return {"name": имя, "ok": False, "critical": важно, "what_ru": что, "fix_ru": чинить}


def _ок(имя: str, примечание: str = "") -> dict:
    return {"name": имя, "ok": True, "note_ru": примечание}


def осмотр(паспорт: dict, быстрый: bool = True) -> dict:
    итоги: list[dict] = []

    # ── ОС ──
    if os.name == "nt":
        итоги.append(_беда("ос", "продукт не работает на Windows",
                           "используйте macOS/Linux или серверный режим продукта"))
    else:
        итоги.append(_ок("ос", sys.platform))

    # ── Python ──
    мин = tuple(паспорт.get("min_python") or (3, 10))
    if sys.version_info < мин:
        итоги.append(_беда("python",
                           "Python %s старше требуемого %s" % (sys.version.split()[0],
                                                               ".".join(map(str, мин))),
                           "переустановите продукт — установщик сам найдёт свежий Python"))
    else:
        итоги.append(_ок("python", sys.version.split()[0]))

    # ── Библиотеки ──
    пропали = []
    for имя in паспорт.get("modules") or []:
        try:
            __import__(имя)
        except Exception:
            пропали.append(имя)
    if пропали:
        итоги.append(_беда("библиотеки",
                           "не читаются: " + ", ".join(пропали),
                           "переустановите продукт из магазина — установщик вернёт их"))
    else:
        итоги.append(_ок("библиотеки", "%d на месте" % len(паспорт.get("modules") or [])))

    # ── Данные: место и права ──
    папка = Path(os.path.expanduser(паспорт.get("data_dir") or "~")).resolve()
    try:
        папка.mkdir(parents=True, exist_ok=True)
        проба = папка / ".проба_доктора"
        проба.write_text("ok"); проба.unlink()
        свободно = shutil.disk_usage(str(папка)).free // (1024 * 1024)
        мин_мб = int(паспорт.get("min_free_mb") or 300)
        if свободно < мин_мб:
            итоги.append(_беда("диск", "свободно %d МБ — меньше нужных %d" % (свободно, мин_мб),
                               "освободите место на диске"))
        else:
            итоги.append(_ок("данные", "%d МБ свободно" % свободно))
        if "Mobile Documents" in str(папка) or "iCloud" in str(папка) or "OneDrive" in str(папка):
            итоги.append(_беда("данные-облако",
                               "папка данных внутри облачной синхронизации — файлы могут "
                               "«уезжать» из-под продукта",
                               "перенесите данные в обычную локальную папку", важно=False))
    except OSError as e:
        итоги.append(_беда("данные", "нет права писать в %s: %s" % (папка, str(e)[:80]),
                           "разрешите запись (на корпоративном устройстве — через ИТ)"))

    # ── Панель: наша ли она на своём порту ──
    порт = паспорт.get("panel_port")
    if порт:
        try:
            with urllib.request.urlopen("http://127.0.0.1:%d/api/health" % int(порт),
                                        timeout=3) as о:
                ответ = json.loads(о.read() or b"{}")
            своё = паспорт.get("product_ru") or ""
            if своё and своё not in str(ответ.get("product", "")):
                итоги.append(_беда("порт", "на порту %s отвечает чужая программа" % порт,
                                   "закройте её (lsof -nP -iTCP:%s -sTCP:LISTEN) и "
                                   "откройте продукт заново" % порт))
            else:
                итоги.append(_ок("панель", "отвечает на %s" % порт))
        except Exception:
            # Из самой панели этой ветки не видно (мы и есть панель); из окна — видно.
            итоги.append(_беда("панель", "локальная панель на порту %s не отвечает" % порт,
                               "переустановите продукт — установщик поднимет её снова",
                               важно=False))

    if not быстрый:
        # ── Сеть до платформы ──
        адрес = паспорт.get("platform") or "https://api.extella.ai/health"
        try:
            urllib.request.urlopen(адрес, timeout=15).read()
            итоги.append(_ок("сеть", "платформа достижима"))
        except urllib.error.HTTPError:
            итоги.append(_ок("сеть", "платформа достижима"))
        except Exception as e:
            причина = str(e)
            if "certificat" in причина.lower():
                итоги.append(_беда("сеть", "сертификат платформы не принимается",
                                   "проверьте ДАТУ И ВРЕМЯ устройства; если верны — "
                                   "корпоративная сеть подменяет сертификаты, попросите "
                                   "ИТ открыть *.extella.ai"))
            else:
                итоги.append(_беда("сеть", "платформа недоступна: %s" % причина[:100],
                                   "проверьте интернет; в корпоративной сети попросите "
                                   "ИТ открыть *.extella.ai"))

        # ── Устройство-исполнитель ──
        исполнитель = паспорт.get("executor")
        if callable(исполнитель):
            try:
                исполнитель()
                итоги.append(_ок("исполнитель", "устройство отвечает"))
            except Exception as e:
                причина = str(e)[:140]
                if "unavailable" in причина.lower() or "target" in причина.lower():
                    итоги.append(_беда("исполнитель",
                                       "устройство-исполнитель Extella не на связи — "
                                       "разбор и другие смысловые задачи будут падать",
                                       "запустите приложение Extella на этом компьютере "
                                       "(слушатель устройства) и повторите"))
                else:
                    итоги.append(_беда("исполнитель", "пробный запуск не прошёл: " + причина,
                                       "повторите через минуту; не прошло — запустите "
                                       "приложение Extella на этом компьютере"))

    беды = [и for и in итоги if not и["ok"]]
    return {"ok": not any(б.get("critical") for б in беды),
            "checks": итоги,
            "problems": len(беды),
            "mode": "быстрый" if быстрый else "полный"}
