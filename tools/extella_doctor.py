"""Доктор среды — одна самопроверка для ЛЮБОГО приложения Extella.

Решение Гульжан 01.09.2026: доктор должен быть универсальным и проверять каждое
приложение. Поэтому этот файл сознательно НЕ знает ничего про Рекрутёра: что
проверять, приложение описывает словарём-паспортом, а доктор умеет проверять.
Файл целиком переносится в другой продукт без правок.

Два режима, и это продуктовое решение, а не техническое:
  быстрый  — при каждом открытии продукта, < полсекунды, только локальное:
             ОС, Python, библиотеки, место, права, своя ли панель на порту;
  полный   — по кнопке «Проверить и починить» в момент отказа: плюс сеть до
             платформы, часы устройства, права app_scopes и живость
             устройства-исполнителя (это секунды и десятки секунд — при каждом
             открытии они наказывали бы здоровых).

Каждая беда возвращается тройкой: что случилось · чем грозит · что нажать/сделать.
Доктор не чинит систему сам (установщик уже починил всё, что можно без человека) —
он превращает «ничего не работает» в одно конкретное действие.

── Зубы (H74, FAILURE_CLASSES.md §G) ────────────────────────────────────────────
Обещание «машинной самопроверки» из DOCTOR_STANDARD.md стоит ноль, пока у доктора
нет CLI, который умеет ПАДАТЬ. Поэтому здесь есть `--selftest`: для каждого класса
поломки, который доктор охраняет, он подсовывает нарочно испорченный паспорт/среду
и требует красноты, а на чистом паспорте требует зелени (§G.4 — к каждому запрету
проверка остатка). Не поймал посаженную беду или покраснел на здоровом — доктор не
страж, и `run_all_gates.sh` это увидит.

Какой класс FAILURE_CLASSES.md ловит доктор, а какой — соседний страж (доктор —
рантайм-проверка среды на машине покупателя, а не статический анализ кода):

  A. Сборка/доставка   — рантайм-проба «это мы на порту?» (панель после подъёма
                         перечитывается: своя ли программа отвечает /api/health).
                         Шов сборки и совпадение с исходником — check_self_check,
                         check_single_source.
  B. Страница          — НЕ доктор: мёртвый обработчик, модал-тупик, заглушки —
                         check_screen_rules, check_waiting_state (статика страницы).
  C. Мост стр.↔устр.   — рантайм-проба исполнителя: живой вызов доходит до
                         устройства и возвращается. Куски >64 КБ и разворот
                         конверта — тесты продукта.
  D. Данные            — рантайм-срез среды: папка данных пишется, есть место, не
                         в облачной синхронизации. Замок писателей и схема данных —
                         check_state_contract.
  E. Платформа         — сеть до платформы, подменённый сертификат, невыданные
                         app_scopes (проба прав), устройство-исполнитель спит,
                         чужой питон (доктор называет интерпретатор). Права в коде —
                         check_app_scopes.
  F. Среда покупателя  — ЦЕЛИКОМ доктор: ОС, Python, библиотеки, место, права,
                         занятый порт, облачная папка, сбитые часы.
  G. Сторожа           — сам `--selftest` доктора с негативным контролем и есть
                         G-класс, применённый к доктору (§G.2, §G.4).
"""

from __future__ import annotations

import argparse
import email.utils
import json
import os
import shutil
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

# Паспорт проверки — то, что приложение говорит о себе. Всё необязательно.
# {
#   "product_ru":  "Рекрутёр",          — как продукт называет себя в /api/health
#   "min_python":  (3, 10),
#   "modules":     ["fitz", "docx"],    — без чего возможности молча откажут
#   "data_dir":    "~/extella_recruiting",
#   "min_free_mb": 300,
#   "panel_port":  8794,
#   "platform":    "https://api.extella.ai/health",
#   "max_clock_skew": 300,              — допуск расхождения часов, секунд
#   "executor":    callable() -> None   — бросает исключение, если исполнитель спит
#   "scopes_probe": callable() -> None  — бросает 403, если app_scopes не выданы
# }
# Из файла-паспорта (JSON/YAML рядом с продуктом) читаются все поля, КРОМЕ callable
# (`executor`, `scopes_probe`) — их несёт только живой продукт, встроивший доктор.

ДОПУСК_ЧАСОВ = 300  # секунд; больше — часы устройства сбиты, платформа отвергнет TLS


def _беда(имя: str, что: str, чинить: str, важно: bool = True, кл: str = "") -> dict:
    итог = {"name": имя, "ok": False, "critical": важно, "what_ru": что, "fix_ru": чинить}
    if кл:
        итог["class"] = кл
    return итог


def _ок(имя: str, примечание: str = "", кл: str = "") -> dict:
    итог = {"name": имя, "ok": True, "note_ru": примечание}
    if кл:
        итог["class"] = кл
    return итог


def осмотр(паспорт: dict, быстрый: bool = True) -> dict:
    итоги: list[dict] = []

    # ── ОС (F) ──
    if os.name == "nt":
        итоги.append(_беда("ос", "продукт не работает на Windows",
                           "используйте macOS/Linux или серверный режим продукта", кл="F"))
    else:
        итоги.append(_ок("ос", sys.platform, кл="F"))

    # ── Python (F) ──
    мин = tuple(паспорт.get("min_python") or (3, 10))
    if sys.version_info < мин:
        итоги.append(_беда("python",
                           "Python %s старше требуемого %s" % (sys.version.split()[0],
                                                               ".".join(map(str, мин))),
                           "переустановите продукт — установщик сам найдёт свежий Python",
                           кл="F"))
    else:
        итоги.append(_ок("python", sys.version.split()[0], кл="F"))

    # ── Библиотеки (F; при отказе называем интерпретатор — это и класс E,
    #    «эксперт исполняется чужим питоном»: «No module named …» только у покупателя) ──
    пропали = []
    for имя in паспорт.get("modules") or []:
        try:
            __import__(имя)
        except Exception:
            пропали.append(имя)
    if пропали:
        итоги.append(_беда("библиотеки",
                           "не читаются: %s (интерпретатор %s)" % (", ".join(пропали),
                                                                    sys.executable),
                           "переустановите продукт из магазина — установщик вернёт их "
                           "в окружение продукта", кл="F"))
    else:
        итоги.append(_ок("библиотеки", "%d на месте" % len(паспорт.get("modules") or []), кл="F"))

    # ── Данные: место и права (F) ──
    папка = Path(os.path.expanduser(паспорт.get("data_dir") or "~")).resolve()
    try:
        папка.mkdir(parents=True, exist_ok=True)
        проба = папка / ".проба_доктора"
        проба.write_text("ok"); проба.unlink()
        свободно = shutil.disk_usage(str(папка)).free // (1024 * 1024)
        мин_мб = int(паспорт.get("min_free_mb") or 300)
        if свободно < мин_мб:
            итоги.append(_беда("диск", "свободно %d МБ — меньше нужных %d" % (свободно, мин_мб),
                               "освободите место на диске", кл="F"))
        else:
            итоги.append(_ок("данные", "%d МБ свободно" % свободно, кл="F"))
        if "Mobile Documents" in str(папка) or "iCloud" in str(папка) or "OneDrive" in str(папка):
            итоги.append(_беда("данные-облако",
                               "папка данных внутри облачной синхронизации — файлы могут "
                               "«уезжать» из-под продукта",
                               "перенесите данные в обычную локальную папку", важно=False, кл="F"))
    except OSError as e:
        итоги.append(_беда("данные", "нет права писать в %s: %s" % (папка, str(e)[:80]),
                           "разрешите запись (на корпоративном устройстве — через ИТ)", кл="F"))

    # ── Панель: наша ли она на своём порту (A — «это мы?» после подъёма) ──
    порт = паспорт.get("panel_port")
    if порт:
        try:
            with urllib.request.urlopen("http://127.0.0.1:%d/api/health" % int(порт),
                                        timeout=3) as о:
                ответ = json.loads(о.read() or b"{}")
            своё = паспорт.get("product_ru") or ""
            if своё and своё not in str(ответ.get("product", "")):
                итоги.append(_беда("порт", "на порту %s отвечает чужая программа" % порт,
                                   "закройте её (lsof -nP -iTCP:%s -sTCP:LISTEN) и "
                                   "откройте продукт заново" % порт, кл="A"))
            else:
                итоги.append(_ок("панель", "отвечает на %s" % порт, кл="A"))
        except Exception:
            # Из самой панели этой ветки не видно (мы и есть панель); из окна — видно.
            итоги.append(_беда("панель", "локальная панель на порту %s не отвечает" % порт,
                               "переустановите продукт — установщик поднимет её снова",
                               важно=False, кл="F"))

    if not быстрый:
        # ── Сеть до платформы и часы устройства (E, F) ──
        адрес = паспорт.get("platform") or "https://api.extella.ai/health"
        _сеть_и_часы(итоги, адрес, int(паспорт.get("max_clock_skew") or ДОПУСК_ЧАСОВ))

        # ── Права app_scopes выданы (E) ──
        проба_прав = паспорт.get("scopes_probe")
        if callable(проба_прав):
            try:
                проба_прав()
                итоги.append(_ок("права", "app_scopes на месте", кл="E"))
            except Exception as e:
                причина = str(e)
                if "403" in причина or "scope" in причина.lower() or "forbidden" in причина.lower():
                    итоги.append(_беда("права",
                                       "платформа отвечает 403 — приложению не выданы права "
                                       "(app_scopes: expert.run/device.run)",
                                       "переустановите продукт из магазина; если повторяется — "
                                       "права выдаёт платформа при публикации, сообщите в поддержку",
                                       кл="E"))
                else:
                    итоги.append(_беда("права", "пробный вызов прав не прошёл: " + причина[:120],
                                       "повторите; не прошло — сообщите в поддержку", кл="E"))

        # ── Устройство-исполнитель (C — мост доходит до устройства и обратно) ──
        исполнитель = паспорт.get("executor")
        if callable(исполнитель):
            try:
                исполнитель()
                итоги.append(_ок("исполнитель", "устройство отвечает", кл="C"))
            except Exception as e:
                причина = str(e)[:140]
                if "unavailable" in причина.lower() or "target" in причина.lower():
                    итоги.append(_беда("исполнитель",
                                       "устройство-исполнитель Extella не на связи — "
                                       "разбор и другие смысловые задачи будут падать",
                                       "запустите приложение Extella на этом компьютере "
                                       "(слушатель устройства) и повторите", кл="C"))
                else:
                    итоги.append(_беда("исполнитель", "пробный запуск не прошёл: " + причина,
                                       "повторите через минуту; не прошло — запустите "
                                       "приложение Extella на этом компьютере", кл="C"))

    беды = [и for и in итоги if not и["ok"]]
    return {"ok": not any(б.get("critical") for б in беды),
            "checks": итоги,
            "problems": len(беды),
            "mode": "быстрый" if быстрый else "полный"}


def _сеть_и_часы(итоги: list[dict], адрес: str, допуск: int) -> None:
    """Одним запросом: достижима ли платформа И не сбиты ли часы устройства.

    Часы проверяются только здесь (полный режим): расхождение видно лишь в
    сравнении с сервером, а быстрый осмотр по решению — только локальный. Сбитые
    часы платформа встречает отвергнутым сертификатом, поэтому это не мелочь.
    """
    дата_сервера = None
    try:
        о = urllib.request.urlopen(адрес, timeout=15)
        дата_сервера = о.headers.get("Date")
        о.read()
        итоги.append(_ок("сеть", "платформа достижима", кл="E"))
    except urllib.error.HTTPError as e:  # 4xx/5xx — платформа ответила, значит достижима
        дата_сервера = e.headers.get("Date") if e.headers else None
        итоги.append(_ок("сеть", "платформа достижима", кл="E"))
    except Exception as e:
        причина = str(e)
        if "certificat" in причина.lower():
            итоги.append(_беда("сеть", "сертификат платформы не принимается",
                               "проверьте ДАТУ И ВРЕМЯ устройства; если верны — "
                               "корпоративная сеть подменяет сертификаты, попросите "
                               "ИТ открыть *.extella.ai", кл="E"))
        else:
            итоги.append(_беда("сеть", "платформа недоступна: %s" % причина[:100],
                               "проверьте интернет; в корпоративной сети попросите "
                               "ИТ открыть *.extella.ai", кл="E"))
        return  # часы без ответа сервера не с чем сравнивать

    if дата_сервера:
        try:
            серверное = email.utils.parsedate_to_datetime(дата_сервера).timestamp()
            расхождение = int(abs(time.time() - серверное))
        except (TypeError, ValueError):
            расхождение = None
        if расхождение is not None and расхождение > допуск:
            итоги.append(_беда("часы",
                               "часы устройства расходятся с платформой на %d c — "
                               "платформа отвергнет соединение" % расхождение,
                               "включите автоматические дату и время в настройках устройства",
                               кл="F"))
        elif расхождение is not None:
            итоги.append(_ок("часы", "в норме (±%d c)" % расхождение, кл="F"))


# ── CLI: доктор на конкретном продукте ────────────────────────────────────────

ИМЕНА_ПАСПОРТА = ("doctor_passport.json", "doctor_passport.yaml", "doctor_passport.yml",
                  "паспорт_доктора.json", "паспорт_доктора.yaml")
КЛЮЧИ_В_МАНИФЕСТЕ = ("доктор", "doctor", "doctor_passport")
# Поля-callable живут только во встроенном продукте: из файла их не прочитать.
ПОЛЯ_ФАЙЛА = ("product_ru", "min_python", "modules", "data_dir", "min_free_mb",
              "panel_port", "platform", "max_clock_skew")


def _прочитать_структуру(файл: Path) -> dict | None:
    текст = файл.read_text(encoding="utf-8", errors="replace")
    if файл.suffix in (".yaml", ".yml"):
        try:
            import yaml  # тот же pyyaml, что уже нужен другим гейтам
        except Exception:
            return None
        данные = yaml.safe_load(текст)
    else:
        данные = json.loads(текст)
    return данные if isinstance(данные, dict) else None


def найти_паспорт(корень: Path) -> tuple[dict | None, str]:
    """Паспорт продукта и то, откуда он взят. Пусто — продукт не принял доктора."""
    for имя in ИМЕНА_ПАСПОРТА:
        файл = корень / имя
        if файл.is_file():
            данные = _прочитать_структуру(файл)
            if isinstance(данные, dict):
                return {к: данные[к] for к in ПОЛЯ_ФАЙЛА if к in данные}, имя
    for имя in ("MANIFEST.yaml", "manifest.yaml", "package.json"):
        файл = корень / имя
        if not файл.is_file():
            continue
        данные = _прочитать_структуру(файл)
        if not isinstance(данные, dict):
            continue
        for ключ in КЛЮЧИ_В_МАНИФЕСТЕ:
            if isinstance(данные.get(ключ), dict):
                п = данные[ключ]
                return {к: п[к] for к in ПОЛЯ_ФАЙЛА if к in п}, "%s → %s" % (имя, ключ)
    return None, ""


def _печать_человеку(итог: dict, откуда: str, каветы: list[str]) -> None:
    знак = "✓" if итог["ok"] else "✗"
    print("Доктор среды · режим %s · паспорт: %s" % (итог["mode"], откуда))
    for ч in итог["checks"]:
        кл = ("[%s] " % ч["class"]) if ч.get("class") else ""
        if ч["ok"]:
            print("  ✓ %s%s — %s" % (кл, ч["name"], ч.get("note_ru", "")))
        else:
            остр = "" if ч.get("critical") else " (не критично)"
            print("  ✗ %s%s%s — %s" % (кл, ч["name"], остр, ч["what_ru"]))
            print("      что сделать: %s" % ч["fix_ru"])
    for к in каветы:
        print("  · %s" % к)
    print("%s ИТОГ: %s, бед %d" % (знак, "готов" if итог["ok"] else "НЕ готов", итог["problems"]))


def запустить_на_продукте(путь: str, полный: bool, как_json: bool) -> int:
    корень = Path(путь).expanduser()
    if not корень.is_dir():
        print("нет папки продукта: %s" % корень, file=sys.stderr)
        return 2
    паспорт, откуда = найти_паспорт(корень)
    if паспорт is None:
        # «Проверять нечего» — это НЕ «прошёл» (правило GATES.md). Продукт не принял
        # доктора: положите doctor_passport.json или ключ `доктор:` в MANIFEST.yaml.
        print("продукт не принял доктора: нет паспорта (%s или ключ `доктор:` в "
              "MANIFEST.yaml). Это НЕ успех — проверять было нечем."
              % ", ".join(ИМЕНА_ПАСПОРТА[:2]), file=sys.stderr)
        return 2

    каветы: list[str] = []
    if полный:
        # Из файла не приходят callable-пробы: честно скажем, что они НЕ проверены,
        # а не покажем зелень «всё хорошо».
        if not паспорт.get("platform"):
            каветы.append("платформа паспортом не задана — берётся api.extella.ai по умолчанию")
        каветы.append("исполнитель и права из файла не проверяются — их несёт живой "
                      "продукт (executor/scopes_probe); запустите доктор изнутри продукта")

    итог = осмотр(паспорт, быстрый=not полный)
    if как_json:
        print(json.dumps({"source": откуда, "caveats": каветы, **итог},
                         ensure_ascii=False, indent=2))
    else:
        _печать_человеку(итог, откуда, каветы)
    return 0 if итог["ok"] else 1


# ── Зубы: --selftest ──────────────────────────────────────────────────────────

class _Сервер:
    """Крошечный локальный /api/health для проверок панели, сети и часов — без внешней сети."""

    def __init__(self, тело: dict, дата: str | None = None):
        import http.server
        import threading
        тело_байты = json.dumps(тело).encode()

        class Обработчик(http.server.BaseHTTPRequestHandler):
            def do_GET(с):
                # send_response_only, а не send_response: последний сам шлёт свой
                # Date (текущий) и затирал бы наш нарочно сбитый — проверка часов
                # тогда всегда зелёная, то есть страж без зубов.
                с.send_response_only(200)
                с.send_header("Content-Type", "application/json")
                с.send_header("Date", дата or email.utils.formatdate(usegmt=True))
                с.send_header("Content-Length", str(len(тело_байты)))
                с.end_headers()
                с.wfile.write(тело_байты)

            def log_message(с, *_):  # тишина в прогоне гейтов
                pass

        self._srv = http.server.HTTPServer(("127.0.0.1", 0), Обработчик)
        self.port = self._srv.server_address[1]
        self._th = threading.Thread(target=self._srv.serve_forever, daemon=True)
        self._th.start()

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self._srv.shutdown()
        self._srv.server_close()


def _бед_имена(итог: dict) -> set:
    return {ч["name"] for ч in итог["checks"] if not ч["ok"]}


def selftest() -> int:
    """Каждый охраняемый класс: сажаем беду — требуем красноты; чистим — требуем зелени."""
    import contextlib
    import io
    import tempfile

    провалы: list[str] = []
    всего = 0

    def требовать(условие: bool, сообщение: str) -> None:
        nonlocal всего
        всего += 1
        if not условие:
            провалы.append(сообщение)

    def тихо(*арг, **кв) -> int:
        # CLI-ветки печатают человеку — в прогоне гейта это шум, глушим оба потока.
        глушь = io.StringIO()
        with contextlib.redirect_stdout(глушь), contextlib.redirect_stderr(глушь):
            return запустить_на_продукте(*арг, **кв)

    with tempfile.TemporaryDirectory() as врем:
        основа = Path(врем)
        живая_папка = основа / "данные"

        # Чистый паспорт: доктор ОБЯЗАН быть зелёным (§G.4 — проверка остатка).
        чистый = {"min_python": (3, 6), "modules": ["os", "sys"],
                  "data_dir": str(живая_папка), "min_free_mb": 1}
        итог = осмотр(чистый, быстрый=True)
        требовать(итог["ok"], "чистый паспорт признан НЕ готовым: %s" % _бед_имена(итог))
        требовать(all(ч.get("class") for ч in итог["checks"]),
                  "есть проверка без класса поломки — карта A–G дырявая")

        # F · Python старше требуемого.
        итог = осмотр({**чистый, "min_python": (99, 0)}, быстрый=True)
        требовать("python" in _бед_имена(итог), "не пойман старый Python")

        # F · пропавшая библиотека.
        итог = осмотр({**чистый, "modules": ["нет_такого_модуля_9d3f1a"]}, быстрый=True)
        требовать("библиотеки" in _бед_имена(итог), "не пойман пропавший модуль")

        # F · нет места (просим заведомо невозможное).
        итог = осмотр({**чистый, "min_free_mb": 10 ** 15}, быстрый=True)
        требовать("диск" in _бед_имена(итог), "не пойман нехватка места")

        # F · нет права писать: data_dir внутри обычного файла.
        файл_помеха = основа / "файл"
        файл_помеха.write_text("x")
        итог = осмотр({**чистый, "data_dir": str(файл_помеха / "внутрь")}, быстрый=True)
        требовать("данные" in _бед_имена(итог), "не поймано отсутствие прав на запись")

        # F · папка данных в облачной синхронизации.
        облако = основа / "Mobile Documents" / "данные"
        итог = осмотр({**чистый, "data_dir": str(облако)}, быстрый=True)
        требовать("данные-облако" in _бед_имена(итог), "не поймана облачная папка данных")

        # A · на порту чужая программа, и наоборот — своя.
        with _Сервер({"product": "ЧужойПродукт"}) as с:
            итог = осмотр({**чистый, "panel_port": с.port, "product_ru": "НашПродукт"}, быстрый=True)
            требовать("порт" in _бед_имена(итог), "не поймана чужая программа на порту")
        with _Сервер({"product": "НашПродукт 1.2"}) as с:
            итог = осмотр({**чистый, "panel_port": с.port, "product_ru": "НашПродукт"}, быстрый=True)
            требовать("панель" in {ч["name"] for ч in итог["checks"] if ч["ok"]},
                      "своя панель на порту не опознана")

        # E · платформа недоступна (полный режим, заведомо мёртвый адрес).
        итог = осмотр({**чистый, "platform": "http://127.0.0.1:1/health"}, быстрый=False)
        требовать("сеть" in _бед_имена(итог), "не поймана недоступная платформа")

        # F · сбитые часы: локальный сервер отдаёт Date на сутки назад.
        сутки_назад = email.utils.formatdate(time.time() - 86400, usegmt=True)
        with _Сервер({"ok": True}, дата=сутки_назад) as с:
            итог = осмотр({**чистый, "platform": "http://127.0.0.1:%d/health" % с.port},
                          быстрый=False)
            требовать("часы" in _бед_имена(итог), "не пойманы сбитые часы устройства")

        # C · устройство-исполнитель спит, и наоборот — отвечает.
        def спит():
            raise RuntimeError("Target is unavailable")
        итог = осмотр({**чистый, "executor": спит}, быстрый=False)
        требовать("исполнитель" in _бед_имена(итог), "не пойман спящий исполнитель")
        итог = осмотр({**чистый, "executor": lambda: None}, быстрый=False)
        требовать("исполнитель" in {ч["name"] for ч in итог["checks"] if ч["ok"]},
                  "живой исполнитель ошибочно признан спящим")

        # E · app_scopes не выданы (403), и наоборот — выданы.
        def без_прав():
            raise RuntimeError("HTTP 403 Forbidden")
        итог = осмотр({**чистый, "scopes_probe": без_прав}, быстрый=False)
        требовать("права" in _бед_имена(итог), "не пойманы невыданные app_scopes")
        итог = осмотр({**чистый, "scopes_probe": lambda: None}, быстрый=False)
        требовать("права" in {ч["name"] for ч in итог["checks"] if ч["ok"]},
                  "выданные права ошибочно признаны невыданными")

        # CLI · «продукт не принял доктора» — не успех.
        пустой = основа / "пустой_продукт"
        пустой.mkdir()
        требовать(тихо(str(пустой), полный=False, как_json=True) == 2,
                  "продукт без паспорта прошёл как успех")

        # CLI · паспорт из файла читается и продукт проходит.
        готовый = основа / "готовый_продукт"
        готовый.mkdir()
        (готовый / "doctor_passport.json").write_text(json.dumps(
            {"min_python": [3, 6], "modules": ["os"], "data_dir": str(готовый / "d"),
             "min_free_mb": 1}), encoding="utf-8")
        требовать(тихо(str(готовый), полный=False, как_json=True) == 0,
                  "здоровый продукт с паспортом не прошёл")

    for п in провалы:
        print("  ✗ %s" % п)
    print("selftest доктора среды: %s (%d из %d проверок класса)"
          % ("провален" if провалы else "пройден", всего - len(провалы), всего))
    return 1 if провалы else 0


def main(аргументы: list[str]) -> int:
    парсер = argparse.ArgumentParser(
        prog="extella_doctor",
        description="Доктор среды Extella: рантайм-самопроверка приложения по паспорту.")
    парсер.add_argument("продукт", nargs="?",
                        help="абсолютный путь к каталогу продукта (с паспортом доктора)")
    парсер.add_argument("--selftest", action="store_true",
                        help="проверить сам доктор: ловит ли посаженные беды и зелен ли на чистом")
    парсер.add_argument("--full", "--полный", dest="полный", action="store_true",
                        help="полный осмотр: сеть, часы, права, исполнитель (секунды)")
    парсер.add_argument("--json", dest="как_json", action="store_true",
                        help="машинный отчёт (без секретов и данных клиента)")
    арг = парсер.parse_args(аргументы)

    if арг.selftest:
        return selftest()
    if not арг.продукт:
        парсер.error("укажите путь к продукту или --selftest")
    return запустить_на_продукте(арг.продукт, арг.полный, арг.как_json)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
