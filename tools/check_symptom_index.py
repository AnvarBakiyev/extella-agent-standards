"""Вход по симптому не отстал от свода (SYMPTOMS.md против DEPLOY_REQUIREMENTS.md).

ЗАЧЕМ. Свод перевалил за шесть десятков разделов, и подряд его не читают — в него
заглядывают, когда уже сломалось. Значит ценность держится не на полноте, а на
находимости по симптому. Вход, который никто не проверяет, отстаёт за неделю: раздел
добавили, строку про него не завели, и человек с белым экраном свод не находит.

ЧТО ПРОВЕРЯЕТСЯ:

  ссылка ведёт куда-то   — каждый номер из входа существует в своде
  ничего не выпало       — каждый раздел свода назван либо в таблице симптомов,
                           либо в списке «без внешнего симптома»
  решение, а не пропуск  — раздел не может быть одновременно там и там

Список «без симптома» — не поблажка, а обязательное решение: отсутствие раздела во
входе становится записанным выбором, а не забывчивостью. Тот же принцип, что у журнала
находок: ноль и «не смотрели» — разные вещи.

    python3 tools/check_symptom_index.py
    python3 tools/check_symptom_index.py --selftest
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
СВОД = КОРЕНЬ / "DEPLOY_REQUIREMENTS.md"
ВХОД = КОРЕНЬ / "SYMPTOMS.md"
ЗАГОЛОВОК_БЕЗ = "## Разделы без внешнего симптома"
НОМЕР = re.compile(r"\bH\d+(?:-[А-Яа-яЁё]+)?")


def разделы_свода(текст: str) -> set:
    return set(re.findall(r"^#{2,3} (H\d+(?:-[А-Яа-яЁё]+)?)\.", текст, re.M))


def разбор_входа(текст: str):
    """Возвращает названные в таблицах и названные в списке «без симптома»."""
    место = текст.find(ЗАГОЛОВОК_БЕЗ)
    верх, низ = (текст[:место], текст[место:]) if место >= 0 else (текст, "")
    # В таблицах берём только столбец «куда»: первый столбец — слова человека,
    # и номер раздела там оказаться не должен.
    в_таблицах = set()
    for строка in верх.splitlines():
        if строка.startswith("|") and строка.count("|") >= 4:
            куда = строка.split("|")[2]
            в_таблицах.update(НОМЕР.findall(куда))
    return в_таблицах, set(НОМЕР.findall(низ))


def проверить(свод: str, вход: str) -> list:
    есть = разделы_свода(свод)
    в_таблицах, без_симптома = разбор_входа(вход)
    беды = []

    висячие = sorted((в_таблицах | без_симптома) - есть)
    if висячие:
        беды.append("во входе названы разделы, которых в своде нет: " + ", ".join(висячие))

    оба = sorted(в_таблицах & без_симптома)
    if оба:
        беды.append("раздел и в таблице, и в списке без симптома — решение неоднозначно: "
                    + ", ".join(оба))

    пропали = sorted(есть - в_таблицах - без_симптома)
    if пропали:
        беды.append("разделы свода не названы во входе ни строкой, ни списком: "
                    + ", ".join(пропали))
    return беды


def _selftest() -> int:
    беды = []
    свод = ("### H1. Раз\n\n### H2. Два\n\n### H3-бис. Три\n\n### H2-П. Приложение\n")
    добрый = ("| что видно | куда | действие |\n"
              "|---|---|---|\n"
              "| белый экран | H1 | смотреть |\n"
              + ЗАГОЛОВОК_БЕЗ + "\n\nH2, H3-бис, H2-П.\n")

    def случай(подпись, вход, ожидаемое):
        найдено = проверить(свод, вход)
        если_есть = any(ожидаемое in б for б in найдено)
        if (ожидаемое == "" and not найдено) or (ожидаемое and если_есть):
            print(f"  ✓ {подпись}")
        else:
            беды.append(f"{подпись}: ответ {найдено}")

    случай("полный вход проходит", добрый, "")
    случай("несуществующий раздел пойман",
           добрый.replace("H1", "H99"), "которых в своде нет")
    случай("выпавший раздел пойман",
           добрый.replace("H2, H3-бис, H2-П.", "H2, H2-П."), "не названы во входе")
    случай("раздел в обоих списках пойман",
           добрый.replace("H2, H3-бис, H2-П.", "H1, H2, H3-бис, H2-П."), "решение неоднозначно")
    # Номер в столбце симптома — не ссылка: там слова человека. Если раздел
    # назван только там, он считается неназванным, и это ловится.
    случай("номер в описании симптома ссылкой не считается",
           добрый.replace("| белый экран | H1 |", "| ошибка H1 на экране | — |"),
           "не названы во входе")

    if беды:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(беды))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


def main(аргументы: list) -> int:
    if "--selftest" in аргументы:
        return _selftest()
    if not ВХОД.is_file():
        print("нет SYMPTOMS.md — входа по симптому не существует")
        return 1
    беды = проверить(СВОД.read_text(encoding="utf-8"), ВХОД.read_text(encoding="utf-8"))
    if беды:
        print(f"вход по симптому отстал от свода, расхождений {len(беды)}:")
        for б in беды:
            print("   -", б)
        return 1
    print("вход по симптому покрывает свод целиком")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
