#!/usr/bin/env python3
"""Окно ОС для приложения, которое живёт на этом компьютере.

ЗАЧЕМ ИНСТРУМЕНТ, А НЕ ТРИ ФАЙЛА. Страницы-обёртки отличаются четырьмя строчками:
имя, адрес, чем проверять доступность, подпись. Скопированные руками, они начинают
расходиться на второй правке — а расхождение здесь тихое: на одной странице чинишь
запасной путь, на двух других он остаётся сломанным. Поэтому каркас один
(templates/local_app_page.html), а различия задаются описанием.

    python3 tools/make_local_app_page.py products/пример
    python3 tools/make_local_app_page.py --все products
    python3 tools/make_local_app_page.py --selftest

Описание берётся из app.json рядом:

    {"имя": "Схемы", "порт": 34786, "путь": "/?offline=1&lang=ru",
     "проба": "/images/spin.gif", "подпись": "…"}

«Проба» — маленький существующий файл приложения. Проверять надо ИМЕННО его, а не
корень: корень у некоторых приложений отдаётся из кэша service worker'а даже когда
сервер мёртв, и проверка становится ложно-зелёной.
"""

import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ШАБЛОН = КОРЕНЬ / "templates" / "local_app_page.html"


def собрать(описание: dict) -> str:
    порт = int(описание["порт"])
    путь = описание.get("путь", "/")
    if путь in ("", "/"):
        # ВОСЬМАЯ ДВЕРЬ (замер 21.08.2026, Заметки и PDF-инструменты). Окно ОС
        # снимает загрузочную шторку по адресу окна: маршрут «/» она считает
        # незавершённым переходом роутера и ждёт настоящего маршрута ВЕЧНО —
        # приложение внутри работает, а человек видит логотип Extella. Спасаются
        # только те приложения, что сами уходят с корня (tududi → /today).
        # Лечение: открывать окно на явном маршруте (memos → /explore,
        # stirling → /home).
        print(f"  ! окно откроется на голом «/» — ОС может держать шторку. "
              f"Задайте маршрут: --путь /home (см. docs/DOCKER_APP_TRACK.md)")
    адрес = f"http://localhost:{порт}{путь}"
    проба = f"http://localhost:{порт}{описание['проба']}"
    подпись = описание.get("подпись") or f"адрес: localhost:{порт} · всё на этом компьютере"
    # Разведчик лежит РЯДОМ С ПРИЛОЖЕНИЕМ: только свой файл может изнутри проверить,
    # дали ли окну хранилище. Снаружи чужое происхождение не прочитать.
    # Пробу теперь несёт сама страница приложения (tools/inject_probe.py), поэтому
    # отдельный адрес разведчика больше не нужен — метка остаётся пустой.
    разведчик = ""
    страница = ШАБЛОН.read_text()
    for метка, значение in (("%ИМЯ%", описание["имя"]), ("%АДРЕС%", адрес),
                            ("%ПРОБА%", проба), ("%РАЗВЕДЧИК%", разведчик),
                            ("%ПОДПИСЬ%", подпись)):
        страница = страница.replace(метка, значение)
    осталось = [м for м in ("%ИМЯ%", "%АДРЕС%", "%ПРОБА%", "%РАЗВЕДЧИК%", "%ПОДПИСЬ%")
                if м in страница]
    if осталось:
        raise SystemExit(f"в шаблоне остались незаполненные метки: {осталось}")
    return страница


def собрать_папку(папка: pathlib.Path) -> int:
    файл = папка / "app.json"
    if not файл.exists():
        print(f"{папка.name}: нет app.json — не местное приложение, пропускаю")
        return 0
    описание = json.loads(файл.read_text())
    # ОБЁРТКА ОКНА И САМО ПРИЛОЖЕНИЕ — РАЗНЫЕ ФАЙЛЫ С ОДНИМ ИМЕНЕМ. У окна это
    # тонкая страница с рамкой и строкой агента; у приложения — весь его код.
    # Положив первое поверх второго, теряешь приложение целиком и молча: имя
    # совпало, размер похож (замер 23.08.2026 — так было затёрто приложение
    # «Документы», спасла только копия в кэше браузера). Проверяем, чем
    # является файл, ПЕРЕД записью.
    цель = папка / "index.html"
    if цель.exists():
        было = цель.read_text(errors="ignore")
        своё = "%АДРЕС%" in ШАБЛОН.read_text() and "extella-окно" in было
        if not своё and len(было) > 8000 and "<iframe" not in было:
            raise SystemExit(
                f"в {цель} лежит НЕ обёртка окна, а что-то своё "
                f"({len(было)} знаков). Похоже на само приложение — перезапись "
                f"стёрла бы его без следа. Уберите файл руками, если правда "
                f"хотите обёртку")
    цель.write_text(собрать(описание))
    print(f"  {описание['имя']}: окно собрано → localhost:{описание['порт']}")
    return 0


def _selftest() -> int:
    провалы = []
    образец = {"имя": "Схемы", "порт": 34786, "путь": "/?offline=1",
               "проба": "/images/spin.gif"}
    стр = собрать(образец)

    проверки = [
        ("имя подставлено", "<title>Схемы</title>" in стр),
        ("адрес подставлен", "http://localhost:34786/?offline=1" in стр),
        ("проба отдельным файлом", "34786/images/spin.gif" in стр),
        ("подпись по умолчанию", "localhost:34786 · всё на этом компьютере" in стр),
        # Ищем НЕЗАМЕНЁННЫЕ МЕТКИ, а не знак процента вообще. Прежняя проверка
        # спотыкалась о комментарий «открывается на 1% масштаба» и о любые
        # проценты в стилях: провал горел красным, хотя все метки подставлены.
        # Проверка, которая врёт про исправное, обесценивает все остальные.
        ("меток не осталось", not __import__("re").search(r"%[А-ЯA-Z_]+%", стр)),
        ("проверка доступности есть", "fetch(ПРОБА" in стр),
        # «Открыть отдельным окном» снято 20.08.2026: отдельное окно Электрона
        # наследует ту же песочницу, совет был легендой и вёл человека в белизну.
        ("отдельного окна больше не советуем", 'target="_blank"' not in стр),
        # Строка агента — общая шапка каждого окна (решение Анвара 20.08.2026):
        # команда живёт там, где взгляд, пульт-посредник снят.
        ("строка агента в шапке", 'id="фраза"' in стр and "_extella_action" in стр),
        ("фраза едет с именем окна", "окно: ОКНО_ИМЯ" in стр),
        ("ожидание видно и повтор заблокирован",
         "сказать_.disabled = true" in стр and ".finally(" in стр),
        # Перезагрузить себя из песочницы приложение не может — обёртка обязана
        # уметь перечитать рамку и по просьбе приложения, и по метке диспетчера.
        ("окно перечитывается по просьбе приложения", "extella_перечитать" in стр),
        # Обновления — кнопкой, не насилием (слово Анвара 21.08.2026):
        # перезагрузка посреди набора съедала ввод и сбрасывала ячейку.
        ("чужая правка предлагает кнопку, а не перезагружает",
         "extella_обновление_ждёт" in стр and 'id="полоска_обновить"' in стр),
        ("метка диспетчера перечитывает окно", "[окно-обновится]" in стр),
        ("вердикт слушается от самого приложения", "extella_проба" in стр),
        # ГЛАВНОЕ ПРАВИЛО ОКНА (16.08.2026). Приложение показывается СРАЗУ, до
        # всяких проверок. Раньше впереди стоял экран-сторож; на живой Доске
        # схем он молчал при полностью исправном приложении — проверка идёт из
        # интернета к вам на компьютер, а браузер такие запросы режет. Сторож
        # прятал работающее и выталкивал человека в отдельное окно.
        ("приложение вставляется сразу, без сторожа",
         "окно_.src = АДРЕС;\nокно_.style.display = 'block';" in стр),
        ("проверка ушла в фон, после вставки",
         стр.index("окно_.src = АДРЕС;\nокно_") < стр.index("fetch(ПРОБА")),
        # Молчание проверки — не доказательство поломки. Оно даёт полоску с
        # выходом, но окно остаётся человеку.
        ("молчание даёт полоску, а не карточку", "полоской(" in стр),
        ("полоску можно закрыть, не теряя окно", 'id="полоска_закрыть"' in стр),
        # Перекрывать окно можно только настоящей бедой: работа не сохранится
        # либо приложения нет вовсе.
        ("карточка остаётся для настоящей беды",
         "не запущено" in стр and "закрывает хранилище" in стр),
    ]
    print("Самопроверка make_local_app_page:")
    for имя, ок in проверки:
        print(("  ✓ " if ок else "  ✗ ") + имя)
        if not ок:
            провалы.append(имя)

    # Описание без обязательного поля обязано падать, а не собирать полустраницу.
    try:
        собрать({"имя": "Без пробы", "порт": 1})
        провалы.append("описание без «проба» не отказало")
        print("  ✗ описание без «проба» не отказало")
    except KeyError:
        print("  ✓ описание без «проба» отказывает")

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    if sys.argv[1] == "--все":
        корень = pathlib.Path(sys.argv[2])
        for п in sorted(корень.iterdir()):
            if п.is_dir():
                собрать_папку(п)
        sys.exit(0)
    sys.exit(собрать_папку(pathlib.Path(sys.argv[1])))
