#!/usr/bin/env python3
"""Окно ОС для приложения, которое живёт на этом компьютере.

ЗАЧЕМ ИНСТРУМЕНТ, А НЕ ТРИ ФАЙЛА. Страницы-обёртки отличаются четырьмя строчками:
имя, адрес, чем проверять доступность, подпись. Скопированные руками, они начинают
расходиться на второй правке — а расхождение здесь тихое: на одной странице чинишь
запасной путь, на двух других он остаётся сломанным. Поэтому каркас один
(templates/local_app_page.html), а различия задаются описанием.

    python3 tools/make_local_app_page.py editions/diagrams
    python3 tools/make_local_app_page.py --все editions
    python3 tools/make_local_app_page.py --selftest

Описание берётся из app.json рядом:

    {"имя": "Схемы", "порт": 34786, "путь": "/?offline=1&lang=ru",
     "проба": "/images/spin.gif", "подпись": "…"}

«Проба» — маленький существующий файл приложения. Проверять надо ИМЕННО его, а не
корень: корень у некоторых приложений отдаётся из кэша service worker'а даже когда
сервер мёртв, и проверка становится ложно-зелёной.
"""

import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ШАБЛОН = КОРЕНЬ / "templates" / "local_app_page.html"


def собрать(описание: dict) -> str:
    порт = int(описание["порт"])
    адрес = f"http://localhost:{порт}{описание.get('путь', '/')}"
    проба = f"http://localhost:{порт}{описание['проба']}"
    подпись = описание.get("подпись") or f"адрес: localhost:{порт} · всё на этом компьютере"
    # Разведчик лежит РЯДОМ С ПРИЛОЖЕНИЕМ: только свой файл может изнутри проверить,
    # дали ли окну хранилище. Снаружи чужое происхождение не прочитать.
    # Пробу теперь несёт сама страница приложения (tools/inject_probe.py), поэтому
    # отдельный адрес разведчика больше не нужен — метка остаётся пустой.
    разведчик = ""
    страница = ШАБЛОН.read_text()
    for метка, значение in (("%ИМЯ%", описание["имя"]), ("%АДРЕС%", адрес),
                            ("%ПРОБА%", проба), ("%РАЗВЕДЧИК%", разведчик),
                            ("%ПОДПИСЬ%", подпись)):
        страница = страница.replace(метка, значение)
    осталось = [м for м in ("%ИМЯ%", "%АДРЕС%", "%ПРОБА%", "%РАЗВЕДЧИК%", "%ПОДПИСЬ%")
                if м in страница]
    if осталось:
        raise SystemExit(f"в шаблоне остались незаполненные метки: {осталось}")
    return страница


def собрать_папку(папка: pathlib.Path) -> int:
    файл = папка / "app.json"
    if not файл.exists():
        print(f"{папка.name}: нет app.json — не местное приложение, пропускаю")
        return 0
    описание = json.loads(файл.read_text())
    (папка / "index.html").write_text(собрать(описание))
    print(f"  {описание['имя']}: окно собрано → localhost:{описание['порт']}")
    return 0


def _selftest() -> int:
    провалы = []
    образец = {"имя": "Схемы", "порт": 34786, "путь": "/?offline=1",
               "проба": "/images/spin.gif"}
    стр = собрать(образец)

    проверки = [
        ("имя подставлено", "<title>Схемы</title>" in стр),
        ("адрес подставлен", "http://localhost:34786/?offline=1" in стр),
        ("проба отдельным файлом", "34786/images/spin.gif" in стр),
        ("подпись по умолчанию", "localhost:34786 · всё на этом компьютере" in стр),
        ("меток не осталось", "%" not in стр.replace("width:100%", "").replace("height:100%", "")),
        # Запасной путь — главное, ради чего этот шаблон существует.
        ("проверка доступности перед вставкой", "fetch(ПРОБА" in стр),
        ("кнопка отдельного окна", 'target="_blank"' in стр),
        ("вердикт слушается от самого приложения", "extella_проба" in стр),
        # Таймер здесь не угадывает «наверное, загрузилось»: он ловит МОЛЧАНИЕ
        # пробы и трактует его как отказ, а не как успех.
        ("молчание считается отказом", "проба молчит" in стр),
        ("карточка перебивает открытое окно", "решено = true;\n  окно_.style.display" in стр),
    ]
    print("Самопроверка make_local_app_page:")
    for имя, ок in проверки:
        print(("  ✓ " if ок else "  ✗ ") + имя)
        if not ок:
            провалы.append(имя)

    # Описание без обязательного поля обязано падать, а не собирать полустраницу.
    try:
        собрать({"имя": "Без пробы", "порт": 1})
        провалы.append("описание без «проба» не отказало")
        print("  ✗ описание без «проба» не отказало")
    except KeyError:
        print("  ✓ описание без «проба» отказывает")

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    if sys.argv[1] == "--все":
        корень = pathlib.Path(sys.argv[2])
        for п in sorted(корень.iterdir()):
            if п.is_dir():
                собрать_папку(п)
        sys.exit(0)
    sys.exit(собрать_папку(pathlib.Path(sys.argv[1])))
