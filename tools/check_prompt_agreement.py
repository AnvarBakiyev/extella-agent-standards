#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Копируемый промпт живёт в двух местах — и они обязаны говорить одно (H112, H78).

ЗАЧЕМ. Промпт для внешнего агента существует дважды: `PROMPT_FOR_EXTERNAL_AGENT.md`
в репозитории и блок «Скопировать» в приложении «Разработка на Extella»
(`store_app/content.json`, раздел 05). Тексты НЕ совпадают дословно и не должны:
в приложении он короче. Но обещания в них обязаны совпадать — а расходятся копии
молча (H78).

Цена расхождения измерена: 28.09.2026 в обеих копиях стояла фраза «упрёшься в свой
предохранитель — поменяй исполнителя», то есть инструкция обходить собственную
защиту другой оболочкой (аудит, F06). Правку пришлось вносить в оба файла руками;
ничто не мешало починить один и забыть второй.

ЧТО ПРОВЕРЯЕТСЯ. Не равенство текстов, а согласие по существу:

  1. ОБЯЗАТЕЛЬНЫЕ обещания есть в ОБЕИХ копиях (каждое своим оборотом);
  2. ЗАПРЕЩЁННЫХ советов нет НИ В ОДНОЙ — это те, что уже стоили нам дня обучения;
  3. обе копии на месте и непусты.

КАКОГО РОДА ЭТА ПРОВЕРКА. Это ПРОВЕРКА ИСХОДНИКОВ: читаются два файла, сеть не
трогается. Зелёный результат означает «копии обещают одно», а не «промпт работает».

    python3 tools/check_prompt_agreement.py
    python3 tools/check_prompt_agreement.py --selftest

Коды выхода: 0 — копии согласны, 1 — разошлись или вернулся запрещённый совет.

ПРИЁМКА 28.09.2026: прогон по двум живым копиям зелёный; пять посевов пойманы.
Первый же боевой прогон упал NameError на опечатке в падеже — самопроверка в тот
момент была зелёной, потому что не запускала боевой путь; теперь запускает.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
РЕПО = КОРЕНЬ / "PROMPT_FOR_EXTERNAL_AGENT.md"
ПРИЛОЖЕНИЕ = КОРЕНЬ / "store_app" / "content.json"

# Каждое обещание — своим оборотом в каждой копии: тексты разной длины, и требовать
# дословного совпадения значит запретить приложению быть короче.
ОБЯЗАТЕЛЬНЫЕ = [
    ("не обходить запрет другим исполнителем",
     r"[Нн]е обходи запрет", r"[Нн]е обходи запрет"),
    ("назвать слой, который отказал",
     r"слой\s*\n?\s*отказал|какой слой", r"какой слой отказал"),
    ("ключ не просить в чат и своих токенов не создавать",
     r"не проси.{0,60}чат|не проси у меня в чат", r"[Нн]е проси присылать ключ в чат"),
    ("подключаться штатным установщиком",
     r"tools/connect_mcp\.py", r"tools/connect_mcp\.py"),
    ("связь проверяется вызовом, а не наличием файла",
     r"проверь связь реальным запросом|связь.{0,40}запросом",
     r"[Сс]вязь проверь запросом списка агентов"),
    ("ключ на диске может отсутствовать — это норма",
     r"на диск не кладёт|может не быть", r"на диске может не быть|его туда не кладёт"),
]

# Советы, каждый из которых уже стоил нам живого времени.
ЗАПРЕЩЁННЫЕ = [
    ("обход защиты сменой исполнителя (F06)", r"[Пп]оменяй исполнителя"),
    ("обещание, что ключ появится на диске сам (H110)",
     r"ключ появится (на диске )?сам|просто открой приложение"),
    ("остановка на пустом ответе (F05)", r"пусто\s*—\s*остановись|или пусто"),
    ("рукопожатие как доказательство подключения (H81, поправка 28.09)",
     r"рукопожатие.{0,40}доказательств|проверено рукопожатием"),
]


def текст_приложения(путь: pathlib.Path) -> str:
    """Тело раздела с копируемым промптом. Ищем по содержимому, а не по номеру:
    разделы переставляют, и привязка к индексу — это та же молча расходящаяся копия."""
    данные = json.loads(путь.read_text(encoding="utf-8"))
    куски = []
    for раздел in данные.get("разделы", []):
        тело = раздел.get("тело") or ""
        if "connect_mcp.py" in тело and "class=\"copy\"" in тело:
            куски.append(тело)
    return "\n".join(куски)


def разбор(репо_текст: str, прил_текст: str) -> list[str]:
    беды = []
    if len(репо_текст.strip()) < 400:
        беды.append("копия в репозитории пуста или подозрительно коротка")
    if len(прил_текст.strip()) < 400:
        беды.append("копируемого блока в приложении нет — кнопка «Копировать» "
                    "потеряла текст")
        return беды

    for имя, реп, прил in ОБЯЗАТЕЛЬНЫЕ:
        # re.S обязателен: в файле репозитория обещания перенесены по
        # строкам, и без него «не проси\nу меня в чат» не находится.
        в_репо = re.search(реп, репо_текст, re.S) is not None
        в_прил = re.search(прил, прил_текст, re.S) is not None
        if в_репо and в_прил:
            continue
        где = ("в приложении" if в_репо else
               "в репозитории" if в_прил else "в обеих копиях")
        беды.append(f"обещание «{имя}» отсутствует {где}")

    for имя, образец in ЗАПРЕЩЁННЫЕ:
        for копия, текст in (("репозиторий", репо_текст), ("приложение", прил_текст)):
            if re.search(образец, текст, re.S):
                беды.append(f"вернулся запрещённый совет — {имя} ({копия})")
    return беды


def прогон() -> int:
    if not РЕПО.exists():
        print("  ✗ нет PROMPT_FOR_EXTERNAL_AGENT.md")
        return 1
    беды = разбор(РЕПО.read_text(encoding="utf-8"), текст_приложения(ПРИЛОЖЕНИЕ))
    for б in беды:
        print("  ✗ " + б)
    if беды:
        print("\nНЕ УСПЕХ: копии промпта разошлись. Правится ОБЕ — файл репозитория "
              "и store_app/content.json, после чего store_app/build.py.")
        return 1
    print("ПРОВЕРКА ИСХОДНИКОВ пройдена: обе копии промпта обещают одно, "
          f"запрещённых советов нет (обязательных обещаний {len(ОБЯЗАТЕЛЬНЫЕ)}, "
          f"запретов {len(ЗАПРЕЩЁННЫЕ)}).")
    return 0


def selftest() -> int:
    """Посев: каждый дефект обязан ловиться, иначе это проверка ради галочки."""
    провалы = []
    репо = РЕПО.read_text(encoding="utf-8")
    прил = текст_приложения(ПРИЛОЖЕНИЕ)

    print("Самопроверка check_prompt_agreement:")
    if разбор(репо, прил):
        провалы.append("живые копии объявлены расходящимися — ложная тревога")
    print("  ✓ на живых копиях тревоги нет")

    # 1. Запрещённый совет вернулся в приложение.
    if not разбор(репо, прил + "\nПоменяй исполнителя: ту же работу сделает эксперт."):
        провалы.append("возврат обхода защиты в приложение не пойман")
    print("  ✓ возврат обхода защиты ловится")

    # 2. Обязательное обещание пропало из репозитория.
    урезанный = репо.replace("Не обходи запрет", "Ну ладно")
    if not разбор(урезанный, прил):
        провалы.append("пропажа обещания в репозитории не поймана")
    print("  ✓ пропажа обязательного обещания ловится")

    # 3. Блок в приложении исчез целиком.
    if not разбор(репо, ""):
        провалы.append("исчезновение копируемого блока не поймано")
    print("  ✓ исчезновение блока в приложении ловится")

    # 4. Вернулось «пусто — остановись».
    if not разбор(репо + "\nОшибка или пусто — остановись.", прил):
        провалы.append("возврат остановки на пустом ответе не пойман")
    print("  ✓ возврат остановки на пустом ответе ловится")

    # 5. Блок ищется по содержимому, а не по номеру раздела.
    if "разделы\"][4]" in pathlib.Path(__file__).read_text(encoding="utf-8"):
        провалы.append("блок привязан к номеру раздела — переставят и проверка ослепнет")
    print("  ✓ блок ищется по содержимому, а не по номеру раздела")

    # БОЕВОЙ ПУТЬ ТОЖЕ ПРОГОНЯЕТСЯ. Без этого самопроверка была зелёной в тот
    # момент, когда прогон() падал NameError на опечатке в падеже.
    import contextlib, io
    тихо = io.StringIO()
    try:
        with contextlib.redirect_stdout(тихо):
            код = прогон()
    except Exception as о:
        провалы.append(f"боевой прогон падает: {type(о).__name__}: {о}")
    else:
        if код != 0:
            провалы.append("боевой прогон красный на живых копиях")
    print("  ✓ боевой прогон выполняется и зелёный")

    if провалы:
        for п in провалы:
            print("  ✗ " + п)
        print("ИТОГ САМОПРОВЕРКИ: провалы есть")
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    # H118: узкая консоль Windows (cp1252) роняет печать по-русски на первом символе.
    import sys as _sys
    for _поток in (_sys.stdout, _sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass
    sys.exit(selftest() if "--selftest" in sys.argv else прогон())
