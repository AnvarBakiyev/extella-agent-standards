#!/usr/bin/env python3
"""Гейт принят, только если его прогнали по живому предмету (H114).

ЗАЧЕМ. Замер 25.09.2026 по всему набору: команда `run` в run_all_gates.sh
запускает ТОЛЬКО `--selftest`, то есть спрашивает у гейта «исправен ли ты» на
рукотворных пробах. Живой прогон — отдельная строка, и её не было у пяти
репозиторных гейтов. Что при этом скрылось:

  • `check_surface_classes` красный на живых данных — из 14 карточек стола у 11 не
    объявлен класс, плюс один паспорт не проходит по трём требованиям. В наборе
    гейт был зелёным всё это время;
  • `check_toolkit` не печатает ни строки за 120 секунд: на каждый тулкит он даёт
    подпроцессу 600 секунд. Его собственная самопроверка зовёт ту же функцию с
    `гонять_selftest=False` — то есть зелёная ИМЕННО ПОТОМУ, что обходит висящую
    ветку. Обход сделан параметром, а не случайно;
  • `check_agent_drift` возвращает 0 со словом «ПРОПУЩЕНО: паспортов не найдено» —
    из клона предмета нет, и пустота рапортуется успехом.

И три независимых случая того, что ПЕРВАЯ редакция гейта над текстом врёт на живом
дереве почти всегда: `check_device_pinning` дал 7 ложных тревог (минифицированные
чужие библиотеки, запись о цели, стрелки схем), `check_file_size_claims` — 2
(число привязано к соседнему файлу, кириллическое имя не увидено),
`check_counted_claims` — 4 из 7 («ни одна проверка», «самопроверка 10/10»,
«Проверка одна: закрой экран», «(21 проверка)» про самопроверку инструмента).

ЧТО ПРОВЕРЯЕТСЯ.

1. **Строка приёмки.** В шапке гейта, с начала строки и без обратных кавычек:
   слово ПРИЁМКА, дата, двоеточие и что дал прогон по живому предмету — сколько
   ложных тревог и что с ними стало. Дата обязательна: число ложных тревог —
   утверждение о прошлом замере (H113), без даты через месяц оно читается как
   «сейчас». Обратные кавычки исключены намеренно, иначе пример формата в
   документации считается выполненным требованием.
2. **Живой прогон в наборе.** Если гейт зарегистрирован строкой `run <имя>`, рядом
   обязана быть строка `run_command … <имя>.py` — кроме гейтов ПО ПРОДУКТУ, которым
   нужен аргумент: их зовёт `stage_gates` с целью, и запускать их в наборе нечем.
ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Третьим пунктом стояла проверка «самопроверка не обходит
предмет»: поиск выключающего флага вида `гонять_selftest=False` внутри selftest.
На живом прогоне она дала одно попадание, и оно оказалось ложным — в
`check_toolkit` флаг выключает предмет у СИНТЕТИЧЕСКОГО пустого тулкита, у которого
проверки нет вовсе, а настоящие тулкиты гоняются полностью. Одно попадание, один
ложный вызов — проверка снята, а не подкручена: ложная тревога дороже пропуска.
Настоящая причина зависания `check_toolkit` оказалась другой и починена по месту —
проверка формы ответа звала живую модель (до 180 секунд) и на машине без модели
молча не проверяла ничего; теперь она читает код и укладывается в 0,8 секунды.

ХРАПОВИК. Доля принятых гейтов записывается в `tools/gate_acceptance.json` и может
только расти. Флаг-дня нет намеренно: требовать строку приёмки сразу у всех — это
пятьдесят правок в один PR, которые никто не прочитает, и приёмка станет обрядом.

ПРИЁМКА 25.09.2026: прогон по 36 гейтам набора дал два попадания, и оба оказались
ошибками самой проверки — поиск обхода предмета сработал на синтетическом тулките
(снят целиком), а пример формата в шапке зачёлся за настоящую строку приёмки
(теперь требуется начало строки без обратных кавычек). После правок ложных нет.
Независимая приёмка 25.09.2026 на другом дереве (main плюс чужие изменения,
32 гейта): ложных тревог нет, все претензии по делу — четыре гейта стояли в
наборе только самопроверкой, и гейт справедливо не засчитывал даже те, у кого
живой прогон есть, пока строка приёмки не написана.

    python3 tools/check_gate_acceptance.py
    python3 tools/check_gate_acceptance.py --обновить
    python3 tools/check_gate_acceptance.py --selftest

Коды выхода: 0 — доля принятых не упала, 1 — упала.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
НАБОР = КОРЕНЬ / "tools" / "run_all_gates.sh"
ХРАПОВИК = КОРЕНЬ / "tools" / "gate_acceptance.json"

# Строка приёмки — с НАЧАЛА строки и без обратных кавычек. Иначе гейт зачитывает
# себе ПРИМЕР формата из собственной шапки: замер 25.09.2026, эта проверка
# насчитала 11,1% вместо 8,6%, потому что пример выглядел как утверждение.
ПРИЁМКА = re.compile(r"^ПРИЁМКА\s+(\d{2}\.\d{2}\.20\d{2})\s*:", re.MULTILINE)


def зарегистрированные(набор: str) -> tuple[set[str], set[str]]:
    """Гейты с самопроверкой в наборе и гейты с живым прогоном в наборе."""
    себя = set(re.findall(r"^run ([a-z_0-9]+)\s*$", набор, re.M))
    живьём = {м.group(1) for м in
              re.finditer(r'run_command "[^"]*" python3 "\$ROOT/tools/([a-z_0-9]+)\.py"', набор)}
    return себя, живьём


def нужен_аргумент(код: str) -> bool:
    """Гейт по продукту: без цели ему проверять нечего, в наборе его не зовут.

    Признак — код выхода 2 «проверять было нечего» описан в шапке, либо разбор
    обязательного позиционного аргумента.
    """
    return bool(re.search(r"add_argument\(\s*[\"'](?!--)", код)
                or "2 — проверять было нечего" in код
                or "2 — каталог" in код
                or "2 — файлы не прочитаны" in код
                or "2 — неверный вызов" in код)


def беды() -> tuple[list[str], int, int]:
    плохо: list[str] = []
    if not НАБОР.exists():
        return ["нет tools/run_all_gates.sh"], 0, 0
    набор = НАБОР.read_text(encoding="utf-8")
    себя, живьём = зарегистрированные(набор)

    принято = рассмотрено = 0
    for имя in sorted(себя):
        ф = КОРЕНЬ / "tools" / f"{имя}.py"
        if not ф.exists():
            плохо.append(f"{имя} зарегистрирован в наборе, но файла нет")
            continue
        код = ф.read_text(encoding="utf-8")
        if not имя.startswith("check_"):
            continue                      # инструменты действия приёмке не подлежат
        рассмотрено += 1

        есть_приёмка = bool(ПРИЁМКА.search(код))
        по_продукту = нужен_аргумент(код)
        есть_живой = имя in живьём
        if есть_приёмка and (есть_живой or по_продукту):
            принято += 1
    return плохо, принято, рассмотрено


def проверить(обновить: bool = False) -> int:
    плохо, принято, всего = беды()
    доля = (принято / всего * 100) if всего else 0.0
    было = 0.0
    if ХРАПОВИК.exists():
        было = float(json.loads(ХРАПОВИК.read_text(encoding="utf-8")).get("доля", 0))

    for б in плохо:
        print("  ✗ " + б)
    print(f"принято по H114: {принято} из {всего} гейтов набора ({доля:.1f}%)")

    if обновить:
        ХРАПОВИК.write_text(json.dumps({"доля": round(доля, 1), "принято": принято,
                                        "всего": всего}, ensure_ascii=False, indent=1) + "\n",
                            encoding="utf-8")
        print(f"Уровень записан: {доля:.1f}%")
        return 1 if плохо else 0

    if доля + 0.05 < было:
        print(f"\nНЕ УСПЕХ (H114): доля принятых упала с {было:.1f}% до {доля:.1f}%. "
              f"У нового гейта обязана быть строка ПРИЁМКА с датой и живой прогон "
              f"в наборе — либо осознанно опусти планку флагом --обновить.")
        return 1
    print(f"доля принятых не упала ({было:.1f}% → {доля:.1f}%)")
    return 0


def _selftest() -> int:
    провалы = []

    def проба(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    print("Самопроверка check_gate_acceptance:")

    набор = ('run check_a\n'
             'run_command "живьём" python3 "$ROOT/tools/check_a.py"\n'
             'run check_b\n')
    себя, живьём = зарегистрированные(набор)
    проба("самопроверяемые прочитаны", себя == {"check_a", "check_b"})
    проба("живой прогон прочитан", живьём == {"check_a"})

    проба("строка приёмки с датой распознана",
          bool(ПРИЁМКА.search("ПРИЁМКА 25.09.2026: прогон дал 4 ложные тревоги.")))
    проба("строка приёмки без даты не считается",
          not ПРИЁМКА.search("ПРИЁМКА: прогон дал 4 ложные тревоги."))
    проба("пример формата в кавычках за приёмку не считается",
          not ПРИЁМКА.search("   строка вида `ПРИЁМКА 25.09.2026: прогон дал N тревог`"))
    проба("приёмка не с начала строки не считается",
          not ПРИЁМКА.search("см. ПРИЁМКА 25.09.2026: прогон"))
    проба("гейт по продукту распознан по позиционному аргументу",
          нужен_аргумент('р.add_argument("папка")'))
    проба("репозиторный гейт по продукту не считается",
          not нужен_аргумент('р.add_argument("--selftest", action="store_true")'))

    проба("H114 назван в тексте проверки",
          "H114" in pathlib.Path(__file__).read_text(encoding="utf-8"))

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы — " + "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    sys.exit(проверить(обновить="--обновить" in sys.argv))
