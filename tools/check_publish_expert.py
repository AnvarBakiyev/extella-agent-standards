# -*- coding: utf-8 -*-
"""Эксперт выкладки проверяется исполнением, а не чтением (H119, H109; F07 аудита 28.09.2026).

ЗАЧЕМ. `experts/dev_publish_private.py` — готовый образец, который промпт велит
внешнему агенту запускать. 28.09.2026 в нём нашлись четыре дефекта сразу:

  * не слал `tags` — магазин отвечал HTTP 400, участник обучения встал на этом;
  * сухой прогон отвечал `status: success` и «Проверка прошла», хотя в сеть не ходил;
  * успех объявлялся по событию `done`, без перечитывания версии из листинга;
  * отдавал ссылку `/app-page/<id>/`, которая отвечает 401.

Эксперт живёт на устройстве и не имеет своей самопроверки, поэтому его проверял
только человек глазами. Этот гейт исполняет функцию эксперта здесь — в СУХОМ
режиме, без сети и без выкладки — и смотрит на ответ.

КАКОГО РОДА ЭТА ПРОВЕРКА. Поведение сухого пути и отказов — исполнением. Сетевой
путь (настоящая выкладка) здесь НЕ исполняется: он создал бы живой листинг. Для
него проверяется исходник: поле tags уходит в форму, успех требует перечитывания.

    python3 tools/check_publish_expert.py
    python3 tools/check_publish_expert.py --selftest

Коды выхода: 0 — эксперт ведёт себя честно, 1 — нет.

ПРИЁМКА 28.09.2026: прогон по живому эксперту выкладки дал четыре настоящих дефекта
(нет tags, сухой прогон = success, ссылка /app-page/ с 401, обещание приватности);
все исправлены. Одна ложная тревога — детектор цеплялся за комментарий «ссылки не
даём: /app-page/…» — устранена: ищется строковый литерал, а не упоминание.
"""

from __future__ import annotations

import json
import os
import pathlib
import re
import sys
import tempfile

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ЭКСПЕРТ = КОРЕНЬ / "experts" / "dev_publish_private.py"
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import platform_client  # noqa: E402  — канонный порядок источников ключа


def загрузить(исходник: str):
    пространство: dict = {}
    exec(compile(исходник, str(ЭКСПЕРТ), "exec"), пространство)
    return пространство["dev_publish_private"]


def разбор(исходник: str) -> list[str]:
    беды = []
    функция = загрузить(исходник)
    with tempfile.TemporaryDirectory() as вр:
        страница = pathlib.Path(вр) / "index.html"
        страница.write_text("<!doctype html><title>проба</title>", encoding="utf-8")
        прежний = os.environ.get("EXTELLA_API_TOKEN")
        # Подставной ключ: сухой путь не должен ходить в сеть ни с каким ключом.
        os.environ["EXTELLA_API_TOKEN"] = "проба-ключ-проба-ключ-проба"
        try:
            без_тегов = json.loads(функция(файл_страницы=str(страница), имя="Проба"))
            сухой = json.loads(функция(файл_страницы=str(страница), имя="Проба",
                                       теги="проба, учёт"))
        finally:
            if прежний is None:
                os.environ.pop("EXTELLA_API_TOKEN", None)
            else:
                os.environ["EXTELLA_API_TOKEN"] = прежний

    if без_тегов.get("status") != "error" or "тег" not in json.dumps(без_тегов, ensure_ascii=False):
        беды.append("без тегов эксперт не отказал до сети — магазин ответит 400")
    if сухой.get("status") == "success":
        беды.append("сухой прогон называет себя success — ложный зелёный")
    if сухой.get("в_сеть_ходили") is not False:
        беды.append("сухой прогон не говорит, что в сеть не ходил")
    if сухой.get("теги") != ["проба", "учёт"]:
        беды.append("теги не разобраны из строки через запятую")

    if not re.search(r'"tags"\s*:\s*json\.dumps', исходник):
        беды.append("поле tags не уходит в форму выкладки")
    # Ищем ССЫЛКУ в строковом литерале кода, а не упоминание: комментарий «ссылки
    # не даём: /app-page/ отвечает 401» — это как раз правильное поведение.
    код_после_описания = исходник.split('"""', 2)[-1]
    if re.search(r"""["'][^"'\n]*/app-page/""", код_после_описания):
        беды.append("эксперт отдаёт ссылку /app-page/ — она отвечает 401")
    if "версия_перечитана" not in исходник or '"unverified"' not in исходник:
        беды.append("успех объявляется без перечитывания версии")
    if "виден только владельцу" in исходник:
        беды.append("эксперт обещает приватность, которую платформа не подтвердила (§24)")

    # Порядок ключей — как у канона «магазин» (H78): копия обязана совпадать.
    файлы = re.findall(r'"(os_token\.txt|api_token\.txt)"', исходник)
    канон = [str(п.name) for м, п in platform_client.источники("магазин")
             if п is not None and п.suffix == ".txt"]
    if файлы[:2] != канон[:2]:
        беды.append(f"порядок ключей эксперта {файлы[:2]} разошёлся с каноном {канон[:2]}")
    return беды


def прогон() -> int:
    беды = разбор(ЭКСПЕРТ.read_text(encoding="utf-8"))
    for б in беды:
        print("  ✗ " + б)
    if беды:
        print("\nНЕ УСПЕХ: эксперт выкладки снова обманывает.")
        return 1
    print("ПРОВЕРКА ПОВЕДЕНИЕМ пройдена: без тегов — отказ до сети, сухой прогон честно "
          "не называет себя успехом, tags уходит в форму, успех требует перечитывания, "
          "ссылки /app-page/ нет, порядок ключей совпадает с каноном.")
    print("Настоящая выкладка здесь не исполнялась — она создала бы живой листинг.")
    return 0


def selftest() -> int:
    провалы = []
    живой = ЭКСПЕРТ.read_text(encoding="utf-8")
    print("Самопроверка check_publish_expert:")
    ложные = разбор(живой)
    if ложные:
        провалы.append("живой эксперт объявлен негодным — ложная тревога: " + "; ".join(ложные))
    else:
        print("  ✓ на живом эксперте тревоги нет")

    посевы = {
        "поле tags убрано из формы": живой.replace('"tags": json.dumps', '"tagz": json.dumps'),
        "сухой прогон снова success": живой.replace('"status": "dry_run"', '"status": "success"'),
        "вернулась ссылка /app-page/": живой.replace(
            '"где_найти": "ОС → Магазин → мои продукты → " + имя',
            '"где_найти": ОС + "/app-page/" + str(лид) + "/"'),
        "вернулось обещание приватности": живой.replace(
            "Листинг скрыт", "Черновик виден только владельцу. Листинг скрыт"),
    }
    было = len(провалы)
    for имя, посев in посевы.items():
        if посев == живой:
            провалы.append(f"посев «{имя}» не лёг — образец в эксперте сменился")
            continue
        if not разбор(посев):
            провалы.append(f"посев «{имя}» не пойман")
    if len(провалы) == было:
        print(f"  ✓ посевы ловятся ({len(посевы)} шт.)")

    import contextlib
    import io
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            код = прогон()
        if код != 0:
            провалы.append("боевой прогон красный на живом эксперте")
        else:
            print("  ✓ боевой прогон выполняется и зелёный")
    except Exception as о:                                       # noqa: BLE001
        провалы.append(f"боевой прогон падает: {type(о).__name__}: {о}")

    if провалы:
        for п in провалы:
            print("  ✗ " + п)
        print("ИТОГ САМОПРОВЕРКИ: провалы есть")
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors="replace")
        except Exception:                                        # noqa: BLE001
            pass
    sys.exit(selftest() if "--selftest" in sys.argv else прогон())
