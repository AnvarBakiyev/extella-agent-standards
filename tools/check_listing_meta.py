#!/usr/bin/env python3
"""Гейт витрины: иконка, описание, теги. Без них магазин превращается в свалку.

ЗАЧЕМ. Перепись 14.08.2026 по нашим десяти листингам:

    без иконки   — 4 из 10 (безымянный серый квадрат на столе, неотличимый от соседа)
    без описания — 3 из 10 (карточка «1С Agent AI», и всё; что это, знает только автор)
    имя с версией — встречается; листинг живёт годами, версия меняется еженедельно

Это не эстетика. Иконка — единственное, по чему человек находит окно среди двенадцати;
описание — единственное, по чему он решает, покупать ли; теги — единственное, по чему
магазин когда-нибудь соберёт полки. Пока продуктов пять, беспорядок незаметен. На
пятидесяти он необратим: чинить придётся вручную, каждую карточку, задним числом.

ВАЖНО ПРО ЯРЛЫКИ. У ярлыка на столе ОС полей меты нет вовсе: отправленные icon,
description и tags платформа молча проглатывает, а перечитывание отдаёт только
name и url (замер 14.08.2026). Поэтому мета живёт на уровне ЛИСТИНГА, и требовать
её надо там — иначе требование невыполнимо и гейт врёт.

    python3 tools/check_listing_meta.py products/пример
    python3 tools/check_listing_meta.py --selftest

Коды выхода: 0 — карточка готова к витрине, 1 — нет.
"""

import json
import pathlib
import re
import sys

# Вид продукта: по нему магазин соберёт полки, когда их сделают. Один тег обязателен
# из этого списка — иначе теги у каждого автора свои и полка не собирается никогда.
ВИДЫ = {"приложение", "издание", "агент", "демо", "инструмент"}

СЛУЖЕБНЫЕ = re.compile(r"\b(test|тест|проба|копия|copy|new|temp|tmp|черновик|draft)\b", re.I)
ВЕРСИЯ_В_ИМЕНИ = re.compile(r"\bv?\d+\.\d+(\.\d+)?\b|\bRC\d*\b|\bбета\b|\bbeta\b", re.I)
ТЕГ = re.compile(r"^[a-zа-яё0-9][a-zа-яё0-9-]{1,23}$")

МИН_ОПИСАНИЕ = 80          # короче — это подпись, а не описание
МАКС_ИМЯ = 40


def отказ(беды):
    print("КАРТОЧКА НЕ ГОТОВА К ВИТРИНЕ:")
    for b in беды:
        print("  ✗", b)
    return 1


def проверить(папка: pathlib.Path) -> int:
    файл = папка / "listing.json"
    if not файл.exists():
        print("нет listing.json — проверять нечего")
        return 0
    try:
        d = json.loads(файл.read_text())
    except json.JSONDecodeError as e:
        return отказ([f"listing.json не читается: {e}"])
    беды = []

    # 1. Иконка. Файл, а не обещание файла.
    иконка = папка / str(d.get("иконка") or "icon.png")
    if not иконка.exists():
        беды.append(f"нет иконки {иконка.name} — на столе продукт станет безымянным "
                    f"серым квадратом, неотличимым от соседнего")
    else:
        байты = иконка.read_bytes()
        if len(байты) < 500:
            беды.append(f"иконка {иконка.name} подозрительно мала ({len(байты)} байт) — "
                        f"похоже на заглушку, а не на картинку")
        if иконка.suffix.lower() == ".png" and not байты.startswith(b"\x89PNG"):
            беды.append(f"{иконка.name} назван png, но png не является")
        # Квадрат: несквадратная иконка в сетке стола обрежется по центру.
        if байты.startswith(b"\x89PNG") and len(байты) > 24:
            ш = int.from_bytes(байты[16:20], "big")
            в = int.from_bytes(байты[20:24], "big")
            if ш and в and abs(ш - в) > max(ш, в) * 0.02:
                беды.append(f"иконка не квадратная ({ш}×{в}) — стол обрежет её по центру")
            elif ш and ш < 128:
                беды.append(f"иконка {ш}×{в} — мелко: на ретине будет мылом, нужно от 128")

    # 2. Описание. Человек читает его ДО покупки, и другого источника у него нет.
    описание = str(d.get("описание") or d.get("description") or "").strip()
    if len(описание) < МИН_ОПИСАНИЕ:
        беды.append(f"описание {len(описание)} знаков (нужно от {МИН_ОПИСАНИЕ}) — "
                    f"по такой карточке нельзя решить, покупать ли")
    elif описание.lower().startswith(str(d.get("name") or "").lower()[:12]) \
            and len(описание) < МИН_ОПИСАНИЕ * 2:
        беды.append("описание начинается с повтора имени — имя человек уже прочитал, "
                    "описание отвечает «что делает и кому это нужно»")

    # 3. Теги. Без вида продукта полки не соберутся никогда.
    теги = d.get("теги") or d.get("tags") or []
    if isinstance(теги, str):
        теги = [т.strip() for т in теги.split(",") if т.strip()]
    if len(теги) < 2:
        беды.append(f"тегов {len(теги)} — нужно минимум два: вид продукта и тема")
    if len(теги) > 6:
        беды.append(f"тегов {len(теги)} — больше шести не тег, а облако: полки не соберутся")
    кривые = [т for т in теги if not ТЕГ.match(str(т))]
    if кривые:
        беды.append(f"теги не по форме {кривые} — только строчные, без пробелов, "
                    f"слова через дефис")
    if not (set(map(str, теги)) & ВИДЫ):
        беды.append(f"нет тега вида продукта — один из {sorted(ВИДЫ)}: по нему магазин "
                    f"соберёт полку, а человек поймёт, что он покупает")

    # 4. Имя. Листинг живёт годами, версия меняется еженедельно.
    имя = str(d.get("name") or d.get("имя") or "").strip()
    if not имя:
        беды.append("нет имени")
    else:
        if len(имя) > МАКС_ИМЯ:
            беды.append(f"имя {len(имя)} знаков — на столе обрежется, держи до {МАКС_ИМЯ}")
        if ВЕРСИЯ_В_ИМЕНИ.search(имя):
            беды.append(f"в имени версия («{имя}») — версия живёт в версии листинга, "
                        f"а в имени становится враньём через неделю")
        if СЛУЖЕБНЫЕ.search(имя):
            беды.append(f"в имени служебное слово («{имя}») — так называется черновик, "
                        f"а не продукт на витрине")

    if беды:
        return отказ(беды)
    print(f"Карточка «{имя}» готова к витрине:")
    print(f"  иконка: {иконка.name} · описание: {len(описание)} знаков · теги: {теги}")
    return 0


def _selftest() -> int:
    import struct
    import tempfile
    import zlib
    провалы = []

    def png(ш=256, в=256):
        """Настоящий png нужного размера: гейт читает заголовок, а не расширение."""
        сиг = b"\x89PNG\r\n\x1a\n"
        ihdr = struct.pack(">II", ш, в) + bytes([8, 6, 0, 0, 0])
        кусок = (struct.pack(">I", len(ihdr)) + b"IHDR" + ihdr
                 + struct.pack(">I", zlib.crc32(b"IHDR" + ihdr)))
        мусор = b"\x00" * 900
        idat = (struct.pack(">I", len(мусор)) + b"IDAT" + мусор
                + struct.pack(">I", zlib.crc32(b"IDAT" + мусор)))
        return сиг + кусок + idat

    ХОРОШАЯ = {
        "name": "Доска",
        "описание": "Бесконечная доска для набросков от руки: схемы, стрелки, подписи. "
                    "Открывается мгновенно, рисунки лежат на этом компьютере.",
        "теги": ["инструмент", "доска", "схемы"],
    }

    def случай(имя, карточка, ждём_провал, иконка=png()):
        with tempfile.TemporaryDirectory() as d:
            p = pathlib.Path(d)
            (p / "listing.json").write_text(json.dumps(карточка, ensure_ascii=False))
            if иконка is not None:
                (p / "icon.png").write_bytes(иконка)
            код = проверить(p)
            ок = (код != 0) if ждём_провал else (код == 0)
            print(("  ✓ " if ок else "  ✗ ") + имя)
            if not ок:
                провалы.append(имя)

    def без(ключ, значение=None):
        к = dict(ХОРОШАЯ)
        if значение is None:
            к.pop(ключ, None)
        else:
            к[ключ] = значение
        return к

    print("Самопроверка check_listing_meta:")
    случай("полная карточка проходит", ХОРОШАЯ, False)
    случай("нет иконки — ловится", ХОРОШАЯ, True, иконка=None)
    случай("иконка-заглушка — ловится", ХОРОШАЯ, True, иконка=b"\x89PNG" + b"\x00" * 40)
    случай("несквадратная иконка — ловится", ХОРОШАЯ, True, иконка=png(512, 256))
    случай("мелкая иконка — ловится", ХОРОШАЯ, True, иконка=png(64, 64))
    случай("не png под именем png — ловится", ХОРОШАЯ, True, иконка=b"GIF89a" + b"\x00" * 900)
    случай("пустое описание — ловится", без("описание", ""), True)
    случай("описание в одну строку — ловится", без("описание", "Доска для рисования"), True)
    случай("один тег — ловится", без("теги", ["доска"]), True)
    случай("тег с пробелом — ловится", без("теги", ["инструмент", "белая доска"]), True)
    случай("нет вида продукта — ловится", без("теги", ["доска", "схемы"]), True)
    случай("облако тегов — ловится",
           без("теги", ["инструмент", "a", "b", "c", "d", "e", "f"]), True)
    случай("версия в имени — ловится", без("name", "Доска v2.1"), True)
    случай("служебное слово в имени — ловится", без("name", "Доска (тест)"), True)
    случай("английские поля тоже читаются",
           {"name": "Board", "description": ХОРОШАЯ["описание"], "tags": ХОРОШАЯ["теги"]}, False)

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    sys.exit(проверить(pathlib.Path(sys.argv[1])))
