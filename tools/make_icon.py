#!/usr/bin/env python3
"""Иконка продукта одной командой — чтобы её не «нарисовать потом».

ЗАЧЕМ. Четыре наших листинга из десяти вышли без иконки. Не из-за лени: чтобы
нарисовать картинку, нужен редактор, палитра под рукой и полчаса, а продукт готов
сейчас. Пока иконка — отдельная работа, её не будет; поэтому она должна получаться
командой, из палитры Extella, без единого внешнего пакета.

    python3 tools/make_icon.py доска editions/board/icon.png
    python3 tools/make_icon.py --образцы /tmp        # все формы разом, посмотреть

Формы намеренно геометрические, без букв: буква в 64 пикселях нечитаема, а знак —
узнаётся. Рисуем в четыре раза крупнее и ужимаем: так края выходят гладкими без
всякой библиотеки.
"""

import pathlib
import struct
import sys
import zlib

РАЗМЕР = 512
СУПЕР = 4                      # рисуем крупнее, потом ужимаем — это и есть сглаживание

# Палитра Extella. Другой цвет в иконке — дефект, а не мелочь.
ЧЕРНИЛА = (10, 10, 10)
ЗОЛОТО = (212, 148, 74)
ПЕТРОЛЬ = (95, 168, 160)
БУМАГА = (245, 243, 238)


def _прямоугольник(x1, y1, x2, y2):
    return lambda x, y: x1 <= x <= x2 and y1 <= y <= y2


def _рамка(x1, y1, x2, y2, толщина):
    внутри = _прямоугольник(x1, y1, x2, y2)
    дырка = _прямоугольник(x1 + толщина, y1 + толщина, x2 - толщина, y2 - толщина)
    return lambda x, y: внутри(x, y) and not дырка(x, y)


def _круг(cx, cy, r):
    return lambda x, y: (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def _полоса(x1, y1, x2, y2, толщина):
    """Отрезок с толщиной: расстояние от точки до отрезка."""
    dx, dy = x2 - x1, y2 - y1
    длина2 = dx * dx + dy * dy or 1

    def внутри(x, y):
        t = max(0.0, min(1.0, ((x - x1) * dx + (y - y1) * dy) / длина2))
        px, py = x1 + t * dx, y1 + t * dy
        return (x - px) ** 2 + (y - py) ** 2 <= (толщина / 2) ** 2
    return внутри


# Знак = список слоёв (форма, цвет). Единица координат — доля от стороны иконки,
# чтобы форма не зависела от размера.
ЗНАКИ = {
    "доска": [(_рамка(.16, .22, .84, .74, .045), БУМАГА),
              (_полоса(.28, .62, .5, .38, .05), ЗОЛОТО),
              (_полоса(.5, .38, .62, .52, .05), ЗОЛОТО),
              (_круг(.72, .34, .045), ПЕТРОЛЬ)],
    "издание": [(_прямоугольник(.18, .2, .82, .3), ЗОЛОТО),
                (_прямоугольник(.18, .36, .82, .46), ПЕТРОЛЬ),
                (_прямоугольник(.18, .52, .82, .62), БУМАГА),
                (_прямоугольник(.18, .68, .58, .78), БУМАГА)],
    "приложение": [(_рамка(.18, .18, .82, .82, .05), БУМАГА),
                   (_круг(.5, .5, .13), ЗОЛОТО)],
    "агент": [(_круг(.5, .38, .15), ЗОЛОТО),
              (_полоса(.28, .78, .72, .78, .1), ПЕТРОЛЬ)],
    "инструмент": [(_полоса(.26, .74, .66, .34, .09), БУМАГА),
                   (_круг(.72, .28, .1), ЗОЛОТО)],
    "гид": [(_рамка(.2, .16, .8, .84, .045), БУМАГА),
            (_прямоугольник(.3, .3, .7, .36), ЗОЛОТО),
            (_прямоугольник(.3, .46, .7, .52), ПЕТРОЛЬ),
            (_прямоугольник(.3, .62, .56, .68), ПЕТРОЛЬ)],
}


def нарисовать(знак: str, размер: int = РАЗМЕР, фон=ЧЕРНИЛА) -> bytes:
    слои = ЗНАКИ.get(знак)
    if слои is None:
        raise SystemExit(f"нет знака «{знак}». Есть: {', '.join(sorted(ЗНАКИ))}")

    б = размер * СУПЕР
    крупно = [[фон] * б for _ in range(б)]
    for форма, цвет in слои:
        for y in range(б):
            fy = y / б
            строка = крупно[y]
            for x in range(б):
                if форма(x / б, fy):
                    строка[x] = цвет

    # Ужимаем: среднее по квадрату СУПЕР×СУПЕР даёт гладкий край.
    ряды = []
    for y in range(размер):
        ряд = bytearray()
        for x in range(размер):
            r = g = b_ = 0
            for dy in range(СУПЕР):
                строка = крупно[y * СУПЕР + dy]
                for dx in range(СУПЕР):
                    ц = строка[x * СУПЕР + dx]
                    r += ц[0]; g += ц[1]; b_ += ц[2]
            n = СУПЕР * СУПЕР
            ряд += bytes((r // n, g // n, b_ // n))
        ряды.append(bytes(ряд))

    сырое = b"".join(b"\x00" + р for р in ряды)

    def кусок(имя, данные):
        return (struct.pack(">I", len(данные)) + имя + данные
                + struct.pack(">I", zlib.crc32(имя + данные)))

    return (b"\x89PNG\r\n\x1a\n"
            + кусок(b"IHDR", struct.pack(">IIBBBBB", размер, размер, 8, 2, 0, 0, 0))
            + кусок(b"IDAT", zlib.compress(сырое, 9))
            + кусок(b"IEND", b""))


def _selftest() -> int:
    провалы = []
    for знак in ЗНАКИ:
        данные = нарисовать(знак, 128)
        ш = int.from_bytes(данные[16:20], "big")
        в = int.from_bytes(данные[20:24], "big")
        сдвиг = данные.index(b"IDAT")
        длина = int.from_bytes(данные[сдвиг - 4:сдвиг], "big")
        data_нач, data_кон = сдвиг + 4, сдвиг + 4 + длина
        # Иконка обязана быть png, квадратной и что-то изображать: сплошной квадрат
        # пройдёт любую проверку размера и при этом останется пустым местом.
        #
        # Считаем цвета по РАСПАКОВАННЫМ пикселям. Первый вариант этой проверки
        # считал их по сжатым байтам и «завалил» две исправные иконки: у форм с
        # прямыми краями сжатие плотнее, и разных байтов в архиве меньше. Проверка
        # мерила степень сжатия, а не картинку.
        пиксели = zlib.decompress(данные[data_нач:data_кон])
        счёт = {}
        for y in range(в):
            строка = пиксели[y * (ш * 3 + 1) + 1:(y + 1) * (ш * 3 + 1)]
            for i in range(0, len(строка), 3):
                ц = строка[i:i + 3]
                счёт[ц] = счёт.get(ц, 0) + 1
        всего = ш * в
        доля_фона = max(счёт.values()) / всего
        # Три цвета мало о чём говорят, а вот «фон занимает почти всё» — говорит прямо:
        # это пустой квадрат. Порог 0.92 держит даже самый сдержанный знак.
        # Размер файла тут ни при чём: плоский знак из прямоугольников сжимается
        # втрое плотнее рисованного и весит 390 байт, оставаясь правильной иконкой.
        # Судим по пикселям, не по весу.
        ок = (данные.startswith(b"\x89PNG") and ш == в == 128
              and len(счёт) >= 4 and доля_фона < 0.92)
        print(("  ✓ " if ок else "  ✗ ") + f"{знак}: {ш}×{в}, {len(данные)} байт, цветов {len(счёт)}, фон {доля_фона:.0%}")
        if not ок:
            провалы.append(знак)
    # Несуществующий знак обязан честно отказать, а не нарисовать пустоту.
    try:
        нарисовать("такого-нет", 64)
        провалы.append("неизвестный знак не отказал")
        print("  ✗ неизвестный знак не отказал")
    except SystemExit:
        print("  ✓ неизвестный знак отказывает честно")
    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    if "--образцы" in sys.argv:
        куда = pathlib.Path(sys.argv[sys.argv.index("--образцы") + 1])
        for знак in ЗНАКИ:
            (куда / f"icon_{знак}.png").write_bytes(нарисовать(знак))
            print("  ", куда / f"icon_{знак}.png")
        sys.exit(0)
    if len(sys.argv) < 3:
        print(__doc__)
        print("знаки:", ", ".join(sorted(ЗНАКИ)))
        sys.exit(2)
    цель = pathlib.Path(sys.argv[2])
    цель.parent.mkdir(parents=True, exist_ok=True)
    цель.write_bytes(нарисовать(sys.argv[1]))
    print(f"иконка готова: {цель} ({цель.stat().st_size} байт)")
