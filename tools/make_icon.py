def _прямоугольник(x1, y1, x2, y2):
    return lambda x, y: x1 <= x <= x2 and y1 <= y <= y2


def _рамка(x1, y1, x2, y2, толщина):
    внутри = _прямоугольник(x1, y1, x2, y2)
    дырка = _прямоугольник(x1 + толщина, y1 + толщина, x2 - толщина, y2 - толщина)
    return lambda x, y: внутри(x, y) and not дырка(x, y)


def _круг(cx, cy, r):
    return lambda x, y: (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def _полоса(x1, y1, x2, y2, толщина):
    """Отрезок с толщиной: расстояние от точки до отрезка."""
    dx, dy = x2 - x1, y2 - y1
    длина2 = dx * dx + dy * dy or 1

    def внутри(x, y):
        t = max(0.0, min(1.0, ((x - x1) * dx + (y - y1) * dy) / длина2))
        px, py = x1 + t * dx, y1 + t * dy
        return (x - px) ** 2 + (y - py) ** 2 <= (толщина / 2) ** 2
    return внутри



def _скруглённый(x1, y1, x2, y2, r):
    """Прямоугольник со скруглёнными углами: у квадрата с острыми углами вид
    самодельный, у скруглённого — вид приложения."""
    def внутри(x, y):
        if not (x1 <= x <= x2 and y1 <= y <= y2):
            return False
        cx = min(max(x, x1 + r), x2 - r)
        cy = min(max(y, y1 + r), y2 - r)
        return (x - cx) ** 2 + (y - cy) ** 2 <= r * r
    return внутри


def _скруглённая_рамка(x1, y1, x2, y2, r, толщина):
    снаружи = _скруглённый(x1, y1, x2, y2, r)
    внутри_ = _скруглённый(x1 + толщина, y1 + толщина, x2 - толщина, y2 - толщина,
                           max(r - толщина, .001))
    return lambda x, y: снаружи(x, y) and not внутри_(x, y)


def _кольцо(cx, cy, r, толщина):
    внеш = _круг(cx, cy, r)
    внутр = _круг(cx, cy, max(r - толщина, .001))
    return lambda x, y: внеш(x, y) and not внутр(x, y)


def _уголок(x, y, размер):
    """Загнутый угол листа: треугольник, который читается как «документ»."""
    return lambda px, py: px >= x and py <= y and (px - x) + (y - py) <= размер


