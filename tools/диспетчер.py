#!/usr/bin/env python3
"""Задача словами → какая способность её решает. Выбирает агент, не человек.

    python3 tools/диспетчер.py "найди поставщиков цемента в Алматы"
    python3 tools/диспетчер.py --selftest

ЗАЧЕМ. Строка уже умеет исполнить «2гис … про Центральный стадион»: человек
называет источник, строка идёт и добывает. Но имя источника — это наша кухня.
Человек думает задачей: «найди поставщиков цемента», «что пишут про эту
компанию», «собери квартиры в Алматы до 30 миллионов». Он не обязан знать, что
для первого годится Справочник 2ГИС, а для третьего — Сборщик объявлений.
Замечание владельца 23.08.2026: «почему туда вообще агент не привязан, который
умеет ходить куда-то и вызывать других экспертов».

ЧТО ДЕЛАЕТ. Читает реестр УСТАНОВЛЕННЫХ способностей вместе с их описаниями и
границами, показывает этот список модели вместе с задачей человека и получает
ответ: какую способность звать и с каким запросом. Ничего не выдумывает сверх
списка — способности, которой нет на полке, в ответе быть не может.

ПОЧЕМУ ОТКАЗ ЛУЧШЕ ДОГАДКИ. Ошибившийся диспетчер молча притащит не те данные,
и человек увидит уверенный результат не на свой вопрос — как было с аптеками
вместо стадиона. Поэтому модель обязана вернуть либо выбор с уверенностью, либо
честное «не знаю»; неуверенный ответ мы превращаем в вопрос человеку, а не в
запуск наугад.
"""

import argparse
import json
import pathlib
import re
import sys

СЮДА = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(СЮДА))
from формы import Отказ  # noqa: E402
import отбор_агентом as О  # noqa: E402 — общий канал разговора с моделью

КАБИНЕТ = pathlib.Path.home() / "extella-cabinet"
СПОСОБНОСТИ = КАБИНЕТ / "способности.json"
КАРТОЧКИ = СЮДА.parent / "editions"

ЗАДАНИЕ = """Ты подбираешь ИНСТРУМЕНТ под задачу человека. Отвечай СТРОГО одним JSON, без пояснений.

ЗАДАЧА ЧЕЛОВЕКА: {задача}

Доступные источники данных (ТОЛЬКО из этого списка можно выбирать):
{список}

Верни:
{{"источник": "<ключ из списка>", "запрос": "<что именно искать этим источником>", "уверенность": "высокая"|"низкая", "почему": "<одна фраза>"}}

Правила:
- «запрос» — то, что подставится в поиск источника: короткая суть без служебных слов. Для справочника организаций это рубрика или название («поставщики цемента», «кофейни»), для площадки объявлений — ссылка на список с фильтрами, если человек её дал.
- Если ни один источник не подходит или ты не уверен, верни {{"отказ": "<одна честная фраза, чего не хватает>"}}. Отказ лучше догадки: неверный источник принесёт уверенные данные не на тот вопрос.
- Не выдумывай источников, которых нет в списке."""


def способности() -> dict:
    """Что стоит на полке ПРЯМО СЕЙЧАС, с описаниями из карточек."""
    if not СПОСОБНОСТИ.exists():
        return {}
    try:
        реестр = json.loads(СПОСОБНОСТИ.read_text())
    except json.JSONDecodeError:
        return {}
    вышло = {}
    for slug, з in реестр.items():
        if з.get("kind") != "source":
            continue                       # выбираем ОТКУДА брать, не куда класть
        карточка = КАРТОЧКИ / slug / "listing.json"
        описание, границы = "", ""
        if карточка.exists():
            try:
                к = json.loads(карточка.read_text())
                описание, границы = к.get("описание", ""), к.get("границы", "")
            except json.JSONDecodeError:
                pass
        вышло[slug] = {"имя": з.get("имя", slug), "описание": описание,
                       "границы": границы}
    return вышло


def как_список(способ: dict) -> str:
    строки = []
    for slug, з in способ.items():
        строки.append(f"- {slug} — {з['имя']}: {з['описание']}"
                      + (f" ГРАНИЦЫ: {з['границы']}" if з["границы"] else ""))
    return "\n".join(строки) or "(ни одного источника не установлено)"


def в_источник_строки(slug: str, источники: dict) -> str:
    """Slug с полки → имя источника в реестре строки.

    Одна вещь называется двумя способами: на полке «2gis», в строке «2гис».
    Перевод берём из реестра способностей (поле «источник»), а если его нет —
    сопоставляем по человеческому имени. Угадывать по похожести букв не станем:
    неверный источник принесёт уверенные данные не на тот вопрос.
    """
    if not СПОСОБНОСТИ.exists():
        return ""
    try:
        реестр = json.loads(СПОСОБНОСТИ.read_text())
    except json.JSONDecodeError:
        return ""
    з = реестр.get(slug) or {}
    если = з.get("источник")
    if если and если in источники:
        return если
    людское = (з.get("имя") or "").strip().lower()
    for ключ, зн in источники.items():
        if людское and str((зн or {}).get("имя", "")).strip().lower() == людское:
            return ключ
    return ""


def подобрать(задача: str, способ: dict | None = None, спроси=None) -> dict:
    способ = способ if способ is not None else способности()
    if not способ:
        raise Отказ("на полке нет ни одного источника данных — ставить нечего "
                    "и выбирать не из чего")
    ответ = (спроси or О._спросить)(ЗАДАНИЕ.format(
        задача=" ".join(задача.split())[:300], список=как_список(способ)))
    if "отказ" in ответ:
        raise Отказ(f"агент честно отказал: {ответ['отказ']}")
    ключ = str(ответ.get("источник") or "").strip()
    if ключ not in способ:
        # Модель назвала то, чего на полке нет. Это не «почти правильно»: такой
        # запуск невозможен, и притворяться, что мы поняли, нельзя.
        raise Отказ(f"агент выбрал источник «{ключ}», которого нет на полке. "
                    f"Есть: {', '.join(способ)}")
    if str(ответ.get("уверенность") or "").strip().lower() != "высокая":
        raise Отказ(f"агент не уверен, что «{способ[ключ]['имя']}» подходит "
                    f"({ответ.get('почему') or 'без объяснения'}). Назовите "
                    f"источник сами — гадать на ваших данных не буду")
    запрос = str(ответ.get("запрос") or "").strip()
    if not запрос:
        raise Отказ(f"агент выбрал «{способ[ключ]['имя']}», но не сказал, что "
                    f"именно искать")
    return {"источник": ключ, "имя": способ[ключ]["имя"], "запрос": запрос,
            "почему": str(ответ.get("почему") or "").strip()}


def _самопроверка() -> int:
    ошибки = []
    полка = {
        "2gis": {"имя": "Справочник 2ГИС",
                 "описание": "организации города: название, рубрика, рейтинг, адрес",
                 "границы": "нужен Робот браузера"},
        "kz-listings": {"имя": "Сборщик объявлений",
                        "описание": "квартиры и авто с Krisha и Kolesa",
                        "границы": "только две площадки"},
    }
    д = подобрать("найди поставщиков цемента в Алматы", полка,
                  спроси=lambda з: {"источник": "2gis", "запрос": "поставщики цемента",
                                    "уверенность": "высокая", "почему": "это организации города"})
    if д["источник"] == "2gis" and д["запрос"] == "поставщики цемента":
        print("  ✓ задача без названия источника ложится на подходящую способность")
    else:
        ошибки.append(f"выбор неверен: {д}")

    # Список для модели обязан содержать И описание, И границы: без границ она
    # выберет 2ГИС для страницы за логином и уверенно принесёт пустоту.
    с = как_список(полка)
    if "нужен Робот браузера" in с and "только две площадки" in с:
        print("  ✓ модель видит и описание, и границы способностей")
    else:
        ошибки.append("границы не попали в список для модели")

    for ответ, чем in (
        ({"источник": "выдуманный", "запрос": "х", "уверенность": "высокая"},
         "источник не с полки"),
        ({"источник": "2gis", "запрос": "х", "уверенность": "низкая",
          "почему": "не уверен"}, "низкая уверенность"),
        ({"источник": "2gis", "запрос": "", "уверенность": "высокая"},
         "пустой запрос"),
        ({"отказ": "не понял, что искать"}, "честный отказ модели"),
    ):
        try:
            подобрать("что-то", полка, спроси=lambda з, о=ответ: о)
            ошибки.append(f"пропущено то, что должно быть отвергнуто: {чем}")
        except Отказ:
            pass
    if not [о for о in ошибки if "пропущено" in о]:
        print("  ✓ выдумка, неуверенность, пустой запрос и отказ — все отвергаются")

    try:
        подобрать("что-то", {}, спроси=lambda з: {})
        ошибки.append("пустая полка не вызвала отказа")
    except Отказ:
        print("  ✓ пустая полка — честный отказ, а не выбор из ничего")

    живые = способности()
    print(f"  · на полке сейчас источников: {len(живые)} "
          f"({', '.join(живые) or 'нет'})")
    for о in ошибки:
        print(f"  ✗ {о}")
    return 1 if ошибки else 0


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("задача", nargs="?", default="")
    р.add_argument("--selftest", action="store_true")
    а = р.parse_args()
    if а.selftest:
        return _самопроверка()
    if not а.задача:
        р.error("нужна задача словами")
    try:
        д = подобрать(а.задача)
    except Отказ as е:
        print(f"отказ: {е}")
        return 1
    print(f"  способность: {д['имя']} [{д['источник']}]")
    print(f"  запрос: {д['запрос']}")
    if д["почему"]:
        print(f"  почему: {д['почему']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
