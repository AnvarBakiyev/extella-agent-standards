#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Что применимо на этой стадии стройки — машинный ответ вместо пересказа стандарта.

ЗАЧЕМ. Стандарт знал один режим, «сразу как в проде», и любая стройка платила полную
цену: паспорт, манифест, бренд, дизайн, кабинет, реестр. На демонстрации клиенту это
стоило дороже самого продукта. Стадии (`stages.yaml`) режут объём, но пока их читают
глазами, каждый чат трактует по-своему — поэтому спецификацией служит эта проверялка,
а не текст.

Использование:
    python3 tools/stage_gates.py --stage demo            # человеку
    python3 tools/stage_gates.py --stage pilot --json    # чату и Console
    python3 tools/stage_gates.py --selftest              # проверка самого файла стадий

Коды выхода: 0 — всё разобралось, 1 — стадия неизвестна или файл стадий сломан.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ФАЙЛ_СТАДИЙ = КОРЕНЬ / "stages.yaml"
ПОРЯДОК = ["demo", "pilot", "prod"]


def _загрузить() -> dict:
    """Читает stages.yaml. PyYAML не обязателен — на чистой машине его может не быть."""
    текст = ФАЙЛ_СТАДИЙ.read_text(encoding="utf-8")
    try:
        import yaml  # noqa: PLC0415
    except ImportError:
        return _разобрать_вручную(текст)
    return yaml.safe_load(текст)


def _разобрать_вручную(текст: str) -> dict:
    """Минимальный разбор нужных полей без PyYAML.

    Нам нужны только списки гейтов и артефактов по стадиям и имена стоп-правил —
    полноценный YAML для этого не требуется, а отсутствие библиотеки не должно
    превращаться в «гейт не запускается» (то есть в отсутствие проверки вовсе).
    """
    стадии: dict = {}
    стоп: list = []
    текущая = None
    ключ = None
    for строка in текст.splitlines():
        если_комментарий = строка.strip().startswith("#") or not строка.strip()
        if если_комментарий:
            continue
        отступ = len(строка) - len(строка.lstrip())
        чистая = строка.strip()
        if отступ == 2 and чистая.endswith(":") and чистая[:-1] in ПОРЯДОК:
            текущая = чистая[:-1]
            стадии[текущая] = {"обязательные_гейты": [], "обязательные_артефакты": [],
                               "сознательно_не_требуем": [], "наследует": None}
            ключ = None
        elif отступ == 0 and чистая == "стоп_правила:":
            текущая, ключ = "__стоп__", None
        elif текущая and отступ == 4 and чистая.endswith(":"):
            ключ = чистая[:-1]
        elif текущая and отступ == 4 and чистая.startswith("наследует:"):
            стадии[текущая]["наследует"] = чистая.split(":", 1)[1].strip()
            ключ = None
        elif чистая.startswith("- ") and текущая == "__стоп__":
            if чистая.startswith("- имя:"):
                стоп.append(чистая.split(":", 1)[1].strip())
        elif чистая.startswith("- ") and текущая and ключ in (
                "обязательные_гейты", "обязательные_артефакты", "сознательно_не_требуем"):
            значение = чистая[2:].split("#", 1)[0].strip()
            if значение:
                стадии[текущая][ключ].append(значение)
    return {"stages": стадии, "стоп_правила": [{"имя": и} for и in стоп]}


def применимое(стадия: str) -> dict:
    """Собирает стадию вместе со всем, что она наследует от предыдущих."""
    данные = _загрузить()
    стадии = данные["stages"]
    if стадия not in стадии:
        raise KeyError(стадия)
    цепочка, текущая = [], стадия
    while текущая:
        цепочка.insert(0, текущая)
        текущая = (стадии[текущая] or {}).get("наследует")
    гейты, артефакты, не_требуем = [], [], []
    for имя in цепочка:
        с = стадии[имя] or {}
        for г in (с.get("обязательные_гейты") or []):
            if г not in гейты:
                гейты.append(г)
        for а in (с.get("обязательные_артефакты") or []):
            артефакты.append(а)
        # Послабления берём только у САМОЙ стадии: то, что не требовалось на демо,
        # на проде обычно требуется — иначе наследование тихо снимало бы проверки.
        if имя == стадия:
            не_требуем = list(с.get("сознательно_не_требуем") or [])
    return {
        "стадия": стадия,
        "наследует": цепочка[:-1],
        "гейты": гейты,
        "артефакты": артефакты,
        "не_требуем": не_требуем,
        "стоп_правила": [п.get("имя") for п in (данные.get("стоп_правила") or [])],
    }


def selftest() -> int:
    провалы = []
    if not ФАЙЛ_СТАДИЙ.is_file():
        print(f"FAIL нет файла стадий: {ФАЙЛ_СТАДИЙ}")
        return 1
    try:
        данные = _загрузить()
    except Exception as e:  # noqa: BLE001 — сообщаем причину, а не молчим
        print(f"FAIL файл стадий не разобрался: {e}")
        return 1

    стадии = данные.get("stages") or {}
    for имя in ПОРЯДОК:
        if имя not in стадии:
            провалы.append(f"нет стадии «{имя}»")

    # Гейт обязан существовать файлом: список, ссылающийся на несуществующую проверялку,
    # выглядит строгим и не проверяет ничего.
    for имя, с in стадии.items():
        for гейт in ((с or {}).get("обязательные_гейты") or []):
            if not (КОРЕНЬ / "tools" / f"{гейт}.py").is_file():
                провалы.append(f"стадия {имя}: гейта {гейт}.py нет в tools/")

    # Прод обязан быть не мягче пилота, пилот — не мягче демо.
    объёмы = []
    for имя in ПОРЯДОК:
        if имя in стадии:
            объёмы.append((имя, len(применимое(имя)["гейты"])))
    for (пред, n1), (след, n2) in zip(объёмы, объёмы[1:]):
        if n2 < n1:
            провалы.append(f"{след} мягче, чем {пред} ({n2} гейтов против {n1})")

    if not (данные.get("стоп_правила") or []):
        провалы.append("нет стоп-правил: быстрая стройка без границ вреда недопустима")

    if провалы:
        for п in провалы:
            print(f"FAIL {п}")
        return 1
    print(f"OK стадии: " + ", ".join(f"{и}={n}" for и, n in объёмы)
          + f", стоп-правил {len(данные['стоп_правила'])}")
    return 0


def main() -> int:
    разбор = argparse.ArgumentParser(description="Что применимо на стадии стройки")
    разбор.add_argument("--stage", choices=ПОРЯДОК)
    разбор.add_argument("--json", action="store_true")
    разбор.add_argument("--selftest", action="store_true")
    арг = разбор.parse_args()

    if арг.selftest:
        return selftest()
    if not арг.stage:
        разбор.error("нужен --stage demo|pilot|prod (или --selftest)")

    итог = применимое(арг.stage)
    if арг.json:
        print(json.dumps(итог, ensure_ascii=False, indent=2))
        return 0

    print(f"Стадия: {арг.stage}"
          + (f" (наследует {', '.join(итог['наследует'])})" if итог["наследует"] else ""))
    print(f"\nГейты — {len(итог['гейты'])}:")
    for г in итог["гейты"]:
        print(f"  • {г}")
    print(f"\nАртефакты — {len(итог['артефакты'])}:")
    for а in итог["артефакты"]:
        print(f"  • {а}")
    if итог["не_требуем"]:
        print("\nСознательно НЕ требуем на этой стадии:")
        for н in итог["не_требуем"]:
            print(f"  • {н}")
    print("\nСтоп-правила (на всех стадиях): " + ", ".join(итог["стоп_правила"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
