#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Гейт «открывается на чужой машине»: вердикт светофором поверх пробы окна.

ЗАЧЕМ. Установка лёгкая, но между «установилось» и «открылось у ДРУГОГО» никто
не встаёт. App Store даёт гарантию открытия, потому что запускает приложение на
чужом устройстве до листинга. Этот гейт — наш эквивалент: он открывает купленную
страницу как чужак (origin=null, как в песочнице рабочего стола ОС) и красит
листинг светофором.

ГИБРИД (решение Анвара 22.08.2026). Бейдж видят все; блок — только на катастрофе
открытия. Принцип деления: блокируем то, что ВИДИТ ГЛАЗ и что НЕ зависит от
стенда, — предупреждаем о том, что говорит консоль, потому что в стенде часть
консольных бед (Failed to fetch, 404 из песочницы) может быть ограничением
стенда, а не продукта. Так гейт не заворачивает живое приложение, но белый экран
или светящаяся метка не пройдут зелёными.

    КРАСНЫЙ (блок):  белый экран · светящаяся {{подстановка}}
    ЖЁЛТЫЙ (пропуск, предупреждение):  плашка связи в окне · консольные беды ·
                                       нет самопроверки
    ЗЕЛЁНЫЙ:  окно живое, текст рисуется, консоль чистая, подстановок нет

    python3 check_opens_elsewhere.py <listing_id>       # проба через прокси (быстро)
    python3 check_opens_elsewhere.py --домен <listing_id>  # на родном origin ОС
    python3 check_opens_elsewhere.py --папка <run_dir>  # вердикт по готовому прогону
    python3 check_opens_elsewhere.py --selftest

Режим --домен = ПРОВЕРЕННЫЙ ЗЕЛЁНЫЙ: браузер сажается на настоящий origin
os.extella.ai (see same_origin_probe.py), запросы приложения проходят как у
покупателя, зелёный становится доверенным. Прокси-режим (без --домен) даёт
надёжный красный (белый экран, метка) и честный жёлтый, но зелёный там неполный
из-за CORS с origin 127.0.0.1.

Коды выхода: 0 — зелёный или жёлтый (публиковать можно), 1 — КРАСНЫЙ (блок),
2 — гейт не смог прогнать пробу.
"""
import json
import pathlib
import re
import subprocess
import sys

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(ЗДЕСЬ))
from probe_window import видимый_текст, разобрать  # noqa: E402

# Беды, видимые ГЛАЗУ и не зависящие от стенда → блок. Проверяем вхождением, а не
# полным равенством: тексты бед пробы содержат подробности (число знаков, кусок).
ЖЁСТКИЕ = ("белый экран", "подстановка светится")

СЛОВА_ОТКАЗА = ("Повторить", "Retry", "Связь", "недоступ", "Ошибка", "ошибка")

# Панели ОС рисуют UI в Shadow DOM внутри #host — dump-dom его НЕ отдаёт (замер
# 22.08.2026: успешный рендер даёт 0 текста в DOM, а падение — плашку в обычном
# DOM, то есть текст ИНВЕРТИРОВАН). Поэтому на родном origin судим по глазу —
# по разбросу яркости скриншота. Замер: спиннер/пусто std=0.010, живая панель
# std=0.136. Порог с запасом посередине.
ПОРОГ_ПУСТО = 0.04
БЕДЫ_РЕНДЕРА = ("Uncaught", "SecurityError", "Failed to fetch", "CORS",
               "net::ERR", "401 (", "500 (", "403 (")


def измерить_плотность(png: pathlib.Path) -> float | None:
    """Разброс яркости скриншота: мало — пусто/спиннер, много — нарисовано."""
    if not png.exists():
        return None
    try:
        итог = subprocess.run(
            ["convert", str(png), "-colorspace", "Gray",
             "-format", "%[fx:standard_deviation]", "info:"],
            capture_output=True, text=True, timeout=30)
        return float(итог.stdout.strip())
    except Exception:                                  # noqa: BLE001
        return None


def классифицировать_домен(std: float | None, конс: list, текст_light: str) -> dict:
    """Вердикт на родном origin: судим по глазу (скриншот) + консоль."""
    жёсткие, мягкие = [], []
    if std is None:
        мягкие.append("не удалось измерить скриншот — перепроверить вручную")
    elif std < ПОРОГ_ПУСТО:
        жёсткие.append(f"экран почти пуст: разброс яркости {std:.3f} < "
                       f"{ПОРОГ_ПУСТО} — человек видит спиннер или белый экран")
    if "{{" in текст_light:
        кусок = текст_light[текст_light.find("{{"):][:50]
        жёсткие.append(f"светящаяся подстановка в обычном DOM: «{кусок}»")
    беды_к = [с for с in конс if any(б in с for б in БЕДЫ_РЕНДЕРА)]
    for с in беды_к[:3]:
        мягкие.append("консоль: " + с.split("CONSOLE")[-1][:150])

    if жёсткие:
        цвет, блок, бейдж = "красный", True, "падает у чужого"
    elif мягкие:
        цвет, блок, бейдж = "жёлтый", False, "открывается с оговоркой"
    else:
        цвет, блок, бейдж = "зелёный", False, "проверено: открывается"
    return {"цвет": цвет, "блок": блок, "бейдж": бейдж,
            "жёсткие": жёсткие, "мягкие": мягкие, "std": std}


def классифицировать(беды: list, текст: str) -> dict:
    """Список бед пробы → вердикт светофором. Без сети — для селфтеста."""
    жёсткие = [б for б in беды if any(п in б for п in ЖЁСТКИЕ)]
    мягкие = [б for б in беды if б not in жёсткие]

    # Плашка честного отказа связи: проба такое НЕ считает бедой (может быть
    # ограничение стенда), но и зелёным это не назовёшь — покупатель у себя
    # может увидеть ровно эту плашку. Жёлтый с явной причиной.
    коротко = len(re.sub(r"\s+", " ", текст).strip()) < 60
    плашка = коротко and any(с in текст for с in СЛОВА_ОТКАЗА)
    if плашка and not жёсткие:
        мягкие = мягкие + [f"окно показало плашку связи: «{текст[:70].strip()}» — "
                           f"в стенде это может быть ограничением стенда; нужен "
                           f"живой прогон на домене ОС, чтобы снять сомнение"]

    if жёсткие:
        цвет, блок, бейдж = "красный", True, "падает у чужого"
    elif мягкие:
        цвет, блок, бейдж = "жёлтый", False, "не проверено полностью"
    else:
        цвет, блок, бейдж = "зелёный", False, "проверено: открывается"
    return {"цвет": цвет, "блок": блок, "бейдж": бейдж,
            "жёсткие": жёсткие, "мягкие": мягкие}


def напечатать(в: dict, лид: str = "") -> None:
    значок = {"зелёный": "✓", "жёлтый": "⚠", "красный": "✕"}[в["цвет"]]
    шапка = f"{значок} {в['цвет'].upper()} — «{в['бейдж']}»"
    print(шапка + (f"   [{лид}]" if лид else ""))
    for б in в["жёсткие"]:
        print("  ✕ стоп:", б)
    for б in в["мягкие"]:
        print("  · предупреждение:", б)
    if в["блок"]:
        print("  → выкладка ЗАБЛОКИРОВАНА: катастрофа открытия у покупателя.")
    elif в["цвет"] == "жёлтый":
        print("  → выкладка разрешена, но листинг честно помечен «не проверено».")
    else:
        print("  → выкладка разрешена, бейдж зелёный.")


def _папка_из_вывода(вывод: str) -> pathlib.Path | None:
    for строка in вывод.splitlines():
        if "скриншот и консоль:" in строка:
            return pathlib.Path(строка.split("скриншот и консоль:")[-1].strip())
    return None


def вердикт_по_папке(папка: pathlib.Path, лид: str = "") -> int:
    dom = (папка / "dom.html")
    конс = (папка / "консоль.txt")
    if not dom.exists():
        print("нет dom.html в прогоне:", папка)
        return 2
    текст_dom = dom.read_text(encoding="utf-8", errors="replace")
    строки = конс.read_text(encoding="utf-8", errors="replace").splitlines() if конс.exists() else []
    if "── песочница ──" in строки:
        рубеж = строки.index("── песочница ──")
        конс_а, конс_б = строки[:рубеж], строки[рубеж + 1:]
    else:
        конс_а, конс_б = строки, []
    беды = разобрать(текст_dom, конс_а, конс_б)
    в = классифицировать(беды, видимый_текст(текст_dom))
    напечатать(в, лид)
    (папка / "вердикт.json").write_text(
        json.dumps(в, ensure_ascii=False, indent=2), encoding="utf-8")
    return 1 if в["блок"] else 0


def прогнать(лид: str) -> int:
    итог = subprocess.run([sys.executable, str(ЗДЕСЬ / "probe_window.py"), лид],
                          capture_output=True, text=True, timeout=300)
    sys.stdout.write(итог.stdout)
    if итог.returncode == 2:
        sys.stderr.write(итог.stderr)
        return 2
    папка = _папка_из_вывода(итог.stdout)
    if not папка or not папка.exists():
        print("не нашёл папку прогона в выводе пробы"); return 2
    return вердикт_по_папке(папка, лид)


def прогнать_домен(лид: str) -> int:
    """Проверенный зелёный: собрать на родном origin, судить по глазу, покрасить."""
    import same_origin_probe
    сб = same_origin_probe.собрать(лид)
    if сб.get("ошибка"):
        print(сб["ошибка"]); return 2
    std = измерить_плотность(сб["папка"] / "окно_на_домене.png")
    в = классифицировать_домен(std, сб["конс"], видимый_текст(сб["dom"]))
    print("режим: проверенный зелёный (origin os.extella.ai, судим по скриншоту)")
    напечатать(в, лид)
    (сб["папка"] / "вердикт.json").write_text(
        json.dumps(в, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"  DOM и скриншот: {сб['папка']}")
    return 1 if в["блок"] else 0


def selftest() -> int:
    ошибки = []
    # белый экран → красный, блок
    в = классифицировать(["страница почти пуста: видимого текста 0 знаков — "
                           "человек увидит белый экран"], "")
    if not (в["цвет"] == "красный" and в["блок"]):
        ошибки.append("белый экран не даёт красный-блок")
    # светящаяся подстановка → красный, блок
    в = классифицировать(["подстановка светится в видимом тексте: «{{token}}» — "
                           "покупатель прочитает метку вместо значения"], "текст {{token}}")
    if not (в["цвет"] == "красный" and в["блок"]):
        ошибки.append("светящаяся подстановка не даёт красный-блок")
    # консольная беда в песочнице → жёлтый, НЕ блок (может быть стенд)
    в = классифицировать(["консоль (в песочнице ОС): Failed to fetch"], "живой текст панели")
    if not (в["цвет"] == "жёлтый" and not в["блок"]):
        ошибки.append("консольная беда не осталась жёлтой без блока")
    # плашка связи в коротком окне → жёлтый, не блок
    в = классифицировать([], "Связь с Extella: отказ. Повторить")
    if not (в["цвет"] == "жёлтый" and not в["блок"]):
        ошибки.append("плашка связи не дала жёлтый без блока")
    # чистое живое окно → зелёный
    в = классифицировать([], "Живой текст панели Агента 1С, много содержимого экрана")
    if not (в["цвет"] == "зелёный" and not в["блок"]):
        ошибки.append("живое окно не признано зелёным")
    # жёсткая беда рядом с мягкой всё равно блокирует
    в = классифицировать(["человек увидит белый экран", "консоль (напрямую): 404 ("], "")
    if not в["блок"]:
        ошибки.append("жёсткая беда рядом с мягкой не заблокировала")
    # ── глазной классификатор домена ──
    # нарисованная панель (высокий разброс), чистая консоль → зелёный
    в = классифицировать_домен(0.136, [], "")
    if not (в["цвет"] == "зелёный" and not в["блок"]):
        ошибки.append("живая панель на домене не дала зелёный")
    # пустой экран (низкий разброс) → красный, блок
    в = классифицировать_домен(0.010, [], "")
    if not (в["цвет"] == "красный" and в["блок"]):
        ошибки.append("пустой экран на домене не заблокирован")
    # нарисовано, но консоль с ошибкой рендера → жёлтый, не блок
    в = классифицировать_домен(0.136, ['CONSOLE "Uncaught TypeError"'], "")
    if not (в["цвет"] == "жёлтый" and not в["блок"]):
        ошибки.append("рендер с консольной ошибкой не дал жёлтый")
    # не смогли измерить скриншот → жёлтый, НЕ ложный блок
    в = классифицировать_домен(None, [], "")
    if в["блок"]:
        ошибки.append("неизмеренный скриншот дал ложный блок")
    # светящаяся подстановка в обычном DOM → красный
    в = классифицировать_домен(0.136, [], "текст {{token}} тут")
    if not в["блок"]:
        ошибки.append("подстановка в обычном DOM не заблокирована")
    for о in ошибки:
        print("  ✗", о)
    print("selftest:", "провален" if ошибки else "пройден")
    return 1 if ошибки else 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    if "--папка" in sys.argv:
        sys.exit(вердикт_по_папке(pathlib.Path(sys.argv[sys.argv.index("--папка") + 1])))
    if "--домен" in sys.argv:
        sys.exit(прогнать_домен(sys.argv[sys.argv.index("--домен") + 1]))
    if len(sys.argv) < 2:
        print(__doc__); sys.exit(2)
    sys.exit(прогнать(sys.argv[1]))
