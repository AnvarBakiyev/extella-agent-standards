#!/usr/bin/env python3
"""Гейт на выходе поверхности отчитался честно (канон H38).

ЗАЧЕМ. Приём «перечитать готовый артефакт, а не поверить преобразованию» пришёл
из чужого чата уже с двумя рабочими воплощениями. Записанный только словами, он
через неделю выродится в отчёт «чисто» без покрытия — это здесь уже случалось с
другими правилами. Проверка охраняет не сам поиск персональных данных (детекторы
у каждой поверхности свои), а ЧЕСТНОСТЬ его отчёта.

ЧТО ПРОВЕРЯЕТСЯ В ОТЧЁТЕ ГЕЙТА:

  проход по артефакту   — отдельный, а не тот же путь в коде, что делал замену;
                          иначе ошибка прячется в обоих и гейт подтверждает себя
  матрица покрытия      — что просмотрено И что НЕ просмотрено; пустая графа
                          непросмотренного означает, что её не заполняли
  запрет слова «чисто»  — гейт не вправе утверждать отсутствие утечек, только
                          отсутствие совпадений по поддерживаемым типам
  подсадное значение    — сканер обязан доказать, что умеет находить. Замер
                          21.08.2026: поиск секретов по 72 записям истории вернул
                          ноль, потому что образец поиска молча уехал пустым
  политика отказа       — клиентская поверхность с остатком не вправе называться
                          пройденной; демонстрационная с реальной величиной
                          обязана быть заблокирована

    python3 tools/check_output_gate.py отчёт.json [ещё.json ...]
    python3 tools/check_output_gate.py --selftest

Коды выхода: 0 — отчёты честны, 1 — есть нарушения.
"""

import json
import pathlib
import re
import sys

# Слова, которыми гейт не вправе описывать свой результат: они утверждают
# отсутствие утечки, а проверка знает лишь про поддерживаемые типы.
ЗАПРЕТ = re.compile(r"утечек нет|данных не осталось|полностью очищен|"
                    r"гарантированно чист|\bчисто\b", re.IGNORECASE)

ПОВЕРХНОСТИ = ("client", "demo")


def проверить(отчёт: dict) -> list:
    беды = []

    поверхность = str(отчёт.get("surface") or "")
    if поверхность not in ПОВЕРХНОСТИ:
        беды.append("не назван класс поверхности: ожидается " + " | ".join(ПОВЕРХНОСТИ))

    # 1. Отдельный проход по готовому артефакту.
    if str(отчёт.get("pass") or "") != "artifact":
        беды.append("проход не по артефакту: гейт обязан перечитать готовый файл, "
                    "а не доверять строке, которую вернуло преобразование")

    # 2. Матрица покрытия с ОБЕИМИ графами.
    покрытие = отчёт.get("coverage")
    if not isinstance(покрытие, dict):
        беды.append("нет матрицы покрытия")
    else:
        if not покрытие.get("scanned"):
            беды.append("в матрице покрытия не перечислено просмотренное")
        if "not_processed" not in покрытие:
            беды.append("в матрице покрытия нет графы непросмотренного — "
                        "её отсутствие читается как «просмотрено всё»")

    # 3. Подсадное значение: сканер доказал, что умеет находить.
    подсадка = отчёт.get("needle")
    if not isinstance(подсадка, dict):
        беды.append("нет подсадного значения: ноль от проверки, ни разу не "
                    "показавшей красного, ничего не доказывает")
    else:
        if not подсадка.get("planted"):
            беды.append("подсадное значение не названо")
        if подсадка.get("found") is not True:
            беды.append("сканер НЕ нашёл подсадное значение — он не ищет")

    # 4. Честная формулировка.
    словами = str(отчёт.get("summary") or "")
    if not словами:
        беды.append("нет формулировки результата словами")
    elif ЗАПРЕТ.search(словами):
        беды.append("формулировка утверждает отсутствие утечки: гейт вправе "
                    "говорить лишь про поддерживаемые типы и просмотренные области")

    # 5. Политика отказа.
    остаток = отчёт.get("residual")
    состояние = str(отчёт.get("status") or "")
    if not isinstance(остаток, int) or остаток < 0:
        беды.append("остаток совпадений не назван числом")
    elif поверхность == "client" and остаток > 0 and состояние != "risk":
        беды.append(f"остаток {остаток}, а состояние «{состояние}»: клиентский "
                    "артефакт с остатком не вправе называться пройденным")
    elif поверхность == "demo" and остаток > 0 and состояние != "blocked":
        беды.append(f"остаток {остаток}, а состояние «{состояние}»: реальная "
                    "величина в демонстрации обязана останавливать публикацию")
    return беды


def _selftest() -> int:
    беды = []

    добротный = {
        "surface": "client", "pass": "artifact", "residual": 0, "status": "passed",
        "coverage": {"scanned": ["тело", "колонтитулы", "строковая таблица"],
                     "not_processed": ["изображения", "макросы"]},
        "needle": {"planted": "990101300123", "found": True},
        "summary": "по поддерживаемым типам и просмотренным областям остаточных "
                   "совпадений не обнаружено",
    }
    if проверить(добротный):
        беды.append("добротный отчёт объявлен нарушением: " + "; ".join(проверить(добротный)))
    else:
        print("  ✓ добротный отчёт проходит")

    def случай(подпись, правка, ожидаемое):
        о = json.loads(json.dumps(добротный))
        о.update(правка)
        найдено = проверить(о)
        if any(ожидаемое in b for b in найдено):
            print(f"  ✓ {подпись}")
        else:
            беды.append(f"{подпись}: не поймано, ответ {найдено}")

    случай("проход не по артефакту пойман", {"pass": "inline"}, "не по артефакту")
    случай("отсутствие графы непросмотренного поймано",
           {"coverage": {"scanned": ["тело"]}}, "нет графы непросмотренного")
    случай("отсутствие подсадного значения поймано", {"needle": None}, "нет подсадного")
    случай("ненайденная подсадка поймана",
           {"needle": {"planted": "x", "found": False}}, "НЕ нашёл подсадное")
    случай("слово о чистоте поймано",
           {"summary": "файл полностью очищен, утечек нет"}, "отсутствие утечки")
    случай("клиентский остаток без пометки риска пойман",
           {"residual": 2, "status": "passed"}, "не вправе называться пройденным")
    случай("реальная величина в демонстрации не остановила публикацию",
           {"surface": "demo", "residual": 1, "status": "risk"},
           "обязана останавливать публикацию")
    случай("неназванный класс поверхности пойман", {"surface": ""}, "не назван класс")

    # Отчёт без числа остатка нельзя считать пройденным.
    случай("остаток не числом пойман", {"residual": "нет"}, "не назван числом")

    if беды:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(беды))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


def main(аргументы: list) -> int:
    if "--selftest" in аргументы:
        return _selftest()
    цели = [pathlib.Path(a) for a in аргументы if not a.startswith("--")]
    if not цели:
        print(__doc__)
        return 2
    плохо = 0
    for путь in цели:
        if not путь.is_file():
            print(f"{путь}: файла нет")
            плохо = 1
            continue
        найдено = проверить(json.loads(путь.read_text(encoding="utf-8")))
        if найдено:
            плохо = 1
            print(f"{путь}: нарушений {len(найдено)}")
            for б in найдено:
                print("   -", б)
        else:
            print(f"{путь}: отчёт честен")
    return плохо


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
