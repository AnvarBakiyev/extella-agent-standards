"""В проводе только латиница: адреса, поля запроса, имена заголовков (канон 4.5в).

ЗАЧЕМ. Кириллица в пути уезжает процентами: `/__шим` приезжает как
`/__%D1%88%D0%B8%D0%BC`, совпадения на сервере нет, и запрос молча не доходит.
Замер 21.08.2026: диагностический маячок с кириллическим адресом не доезжал — то
есть инструмент, поставленный ловить молчаливые отказы, сам отказывал молча.
В журнале такая строка вдобавок нечитаема.

Правило узкое намеренно: русский остаётся в коде, в именах переменных и в
пояснениях. Запрещён он ТОЛЬКО в проводе — в адресе, в именах полей запроса и в
именах заголовков.

ОБЛАСТЬ УЗКАЯ НАМЕРЕННО. Проверяются файлы, которые исполняются в окне и ходят
в сеть сами. По всему дереву та же проверка даёт восемнадцать срабатываний, и все
до одного — образцы внутри чужих самопроверок и заготовки в пояснениях. Проверка
с таким шумом отключается, а не читается; лучше охранять меньшую площадь, но
без ложных тревог.

    python3 tools/check_wire_ascii.py templates/storage_shim.html
    python3 tools/check_wire_ascii.py --selftest
"""

import pathlib
import re
import sys

# Строковые литералы, похожие на адрес или на имя заголовка.
АДРЕС = re.compile(r"""["'`](/[^"'`\s]*|https?://[^"'`\s]*)["'`]""")
ЗАГОЛОВОК = re.compile(r"""(?:setRequestHeader|send_header|headers\[)\s*\(?\s*["']([^"']+)["']""")
КИРИЛЛИЦА = re.compile(r"[А-Яа-яЁё]")
РАСШИРЕНИЯ = (".html", ".js", ".mjs", ".py")


# Подстановка вида {лид} до провода не доезжает: имя переменной заменяется
# значением. Ловить её — ложная тревога, а ложная тревога дороже пропуска:
# проверку с шумом перестают читать. Замер: без этого правила 44 срабатывания
# на дереве, из них настоящее одно.
ПОДСТАНОВКА = re.compile(r"\{[^{}]*\}|%\([^)]*\)[sdr]|\$\{[^}]*\}")
# Местные файлы адресом не являются, хотя и начинаются с косой черты.
МЕСТНЫЙ_ФАЙЛ = re.compile(r"^/(tmp|Users|home|var|etc|private)/")


def проверить_текст(текст: str) -> list:
    беды = []
    for м in АДРЕС.finditer(текст):
        адрес = м.group(1)
        if МЕСТНЫЙ_ФАЙЛ.match(адрес):
            continue
        голый = ПОДСТАНОВКА.sub("", адрес)
        if КИРИЛЛИЦА.search(голый):
            беды.append("кириллица в адресе: " + адрес[:70])
    for м in ЗАГОЛОВОК.finditer(текст):
        if КИРИЛЛИЦА.search(м.group(1)):
            беды.append("кириллица в имени заголовка: " + м.group(1)[:40])
    return беды


def проверить_файл(путь: pathlib.Path) -> list:
    try:
        текст = путь.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return []
    return [f"{путь}: {б}" for б in проверить_текст(текст)]


def обойти(цели: list) -> list:
    беды = []
    for цель in цели:
        путь = pathlib.Path(цель)
        # Собственные образцы самопроверки — не находка: в них кириллица нарочно.
        файлы = [путь] if путь.is_file() else [
            ф for ф in путь.rglob("*")
            if ф.is_file() and ф.suffix in РАСШИРЕНИЯ and "node_modules" not in ф.parts
            and ф.name != pathlib.Path(__file__).name
        ]
        for ф in файлы:
            беды.extend(проверить_файл(ф))
    return беды


def _selftest() -> int:
    беды = []

    def случай(подпись, текст, должно_поймать):
        найдено = проверить_текст(текст)
        поймано = bool(найдено)
        if поймано == должно_поймать:
            print(f"  ✓ {подпись}")
        else:
            беды.append(f"{подпись}: ответ {найдено}")

    случай("кириллический путь пойман", 'new Image().src = "/__шим?этап=1";', True)
    случай("латинский путь проходит", 'new Image().src = "/__shim?stage=1";', False)
    случай("кириллица в поле запроса поймана", 'fetch("/api/x?что=1")', True)
    случай("кириллица в полном адресе поймана", 'fetch("https://os.extella.ai/путь")', True)
    случай("кириллица в имени заголовка поймана",
           'r.setRequestHeader("Наш-Ключ", v)', True)
    # Русский в коде и в пояснениях — не нарушение: правило только про провод.
    случай("русский текст в коде проходит",
           'var сообщение = "не удалось прочитать файл"; // пояснение', False)
    случай("подстановка с кириллицей не тревога",
           'requests.get(f"https://os.extella.ai/app-page/{лид}/")', False)
    случай("местный файл не адрес", 'open("/tmp/форма_1.json")', False)
    случай("русский в теле запроса проходит",
           'fetch("/api/x", {body: JSON.stringify({причина: "нет сети"})})', False)

    if беды:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(беды))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


def main(аргументы: list) -> int:
    if "--selftest" in аргументы:
        return _selftest()
    цели = [a for a in аргументы if not a.startswith("--")]
    if not цели:
        print(__doc__)
        return 2
    беды = обойти(цели)
    if беды:
        print(f"кириллица в проводе, мест: {len(беды)}")
        for б in беды:
            print("   -", б)
        return 1
    print("в проводе только латиница")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
