"""Экраны продукта по правилам скилла интерфейса: одна задача, одно действие.

ЗАЧЕМ. Скилл `extella-ui` описывает правила, но проверяет их глазами. Глаза
устают: продукт вырос в одну простыню с пятью бронзовыми кнопками подряд, и
заметил это владелец, а не прогон. Часть правил считается машиной — вот она.

ЧТО ПРОВЕРЯЕТСЯ:

  одно бронзовое действие на экран — два означают, что человек выбирает вместо
                                     того, чтобы работать
  радиусы только из кода           — 8 у мелких контролов, 12 у панелей,
                                     999 у кнопок-действий, 50% у круглых
  шрифт кнопок наследуется         — без правила браузер набирает их Arial
  без эмодзи и капса в заголовках  — прямо запрещено дизайн-кодом

Понятность экрана машина не проверяет: пункты 1–7 скилла остаются глазами.

    python3 tools/check_screen_rules.py store_app/index.html
    python3 tools/check_screen_rules.py --selftest
"""

import pathlib
import re
import sys

РАДИУСЫ = {"8", "12", "999", "50"}
ЭМОДЗИ = re.compile(r"[\U0001F300-\U0001FAFF☀-➿]")
ЭКРАН = re.compile(r'<section[^>]*class="[^"]*экран[^"]*"[^>]*data-экран="([^"]+)"')
ГЛАВНОЕ = 'class="btn main"'
# querySelector(...) или getElementById(...), у которого СРАЗУ берут свойство.
# Если элемента нет, страница падает целиком — а видно это только исполнением.
СЛЕПОЕ = re.compile(
    r"\.querySelector\(\s*['\"][^'\"]+['\"]\s*\)\s*\.\s*(?:on\w+|textContent|value|style|classList)"
    r"\s*=")


def проверить_текст(текст: str) -> list:
    беды = []

    # Одно бронзовое действие на экран.
    куски = ЭКРАН.split(текст)
    if len(куски) > 1:
        пары = list(zip(куски[1::2], куски[2::2]))
        for имя, тело in пары:
            сколько = тело.count(ГЛАВНОЕ)
            if сколько > 1:
                беды.append(f"экран «{имя}»: бронзовых действий {сколько} — "
                            "человек выбирает вместо того, чтобы работать")

    for r in set(re.findall(r"border-radius:\s*([\d.]+)(?:px|%)", текст)):
        if r not in РАДИУСЫ:
            беды.append(f"радиус {r} мимо дизайн-кода: бывают 8, 12, 999 и 50%")

    if "font-family:inherit" not in текст.replace(" ", ""):
        беды.append("нет правила наследования шрифта кнопками — браузер наберёт их Arial")

    if ЭМОДЗИ.search(текст):
        беды.append("эмодзи в интерфейсе запрещены дизайн-кодом")

    # Найденное разыменовывают, не проверив. Замер 22.08.2026: обход ВСЕХ
    # section страницы дёргал .querySelector('.head').onclick, новый экран
    # заголовка не имел — и вся отрисовка обрывалась молча. Меню было видно,
    # содержимого не было ни на одном экране, и ни одна проверка этого не
    # заметила: все они читали строки, а не исполняли страницу.
    for м in СЛЕПОЕ.finditer(текст):
        беды.append("найденное разыменовано без проверки на пустоту: "
                    + м.group(0)[:60].replace("\n", " "))

    for м in re.finditer(r"<h[12][^>]*>([^<]{4,})", текст):
        if re.search(r"[А-ЯЁ]{4,}", м.group(1)):
            беды.append("капс в заголовке: " + м.group(1)[:40])
    return беды


def _selftest() -> int:
    беды = []
    добрый = ('<section class="экран" data-экран="а"><button class="btn main">Собрать</button></section>'
              '<section class="экран" data-экран="б"><button class="btn">Ещё</button></section>'
              '<style>button,input,select,textarea{font-family:inherit}'
              '.к{border-radius:12px}.м{border-radius:8px}</style><h1>Заголовок</h1>')

    def случай(подпись, текст, ожидаемое):
        найдено = проверить_текст(текст)
        ок = (not найдено) if ожидаемое == "" else any(ожидаемое in б for б in найдено)
        print(("  ✓ " if ок else "  ✗ ") + подпись + ("" if ок else f" · ответ {найдено}"))
        if not ок:
            беды.append(подпись)

    случай("добрый экран проходит", добрый, "")
    случай("две бронзы на экране пойманы",
           добрый.replace('<button class="btn">Ещё</button>',
                          '<button class="btn main">Ещё</button>')
                 .replace('data-экран="б"', 'data-экран="а2"')
                 .replace('</section><section class="экран" data-экран="а2">', ''),
           "бронзовых действий")
    случай("чужой радиус пойман", добрый.replace("12px", "14px"), "мимо дизайн-кода")
    случай("шрифт кнопок пойман", добрый.replace("font-family:inherit", "font-family:Arial"),
           "наберёт их Arial")
    случай("эмодзи поймано", добрый.replace("Заголовок", "Заголовок \U0001F600"), "эмодзи")
    случай("капс в заголовке пойман", добрый.replace("Заголовок", "ЗАГОЛОВОК"), "капс")
    случай("слепое разыменование поймано",
           добрый + "<script>s.querySelector('.head').onclick = f;</script>",
           "без проверки на пустоту")
    случай("проверка на пустоту проходит",
           добрый + "<script>var г = s.querySelector('.head'); if (г) г.onclick = f;</script>", "")

    if беды:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(беды))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


def main(аргументы: list) -> int:
    if "--selftest" in аргументы:
        return _selftest()
    цели = [pathlib.Path(a) for a in аргументы if not a.startswith("--")]
    if not цели:
        print(__doc__)
        return 2
    плохо = 0
    for путь in цели:
        найдено = проверить_текст(путь.read_text(encoding="utf-8"))
        if найдено:
            плохо = 1
            print(f"{путь}: нарушений {len(найдено)}")
            for б in найдено:
                print("   -", б)
        else:
            print(f"{путь}: правила экранов соблюдены")
    return плохо


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
