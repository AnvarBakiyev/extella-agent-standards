#!/usr/bin/env python3
"""Число проверок не пишется руками: его называет машина (H113).

ЗАЧЕМ. За сутки 24–25.09.2026 один класс поймался трижды, и каждый раз не автор,
а второй читатель: «116 правил» (через час их стало 118), «около 10 КБ» про
оглавление (16 КБ байтами), «9 КБ» про вход (6,7 КБ). Четвёртый случай нашёлся
замером: `BUILD_STAGES.md` и приложение «Разработка на Extella» обещали на
продакшене «21 гейт», а `stage_gates.py --stage prod` требует 25 — расхождение
жило в тексте, по которому люди готовили выпуск.

ПОЧЕМУ ЛОВИТ НЕ АВТОР. Число описывает ДРУГОЙ файл. Автор правит один файл,
число лежит в другом, и в момент правки оно выглядит верным. Ревью тут не
помогает: у читающего перед глазами тот же текст, а не факт.

ЧТО ПРОВЕРЯЕТСЯ. В текстах для людей и в содержимом приложения нельзя писать
количество обязательных проверок словами или цифрами. Вместо числа называется
команда, которая его считает. Проверка узкая намеренно: запретить написанное
число дешевле и надёжнее, чем сверять каждое, а ложная тревога в гейте дороже
пропуска — её перестают читать.

Числа, которые проверка НЕ трогает: количество пунктов рядом с самим списком
(«четыре правила» над четырьмя пунктами — правится в одном абзаце), лимиты
платформы («тело до 64 КБ» — их считать нечем, они датируются замером) и
история в `CHANGELOG.md` (она описывает состояние на тот день и верна).

ПРИЁМКА 25.09.2026: прогон по репозиторию дал 4 ложные тревоги из 7 попаданий
(«ни одна проверка», «самопроверка 10/10», «Проверка одна: закрой экран»,
«(21 проверка)» про самопроверку инструмента) — все четыре стали пробами.
Настоящих находок 3: «21 гейт» при 25, «29 проверок» при 76, «`prod` — 21».

    python3 tools/check_counted_claims.py
    python3 tools/check_counted_claims.py --selftest

Коды выхода: 0 — чисел нет, 1 — число написано руками.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

ЧИСЛО = (r"(?:\d{1,3}|одна|два|две|три|четыре|пять|шесть|семь|восемь|девять|"
         r"десять|одиннадцать|двенадцать|тринадцать|двадцать|двадцать одна|"
         r"двадцать одну|двадцать пять|one|two|three|four|five|six|seven|eight|"
         r"nine|ten|eleven|twelve|twenty|twenty-one|twenty-five)")
ПРОВЕРКА = r"(?:гейт\w*|провер(?:ка|ки|ок|ки)|gates?|checks?)"

# Число и слово рядом в любом порядке: «21 гейт», «двадцать одна проверка»,
# «проверок — 25», «21 checks».
ШАБЛОНЫ = (
    re.compile(ЧИСЛО + r"\s+" + ПРОВЕРКА, re.IGNORECASE),
    re.compile(ПРОВЕРКА + r"\s*[—:-]?\s*" + ЧИСЛО, re.IGNORECASE),
    # Имя стадии и голое число без слова «гейт»: «`prod` — 21». Такую форму
    # первая редакция гейта пропустила, и рядом с исправленной строкой осталось
    # неверное число — замер 25.09.2026, START_HERE.md.
    re.compile(r"(?:build|prod|продакшен|сборка)`?\s*[—:-]\s*" + ЧИСЛО,
               re.IGNORECASE),
)

# Одного числа рядом со словом «проверка» мало: живой прогон дал четыре ложные
# тревоги из семи — «ни одна проверка», «самопроверка 10/10», «Проверка одна:
# закрой экран», «(21 проверка)» про самопроверку одного инструмента. Ложная
# тревога в гейте дороже пропуска: её перестают читать. Поэтому требуется ещё и
# предмет: речь про объём проверок стадии или про то, что гоняет CI.
ПРЕДМЕТ = re.compile(r"стади\w*|\bbuild\b|\bprod\b|продакшен|сборк\w*|"
                     r"обязательн\w*|\bCI\b|run_all_gates", re.IGNORECASE)
# «ни одна проверка» — оборот речи, а не количество.
НЕ_СЧЁТ = re.compile(r"ни одн\w+\s+провер|самопроверка\s*\d", re.IGNORECASE)

# Рядом со списком число законно: его правят в том же абзаце.
РЯДОМ_СО_СПИСКОМ = re.compile(r"^\s*(?:[-*+]|\d+\.|\|)")
# Датированный замер — это история, а не обещание.
ДАТА = re.compile(r"\b\d{2}\.\d{2}\.20\d{2}\b")
# Цитата неверного числа законна там, где сказано, что оно неверно: свод обязан
# уметь назвать находку дословно. Правило то же, что у запрета текста в H110.
# Число в «кавычках-ёлочках» плюс слово, объявляющее его неверным.
В_КАВЫЧКАХ = re.compile(r"«[^»]*\d[^»]*»|«[^»]*(?:одна|два|две|три|четыре|пять)[^»]*»",
                        re.IGNORECASE)
ОПРОВЕРЖЕНИЕ = re.compile(r"а машина|по факту|при \d|неверн\w*|устарел\w*|"
                          r"обещал\w*|стояло|не видел|оставили|требовал\w*",
                          re.IGNORECASE)

МИМО_ФАЙЛОВ = ("CHANGELOG.md", "LAB.md")
# Гейты и их самопроверки сами содержат образцы запрещённых фраз.
МИМО_ПУТЕЙ = ("/.git/", "/dist/", "/rules/", "/tools/", "/evidence/",
              "store_app/index.html", "/store_app/product/")


def мимо(путь: str) -> bool:
    return (any(ч in путь for ч in МИМО_ПУТЕЙ)
            or pathlib.Path(путь).name in МИМО_ФАЙЛОВ)


def беды_текста(текст: str, где: str) -> list[str]:
    плохо = []
    for н, строка in enumerate(текст.splitlines(), 1):
        if РЯДОМ_СО_СПИСКОМ.match(строка) or ДАТА.search(строка):
            continue
        if not ПРЕДМЕТ.search(строка) or НЕ_СЧЁТ.search(строка):
            continue
        if В_КАВЫЧКАХ.search(строка) and ОПРОВЕРЖЕНИЕ.search(строка):
            continue
        for ш in ШАБЛОНЫ:
            м = ш.search(строка)
            if м:
                плохо.append(f"{где}:{н} число проверок написано руками — «"
                             f"{м.group(0).strip()}»; назови команду, а не число")
                break
    return плохо


def беды() -> list[str]:
    плохо: list[str] = []

    for ф in sorted(КОРЕНЬ.rglob("*.md")):
        путь = str(ф.relative_to(КОРЕНЬ))
        if мимо("/" + путь):
            continue
        плохо += беды_текста(ф.read_text(encoding="utf-8"), путь)

    содержимое = КОРЕНЬ / "store_app" / "content.json"
    if содержимое.exists():
        данные = json.loads(содержимое.read_text(encoding="utf-8"))
        for р in данные.get("разделы") or []:
            for поле in ("тело", "тело_en"):
                плохо += беды_текста(р.get(поле) or "",
                                     f"content.json раздел {р.get('номер','?')} {поле}")
    return плохо


def проверить() -> int:
    плохо = беды()
    for б in плохо:
        print("  ✗ " + б)
    if плохо:
        print("\nНЕ УСПЕХ (H113): число проверок живёт в тексте отдельно от факта.")
        return 1
    print("H113 цел: количество проверок нигде не написано руками.")
    return 0


def _selftest() -> int:
    провалы = []

    def проба(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    print("Самопроверка check_counted_claims:")

    проба("«21 гейт» ловится",
          беды_текста("На стадии prod применяется весь набор (21 гейт).", "x") != [])
    проба("«двадцать одна проверка» ловится",
          беды_текста("Для этой стадии обязательна двадцать одна проверка.", "x") != [])
    проба("«`prod` — 21» без слова «гейт» ловится",
          беды_текста("Объём задаёт стадия: `prod` — 21.", "x") != [])
    проба("«проверок — 25» ловится",
          беды_текста("Обязательных проверок — 25.", "x") != [])
    проба("английское «21 checks» ловится",
          беды_текста("On prod twenty-one checks are mandatory.", "x") != [])
    проба("команда вместо числа проходит",
          беды_текста("Точное число для стадии называет stage_gates.py --stage prod.", "x") == [])
    проба("пункт списка не трогается",
          беды_текста("- три проверки этого раздела", "x") == [])
    проба("датированный замер не трогается",
          беды_текста("Замер 25.09.2026: 25 гейтов на продакшене.", "x") == [])
    проба("лимит платформы не трогается",
          беды_текста("Тело запроса — до 64 КБ, ответ меньше 200 КБ.", "x") == [])
    # Контроль на ложные тревоги: живые строки, которые гейт обязан пропустить.
    for оборот in ("видела ни одна проверка запуском:",
                   "самопроверка 10/10). Он не прячет проблемы: паспорт, не прошедший гейт",
                   "Проверка одна: закрой остальной экран и посмотри",
                   "Самопроверка инструмента: --selftest (21 проверка)."):
        проба(f"оборот речи пропускается: «{оборот[:34]}…»",
              беды_текста(оборот, "x") == [])

    проба("цитата неверного числа рядом с опровержением пропускается",
          беды_текста("На стадии prod обещали «21 гейт», а машина требовала 25.", "x") == [])
    проба("то же число без опровержения ловится",
          беды_текста("На стадии prod применяется «21 гейт».", "x") != [])

    проба("H113 назван в тексте проверки",
          "H113" in pathlib.Path(__file__).read_text(encoding="utf-8"))
    # Живого дерева здесь НЕТ намеренно (H114) — см. соседние гейты.

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы — " + "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    sys.exit(_selftest() if "--selftest" in sys.argv else проверить())
