#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Подключить агента к Extella, не спрашивая у человека ничего.

ЗАЧЕМ. Вход в канон велел агенту: «попроси пользователя открыть Extella и
написать в чате „Сгенерируй мне API-токен“, пусть пришлёт строку тебе». Готовый
промпт рядом запрещал ровно это: «не проси переслать его в чат». Противоречие
внутри единственного входа, и побеждал README — промпт сам отправляет агента
читать README как источник правды. Человек, который Extella не знает, упирался
в тупик: где чат, что писать, куда вставлять секрет (замер владельца 26.08.2026).

ЧЕМ ДОКАЗЫВАЕТСЯ ПОДКЛЮЧЕНИЕ. Рукопожатием — нельзя. Замер 28.09.2026:
`initialize` с заведомо неверным ключом отвечает HTTP 200 и `"result"`, а
`tools/list` отдаёт каталог инструментов и вовсе без авторизации. Прежняя
редакция считала успехом подстроку `"result"` — то есть объявляла «подключено»
на любой строке вместо ключа. Именно так новичок уходил искать поломку там, где
её нет. Доказательство только одно: ВЫЗОВ защищённого инструмента, читающего
данные аккаунта, и разбор его ответа.

ЗАЧЕМ ЗАГОЛОВОК АГЕНТА. Тем же замером: `tools/call list_agents` с верным ключом,
но без `X-Agent-Id`, отвечает `isError: true` и текстом «Failed to resolve
dependency 'token'» — сообщение винит ключ, хотя ключ верен. С непустым
`X-Agent-Id` тот же вызов отдаёт данные. Заголовку достаточно быть непустым:
несуществующий идентификатор агента даёт тот же ответ, что и настоящий (это
проверено на list_agents; инструменты, работающие В области агента, требуют
настоящего). Поэтому подключение возможно и на пустом аккаунте, а своего агента
человек заводит после.

ЧТО ДЕЛАЕТ.
  1. находит ключ по канонному порядку (тому же, что у platform_client);
  2. проверяет доступ ВЫЗОВОМ инструмента и разбирает ответ по полям;
  3. прописывает MCP-сервер клиенту (Claude Code, Codex) со всеми заголовками;
  4. если ключа нет или доступ не доказан — называет одно действие человека.

ГДЕ ЛЕЖИТ СЕКРЕТ. Claude Code умеет `headersHelper` — скрипт, который отдаёт
заголовки в момент вызова. Тогда ключ не попадает ни в конфиг, ни в аргументы
команды (а значит, и в `ps`). Этим путём и идём. У Codex такого нет: ему ключ
пишется в `~/.codex/config.toml`, поэтому файл переводится в режим 600 и это
сказано вслух, а не умолчано.

ЧУЖОЕ НЕ ТРОГАЕМ. Уже настроенный и живой сервер `extella` не переписывается:
у человека может быть своя связка на другой аккаунт.

    python3 tools/connect_mcp.py              # подключить
    python3 tools/connect_mcp.py --проверить  # только сказать, как есть
    python3 tools/connect_mcp.py --json
    python3 tools/connect_mcp.py --selftest

Коды выхода: 0 — только если доступ доказан вызовом и клиент настроен.
1 — нужен человек: нет ключа, ключ не признан, клиента нет, запись не прошла.
"""

import argparse
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import urllib.error
import urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import platform_client  # общий список источников ключа: копий больше нет (F02)

ЯДРО_MCP = "https://api.extella.ai/mcp/"
# Второй, ЧЕСТНЫЙ канал: им уточняем причину отказа MCP.
ЯДРО_REST = "https://api.extella.ai"
ИМЯ_СЕРВЕРА = "extella"
# Читающий инструмент, которым доказывается доступ. Ничего не меняет.
ПРОБНЫЙ_ИНСТРУМЕНТ = "list_agents"
# Платформе достаточно НЕПУСТОГО значения (замер 28.09.2026). Если человек
# завёл своего агента — берём его, чтобы проба шла в той же области, где
# потом пойдёт работа.
ЗАПАСНОЙ_АГЕНТ = "agent_extella_default"
ФАЙЛ_АГЕНТА = ".extella/agent_id.txt"

# Замер 24.09.2026 на Extella 1.3.0: приложение НЕ кладёт ключ на диск — в его сборке
# нет ни одного упоминания `api_token`, `.extella/` или `token.txt`, а файлы на машине
# владельца остались от прежних заходов (июль–август). Прежний текст отправлял человека
# «просто открыть приложение», и на новой машине это не срабатывало никогда: именно на
# этом встали коллеги. Рабочий путь появился в той же версии — свой экран токенов.
НЕТ_КЛЮЧА = ("Ключа на этой машине нет, и приложение само его на диск не кладёт. "
             "Одно действие человека: в приложении Extella открыть Library → System → "
             "Tokens, создать токен и скопировать его, затем сохранить в "
             "~/.extella/api_token.txt (права 600) или передать переменной "
             "EXTELLA_API_TOKEN. Присылать ключ в переписку не нужно никогда.")


def дом() -> pathlib.Path:
    """Домашняя папка берётся из окружения, а не кэшируется: иначе самопроверку
    негде прогнать, не тронув настоящие конфиги человека."""
    return pathlib.Path(os.environ.get("HOME") or pathlib.Path.home())


def места():
    """Больше не свой список: порядок берётся из platform_client, назначение
    «ядро» — мы настраиваем MCP ядра, а не магазин. Своя копия разошлась бы
    молча, и человек получил бы «из терминала работает, из приложения нет» —
    это H78, и самопроверка ниже сверяет наш порядок с канонным списком, а не
    надеется на память."""
    return platform_client.источники("ядро")


def найти_ключ():
    """Первый непустой источник — для совместимости с прежними вызовами."""
    найдено = platform_client.найденные("ядро")
    if not найдено:
        return "", None, ""
    место, значение, путь = найдено[0]
    return значение, путь, место


def агент_для_пробы() -> str:
    """Свой агент, если человек его уже завёл; иначе платформенный. Значение
    обязано быть непустым — пустое даёт отказ, винящий ключ."""
    файл = дом() / ФАЙЛ_АГЕНТА
    if файл.exists():
        своё = файл.read_text(encoding="utf-8").strip()
        if своё:
            return своё
    return ЗАПАСНОЙ_АГЕНТ


def заголовки(ключ: str, агент: str) -> dict:
    """Один набор заголовков для пробы и для конфигурации клиента: разъедутся —
    проба будет доказывать не то, чем человек потом работает."""
    return {"Content-Type": "application/json",
            "Accept": "application/json, text/event-stream",
            "X-Auth-Token": ключ, "X-Profile-Id": "default",
            "X-Agent-Id": агент}


def последний_ответ(текст: str):
    """MCP отвечает потоком `data: {...}`. Берём последний разобранный объект;
    ни одного — значит ответ не наш, и это не успех."""
    найдено = None
    for строка in текст.splitlines():
        строка = строка.strip()
        if строка.startswith("data:"):
            строка = строка[5:].strip()
        if not строка.startswith("{"):
            continue
        try:
            найдено = json.loads(строка)
        except json.JSONDecodeError:
            continue
    return найдено


def _запрос(тело: dict, ключ: str, агент: str, сессия: str, таймаут: int):
    з = заголовки(ключ, агент)
    if сессия:
        з["Mcp-Session-Id"] = сессия
    запрос = urllib.request.Request(ЯДРО_MCP, data=json.dumps(тело).encode(),
                                    method="POST", headers=з)
    with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
        return (ответ.read(600_000).decode("utf-8", "replace"),
                ответ.headers.get("Mcp-Session-Id") or "")


def уточнить_по_rest(ключ: str, таймаут: int = 40) -> str:
    """MCP на неверный ключ отвечает HTTP 200 и словом про «зависимость token» —
    по нему причину не назвать. REST в этот же момент отвечает честно: замер
    28.09.2026 дал HTTP 401 «Invalid or expired token» на неверный ключ и HTTP 200
    на верный, причём БЕЗ заголовка агента. Поэтому причину спрашиваем у REST,
    а не пересказываем формулировку MCP.
    """
    запрос = urllib.request.Request(
        f"{ЯДРО_REST}/api/agent/list", data=b"{}", method="POST",
        headers={"Content-Type": "application/json",
                 "X-Auth-Token": ключ, "X-Profile-Id": "default"})
    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
            если_200 = ответ.status == 200
    except urllib.error.HTTPError as о:
        if о.code in (401, 403):
            return ("Extella не признала ключ (REST: HTTP "
                    f"{о.code}). Library → System → Tokens, создать новый "
                    "и сохранить в ~/.extella/api_token.txt.")
        return f"ключ не доказан: REST ответил {о.code}, MCP — отказом инструмента"
    except Exception as о:
        return (f"MCP отказал инструменту, а REST не ответил ({str(о)[:60]}) — "
                "причину назвать нечем, проверь сеть и повтори")
    if если_200:
        # Ключ верен, а MCP всё равно отказал: дело в канале, а не в человеке.
        return ("ключ ВЕРЕН — REST с ним отвечает 200, но MCP отказал вызову "
                "инструмента. Причина не в ключе: проверь адрес MCP и заголовки "
                "(нужен непустой X-Agent-Id), а токен не меняй.")
    return "ключ не доказан ни MCP, ни REST"


def проверить_доступ(ключ: str, таймаут: int = 60) -> dict:
    """Пять раздельных состояний вместо одного «подключено».

    сервер_доступен — Extella ответила на рукопожатие (ничего не доказывает);
    ключ_признан    — защищённый инструмент ВЫЗВАН и отдал данные аккаунта.

    Пустой список у нового аккаунта — законный успех, а не отказ.
    """
    итог = {"сервер_доступен": False, "ключ_признан": False,
            "этап": "рукопожатие", "почему": "", "агент_пробы": агент_для_пробы()}
    агент = итог["агент_пробы"]
    # Заголовки HTTP — latin-1. Кириллица в ключе означает, что скопирован не тот
    # текст; без этой проверки человек получает невнятную ошибку кодека.
    try:
        ключ.encode("latin-1")
    except UnicodeEncodeError:
        итог["почему"] = ("в ключе нелатинские символы — скорее всего скопирован "
                          "не тот текст. Library → System → Tokens, скопировать "
                          "значение целиком.")
        итог["причина_местная"] = True  # до сети не дошли ПО НАШЕЙ проверке
        return итог
    рукопожатие = {"jsonrpc": "2.0", "id": 1, "method": "initialize",
                   "params": {"protocolVersion": "2024-11-05", "capabilities": {},
                              "clientInfo": {"name": "extella-standards",
                                             "version": "2"}}}
    try:
        текст, сессия = _запрос(рукопожатие, ключ, агент, "", таймаут)
    except urllib.error.HTTPError as о:
        итог["почему"] = f"Extella ответила {о.code} на рукопожатие MCP"
        return итог
    except Exception as о:
        итог["почему"] = f"не дошёл до Extella ({str(о)[:80]})"
        return итог
    if not последний_ответ(текст):
        итог["почему"] = "ответ на рукопожатие не разобран как JSON-RPC"
        return итог
    итог["сервер_доступен"] = True
    итог["этап"] = "вызов инструмента"

    вызов = {"jsonrpc": "2.0", "id": 2, "method": "tools/call",
             "params": {"name": ПРОБНЫЙ_ИНСТРУМЕНТ, "arguments": {}}}
    try:
        текст, _ = _запрос(вызов, ключ, агент, сессия, таймаут)
    except urllib.error.HTTPError as о:
        итог["почему"] = (
            "ключ найден, но Extella его не признала — похоже, он от другого "
            "аккаунта. Library → System → Tokens, создать новый."
            if о.code in (401, 403) else
            f"Extella ответила {о.code} на вызов {ПРОБНЫЙ_ИНСТРУМЕНТ}")
        return итог
    except Exception as о:
        итог["почему"] = f"вызов инструмента не дошёл ({str(о)[:80]})"
        return итог

    ответ = последний_ответ(текст)
    if not ответ:
        итог["почему"] = "ответ инструмента не разобран как JSON-RPC"
        return итог
    if "error" in ответ:
        итог["почему"] = str(ответ["error"].get("message", ""))[:160]
        return итог
    результат = ответ.get("result") or {}
    if результат.get("isError"):
        # HTTP 200 и «result» — но инструмент отказал. Ровно это прежняя
        # редакция считала успехом.
        куски = результат.get("content") or [{}]
        текст_ошибки = str(куски[0].get("text", ""))[:200]
        if "dependency 'token'" in текст_ошибки:
            итог["почему"] = уточнить_по_rest(ключ)
            return итог
        итог["почему"] = текст_ошибки or "инструмент вернул ошибку без текста"
        return итог
    итог["ключ_признан"] = True
    итог["этап"] = "доступ доказан"
    return итог


def обезвредить(текст: str, ключ: str) -> str:
    """Ни один наш вывод не имеет права нести значение ключа."""
    чистый = текст.replace(ключ, "…") if ключ else текст
    # На случай, если ключ пришёл в ответе не тем же написанием.
    return re.sub(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}",
                  "…", чистый)


def написать_помощника(файл_ключа) -> pathlib.Path:
    """Скрипт отдаёт заголовки в момент вызова, читая ключ из файла. Значение
    не попадает ни в конфиг MCP, ни в аргументы команды, ни в `ps`."""
    папка = дом() / ".extella" / "mcp"
    папка.mkdir(parents=True, exist_ok=True)
    помощник = папка / "standards.sh"
    # Если ключ пришёл переменной окружения, файла нет — помощник обязан читать
    # ЯДРОВЫЙ файл, а не магазинный: он настраивает MCP ядра.
    источник = str(файл_ключа) if файл_ключа else str(
        дом() / platform_client.ФАЙЛ_ЯДРА)
    помощник.write_text(
        "#!/bin/sh\n"
        "# Заголовки для MCP Extella. Ключ читается из файла в момент вызова:\n"
        "# так он не лежит в конфиге агента и не виден в списке процессов.\n"
        "# X-Agent-Id обязателен: без него КАЖДЫЙ вызов инструмента отвечает\n"
        "# \"Failed to resolve dependency token\" — и человек чинит ключ,\n"
        "# который в порядке (замер 28.09.2026).\n"
        f'AGENT=$(cat "$HOME/{ФАЙЛ_АГЕНТА}" 2>/dev/null)\n'
        f'[ -n "$AGENT" ] || AGENT="{ЗАПАСНОЙ_АГЕНТ}"\n'
        f'printf \'{{"X-Auth-Token":"%s","X-Profile-Id":"default","X-Agent-Id":"%s"}}\\n\' '
        f'"$(cat "{источник}")" "$AGENT"\n',
        encoding="utf-8")
    os.chmod(помощник, 0o700)
    return помощник


def уже_настроен_claude() -> bool:
    конфиг = дом() / ".claude.json"
    if not конфиг.exists():
        return False
    try:
        d = json.loads(конфиг.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return False
    if ИМЯ_СЕРВЕРА in (d.get("mcpServers") or {}):
        return True
    # И область проекта: там связка могла остаться от прежних попыток.
    for пр in (d.get("projects") or {}).values():
        if ИМЯ_СЕРВЕРА in ((пр or {}).get("mcpServers") or {}):
            return True
    return False


def подключить_claude(ключ: str, файл_ключа, сухой: bool) -> dict:
    if not shutil.which("claude"):
        return {"клиент": "claude", "состояние": "нет на машине"}
    if уже_настроен_claude():
        return {"клиент": "claude", "состояние": "уже настроен — не трогаю"}
    if сухой:
        return {"клиент": "claude", "состояние": "подключил бы через headersHelper"}
    помощник = написать_помощника(файл_ключа)
    описание = json.dumps({"type": "http", "url": ЯДРО_MCP,
                           "headersHelper": str(помощник)}, ensure_ascii=False)
    # --scope user обязателен: без него сервер ложится в область ТЕКУЩЕЙ папки
    # (`projects.<cwd>` в ~/.claude.json). Агент настроил бы связку в каталоге,
    # где случайно оказался, а в остальных её бы не было — и человек честно
    # видел бы «не подключено» после успешного отчёта (замер 26.08.2026).
    итог = subprocess.run(
        ["claude", "mcp", "add-json", "--scope", "user", ИМЯ_СЕРВЕРА, описание],
        capture_output=True, text=True, timeout=120)
    вывод = ((итог.stdout or "") + (итог.stderr or "")).strip()
    if итог.returncode == 0:
        return {"клиент": "claude", "состояние": "подключено",
                "секрет_в_конфиге": False}
    return {"клиент": "claude", "состояние": "отказ",
            "почему": обезвредить(вывод, ключ)[:200]}


def подключить_codex(ключ: str, сухой: bool) -> dict:
    """Codex держит MCP в TOML `[mcp_servers.*]`. README раньше показывал ему
    JSON `mcpServers` — формат Claude Code; по нему Codex не подключался."""
    конфиг = дом() / ".codex" / "config.toml"
    if not конфиг.parent.exists():
        return {"клиент": "codex", "состояние": "нет на машине"}
    текст = конфиг.read_text(encoding="utf-8") if конфиг.exists() else ""
    if f"[mcp_servers.{ИМЯ_СЕРВЕРА}]" in текст:
        return {"клиент": "codex", "состояние": "уже настроен — не трогаю"}
    if сухой:
        return {"клиент": "codex", "состояние": "дописал бы в config.toml",
                "секрет_в_конфиге": True}
    кусок = (f'\n[mcp_servers.{ИМЯ_СЕРВЕРА}]\n'
             f'enabled = true\n'
             f'url = "{ЯДРО_MCP}"\n'
             f'\n[mcp_servers.{ИМЯ_СЕРВЕРА}.http_headers]\n'
             f'X-Auth-Token = "{ключ}"\n'
             f'X-Profile-Id = "default"\n'
             # Без агента Codex получит тот же отказ, винящий ключ.
             f'X-Agent-Id = "{агент_для_пробы()}"\n')
    конфиг.write_text(текст + кусок, encoding="utf-8")
    os.chmod(конфиг, 0o600)  # у Codex нет помощника заголовков: ключ лежит в файле
    return {"клиент": "codex", "состояние": "подключено", "секрет_в_конфиге": True,
            "почему": "у Codex нет headersHelper — ключ в config.toml, файл 600"}


def подключить(сухой: bool) -> dict:
    # НЕ УГАДЫВАЕМ, КАКОЙ ФАЙЛ ЖИВОЙ. Раньше брался первый попавшийся, и мёртвый
    # ключ от прежнего аккаунта побеждал рабочий из соседнего файла. Теперь каждый
    # источник ДОКАЗЫВАЕТСЯ вызовом, и в отчёте сказано, который сработал.
    найдено = platform_client.найденные("ядро")
    if not найдено:
        return {"итог": "нужен человек", "почему": НЕТ_КЛЮЧА, "клиенты": []}
    отвергнутые, ключ, файл, место, доступ = [], "", None, "", None
    for м, значение, путь in найдено:
        проба = проверить_доступ(значение)
        if проба["ключ_признан"]:
            ключ, файл, место, доступ = значение, путь, м, проба
            break
        отвергнутые.append(f"{м}: {проба['почему'][:90]}")
        доступ = доступ or проба
    if not ключ:
        почему = (доступ or {}).get("почему") or НЕТ_КЛЮЧА
        if not (доступ or {}).get("сервер_доступен") and not (доступ or {}).get("причина_местная"):
            почему = f"до Extella не дошли: {почему}"
        return {"итог": "нужен человек", "почему": почему,
                "проверено_источников": len(найдено), "отвергнуты": отвергнутые,
                "доступ": доступ, "клиенты": []}

    клиенты = [подключить_claude(ключ, файл, сухой), подключить_codex(ключ, сухой)]
    нашлись = [к for к in клиенты if к["состояние"] != "нет на машине"]
    отказы = [к for к in клиенты if к["состояние"] == "отказ"]

    # ЧЕТЫРЕ РАЗНЫХ ИСХОДА ВМЕСТО ОДНОГО. Прежняя редакция называла «подключено»
    # даже состояние «клиент не найден» и отдавала 0 — человек читал успех и шёл
    # дальше, хотя работать было нечем.
    if not нашлись:
        итог = "клиент не найден"
    elif отказы:
        итог = "нужен человек"
    else:
        итог = "клиент настроен"

    отчёт = {"итог": итог, "ключ_взят": место, "доступ": доступ,
             "отвергнуты": отвергнутые,
             "ключ_проверен": f"вызовом {ПРОБНЫЙ_ИНСТРУМЕНТ}, ответ разобран",
             "клиенты": клиенты}
    if отказы:
        отчёт["почему"] = "; ".join(
            f"{к['клиент']}: {к.get('почему', 'отказ записи')}" for к in отказы)
    if итог == "клиент настроен":
        свежие = [к for к in клиенты if к["состояние"] == "подключено"]
        отчёт["требуется_перезапуск"] = bool(свежие)
        # Скрипт НЕ ИМЕЕТ ПРАВА утверждать последний шаг: вызов из самого клиента
        # произойдёт только после его перезапуска. Честно называем это отдельно.
        отчёт["инструмент_вызван_из_клиента"] = False
    return отчёт


def код_выхода(отчёт: dict) -> int:
    """Ноль — только когда доступ доказан вызовом и клиент настроен."""
    return 0 if отчёт.get("итог") == "клиент настроен" else 1


def напечатать(отчёт: dict) -> None:
    if отчёт["итог"] == "нужен человек":
        print("✗ " + отчёт["почему"])
        for о in отчёт.get("отвергнуты") or []:
            print("    не подошёл " + о)
        return
    print(f"ключ взят: {отчёт['ключ_взят']} · проверен {отчёт['ключ_проверен']}")
    доступ = отчёт.get("доступ") or {}
    print(f"  сервер Extella: {'доступен' if доступ.get('сервер_доступен') else 'нет'}")
    print(f"  ключ признан:   {'да' if доступ.get('ключ_признан') else 'нет'}"
          f" (агент пробы {доступ.get('агент_пробы', '—')})")
    for о in отчёт.get("отвергнуты") or []:
        print("  не подошёл " + о)
    for к in отчёт["клиенты"]:
        строка = f"  {к['клиент']}: {к['состояние']}"
        if к.get("почему"):
            строка += f" — {к['почему']}"
        print(строка)
    if отчёт["итог"] == "клиент не найден":
        print("✗ ни Claude Code, ни Codex на этой машине не найдены — "
              "настраивать нечего")
        return
    if отчёт.get("требуется_перезапуск"):
        print("Осталось одно: перезапустить клиент и вызвать любой инструмент "
              "Extella. До этого вызова подключение не доказано.")
    else:
        print("Клиент уже был настроен — значение ключа нигде не показано.")


