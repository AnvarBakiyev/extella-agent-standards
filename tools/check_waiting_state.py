#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Ожидание должно быть видно: кнопка, которая молчит, — дефект.

ЗАЧЕМ. Нажатие запускает эксперта. Ядро отвечает за 1,7 секунды, эксперт — за 13,
вызов со страницы до устройства — за 13–17. Всё это время человек смотрит на
неизменившийся экран. Он не читает журналы и не знает, что что-то идёт: он жмёт
второй раз, потом третий, потом решает, что продукт сломан. Двойное нажатие — это
не только нервы: второй запуск уходит на платформу и делает работу дважды.

ЧТО ПРОВЕРЯЕТСЯ. У каждой функции, которая ходит на платформу:

  1. состояние ожидания включается ДО вызова (кнопка выключена или помечена);
  2. есть finally — иначе первая же ошибка оставит кнопку мёртвой навсегда;
  3. состояние снимается (кнопку возвращают в работу);
  4. для вызовов эксперта и устройства — ещё и слова на экране: спиннер без
     подписи через десять секунд неотличим от зависания.

ЧЕГО ПРОВЕРКА НЕ УМЕЕТ. Она не измеряет время до первого кадра и не判 судит о
красоте. Это работа человека и правила по дизайну (автор Элла).

Фоновая задача, которую никто не ждёт, освобождается строкой-пометкой над
функцией:  // ожидание: фоновая задача

  python3 check_waiting_state.py app/index.html app/panel.js
  python3 check_waiting_state.py --selftest

Коды выхода: 0 — ожидание видно везде, 1 — есть немые кнопки, 2 — файлы не прочитаны.
"""
import pathlib
import re
import sys

# Вызовы, после которых человек ждёт. run_expert и device — самые долгие.
ПЛАТФОРМА = re.compile(
    r"(await\s+fetch\s*\(|fetch\s*\(\s*['\"`]/api|run_expert|/api/ext/core|"
    r"agent/run|await\s+api\s*\()")
ДОЛГИЕ = re.compile(r"(run_expert|/api/ext/core|agent/run|device)")

# Пометка «ожидания не нужно»: фоновый опрос, автосохранение, телеметрия.
ОСВОБОЖДЕНИЕ = "ожидание: фоновая задача"

# Включение ожидания. Написаний много, поэтому список открытый и обновляемый.
ВКЛЮЧЕНИЕ = re.compile(
    r"(disabled\s*=\s*true|setAttribute\(\s*['\"]disabled|aria-busy|"
    r"setBusy\s*\(\s*(?!false)|classList\.add\s*\(\s*['\"][^'\"]*"
    r"(busy|wait|load|progress|ожид|загруз))", re.IGNORECASE)
СНЯТИЕ = re.compile(
    r"(disabled\s*=\s*false|removeAttribute\(\s*['\"]disabled|"
    r"setBusy\s*\(\s*false|classList\.remove)", re.IGNORECASE)
# Слова на экране: текст, который человек прочитает.
СЛОВА = re.compile(r"(textContent\s*=|innerText\s*=|innerHTML\s*=|toast\s*\(|"
                   r"статус\s*\(|setStatus\s*\()")

# Обращение к экрану. Функция, которая НИ РАЗУ не трогает экран, — это транспорт
# (общий помощник запроса). Показывать ожидание ей нечем и не нужно: состояние
# показывает тот, у кого есть кнопка. Проверять транспорт — верный способ
# получить полсотни ложных тревог и отключённую проверку.
ЭКРАН = re.compile(
    r"(document\.|querySelector|getElementById|textContent|innerText|innerHTML|"
    r"classList|\.disabled|\.style\.|toast\s*\(|render[A-ZА-Я\w]*\s*\()")

НАЧАЛО_ФУНКЦИИ = re.compile(
    r"(function\s*[\w$]*\s*\([^)]*\)\s*\{|\([^()]*\)\s*=>\s*\{|"
    r"[\w$]+\s*\([^()]*\)\s*\{)")


def _тело(текст: str, с: int) -> tuple:
    """Границы тела функции от её открывающей скобки. Считаем скобки, а не гадаем."""
    i = текст.find("{", с)
    if i < 0:
        return (с, с)
    глубина = 0
    for j in range(i, len(текст)):
        if текст[j] == "{":
            глубина += 1
        elif текст[j] == "}":
            глубина -= 1
            if глубина == 0:
                return (i, j + 1)
    return (i, len(текст))


def функции_с_вызовом(текст: str) -> list:
    """Функции, внутри которых есть вызов платформы. Самая внутренняя выигрывает."""
    найдено = []
    for м in НАЧАЛО_ФУНКЦИИ.finditer(текст):
        н, к = _тело(текст, м.start())
        тело = текст[н:к]
        if not ПЛАТФОРМА.search(тело):
            continue
        if not ЭКРАН.search(тело):
            continue                       # транспорт, а не кнопка
        найдено.append((м.start(), н, к))
    # Вложенные функции: оставляем самую внутреннюю, иначе одна и та же кнопка
    # будет названа дважды.
    итог = []
    for с, н, к in найдено:
        если_вложена = any(н2 < н and к <= к2 for _, н2, к2 in найдено if (н2, к2) != (н, к))
        if not если_вложена:
            итог.append((с, н, к))
    return итог


def проверить_текст(текст: str) -> list:
    беды = []
    for с, н, к in функции_с_вызовом(текст):
        # Пометка ищется в двух строках над функцией.
        выше = текст[max(0, с - 200):с]
        if ОСВОБОЖДЕНИЕ in выше.split("\n")[-3:][0] or ОСВОБОЖДЕНИЕ in выше:
            continue
        тело = текст[н:к]
        строка = текст[:с].count("\n") + 1
        вызов = ПЛАТФОРМА.search(тело)
        до_вызова = тело[:вызов.start()] if вызов else тело

        if not ВКЛЮЧЕНИЕ.search(до_вызова):
            беды.append((строка, "ожидание не включено ДО вызова — человек увидит "
                                 "неизменившийся экран и нажмёт второй раз"))
        elif "finally" not in тело:
            беды.append((строка, "нет finally — первая же ошибка оставит кнопку "
                                 "выключенной навсегда"))
        elif not СНЯТИЕ.search(тело):
            беды.append((строка, "ожидание включается, но не снимается — кнопка "
                                 "останется мёртвой после успеха"))
        elif ДОЛГИЕ.search(тело) and not СЛОВА.search(тело):
            беды.append((строка, "долгий вызов без слов на экране — через десять "
                                 "секунд спиннер неотличим от зависания"))
    return беды


def selftest() -> int:
    ошибки = []

    хорошо = """
    async function сохранить() {
      кнопка.disabled = true;
      статус.textContent = 'Агент читает базу…';
      try {
        const r = await fetch('/api/ext/core/kv/set', {method:'POST'});
        статус.textContent = r.ok ? 'Готово' : 'Платформа отказала';
      } catch (e) {
        статус.textContent = 'Запрос не ушёл: ' + e.message;
      } finally {
        кнопка.disabled = false;
      }
    }"""
    if проверить_текст(хорошо):
        ошибки.append(f"правильная кнопка признана немой: {проверить_текст(хорошо)}")

    случаи = [
        ("без ожидания", хорошо.replace("кнопка.disabled = true;", ""), "не включено"),
        ("без finally", хорошо.replace("} finally {", "} if (false) {"), "finally"),
        ("без снятия", хорошо.replace("кнопка.disabled = false;", ""), "не снимается"),
        ("долгий без слов", """
    async function пуск() {
      b.disabled = true;
      try { await fetch('/api/ext/core/run_expert'); }
      finally { b.disabled = false; }
    }""", "без слов"),
    ]
    for имя, текст, ожидание in случаи:
        найдено = проверить_текст(текст)
        if not найдено:
            ошибки.append(f"«{имя}»: проверка промолчала")
        elif not any(ожидание in п for _, п in найдено):
            ошибки.append(f"«{имя}»: причина не названа, получено {найдено}")

    # Общий транспорт проверки не касается: экран он не трогает.
    транспорт = ("async function api(m, a){ const r = await fetch('/api/'+m, "
                 "{method:'POST'}); return r.json(); }")
    if проверить_текст(транспорт):
        ошибки.append("общий транспорт принят за кнопку")

    # Функция без вызова платформы проверку не касается.
    if проверить_текст("function красить(){ el.style.color = 'red'; }"):
        ошибки.append("функция без вызова платформы принята за кнопку")

    # Фоновая задача освобождается пометкой.
    фон = "// ожидание: фоновая задача\nasync function опрос(){ await fetch('/api/state'); }"
    if проверить_текст(фон):
        ошибки.append("помеченная фоновая задача всё равно красная")

    for с in ошибки:
        print(f"  ✗ {с}")
    print("selftest: " + ("провален" if ошибки else "пройден"))
    return 1 if ошибки else 0


def main(аргументы: list) -> int:
    if "--selftest" in аргументы:
        return selftest()
    файлы = [pathlib.Path(а) for а in аргументы if not а.startswith("-")]
    if not файлы:
        print("нечего проверять: укажи файлы интерфейса (.html, .js)")
        return 2
    всего = 0
    for путь in файлы:
        if not путь.exists():
            print(f"нет файла {путь}")
            return 2
        беды = проверить_текст(путь.read_text(encoding="utf-8", errors="replace"))
        всего += len(беды)
        print(f"\n{путь}: " + ("ожидание видно везде" if not беды
                               else f"немых кнопок {len(беды)}"))
        for строка, причина in беды:
            print(f"  · строка {строка}: {причина}")
    return 1 if всего else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
