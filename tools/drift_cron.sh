#!/usr/bin/env bash
# Утренняя сверка живых агентов с паспортами. Молчит, когда всё сходится.
#
# 02:00 UTC = 07:00 Алматы: отчёт ждёт к началу работы, а не приходит среди дня.
# Не 03:00 UTC — там уже стоят ops-сводки, и два разных отчёта в одной куче
# перестают читаться оба.
#
# Сверка ТАКЖЕ входит в релизные гейты (run_all_gates.sh), поэтому любой выпуск
# её и так прогоняет. Это расписание закрывает промежуток между выпусками.
set -u
cd "$(dirname "$0")/.."
OUT=$(python3 tools/check_agent_drift.py 2>&1)
if [ $? -eq 0 ]; then exit 0; fi          # сошлось — молчим, шум не нужен
printf 'РАСХОЖДЕНИЕ ПРАВ АГЕНТОВ %s\n\n%s\n' "$(date -u +%Y-%m-%dT%H:%MZ)" "$OUT"
