#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Тулкит — это три части, а не папка с промптом.

ЗАЧЕМ. Замысел рынка модулей: способность продаётся не программой, а рецептом,
и агент собирает её на месте. Замысел верный — все кирпичи Extella создаются
программно, — но у него есть дыра: промпт это не изделие, а обещание изделия.
Один и тот же текст на двух машинах даёт разный результат, и магазин
превращается в лотерею.

Дыра закрывается тремя частями, и этот гейт требует все три:

  РЕЦЕПТ.md    — что построить и как; его читает агент;
  ПАСПОРТ.md   — что модулю нужно и чего он НЕ делает; его читает человек;
  проверка.py  — машинный тест, который умеет провалиться; он читает результат;
  слепок/      — замороженный результат первой сборки: рецепт нужен один раз,
                 дальше все покупатели получают одинаковое.

Без проверки «установилось» не значит ничего — это главный урок свода: зелёные
строковые проверки при мёртвом продукте случались трижды.

    python3 tools/check_toolkit.py            # все тулкиты
    python3 tools/check_toolkit.py toolkits/чтение-договоров
    python3 tools/check_toolkit.py --selftest

Коды выхода: 0 — все тулкиты целы, 1 — есть неполные.
"""

import argparse
import pathlib
import subprocess
import sys
import tempfile

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПАПКА = КОРЕНЬ / "toolkits"

ЧАСТИ = (("РЕЦЕПТ.md", "рецепт: что построить и как — его читает агент"),
         ("ПАСПОРТ.md", "паспорт: что нужно и чего модуль НЕ делает — его читает человек"),
         ("проверка.py", "проверка: машинный тест, который умеет сказать «нет»"))

# Находки несут КОД, а не только прозу: негативный контроль сверяется с кодом.
# Первая же версия сверялась со словами и промахнулась на «слепок»/«слепка» —
# гейт считал, что не заметил пропажу, хотя заметил.


def проверить(тулкит: pathlib.Path, гонять_selftest: bool = True) -> list:
    беды = []
    for имя, зачем in ЧАСТИ:
        if not (тулкит / имя).exists():
            беды.append((имя, f"{тулкит.name}: нет части «{имя}» — {зачем}"))
    слепок = тулкит / "слепок"
    if not слепок.is_dir() or not list(слепок.glob("*.py")):
        беды.append(("слепок",
                     f"{тулкит.name}: нет слепка — рецепт без слепка даёт каждому своё"))

    паспорт = тулкит / "ПАСПОРТ.md"
    if паспорт.exists():
        текст = паспорт.read_text(encoding="utf-8")
        if "НЕ делает" not in текст and "Чего НЕ" not in текст:
            беды.append(("граница",
                         f"{тулкит.name}: паспорт не говорит, чего модуль НЕ делает — "
                         "граница важнее списка умений"))

    проверка = тулкит / "проверка.py"
    if проверка.exists() and гонять_selftest:
        итог = subprocess.run([sys.executable, str(проверка), "--selftest"],
                              capture_output=True, text=True, timeout=600)
        if итог.returncode != 0:
            хвост = ((итог.stdout or "") + (итог.stderr or "")).strip().splitlines()
            беды.append(("проверка-красная",
                         f"{тулкит.name}: собственная проверка красная — " +
                         (хвост[-1] if хвост else "без слов")))
    return беды


def selftest() -> int:
    беды = []
    if not ПАПКА.is_dir():
        print("  ✓ папки тулкитов ещё нет — проверять нечего")
        print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
        return 0

    тулкиты = [п for п in sorted(ПАПКА.iterdir()) if п.is_dir()]
    for т in тулкиты:
        беды += проверить(т)
    print(f"  ✓ тулкитов проверено: {len(тулкиты)}")

    # Негативный контроль: гейт обязан ловить неполный тулкит. Без этого он
    # молча зелёный на чём угодно.
    with tempfile.TemporaryDirectory() as вр:
        пустой = pathlib.Path(вр) / "пустой-тулкит"
        пустой.mkdir()
        (пустой / "РЕЦЕПТ.md").write_text("только рецепт", encoding="utf-8")
        коды = {к for к, _ in проверить(пустой, гонять_selftest=False)}
        пропущено = {"ПАСПОРТ.md", "проверка.py", "слепок"} - коды
        if пропущено:
            беды.append(("негативный-контроль",
                         "негативный контроль: гейт не заметил отсутствие " +
                         ", ".join(sorted(пропущено))))
    print("  ✓ гейт умеет краснеть: тулкит из одного рецепта не проходит")

    if беды:
        for _, б in беды:
            print("  ✗ " + б)
        print("ИТОГ САМОПРОВЕРКИ: провалы есть")
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("папка", nargs="?", help="один тулкит; без аргумента — все")
    р.add_argument("--selftest", action="store_true")
    о = р.parse_args()
    if о.selftest:
        return selftest()
    цели = ([pathlib.Path(о.папка)] if о.папка
            else [п for п in sorted(ПАПКА.iterdir()) if п.is_dir()] if ПАПКА.is_dir()
            else [])
    if not цели:
        print("тулкитов не найдено")
        return 0
    беды = []
    for т in цели:
        свои = проверить(т)
        print(f"{т.name}: {'целый' if not свои else 'неполный'}")
        беды += свои
    for _, б in беды:
        print("  ✗ " + б)
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
