#!/usr/bin/env python3
"""Словарь из пяти форм — общий язык приложений Extella.

ЗАЧЕМ. Сегодня каждая связка приложений — отдельный инструмент: Астра→доска,
доска→приложение, доска→правила. Три приложения дали три инструмента; при пятистах
приложениях пар выходит около 250 тысяч, и это не вопрос темпа, а вопрос устройства.

Здесь ломается сам счёт. Приложение-источник не знает про приложение-получателя, и
наоборот: оба знают только этот словарь. Источник обязан привести своё содержимое к
одной из пяти форм, получатель обязан уметь показать все пять. Тогда работы не
N×M, а N+M.

Пять форм — это НЕ «удобный набор на сегодня», а сознательный предел. Словарь,
который растёт под каждое новое приложение, — это тот же N×M, только записанный в
одном файле. Новая форма добавляется, лишь когда её нельзя выразить существующими,
и это решение уровня владельца, а не удобства.

  список   — строки с полями        (города Астры, долги из 1С, вакансии)
  число    — один итог с подписью   (сумма оттока, остаток по счёту)
  шаги     — этапы процесса         (порядок расчётов по договору)
  связи    — «А → Б» с подписью     (просрочка → пеня, условие → действие)
  документ — текст по разделам      (договор, инструкция, отчёт)

    python3 tools/формы.py --selftest
    python3 tools/формы.py --пример список
"""

import argparse
import json
import sys

ФОРМЫ = ("list", "number", "steps", "links", "document")

# ── язык словаря ─────────────────────────────────────────────────────────────
# КЛЮЧИ ПО-АНГЛИЙСКИ, ЧЕЛОВЕЧЕСКИЙ ТЕКСТ — НА ЛЮБОМ. Решение владельца
# 23.08.2026: платформу делаем международной. Язык платформенного ядра —
# забота техотдела; всё, до чего техотдел не дотягивается, — наше, и здесь
# контракт английский. Это касается ИМЁН полей, а не содержимого: заголовок,
# подписи и названия строк как были на языке человека, так и остаются.
#
# СТАРЫЕ ИМЕНА ПРИНИМАЕМ. На русских ключах уже написаны живые паспорта
# источников на диске и переданный человеком промпт агента Баға. Ломать их
# одномоментно нельзя: мы бы чинили чужое, ничего не спросив. Вход принимает
# оба языка, выход — всегда английский, и так старое само вымывается.
ПО_РУССКИ = {
    "форма": "form", "заголовок": "title", "подпись": "caption",
    "значение": "value", "строки": "rows", "шаги": "steps", "связи": "links",
    "разделы": "sections", "имя": "name", "поля": "fields", "текст": "text",
    "от": "from", "к": "to",
}
ФОРМЫ_ПО_РУССКИ = {"список": "list", "число": "number", "шаги": "steps",
                   "связи": "links", "документ": "document"}


# Как форма называется ДЛЯ ЧЕЛОВЕКА. Ключи английские — это контракт машин;
# в терминал и на карточку человеку выводим слово его языка. Смешивать нельзя:
# «Форма «list»» в отчёте — это протокол, вылезший в интерфейс.
ПО_ЧЕЛОВЕЧЕСКИ = {"list": "список", "number": "число", "steps": "шаги",
                  "links": "связи", "document": "документ"}


def по_человечески(форма: str) -> str:
    """Имя формы для показа человеку."""
    return ПО_ЧЕЛОВЕЧЕСКИ.get(форма, форма)


def перевести(значение):
    """Русские имена полей — в английские. Содержимое не трогаем."""
    if isinstance(значение, list):
        return [перевести(э) for э in значение]
    if not isinstance(значение, dict):
        return значение
    вышло = {}
    for ключ, зн in значение.items():
        новый = ПО_РУССКИ.get(ключ, ключ)
        # «поля» строки — это названия колонок, придуманные источником:
        # переводить их нельзя, это человеческий текст, а не имена полей.
        вышло[новый] = зн if новый == "fields" else перевести(зн)
    if вышло.get("form") in ФОРМЫ_ПО_РУССКИ:
        вышло["form"] = ФОРМЫ_ПО_РУССКИ[вышло["form"]]
    return вышло


class Отказ(Exception):
    """Отказ, который называет причину и что делать дальше."""


# ── описание форм ────────────────────────────────────────────────────────────
# Для каждой формы: обязательные поля верхнего уровня и правило для содержимого.
# Держим описание ДАННЫМИ, а не кодом: так проверка и пример не разъезжаются —
# они читают одно и то же место.
ОПИСАНИЕ = {
    "list":     {"поле": "rows",     "обязательно": ("name",),         "не_пусто": True},
    "number":   {"поле": None,       "обязательно": (),                "не_пусто": False},
    "steps":    {"поле": "steps",    "обязательно": ("name",),         "не_пусто": True},
    "links":    {"поле": "links",    "обязательно": ("from", "to"),    "не_пусто": True},
    "document": {"поле": "sections", "обязательно": ("name", "text"),  "не_пусто": True},
}

ПРЕДЕЛ_СТРОК = 200          # больше не читается глазами и не влезает на доску
ПРЕДЕЛ_ТЕКСТА = 4000        # раздел документа: длиннее — это уже файл, а не карточка


def проверить(д: dict) -> dict:
    """Проверить содержимое и вернуть его же. Ошибка называет, что чинить.

    Проверка строгая нарочно. Форма, приехавшая «почти правильной», рисуется
    криво, и человек винит доску, а не источник. Пусть лучше источник узнает
    о своей ошибке в тот момент, когда её ещё видно, кто допустил.
    """
    if not isinstance(д, dict):
        raise Отказ(f"ожидался словарь с полем «form», пришло {type(д).__name__}")
    д = перевести(д)                      # старые русские ключи — в канон
    форма = д.get("form")
    if форма not in ФОРМЫ:
        raise Отказ(f"неизвестная форма «{форма}». Словарь знает только: "
                    f"{', '.join(ФОРМЫ)}. Приведите содержимое к одной из них — "
                    f"новые формы добавляются решением владельца, а не источником")
    if not str(д.get("title") or "").strip():
        raise Отказ(f"у формы «{форма}» нет заголовка: без него человек не поймёт, "
                    f"что перед ним нарисовано")

    о = ОПИСАНИЕ[форма]
    if форма == "number":
        if д.get("value") in (None, ""):
            raise Отказ("у формы «number» нет поля «value»")
        return д

    пункты = д.get(о["поле"])
    if not isinstance(пункты, list):
        raise Отказ(f"у формы «{форма}» должно быть поле «{о['поле']}» — список")
    if о["не_пусто"] and not пункты:
        raise Отказ(f"у формы «{форма}» поле «{о['поле']}» пустое. Пустой результат — "
                    f"это тоже ответ, но рисовать его нечем: скажите словами")
    if len(пункты) > ПРЕДЕЛ_СТРОК:
        raise Отказ(f"в «{о['поле']}» {len(пункты)} пунктов при пределе {ПРЕДЕЛ_СТРОК}. "
                    f"Отберите главное в источнике: доска — не выгрузка, а картина")

    for i, п in enumerate(пункты, 1):
        if not isinstance(п, dict):
            raise Отказ(f"пункт {i} в «{о['поле']}» — не словарь")
        for имя in о["обязательно"]:
            if not str(п.get(имя) or "").strip():
                raise Отказ(f"в пункте {i} нет поля «{имя}» "
                            f"(обязательные для «{форма}»: {', '.join(о['обязательно'])})")
        if форма == "document" and len(str(п["text"])) > ПРЕДЕЛ_ТЕКСТА:
            raise Отказ(f"раздел «{п['name']}» длиннее {ПРЕДЕЛ_ТЕКСТА} знаков — "
                        f"разбейте на разделы, иначе это не карточка, а файл")
        if форма == "list":
            поля = п.get("fields") or {}
            if not isinstance(поля, dict):
                raise Отказ(f"в строке {i} поле «fields» должно быть словарём "
                            f"«название колонки: значение»")
    return д


def строки_пункта(п: dict, форма: str) -> list:
    """Пункт → строки для показа. Одно место на все получатели.

    Здесь же лежит правило порядка: поля выводятся в том порядке, в котором их
    положил источник. Сортировать по алфавиту нельзя — источник знает, что
    важнее, а алфавит не знает ничего.
    """
    if форма == "list":
        вывод = [str(п["name"])]
        for название, значение in (п.get("fields") or {}).items():
            вывод.append(f"{название}: {значение}")
        return вывод
    if форма == "steps":
        return [str(п["name"])] + ([str(п["caption"])] if п.get("caption") else [])
    if форма == "links":
        подпись = f" — {п['caption']}" if п.get("caption") else ""
        return [f"{п['from']} → {п['to']}{подпись}"]
    if форма == "document":
        return [str(п["name"]), str(п["text"])]
    return [json.dumps(п, ensure_ascii=False)]


def пример(форма: str) -> dict:
    """Рабочий пример формы. Нужен и людям, и модели, которая пишет паспорт."""
    примеры = {
        "list": {
            "form": "list", "title": "Отток по городам",
            "caption": "источник: витрина оттока, данные синтетические",
            "rows": [
                {"name": "Алматы", "fields": {"отток": "21%", "ушло": "1 240",
                                              "потеряно": "18,4 млн ₸"}},
                {"name": "Астана", "fields": {"отток": "14%", "ушло": "870",
                                              "потеряно": "11,2 млн ₸"}},
            ]},
        "number": {
            "form": "number", "title": "Остаток по счёту 1210",
            "value": "16 842 475 ₸",
            "caption": "получено двумя независимыми путями, цифры совпали"},
        "steps": {
            "form": "steps", "title": "Порядок расчётов по договору",
            "steps": [
                {"name": "Отгрузка", "caption": "накладная подписана обеими сторонами"},
                {"name": "Оплата", "caption": "10 банковских дней с даты накладной"},
                {"name": "Просрочка", "caption": "пеня 0,1% в день"},
            ]},
        "links": {
            "form": "links", "title": "Правила по договору",
            "links": [
                {"from": "просрочка больше 30 дней", "to": "претензия",
                 "caption": "с расчётом пени"},
                {"from": "долг больше 5 млн", "to": "остановка отгрузок", "caption": ""},
            ]},
        "document": {
            "form": "document", "title": "Договор поставки № 14",
            "sections": [
                {"name": "Предмет", "text": "Поставка оборудования по спецификации."},
                {"name": "Расчёты", "text": "Оплата в течение 10 банковских дней."},
            ]},
    }
    if форма not in примеры:
        raise Отказ(f"нет примера для «{форма}»; словарь знает: {', '.join(ФОРМЫ)}")
    return примеры[форма]


def selftest() -> int:
    ошибки = []

    for ф in ФОРМЫ:
        try:
            проверить(пример(ф))
        except Отказ as о:
            ошибки.append(f"собственный пример «{ф}» не проходит проверку: {о}")
    if not ошибки:
        print(f"  ✓ все {len(ФОРМЫ)} формы имеют рабочий пример, и он проходит проверку")

    # Проверка обязана ОТКАЗЫВАТЬ. Проверка, которая всё пропускает, опаснее её
    # отсутствия: она создаёт уверенность там, где её нет.
    плохие = [
        ({"form": "table", "title": "х"}, "неизвестная форма"),
        ({"form": "list", "rows": [{"name": "а"}]}, "нет заголовка"),
        ({"form": "list", "title": "х", "rows": []}, "пустой список"),
        ({"form": "links", "title": "х", "links": [{"from": "а"}]}, "связь без «to»"),
        ({"form": "number", "title": "х"}, "число без значения"),
        ({"form": "list", "title": "х",
          "rows": [{"name": "а"}] * (ПРЕДЕЛ_СТРОК + 1)}, "выше предела строк"),
    ]
    for д, чем in плохие:
        try:
            проверить(д)
            ошибки.append(f"пропущено то, что должно быть отвергнуто: {чем}")
        except Отказ:
            pass
    if not [о for о in ошибки if "пропущено" in о]:
        print(f"  ✓ проверка отвергает все {len(плохие)} испорченных случая")

    # ПЕРЕВОД СТАРЫХ КЛЮЧЕЙ. На русских именах написаны живые паспорта на диске
    # и переданный человеком промпт агента: если приём сломается, у людей
    # перестанет работать то, чего они не трогали.
    старая = {"форма": "список", "заголовок": "Проба", "подпись": "п",
              "строки": [{"имя": "Алматы", "поля": {"отток": "21%"}}]}
    новая = проверить(старая)
    if (новая["form"] == "list" and новая["title"] == "Проба"
            and новая["rows"][0]["name"] == "Алматы"):
        print("  ✓ форма на старых русских ключах принимается и приводится к канону")
    else:
        ошибки.append(f"старые ключи не переводятся: {новая}")
    if новая["rows"][0]["fields"] == {"отток": "21%"}:
        print("  ✓ названия колонок НЕ переводятся — это текст человека, а не имена полей")
    else:
        ошибки.append(f"названия колонок испорчены переводом: {новая['rows'][0]}")

    # Порядок полей — часть смысла: источник ставит важное первым.
    п = {"name": "Алматы", "fields": {"отток": "21%", "ушло": "1 240"}}
    с = строки_пункта(п, "list")
    if с != ["Алматы", "отток: 21%", "ушло: 1 240"]:
        ошибки.append(f"порядок полей не сохранён: {с}")
    else:
        print("  ✓ порядок полей сохраняется — сортировка по алфавиту потеряла бы смысл")

    # Словарь закрыт намеренно: рост под каждое приложение вернул бы N×M.
    if len(ФОРМЫ) != 5:
        ошибки.append(f"форм стало {len(ФОРМЫ)}: расширение словаря — решение владельца, "
                      f"а не побочный эффект правки")
    else:
        print("  ✓ словарь закрыт на пяти формах")

    print("\n" + ("ИТОГ САМОПРОВЕРКИ: все проверки прошли" if not ошибки
                  else "ОТКАЗ:\n  " + "\n  ".join(ошибки)))
    return 1 if ошибки else 0


def main() -> int:
    р = argparse.ArgumentParser(description="Словарь из пяти форм")
    р.add_argument("--selftest", action="store_true")
    р.add_argument("--пример", metavar="ФОРМА")
    р.add_argument("--проверить", metavar="ФАЙЛ")
    а = р.parse_args()
    if а.selftest:
        return selftest()
    try:
        if а.пример:
            print(json.dumps(пример(а.пример), ensure_ascii=False, indent=2))
            return 0
        if а.проверить:
            import pathlib
            д = проверить(json.loads(pathlib.Path(а.проверить).read_text()))
            print(f"✓ форма «{д['форма']}» верна: {д['заголовок']}")
            return 0
    except Отказ as о:
        print(f"ОТКАЗ: {о}", file=sys.stderr)
        return 1
    р.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
