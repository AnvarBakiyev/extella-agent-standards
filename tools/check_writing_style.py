#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проверка языка инструкций по WRITING_RULES.md (автор правила — Элла).

Проверяет только то, что поддаётся счёту:

  1. внутренние словечки, которые понятны команде и непонятны читателю;
  2. «мы», «у нас», «наш» — читатель не входит в команду;
  3. термин, использованный без определения при первом появлении.

Остальные правила проверяет человек. Машина не умеет отличить оценку от факта,
и делать вид, что умеет, — тот самый зелёный статус, который ничего не значит.

  python3 check_writing_style.py README.md store_app/content.json
  python3 check_writing_style.py --selftest

Коды выхода: 0 — нарушений нет, 1 — есть нарушения, 2 — файлы не прочитаны.
"""
import json
import pathlib
import re
import sys

# Словечко → чем его заменить. Замена нужна в тексте отказа: «так нельзя» без
# «а как можно» заставляет человека придумывать формулировку заново.
СЛОВЕЧКИ = {
    "грабл": "«частые ошибки» или прямое название того, что ломается",
    "пушь": "«отправь изменения в удалённый репозиторий»",
    "пушить": "«отправлять изменения в удалённый репозиторий»",
    "залить": "«загрузить» или «опубликовать» — смотря что происходит",
    "молча мёртв": "«не сможет работать» плюс что именно увидит человек",
    "свой мир": "«у каждого агента свой набор доступных объектов»",
    "ехать с кодом": "«поставляться вместе с кодом»",
    "уезжает покупателю": "«целиком получает покупатель»",
    "нафиг": "убрать",
    "костыл": "назвать обход прямо: что именно обходится и почему",
    "дешёв": "сказать, чего это стоит на самом деле: времени, денег, риска",
    "юзер": "«пользователь» или «покупатель»",
    "фича": "«возможность» или название самой возможности",
    "деплой": "«выкладка» или «установка» — смотря что происходит",
    "апдейт": "«обновление»",
    "коммитить": "«сохранять изменения в репозиторий»",
}

# «Мы» уместно в разборе поломки внутри команды и неуместно в инструкции.
# Формы перечислены поимённо. Шаблон «наш\w*» ловил «нашлась» и «нашёл» —
# ложная тревога в проверке дороже пропуска: её перестают читать.
МЫ = re.compile(
    r"(?<![\w-])(мы|нам|нами|у нас|наш|наша|наше|наши|нашего|нашему|нашим|"
    r"нашем|нашей|нашею|наших|нашими|нашу)(?![\w-])", re.IGNORECASE)

# Термины, которые нельзя оставлять без определения. Список короткий намеренно:
# требовать определения к каждому слову — способ сделать проверку невыносимой
# и получить её отключение.
ТЕРМИНЫ = ("скоуп", "листинг", "предрелиз", "гейт", "мнемоник")

ОКНО = 260          # столько знаков после первого появления читает проверка


# Слово в кавычках-ёлочках, названное как слово, — это упоминание, а не
# употребление: «Грабли» в правиле про жаргон учат его не писать. Длину
# ограничиваем намеренно: короткая кавычка называет термин, длинная — цитирует
# целую фразу, и внутри неё нарушение остаётся нарушением.
УПОМИНАНИЕ = re.compile(r"«[^»]{1,24}»")


def _без_левой_колонки(текст: str) -> str:
    """Убрать колонку «Было» из таблиц, которые учат правилу.

    Документ, объясняющий язык, обязан показать плохой пример рядом с хорошим.
    Без этого исключения правило не может быть записано так, чтобы само себя
    не нарушало.
    """
    строки = текст.split("\n")
    учебная = False
    итог = []
    for с in строки:
        ячейки = [я.strip() for я in с.split("|")]
        заголовок = "было" in с.lower() and "стало" in с.lower() and с.count("|") >= 3
        if заголовок:
            учебная = True
            continue
        if учебная and с.count("|") >= 3:
            итог.append(" | ".join(ячейки[2:]))       # оставляем только «Стало»
            continue
        if учебная and not с.strip().startswith("|"):
            учебная = False
        итог.append(с)
    return "\n".join(итог)


def очистить(путь: pathlib.Path, текст: str) -> str:
    """Оставить только то, что читает человек.

    Команды, код и адреса под правило не подпадают: там «deploy» — это имя
    файла, а не слово из инструкции.
    """
    if путь.suffix == ".json":
        try:
            текст = " ".join(_строки(json.loads(текст)))
        except json.JSONDecodeError:
            pass
    текст = re.sub(r"```.*?```", " ", текст, flags=re.S)      # блоки кода
    текст = re.sub(r"<code>.*?</code>", " ", текст, flags=re.S)
    текст = re.sub(r"`[^`]*`", " ", текст)                     # код в строке
    текст = re.sub(r"https?://\S+", " ", текст)
    текст = re.sub(r"<[^>]+>", " ", текст)                     # разметка
    текст = _без_левой_колонки(текст)
    текст = УПОМИНАНИЕ.sub(" ", текст)
    return текст


def _строки(о) -> list:
    if isinstance(о, str):
        return [о]
    if isinstance(о, dict):
        return [с for з, v in о.items() for с in _строки(v)]
    if isinstance(о, list):
        return [с for v in о for с in _строки(v)]
    return []


def проверить_текст(текст: str) -> list:
    нарушения = []

    низ = текст.lower()
    for словечко, замена in СЛОВЕЧКИ.items():
        i = низ.find(словечко)
        if i >= 0:
            нарушения.append((текст[max(0, i - 40):i + 60].strip(),
                              f"внутреннее словечко «{словечко}» — {замена}"))

    for м in МЫ.finditer(текст):
        нарушения.append((текст[max(0, м.start() - 50):м.end() + 50].strip(),
                          f"«{м.group(0)}» — читатель не входит в команду, "
                          f"напиши факт без упоминания команды"))
        break                       # одного примера хватает, список не нужен

    for термин in ТЕРМИНЫ:
        i = низ.find(термин)
        if i < 0:
            continue
        рядом = текст[i:i + ОКНО]
        # Определение засчитывается в любом из двух видов: «термин — это …»
        # или «Термин. Это …». Оба встречаются в живом тексте.
        if not re.search(r"(—|-)\s*это\b", рядом, re.IGNORECASE):
            нарушения.append((текст[max(0, i - 30):i + 70].strip(),
                              f"термин «{термин}» встречается без определения — "
                              f"объясни его там же, одной строкой"))
    return нарушения


def проверить_файл(путь: pathlib.Path) -> list:
    return проверить_текст(очистить(путь, путь.read_text(encoding="utf-8")))


def selftest() -> int:
    """Каждая проверка обязана покраснеть на нарочно испорченном тексте."""
    ошибки = []

    чисто = ("Скоуп — это набор объектов, доступных конкретному агенту. "
             "Листинг — это карточка продукта в магазине. "
             "Проверяй доступность Expert по имени у того агента, который "
             "будет им пользоваться.")
    if проверить_текст(чисто):
        ошибки.append(f"чистый текст признан плохим: {проверить_текст(чисто)}")

    случаи = [
        ("словечко", чисто + " Грабли, на которые наступают все.", "словечко"),
        ("мы", чисто + " У нас уже приезжал такой продукт.", "команд"),
        ("термин без определения", "Скоуп решает всё, проверяй по имени.", "определения"),
        ("жаргон в другом падеже", чисто + " Это костыли, а не решение.", "костыл"),
    ]
    for имя, текст, ожидание in случаи:
        найдено = проверить_текст(текст)
        if not найдено:
            ошибки.append(f"«{имя}»: проверка промолчала")
        elif not any(ожидание in п for _, п in найдено):
            ошибки.append(f"«{имя}»: причина не названа, получено {найдено}")

    # Код под правило не подпадает: иначе имя файла deploy_page_product.py
    # сделает любой технический текст красным.
    с_кодом = чисто + "\n```bash\npython3 tools/deploy_page_product.py\n```\n"
    if проверить_текст(очистить(pathlib.Path("x.md"), с_кодом)):
        ошибки.append("команда в блоке кода принята за текст")

    # Документ, который учит правилу, показывает плохой пример — и не должен
    # из-за этого краснеть. При этом нарушение в правой колонке ловится.
    учебный = ("| Было | Стало |\n|---|---|\n"
               "| Грабли, на которые наступают все | Частые ошибки |\n")
    if проверить_текст(очистить(pathlib.Path("x.md"), учебный)):
        ошибки.append("пример нарушения в колонке «Было» принят за нарушение")
    плохой_справа = ("| Было | Стало |\n|---|---|\n"
                     "| Частые ошибки | Грабли, на которые наступают все |\n")
    if not проверить_текст(очистить(pathlib.Path("x.md"), плохой_справа)):
        ошибки.append("нарушение в колонке «Стало» пропущено")
    if проверить_текст(очистить(pathlib.Path("x.md"), "Слово «грабли» писать нельзя.")):
        ошибки.append("названное слово принято за употреблённое")
    if not проверить_текст(очистить(pathlib.Path("x.md"),
                                    "Здесь описаны грабли, на которые наступают все.")):
        ошибки.append("употреблённое слово пропущено")

    # «Нашлась» — это глагол, а не притяжательное местоимение. Шаблон, который
    # их путает, делает проверку невыносимой и её отключают.
    for глагол in ("Запись не нашлась.", "Он нашёл ошибку.", "Мы нашли причину."):
        есть = bool(проверить_текст(чисто + " " + глагол))
        должно = глагол.startswith("Мы")
        if есть != должно:
            ошибки.append(f"«{глагол}» оценён как {есть}, ожидалось {должно}")

    # JSON читается по значениям строк, а не как файл целиком.
    j = json.dumps({"тело": "Грабли, на которые наступают все"}, ensure_ascii=False)
    if not проверить_текст(очистить(pathlib.Path("x.json"), j)):
        ошибки.append("нарушение внутри JSON не найдено")

    for с in ошибки:
        print(f"  ✗ {с}")
    print("selftest: " + ("провален" if ошибки else "пройден"))
    return 1 if ошибки else 0


def main(аргументы: list) -> int:
    if "--selftest" in аргументы:
        return selftest()
    файлы = [pathlib.Path(а) for а in аргументы if not а.startswith("-")]
    if not файлы:
        print("нечего проверять: укажи файлы")
        return 2
    всего = 0
    for путь in файлы:
        if not путь.exists():
            print(f"нет файла {путь}")
            return 2
        нарушения = проверить_файл(путь)
        всего += len(нарушения)
        print(f"\n{путь}: " + ("нарушений нет" if not нарушения
                               else f"нарушений {len(нарушения)}"))
        for кусок, причина in нарушения:
            print(f"  · {причина}")
            print(f"    …{' '.join(кусок.split())[:120]}…")
    return 1 if всего else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
