#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Кто ведёт продукт: наш он или чужой.

ЗАЧЕМ. Гейты копий сравнивают продукты с каноном. Когда продукт ведёт другой
человек, его расхождение — не наша задача: править чужое живое запрещено
стоп-правилом. Но и молчать о расхождении нельзя.

Поэтому середина: расхождение показывается всегда, а прогон валится только на
своих продуктах. Постоянно красный прогон читать перестают, и вместе с ним
перестают замечать настоящие поломки — это дороже, чем незакрытый чужой долг.

Список — `ВЕДУТ_ДРУГИЕ.txt` в корне репозитория, одно имя на строку.
"""
import pathlib

СПИСОК = pathlib.Path(__file__).resolve().parents[1] / "ВЕДУТ_ДРУГИЕ.txt"


def ведут_другие() -> set:
    """Имена продуктов, которые сопровождает не наша команда."""
    if not СПИСОК.exists():
        return set()
    имена = set()
    for строка in СПИСОК.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if строка and not строка.startswith("#"):
            имена.add(строка)
    return имена


def selftest() -> int:
    ошибки = []
    свои = ведут_другие()
    if not свои:
        ошибки.append("список пуст: либо файла нет, либо он не читается")
    # Комментарии и пустые строки не должны попадать в список.
    if any(и.startswith("#") or not и for и in свои):
        ошибки.append(f"в список попали строки-комментарии: {свои}")
    for с in ошибки:
        print(f"  ✗ {с}")
    print(f"selftest: " + ("провален" if ошибки
                           else f"пройден, продуктов у других: {len(свои)}"))
    return 1 if ошибки else 0


if __name__ == "__main__":
    import sys
    sys.exit(selftest())
