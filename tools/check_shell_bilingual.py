#!/usr/bin/env python3
"""Оболочка страницы продукта двуязычна, как и её содержимое (H117).

ЗАЧЕМ. Замер 27.09.2026: все 19 разделов руководства и шапка были на двух языках и
охранялись гейтом, а ОБОЛОЧКА — кнопки, статусы, отказы, демонстрация «День первый» —
только по-русски: 679 видимых строк, около 24 600 знаков россыпью по 1733 строкам
шаблона. Переключатель языка при этом работал и переключал лишь содержимое. Поставить
английский по умолчанию в таком виде значило дать англичанину английские разделы
внутри русского окна — ровно то, что сам шаблон называет хуже честного одного языка.

ЧТО ПРОВЕРЯЕТСЯ.

1. В `store_app/shell.json` у каждой строки непустые `ru` и `en`.
2. Каждый ключ, названный в шаблоне через `data-t` или `data-t-подсказка`, есть в
   таблице; каждый ключ таблицы используется в шаблоне или в коде страницы. Мёртвый
   ключ — это перевод, которого никто не увидит.
3. Остаток непереведённого мерится и держится ХРАПОВИКОМ: число видимых русских
   строк в шаблоне может только уменьшаться. Флаг-дня нет намеренно — перевести
   24 600 знаков одним PR значит получить непроверяемую простыню.

ПРИЁМКА 28.09.2026: прогон по живому шаблону нашёл ЧЕТЫРЕ ошибки в самой проверке,
все ложные тревоги и все ставшие пробами. (1) За видимый текст считались имена
классов CSS — «дп-строки», «дп-исход», «дп-цена» — и обрывки разметки; из-за этого
число в отчёте завышалось в три с половиной раза: 196 настоящих строк текста против
679 «найденных». (2) Ключи в тернарном выражении объявлялись мёртвыми. (3) Пустая
строка рядом сдвигала парность кавычек и съедала следующий ключ. (4) Шаблон отсева
склеек использовал \w, а в Python \w ВКЛЮЧАЕТ кириллицу — обычная русская фраза
выбрасывалась как склейка подстановки. После правок ложных тревог нет.

    python3 tools/check_shell_bilingual.py
    python3 tools/check_shell_bilingual.py --обновить
    python3 tools/check_shell_bilingual.py --selftest

Коды выхода: 0 — остаток не вырос, 1 — вырос или таблица несогласна с шаблоном.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ШАБЛОН = КОРЕНЬ / "store_app" / "page.template.html"
ТАБЛИЦА = КОРЕНЬ / "store_app" / "shell.json"
ХРАПОВИК = КОРЕНЬ / "tools" / "shell_bilingual.json"

КИРИЛЛИЦА = re.compile(r"[А-Яа-яЁё]")
# Поля данных и роли — это код, а не текст для человека.
КОД = {"тело", "тело_en", "заголовок", "заголовок_en", "разделы", "тема", "тема_en",
       "роль", "версия_содержимого", "что_нового", "шапка", "метка", "лид",
       "вступление", "правила_входа", "промпт-агенту", "ловушки", "витрина",
       "установщик", "оболочка_минимум", "перевод_от", "строки", "пункты", "версия"}


def без_комментариев(текст: str) -> str:
    """Комментарии писаны для нас, их не переводят."""
    текст = re.sub(r"<!--.*?-->", " ", текст, flags=re.S)
    текст = re.sub(r"^\s*//[^\n]*$", " ", текст, flags=re.M)
    текст = re.sub(r"(?<=[;,)\s])//[^\n]*$", " ", текст, flags=re.M)
    return текст


def видимые_строки(шаблон: str) -> list[str]:
    """Русский ТЕКСТ ДЛЯ ЧЕЛОВЕКА, а не всё, где есть кириллица.

    Первая редакция считала видимым текстом имена классов CSS — «дп-строки»,
    «дп-исход», «дп-цена» — и куски разметки вроде «<p class="дп-строки">». Из 472
    «непереведённых строк» текстом было меньше половины, и число в отчёте не
    измеряло того, что обещало (замер 27.09.2026). Это тот же класс, что H113:
    число, живущее отдельно от факта.

    Отсюда правила отбора. Текст для человека:
      • содержит пробел — имя класса и служебный ключ его не содержат;
      • содержит слово из трёх и более кириллических букв;
      • не начинается с «<» и не является куском разметки;
      • не является склейкой подстановки вида «' + о.message + '».
    """
    чистый = без_комментариев(шаблон)
    # Разметка с ключом уже переведена — её не считаем.
    чистый = re.sub(r"<([a-z0-9]+)([^>]*\bdata-t=)[^>]*>.*?</\1>", " ", чистый, flags=re.S)
    # Значения class= и id= — это код, а не текст.
    чистый = re.sub(r'\b(?:class|id|data-[a-zа-яё-]+)="[^"]*"', " ", чистый)
    лит = re.findall(r"'([^'\n]*)'", чистый) + re.findall(r'"([^"\n]*)"', чистый)
    разм = re.findall(r">\s*([^<>{}\n]*)\s*<", чистый)
    слово = re.compile(r"[А-Яа-яЁё]{3,}")
    найдено = []
    for кусок in лит + разм:
        к = кусок.strip()
        if len(к) < 3 or к in КОД:
            continue
        if "<" in к or ">" in к:            # обрывок разметки
            continue
        if " " not in к:                    # имя класса, ключ, идентификатор
            continue
        if not слово.search(к):
            continue
        # Список имён классов: «дп-исход готов». Каждое слово либо через дефис,
        # либо короткое служебное — прозой это не бывает.
        if all(re.fullmatch(r"[a-zа-яё0-9]+(?:-[a-zа-яё0-9]+)*", с)
               for с in к.split()) and "-" in к:
            continue
        # Склейка подстановки: «' + о.message + '» текстом не является. Проверяется
        # наличием склейки, а не шаблоном по \w: в Python \w ВКЛЮЧАЕТ кириллицу
        # (в JavaScript — наоборот исключает), и прежняя редакция этим шаблоном
        # выбрасывала обычную русскую фразу как склейку. Третий случай за сутки,
        # когда \w значит не то, что кажется.
        if "' + " in к or " + '" in к:
            continue
        найдено.append(к)
    return найдено


def ключи_шаблона(шаблон: str, известные: set[str] | None = None) -> set[str]:
    """Ключи, которые шаблон действительно использует.

    Ключ из кода ищется как СТРОКОВЫЙ ЛИТЕРАЛ, а не по шаблону «т('ключ')». Первая
    редакция требовала вызова впритык и не увидела ключи в тернарном выражении —
    `тф(черезАгента ? 'дп.3.цена_агент' : 'дп.3.цена_модель', …)`: оба считались
    мёртвыми, хотя оба работают (замер 27.09.2026). Литерал, равный ключу таблицы,
    и есть использование.
    """
    из_разметки = set(re.findall(r'data-t(?:-подсказка|-значение)?="([^"]+)"', шаблон))
    if известные is not None:
        # Прямой поиск, а не разбор кавычек шаблоном: пустая строка рядом сдвигает
        # парность и съедает следующий ключ. Замер 27.09.2026 — в строке
        # `(черезАгента ? '' : т('дп.3.где_модель'))` регулярка сочла литералом
        # « : т(» и ключ потеряла, объявив рабочий перевод мёртвым.
        из_кода = {к for к in известные if f"'{к}'" in шаблон}
    else:
        из_кода = {л for л in re.findall(r"'([^'\n]+)'", шаблон)
                   if re.fullmatch(r"[A-Za-zА-Яа-яЁё0-9_]+(?:\.[A-Za-zА-Яа-яЁё0-9_]+)+", л)}
    return из_разметки | из_кода


def беды() -> tuple[list[str], int]:
    плохо: list[str] = []
    if not ТАБЛИЦА.exists():
        return ["нет store_app/shell.json — строкам оболочки негде жить"], 0
    таблица = json.loads(ТАБЛИЦА.read_text(encoding="utf-8")).get("строки") or {}
    шаблон = ШАБЛОН.read_text(encoding="utf-8")

    for ключ, з in sorted(таблица.items()):
        if not str(з.get("ru") or "").strip():
            плохо.append(f"{ключ}: нет русского текста")
        if not str(з.get("en") or "").strip():
            плохо.append(f"{ключ}: нет английского перевода")

    в_шаблоне = ключи_шаблона(шаблон, set(таблица))
    нет_в_таблице = sorted(в_шаблоне - set(таблица))
    if нет_в_таблице:
        плохо.append("шаблон зовёт ключи, которых нет в таблице: " + ", ".join(нет_в_таблице[:6]))
    мёртвые = sorted(set(таблица) - в_шаблоне)
    if мёртвые:
        плохо.append("в таблице мёртвые ключи, их никто не видит: " + ", ".join(мёртвые[:6]))

    return плохо, len(видимые_строки(шаблон))


def проверить(обновить: bool = False) -> int:
    плохо, осталось = беды()
    было = None
    if ХРАПОВИК.exists():
        было = int(json.loads(ХРАПОВИК.read_text(encoding="utf-8")).get("осталось", 0))

    for б in плохо:
        print("  ✗ " + б)
    print(f"непереведённых строк оболочки: {осталось}" +
          (f" (было {было})" if было is not None else ""))

    if обновить:
        ХРАПОВИК.write_text(json.dumps({"осталось": осталось}, ensure_ascii=False,
                                       indent=1) + "\n", encoding="utf-8")
        print(f"Уровень записан: {осталось}")
        return 1 if плохо else 0

    if плохо:
        print("\nНЕ УСПЕХ (H117): таблица строк оболочки не согласна с шаблоном.")
        return 1
    if было is not None and осталось > было:
        print(f"\nНЕ УСПЕХ (H117): непереведённых строк стало больше ({было} → {осталось}). "
              f"Новую строку оболочки заводить в shell.json сразу с английским.")
        return 1
    print("H117: остаток не вырос.")
    return 0


def _selftest() -> int:
    провалы = []

    def проба(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    print("Самопроверка check_shell_bilingual:")

    проба("комментарий в коде за видимый текст не считается",
          видимые_строки("  // это пояснение для нас\n<p>Hello</p>") == [])
    проба("комментарий разметки тоже не считается",
          видимые_строки("<!-- пояснение для нас -->\n<p>Hello</p>") == [])
    проба("русская подпись без ключа ловится",
          видимые_строки('<button>Найди ответ по вопросу</button>') != [])
    проба("имя класса CSS за текст не считается",
          видимые_строки('<p class="дп-строки">x</p>' + "в.className = 'дп-исход готов';") == [])
    проба("обрывок разметки за текст не считается",
          видимые_строки("""var x = '<p class="дп-цена">';""") == [])
    проба("склейка подстановки за текст не считается",
          видимые_строки("var x = ' + о.message + ';") == [])
    проба("подпись с ключом уже переведена и не считается",
          видимые_строки('<button data-t="вкладка.начало">Начало</button>') == [])
    проба("поле данных за текст не считается",
          видимые_строки('var x = "тело_en";') == [])
    проба("ключи читаются и из разметки, и из кода",
          ключи_шаблона('<p data-t="а.б">x</p>' + "т('в.г')") == {"а.б", "в.г"})
    проба("ключ строки с подстановкой читается тоже",
          ключи_шаблона("тф('д.е', {сек: 1})") == {"д.е"})
    проба("ключ в тернарном выражении читается",
          ключи_шаблона("тф(x ? 'а.б' : 'в.г', {})", {"а.б", "в.г"}) == {"а.б", "в.г"})
    проба("чужой литерал за ключ не считается, когда список известен",
          ключи_шаблона("var x = 'journey_scan';", {"а.б"}) == set())
    проба("пустая строка рядом не съедает ключ",
          ключи_шаблона("(x ? '' : т('а.б'))", {"а.б"}) == {"а.б"})
    проба("H117 назван в тексте проверки",
          "H117" in pathlib.Path(__file__).read_text(encoding="utf-8"))

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы — " + "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    sys.exit(проверить(обновить="--обновить" in sys.argv))
