#!/usr/bin/env python3
"""Издание в магазин одной командой: проверить → выложить → купить себе → принять.

Это замена инструкции «куда нажать в форме». Деплой у нас код, а не действия:
что делается руками, идёт со скоростью рук (AGENT_BUILD_GUIDE §5б).

    python3 tools/deploy_edition.py editions/founder            # весь путь
    python3 tools/deploy_edition.py editions/founder --сухой    # ничего не менять, показать план
    python3 tools/deploy_edition.py editions/founder --выдать-права
    python3 tools/deploy_edition.py editions/founder --разрешить-публичную-версию

Что делает по шагам:

1. гоняет `check_edition` — паспорт, данные, права, тема. Красный гейт останавливает всё;
2. заводит агента издания **по API**, если его ещё нет (замер 14.08.2026: такой агент
   экспертов запускает, человек нужен только там, где нужна модель);
3. пишет экспертов издания в скоуп ЭТОГО агента через REST и **сверяет по содержимому**;
4. новый листинг выкладывает предрелизом. Есть листинг — добавляет ВЕРСИЮ, а не новый листинг;
   у уже опубликованного листинга это публичное действие и требует отдельный флаг владельца;
5. покупает себе в **существующего** агента, чтобы не плодить пустых;
6. приёмка чтением состояния: покупка, страница, права, ярлык.

Останавливается перед публичным действием: `Publish` нового листинга или `add-version`
у уже опубликованного. Решение принимает человек.
"""

import json
import pathlib
import re
import subprocess
import sys
import urllib.error
import urllib.request
import uuid

ОС = "https://os.extella.ai"
ЯДРО = "https://api.extella.ai"
КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent


class Отказ(Exception):
    """Отказ, который называет причину и что делать дальше."""


# --- доступ -----------------------------------------------------------------

def токен() -> str:
    for путь, поле in ((pathlib.Path.home() / ".extella" / "os_token.txt", None),
                       (pathlib.Path.home() / ".extella" / "api_token.txt", None),
                       (pathlib.Path.home() / "extella_wizard" / "app" / "config.json", "json")):
        if not путь.exists():
            continue
        текст = путь.read_text().strip()
        if поле == "json":
            d = json.loads(текст)
            for k in ("auth_token", "token", "AUTH_TOKEN", "extella_token"):
                if d.get(k):
                    return str(d[k])
        elif текст:
            return текст
    raise Отказ("нет доступа к Extella на этой машине: нужен файл ~/.extella/api_token.txt. "
                "Открой приложение Extella один раз — он появится сам")


def запрос(база, путь, *, тело=None, поля=None, файлы=None, заголовки=None, метод=None, таймаут=180):
    з = {"X-Extella-Token": токен()}
    з.update(заголовки or {})
    данные = None
    if тело is not None:
        данные = json.dumps(тело).encode()
        з["Content-Type"] = "application/json"
    elif поля is not None or файлы is not None:
        граница = uuid.uuid4().hex
        куски = []
        for k, v in (поля or {}).items():
            куски.append(f"--{граница}\r\nContent-Disposition: form-data; "
                         f'name="{k}"\r\n\r\n{v}\r\n'.encode())
        for k, п in (файлы or {}).items():
            п = pathlib.Path(п)
            куски.append(f"--{граница}\r\nContent-Disposition: form-data; "
                         f'name="{k}"; filename="{п.name}"\r\n'
                         f"Content-Type: application/octet-stream\r\n\r\n".encode()
                         + п.read_bytes() + b"\r\n")
        куски.append(f"--{граница}--\r\n".encode())
        данные = b"".join(куски)
        з["Content-Type"] = f"multipart/form-data; boundary={граница}"
    r = urllib.request.Request(база + путь, data=данные, headers=з,
                               method=метод or ("POST" if данные else "GET"))
    try:
        with urllib.request.urlopen(r, timeout=таймаут) as о:
            текст = о.read().decode()
            return о.status, текст
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode()[:400]
    except Exception as e:
        raise Отказ(f"не дошёл до платформы ({e}). Проверь сеть и повтори")


def как_json(текст, что="ответ"):
    try:
        return json.loads(текст)
    except Exception:
        raise Отказ(f"{что} пришёл не в JSON: {текст[:160]}")


def из_потока(текст, что="публикация", код=200):
    """SSE-поток: берём событие done, а на error честно падаем.

    Отказ платформы (код != 200) приходит сюда обычным телом и раньше терялся:
    поток без «done» мы объясняли обрывом, а на деле это был честный ответ
    «At least one tag is required». Причину теперь видно сразу.
    """
    if код != 200:
        raise Отказ(f"{что}: платформа отказала ({код}) — {текст[:200]}")
    итог = None
    for строка in текст.split("\n"):
        строка = строка.strip()
        if not строка.startswith("data:"):
            continue
        с = как_json(строка[5:].strip(), что)
        if с.get("type") == "error":
            raise Отказ(f"{что} не прошла: {с.get('message') or с}")
        if с.get("type") == "done":
            итог = с
    if итог is None:
        raise Отказ(f"{что}: платформа не прислала завершение. Проверь состояние чтением, "
                    f"прежде чем повторять — повтор создаст дубль")
    return итог


# --- паспорт ----------------------------------------------------------------

def паспорт(папка: pathlib.Path) -> dict:
    sys.path.insert(0, str(КОРЕНЬ / "tools"))
    import check_edition
    d = check_edition.разобрать_yaml((папка / "edition.yaml").read_text())
    return d


def значение(узел, *путь, умолчание=None):
    for к in путь:
        if not isinstance(узел, dict):
            return умолчание
        узел = узел.get(к)
    return узел if узел is not None else умолчание


# --- шаги -------------------------------------------------------------------

def гейт(папка, сказать):
    # Паспорт — что издание из себя представляет. Карточка — как его увидят на витрине.
    # Второе добавлено 14.08.2026: четыре наших листинга из десяти вышли без иконки,
    # три — без описания. Мету надо требовать в момент выкладки, потом её не доделывают.
    for имя, отказ_текст in (("check_edition.py", "поправь паспорт"),
                             ("check_listing_meta.py", "доделай карточку: иконка, "
                                                       "описание, теги")):
        итог = subprocess.run([sys.executable, str(КОРЕНЬ / "tools" / имя), str(папка)],
                              capture_output=True, text=True)
        сказать(итог.stdout.strip() or итог.stderr.strip())
        if итог.returncode != 0:
            raise Отказ(f"гейт {имя} красный — сначала {отказ_текст}, потом деплой")


def агент_издания(папка, имя, сказать, сухой):
    свой = папка / "listing.json"
    если_есть = json.loads(свой.read_text()) if свой.exists() else {}
    if если_есть.get("agent_id"):
        сказать(f"агент издания уже есть: {если_есть['agent_id']}")
        return если_есть["agent_id"]
    if сухой:
        сказать("создал бы агента издания по API (пустой набор инструментов)")
        return "agent_БУДЕТ_СОЗДАН"
    код, т = запрос(ЯДРО, "/api/agent/create", тело={
        "name": имя, "provider": "custom", "model": "qwen3.7-max", "tools": [],
        "description": f"Агент издания «{имя}». Инструменты пусты намеренно."})
    if код not in (200, 201):
        raise Отказ(f"агент не создан ({код}): {т[:200]}")
    ид = как_json(т).get("content", {}).get("id") or как_json(т).get("id")
    if not ид:
        raise Отказ(f"агент создан, но id не пришёл: {т[:200]}")
    сказать(f"агент издания создан по API: {ид} (инструменты пусты)")
    return ид


def эксперты(папка, agent_id, сказать, сухой):
    файлы = sorted(папка.glob("expert_*.py"))
    if not файлы:
        сказать("экспертов в издании нет — страница обойдётся без вызовов")
        return []
    записано = []
    for ф in файлы:
        имя = re.sub(r"^expert_", "", ф.stem)
        if сухой:
            сказать(f"записал бы эксперта {имя} в скоуп {agent_id}")
            записано.append(имя)
            continue
        код = ф.read_text()
        ст, т = запрос(ЯДРО, "/api/expert/save",
                       тело={"name": имя, "description": f"Эксперт издания: {имя}", "code": код},
                       заголовки={"X-Auth-Token": токен(), "X-Profile-Id": "default",
                                  "X-Agent-Id": agent_id})
        if ст != 200 or как_json(т).get("status") != "success":
            raise Отказ(f"эксперт {имя} не записан ({ст}): {т[:200]}")
        # Сверка по содержимому, а не по слову «success».
        ст, т = запрос(ЯДРО, "/api/expert/get", тело={"name": имя},
                       заголовки={"X-Auth-Token": токен(), "X-Profile-Id": "default",
                                  "X-Agent-Id": agent_id})
        пришло = как_json(т).get("expert_code", "")
        if пришло.strip() != код.strip():
            raise Отказ(f"эксперт {имя} записался иначе, чем в файле: "
                        f"{len(код)} знаков против {len(пришло)}")
        сказать(f"эксперт {имя}: записан и сверен посимвольно")
        записано.append(имя)
    return записано


def выложить(папка, d, agent_id, сказать, сухой, разрешить_публичную_версию=False):
    страница = папка / "index.html"
    if not страница.exists():
        raise Отказ("нет index.html — страницы у издания нет, выкладывать нечего")
    права = значение(d, "права_приложения", "_список", умолчание=[])
    имя = значение(d, "издание", "имя", умолчание=папка.name)
    версия = str(значение(d, "издание", "версия", умолчание="0.1.0"))
    тег = значение(d, "издание", "тег", умолчание="")

    свой = папка / "listing.json"
    прежний = json.loads(свой.read_text()) if свой.exists() else {}
    поля = {"version": версия, "price_credits": "0",
            "app_scopes": json.dumps(права, ensure_ascii=False)}

    # Мета витрины едет вместе с версией: иконка — отдельным файлом, рядом со
    # страницей (одна версия несёт page, archive и icon — три поля, H10). Пока иконку
    # не отправляли ВООБЩЕ, поэтому продукты выходили безымянными квадратами.
    файлы = {"page": страница}
    иконка = папка / str(прежний.get("иконка") or "icon.png")
    if иконка.exists():
        файлы["icon"] = иконка
    else:
        сказать("иконки нет — карточка выйдет серым квадратом (гейт это ловит)")

    # Мета едет с КАЖДОЙ версией, а не только при создании листинга: платформа
    # 15.08.2026 стала отвечать «At least one tag is required» на add-version,
    # и все четыре продукта молча перестали обновляться.
    описание = str(прежний.get("описание") or значение(d, "для_кого", умолчание=имя)).strip()
    теги = list(прежний.get("теги") or ([тег] if тег else []))
    if тег and тег not in теги:
        теги.append(тег)
    if теги:
        поля["tags"] = json.dumps(теги, ensure_ascii=False)
    поля["description"] = описание

    if прежний.get("listing_id"):
        # Листинг есть — добавляем ВЕРСИЮ. publish-stream создал бы дубль листинга.
        if сухой:
            сказать(f"добавил бы версию {версия} к листингу {прежний['listing_id']}")
            сказать("если листинг уже публичный, нужен --разрешить-публичную-версию")
            return прежний
        код, текст = запрос(ОС, "/api/my-listings")
        свои = как_json(текст, "список листингов владельца").get("listings", []) if код == 200 else []
        живой = next((x for x in свои if x.get("id") == прежний["listing_id"]), None)
        if живой is None:
            raise Отказ("существующий листинг не найден у текущего токена")
        if живой.get("published") is True and not разрешить_публичную_версию:
            raise Отказ(
                "листинг уже опубликован: новая версия сразу станет публичной. "
                "После явного решения владельца повтори с --разрешить-публичную-версию"
            )
        код, т = запрос(ОС, f"/api/add-version-stream/{прежний['listing_id']}",
                        поля=поля, файлы=файлы)
        готово = из_потока(т, "добавление версии", код)
        сказать(f"версия {версия} добавлена к листингу {прежний['listing_id']}")
        прежний["version_id"] = готово.get("version_id", прежний.get("version_id"))
        return прежний

    # Описание и теги берутся из карточки продукта, а не из паспорта: «для_кого» —
    # это заметка для нас, а на витрине человек читает описание и по тегам находит
    # полку. Паспорт остаётся запасным вариантом, чтобы деплой не падал.
    описание = str(прежний.get("описание") or значение(d, "для_кого", умолчание=имя)).strip()
    теги = прежний.get("теги") or ([тег] if тег else [])
    if тег and тег not in теги:
        теги = list(теги) + [тег]
    поля.update({"name": имя, "description": описание})
    if agent_id:
        поля.update({"attach_agent": "1", "source_id": agent_id})
    if теги:
        поля["tags"] = json.dumps(теги, ensure_ascii=False)
    if сухой:
        сказать(f"создал бы листинг «{имя}» с правами {права}")
        return {"listing_id": "БУДЕТ", "version_id": "БУДЕТ"}
    код, т = запрос(ОС, "/api/publish-stream", поля=поля, файлы=файлы)
    готово = из_потока(т, "публикация", код)
    сказать(f"листинг создан: {готово['listing_id']} · снимок: {готово.get('stats')}")
    return {"listing_id": готово["listing_id"], "version_id": готово["version_id"]}


def купить(лист, agent_id, сказать, сухой):
    if сухой:
        сказать("купил бы себе в существующего агента издания")
        return
    тело = ({"deploy_mode": "existing", "target_agent_id": agent_id} if agent_id
            else {"deploy_mode": "none"})
    код, т = запрос(ОС, f"/api/purchase-stream/{лист['version_id']}", тело=тело)
    готово = из_потока(т, "покупка")
    сказать(f"поставлено себе: агент {готово.get('deployed_id')} · "
            f"ярлык {готово.get('webapp_shortcut') or 'не создан'}")


def приёмка(лист, d, выдать_права, сказать):
    lid = лист["listing_id"]
    беды = []
    код, т = запрос(ОС, f"/api/purchase-check/{lid}")
    if код != 200 or not как_json(т).get("purchased"):
        беды.append("покупки нет")
    код, т = запрос(ОС, f"/app-page/{lid}/")
    if код != 200:
        беды.append(f"страница отдаётся с кодом {код}")
    elif "{" + "{app_token" in т:
        беды.append("app_token не подставлен — страница открыта мимо ОС")
    else:
        сказать(f"страница: 200, {len(т)} знаков, app_token подставлен")

    код, т = запрос(ОС, f"/api/app-permissions/{lid}")
    п = как_json(т)
    не_выдано = set(п.get("requested", [])) - set(п.get("granted", []))
    if не_выдано and выдать_права:
        запрос(ОС, f"/api/app-permissions/{lid}", тело={"scopes": п["requested"]})
        п = как_json(запрос(ОС, f"/api/app-permissions/{lid}")[1])
        не_выдано = set(п.get("requested", [])) - set(п.get("granted", []))
    сказать(f"права: запрошено {п.get('requested')} · выдано {п.get('granted')}")
    if не_выдано:
        сказать(f"  ждут выдачи: {sorted(не_выдано)} — это согласие покупателя, "
                f"включается в правах приложения")

    код, т = запрос(ОС, "/api/desktop-state")
    ярлыки = как_json(т)["state"]["shortcuts"]
    if not any(lid in v.get("url", "") for v in ярлыки.values()):
        беды.append("ярлыка нет — страницу приложили после покупки; создай ярлык "
                    f"на /app-page/{lid}/ со слэшем, БЕЗ заголовков (H5-квинта)")
    else:
        сказать("ярлык на месте")
    return беды


# --- сборка целиком ---------------------------------------------------------

def деплой(папка: pathlib.Path, сухой=False, выдать_права=False,
           разрешить_публичную_версию=False, сказать=print):
    if not (папка / "edition.yaml").exists():
        raise Отказ(f"в {папка} нет edition.yaml — это не издание")
    сказать(f"— издание: {папка}")
    гейт(папка, сказать)
    d = паспорт(папка)
    имя = значение(d, "издание", "имя", умолчание=папка.name)

    # Продукту, который никуда не ходит, агент не нужен вовсе: страница живёт сама.
    # Раньше деплой заводил агента ВСЕГДА — и на такой странице спотыкался о ядро,
    # которое ждёт свой заголовок. Заводим агента только тем, кому есть что запускать.
    сам_по_себе = (str(значение(d, "не_ходит_к_платформе") or "").lower().startswith("да")
                   and not list(папка.glob("expert_*.py")))
    if сам_по_себе:
        сказать("продукт никуда не ходит: агент и эксперты не нужны")
        ид = None
    else:
        ид = агент_издания(папка, имя, сказать, сухой)
        эксперты(папка, ид, сказать, сухой)
    лист = выложить(папка, d, ид, сказать, сухой, разрешить_публичную_версию)

    if сухой:
        сказать("— сухой прогон: ничего не изменено")
        return 0

    # Карточка ДОПОЛНЯЕТСЯ результатом выкладки, а не заменяется им.
    #
    # Первая версия писала сюда только то, что вернула платформа, — и стирала
    # описание, теги и имя файла иконки, которые человек написал руками. Продукт
    # выкладывался один раз нормально, а на втором заходе выходил безымянным.
    # Поймал это гейт карточки на повторном деплое доски.
    файл = папка / "listing.json"
    карточка = json.loads(файл.read_text()) if файл.exists() else {}
    карточка.update(лист)
    карточка["agent_id"] = ид
    карточка["name"] = имя
    файл.write_text(json.dumps(карточка, ensure_ascii=False, indent=2) + "\n")

    купить(лист, ид, сказать, сухой)
    беды = приёмка(лист, d, выдать_права, сказать)

    if беды:
        сказать("\nПРИЁМКА НЕ ПРОЙДЕНА:")
        for b in беды:
            сказать("  ✗ " + b)
        return 1
    сказать("\nПредрелиз готов и принят чтением состояния.")
    сказать(f"  листинг {лист['listing_id']} · версия {лист['version_id']}")
    сказать("  ОСТАНОВ: кнопку Publish жмёт человек — она видна всем. Обратима: tools/set_published.py <id> --убрать (H26).")
    сказать("  Перед ней открой окно и пройди свой сценарий целиком: гейты приёмку не заменяют.")
    return 0


def _selftest() -> int:
    """Проверяем разбор потока и правило «есть листинг — добавляем версию»."""
    провалы = []

    def проверка(имя, функция):
        try:
            функция()
            print(f"  ✓ {имя}")
        except AssertionError as e:
            провалы.append(f"{имя}: {e}")
            print(f"  ✗ {имя}: {e}")

    def поток_берёт_done():
        т = 'data: {"type": "saving"}\n\ndata: {"type": "done", "listing_id": "L", "version_id": "V"}\n'
        assert из_потока(т)["listing_id"] == "L", "не нашёл событие done"

    def поток_падает_на_ошибке():
        try:
            из_потока('data: {"type": "error", "message": "нет агента"}\n')
        except Отказ as e:
            assert "нет агента" in str(e), f"причина потеряна: {e}"
            return
        raise AssertionError("ошибка в потоке прошла молча")

    def поток_падает_без_завершения():
        try:
            из_потока('data: {"type": "saving"}\n')
        except Отказ as e:
            assert "дубль" in str(e), "не предупредил про дубль при повторе"
            return
        raise AssertionError("оборванный поток принят за успех")

    def не_издание_отвергается():
        import tempfile
        with tempfile.TemporaryDirectory() as d:
            try:
                деплой(pathlib.Path(d), сухой=True, сказать=lambda *_: None)
            except Отказ:
                return
        raise AssertionError("папка без паспорта принята за издание")

    print("Самопроверка deploy_edition:")
    проверка("поток: берётся событие done", поток_берёт_done)
    проверка("поток: ошибка не проходит молча", поток_падает_на_ошибке)
    проверка("поток: обрыв не считается успехом", поток_падает_без_завершения)
    проверка("папка без паспорта отвергается", не_издание_отвергается)

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


