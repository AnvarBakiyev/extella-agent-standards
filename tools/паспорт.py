def ответ_словами(ответ: dict) -> str:
    """Достать из ответа платформы то, что модель СКАЗАЛА, а не то, что думала.

    Замер 19.08.2026: ответ приходит массивом `output`, где первым лежит блок
    `reasoning` — ход мыслей модели. Наивный поиск «первых фигурных скобок по
    всему ответу» выдирал JSON из рассуждений, и паспорт получался из черновика.
    Снаружи это выглядело как «модель не поняла формат», хотя она его поняла.
    """
    куски = []
    for блок in ответ.get("output") or []:
        if блок.get("type") == "reasoning":
            continue                       # мысли — не ответ
        for часть in блок.get("content") or []:
            куски.append(часть.get("text") or часть.get("output_text") or "")
    if куски:
        return "\n".join(куски)
    # Старые сборки платформы отвечали плоско — путь оставляем, но вторым.
    return ответ.get("response") or ответ.get("output_text") or json.dumps(ответ)


def спросить_модель(имя: str, обр: dict) -> dict:
    тело = {
        "agent_id": АГЕНТ,
        # Поле называется input, не message: замер 19.08.2026 — message даёт 422
        # «Field required», и это выглядит как отказ модели, а не как опечатка.
        "input": ЗАДАНИЕ.format(формы=", ".join(ФОРМЫ), имя=имя,
                                  образец=json.dumps(обр, ensure_ascii=False)[:ПРЕДЕЛ_ОБРАЗЦА]),
    }
    з = urllib.request.Request(
        f"{ЯДРО}/api/agent/run", data=json.dumps(тело, ensure_ascii=False).encode(),
        headers={"X-Auth-Token": токен(), "X-Profile-Id": "default",
                 "X-Agent-Id": АГЕНТ, "Content-Type": "application/json"},
        method="POST")
    try:
        # Прогон агента идёт секунды и легко упирается в клиентский таймаут.
        # 180 с — не запас «на всякий случай», а измеренная реальность платформы.
        with urllib.request.urlopen(з, timeout=180) as о:
            ответ = json.loads(о.read().decode())
    except urllib.error.HTTPError as е:
        raise Отказ(f"платформа отказала ({е.code}): {е.read().decode()[:200]}")
    except (urllib.error.URLError, OSError) as е:
        raise Отказ(f"платформа недоступна: {е}")

    текст = ответ_словами(ответ)
    м = re.search(r"\{.*\}", текст, re.S)
    if not м:
        raise Отказ(f"модель ответила не JSON: {текст[:200]}")
    try:
        return json.loads(м.group(0))
    except json.JSONDecodeError as е:
        raise Отказ(f"модель вернула испорченный JSON ({е}): {м.group(0)[:200]}")


# ── исполнение паспорта: чистый код, без модели ──────────────────────────────

def _пройти(данные, путь: list, развернуть: list):
    """Пройти по пути, разворачивая строки-с-JSON там, где сказал паспорт."""
    у = данные
    for ключ in путь:
        if isinstance(у, list):
            try:
                у = у[int(ключ)]
                continue
            except (ValueError, IndexError):
                raise Отказ(f"путь «{ключ}» не годится: здесь список из {len(у)}")
        if not isinstance(у, dict) or ключ not in у:
            есть = ", ".join(list(у)[:8]) if isinstance(у, dict) else type(у).__name__
            raise Отказ(f"в данных нет ключа «{ключ}» (есть: {есть}). "
                        f"Паспорт устарел — перечитайте формат")
        у = у[ключ]
        if ключ in развернуть and isinstance(у, str):
            try:
                у = json.loads(у)
            except json.JSONDecodeError:
                raise Отказ(f"ключ «{ключ}» помечен как JSON-строка, но не разбирается")
    return у


def применить(п: dict, данные: dict) -> dict:
    """Паспорт + данные → форма. Ни одного обращения к модели: только чтение полей."""
    if not п.get("форма"):
        raise Отказ(f"паспорт без формы: {п.get('почему') or 'модель не поняла формат'}")
    сырьё = _пройти(данные, п.get("путь") or [], п.get("развернуть") or [])
    д = {"форма": п["форма"], "заголовок": п.get("заголовок") or п.get("приложение"),
         "подпись": п.get("подпись") or ""}

    if п["форма"] == "число":
        д["значение"] = (сырьё.get(п["значение_поле"]) if isinstance(сырьё, dict)
                         else сырьё)
        return проверить(д)

    if not isinstance(сырьё, list):
        raise Отказ(f"по пути {п.get('путь')} лежит {type(сырьё).__name__}, "
                    f"а форме «{п['форма']}» нужен список")

    поле = {"список": "строки", "шаги": "шаги", "связи": "связи",
            "документ": "разделы"}[п["форма"]]
    пункты = []
    for с in сырьё:
        if not isinstance(с, dict):
            continue
        if п["форма"] == "список":
            пункты.append({"имя": str(с.get(п["имя_поле"], "")),
                           "поля": {показ: с.get(поле_ист)
                                    for показ, поле_ист in (п.get("поля") or {}).items()
                                    if с.get(поле_ист) is not None}})
        elif п["форма"] == "шаги":
            пункты.append({"имя": str(с.get(п["имя_поле"], "")),
                           "подпись": str(с.get(п.get("подпись_поле"), "") or "")})
        elif п["форма"] == "связи":
            пункты.append({"от": str(с.get(п["от_поле"], "")),
                           "к": str(с.get(п["к_поле"], "")),
                           "подпись": str(с.get(п.get("подпись_поле"), "") or "")})
        else:
            пункты.append({"имя": str(с.get(п["имя_поле"], "")),
                           "текст": str(с.get(п["текст_поле"], ""))})
    д[поле] = [х for х in пункты if any(str(з).strip() for з in х.values())]
    return проверить(д)


def путь_паспорта(имя: str) -> pathlib.Path:
    return ПАПКА / f"{имя}.json"


def прочитать(имя: str) -> dict:
    ф = путь_паспорта(имя)
    if not ф.exists():
        raise Отказ(f"нет паспорта «{имя}». Сделать: "
                    f"python3 tools/паспорт.py --файл <файл> --имя {имя}")
    return json.loads(ф.read_text())


def написать(имя: str, файл: pathlib.Path) -> int:
    данные = json.loads(файл.read_text())
    обр = образец(данные)
    print(f"\nЧитаю формат «{имя}» моделью — один раз, дальше работает код.")
    print(f"  образец: {len(json.dumps(обр, ensure_ascii=False))} знаков "
          f"(из файла на {файл.stat().st_size // 1024} КБ)")
    начало = time.time()
    п = спросить_модель(имя, обр)
    print(f"  модель ответила за {time.time() - начало:.0f} с")

    if not п.get("форма"):
        print(f"\n  Модель говорит: под словарь не ложится — {п.get('почему')}")
        print("  Это честный ответ. Такое приложение показывается своим окном, "
              "а не доской.")
        return 1

    п.update({"приложение": имя, "источник_файл": str(файл),
              "написан": time.strftime("%Y-%m-%d %H:%M"), "подтверждён": False})
    ПАПКА.mkdir(parents=True, exist_ok=True)
    путь_паспорта(имя).write_text(json.dumps(п, ensure_ascii=False, indent=2))
    print(f"\n  форма: {п['форма']} · заголовок: {п.get('заголовок')}")
    print(f"  путь: {п.get('путь')} · поля: {list((п.get('поля') or {}).keys()) or '—'}")

    try:
        д = применить(п, данные)
        число = len(д.get("строки") or д.get("шаги") or д.get("связи")
                    or д.get("разделы") or [1])
        print(f"  ПРОБА: паспорт исполнен кодом, получено пунктов: {число}")
        первый = (д.get("строки") or д.get("шаги") or д.get("связи")
                  or д.get("разделы") or [д])[0]
        print(f"  первый пункт: {json.dumps(первый, ensure_ascii=False)[:180]}")
    except Отказ as о:
        print(f"  ПРОБА НЕ ПРОШЛА: {о}")
        print("  Паспорт сохранён неподтверждённым — чинить или перечитать формат.")
        return 1

    print(f"\n  Паспорт лежит: {путь_паспорта(имя)}")
    print(f"  НЕ ПОДТВЕРЖДЁН. Посмотрите первый пункт выше: если модель поняла формат "
          f"верно —\n  python3 tools/паспорт.py --имя {имя} --подтвердить")
    return 0


def selftest() -> int:
    ошибки = []

    # Образец обязан резать. Иначе содержимое клиента уедет наружу целиком.
    большой = {"строки": [{"а": "б" * 500} for _ in range(400)]}
    о = образец(большой)
    if len(json.dumps(о, ensure_ascii=False)) > 1200:
        ошибки.append("образец не урезается — наружу уйдёт всё содержимое")
    else:
        print("  ✓ образец урезается: модель видит форму, а не все данные клиента")

    # Работа наших приложений лежит строкой с JSON внутри — это норма, не край.
    о = образец({"excalidraw": json.dumps([{"type": "rectangle"}] * 50)})
    if "__json_строкой__" not in json.dumps(о, ensure_ascii=False):
        ошибки.append("строка с JSON внутри не разворачивается — модель увидит стену")
    else:
        print("  ✓ работа приложения строкой-с-JSON разворачивается для модели")

    п = {"форма": "список", "заголовок": "Проба", "путь": ["данные"],
         "имя_поле": "город", "поля": {"отток": "доля", "ушло": "ушло"}}
    д = применить(п, {"данные": [{"город": "Алматы", "доля": "21%", "ушло": 1240},
                                 {"город": "Астана", "доля": "14%", "ушло": 870}]})
    if [с["имя"] for с in д["строки"]] != ["Алматы", "Астана"]:
        ошибки.append(f"исполнение паспорта потеряло строки: {д}")
    elif list(д["строки"][0]["поля"]) != ["отток", "ушло"]:
        ошибки.append("порядок полей паспорта не сохранён")
    else:
        print("  ✓ паспорт исполняется кодом, без обращения к модели")

    try:
        применить({"форма": "список", "заголовок": "х", "путь": ["нету"],
                   "имя_поле": "и"}, {"данные": []})
        ошибки.append("устаревший паспорт не отвергнут — нарисовал бы пустоту молча")
    except Отказ as о:
        if "нет ключа" not in str(о):
            ошибки.append(f"отказ не называет причину: {о}")
        else:
            print("  ✓ устаревший паспорт отказывает и называет, что искал")

    try:
        применить({"форма": None, "почему": "не ложится"}, {})
        ошибки.append("паспорт без формы принят")
    except Отказ:
        print("  ✓ «не ложится под словарь» — честный ответ, а не молчаливая пустота")

    print("\n" + ("ИТОГ САМОПРОВЕРКИ: все проверки прошли" if not ошибки
                  else "ОТКАЗ:\n  " + "\n  ".join(ошибки)))
    return 1 if ошибки else 0


def main() -> int:
    р = argparse.ArgumentParser(description="Паспорт приложения: формат читается один раз")
    р.add_argument("--файл", help="файл с содержимым приложения (json)")
    р.add_argument("--имя", help="как называется приложение")
    р.add_argument("--подтвердить", action="store_true")
    р.add_argument("--достать", action="store_true", help="паспорт + данные → форма")
    р.add_argument("--selftest", action="store_true")
    а = р.parse_args()
    if а.selftest:
        return selftest()
    try:
        if а.подтвердить:
            п = прочитать(а.имя)
            п["подтверждён"] = True
            п["подтверждён_когда"] = time.strftime("%Y-%m-%d %H:%M")
            путь_паспорта(а.имя).write_text(json.dumps(п, ensure_ascii=False, indent=2))
            print(f"✓ паспорт «{а.имя}» подтверждён — рисовать по нему можно")
            return 0
        if а.достать:
            п = прочитать(а.имя)
            файл = pathlib.Path(а.файл or п["источник_файл"])
            print(json.dumps(применить(п, json.loads(файл.read_text())),
                             ensure_ascii=False, indent=2))
            return 0
        if а.файл and а.имя:
            return написать(а.имя, pathlib.Path(а.файл).expanduser())
    except Отказ as о:
        print(f"ОТКАЗ: {о}", file=sys.stderr)
        return 1
    р.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
