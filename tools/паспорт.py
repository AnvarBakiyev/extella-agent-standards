# ── образец: показать модели форму, а не объём ───────────────────────────────

def образец(значение, глубина: int = 0):
    """Урезать содержимое до формы. Модели нужен вид данных, а не все данные.

    Длинный образец не делает ответ точнее: он делает запрос дороже, медленнее и
    повышает шанс, что содержимое клиента уедет наружу целиком. Три элемента
    списка показывают структуру ровно так же, как три тысячи.
    """
    if глубина > 4:
        return "…"
    if isinstance(значение, dict):
        return {к: образец(з, глубина + 1) for к, з in list(значение.items())[:25]}
    if isinstance(значение, list):
        return [образец(з, глубина + 1) for з in значение[:3]] + (
            [f"…ещё {len(значение) - 3}"] if len(значение) > 3 else [])
    if isinstance(значение, str):
        # Наши приложения кладут работу строкой с JSON внутри — разворачиваем,
        # иначе модель увидит стену текста вместо структуры.
        о = значение.strip()
        if о[:1] in "[{" and len(о) > 40:
            try:
                return {"__json_строкой__": образец(json.loads(о), глубина + 1)}
            except json.JSONDecodeError:
                pass
        return значение[:200] + ("…" if len(значение) > 200 else "")
    return значение


