#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Текст приложения — это выпуск покупателю, а не правка файла (F12 аудита 28.09.2026).

ЗАЧЕМ. `store_app/content.json` читается установленными приложениями публично, без
токена и без нашей выкладки: merge в main — и текст у людей изменился. При этом
страница применяет содержимое, **только если версия строго новее** (H14). Отсюда два
разных провала, и оба тихие:

  * версию подняли, а текст не посмотрели — люди получили непроверенное;
  * текст поменяли, а версию НЕ подняли — люди не получили ничего, и правка живёт
    только в репозитории.

Второй случился у нас 28.09.2026: в PR #77 из приложения убрали совет обходить
предохранитель, версию содержимого не тронули — и у установленных остался прежний
вредный текст. Один гейт ловит оба.

ЧТО ПРОВЕРЯЕТСЯ:

  1. отпечаток текста совпадает с записанным для текущей версии; разошёлся —
     значит текст меняли после выпуска и версию надо поднять;
  2. версия строго новее предыдущего выпуска (иначе страница её не возьмёт);
  3. у текущей версии есть строка «что нового» — человек должен прочесть, что
     ему прилетело;
  4. у каждого раздела заполнены оба языка;
  5. у каждой кнопки «Копировать» непустой текст;
  6. ссылки в копируемых блоках полные (`raw.githubusercontent.com/...`), без
     сокращений вида `.../main/`: сокращение нельзя вставить в чат агента;
  7. рукописные метки версий в `store_app/README.md` не спорят с `listing.json`.

    python3 tools/check_content_release.py                 # проверка
    python3 tools/check_content_release.py --предпросмотр  # что увидят установленные
    python3 tools/check_content_release.py --записать      # зафиксировать выпуск
    python3 tools/check_content_release.py --selftest

Коды выхода: 0 — содержимое готово к выпуску, 1 — нет.

ГРАНИЦА. Это ПРОВЕРКА ИСХОДНИКОВ. Она не открывает приложение, не жмёт кнопки и не
доказывает, что текст выглядит на экране как задумано. Подтверждение владельца
остаётся за человеком — гейт лишь не даёт выпустить молча.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
СОДЕРЖИМОЕ = КОРЕНЬ / "store_app" / "content.json"
ЛИСТИНГ = КОРЕНЬ / "store_app" / "listing.json"
ЧИТАЙ_МЕНЯ = КОРЕНЬ / "store_app" / "README.md"
ВЫПУСКИ = КОРЕНЬ / "store_app" / "выпуски_содержимого.json"

СОКРАЩЁННАЯ_ССЫЛКА = re.compile(r"\.\.\./main/")
ПОЛНАЯ_ССЫЛКА = re.compile(r"https://raw\.githubusercontent\.com/")


def данные() -> dict:
    return json.loads(СОДЕРЖИМОЕ.read_text(encoding="utf-8"))


def отпечаток(d: dict) -> str:
    """Отпечаток ТЕКСТА, а не файла: перестановка ключей или отступы не должны
    выглядеть как новый выпуск, а изменение любой буквы — должно."""
    куски = [str(d.get("шапка", ""))]
    for раздел in d.get("разделы", []):
        for поле in ("номер", "заголовок", "тело", "заголовок_en", "тело_en"):
            куски.append(str(раздел.get(поле, "")))
    return hashlib.sha256("\u0000".join(куски).encode("utf-8")).hexdigest()


def как_число(версия: str):
    """«2026-09-28.1» → сравнимый кортеж. Неразборчивое отдаётся строкой, чтобы
    гейт сказал об этом словами, а не сравнил молча неверно."""
    m = re.fullmatch(r"(\d{4})-(\d{2})-(\d{2})\.(\d+)", str(версия).strip())
    if not m:
        return None
    return tuple(int(ч) for ч in m.groups())


def журнал() -> dict:
    if ВЫПУСКИ.exists():
        return json.loads(ВЫПУСКИ.read_text(encoding="utf-8"))
    return {"выпуски": []}


def разбор(d: dict, ж: dict, читай_меня: str = "", листинг: dict | None = None) -> list[str]:
    беды = []
    версия = str(d.get("версия_содержимого", "")).strip()
    если_число = как_число(версия)
    if not версия:
        беды.append("нет «версия_содержимого» — страница не поймёт, что появилось новее")
    elif если_число is None:
        беды.append(f"версия «{версия}» не вида ГГГГ-ММ-ДД.N — сравнить нельзя")

    записи = ж.get("выпуски", [])
    последняя = записи[-1] if записи else None
    сейчас = отпечаток(d)

    if последняя:
        прежнее_число = как_число(последняя["версия"])
        текст_менялся = последняя["отпечаток"] != сейчас
        # ПОРЯДОК ВЕРСИЙ ПРОВЕРЯЕТСЯ ОТДЕЛЬНО ОТ ТЕКСТА. Раньше проверка пряталась
        # внутрь ветки «текст изменился», и версия, уехавшая назад при неизменном
        # тексте, проходила молча — самопроверка это и поймала.
        не_новее = (если_число and прежнее_число and если_число <= прежнее_число)
        if текст_менялся and версия == последняя["версия"]:
            беды.append(
                "ТЕКСТ ИЗМЕНИЛСЯ, А ВЕРСИЯ ТА ЖЕ: страница применяет содержимое только "
                "если оно строго новее (H14), значит установленные НЕ получат правку. "
                "Поднимите «версия_содержимого» и добавьте строку в «что_нового».")
        elif не_новее and (текст_менялся or если_число < прежнее_число):
            беды.append(f"версия {версия} не новее выпущенной {последняя['версия']} — "
                        "страница её не возьмёт")

    что_нового = {str(з.get("версия", "")) for з in d.get("что_нового", [])}
    if версия and версия not in что_нового:
        беды.append(f"в «что_нового» нет строки про {версия} — человек не узнает, "
                    "что ему прилетело")

    for раздел in d.get("разделы", []):
        имя = раздел.get("номер") or раздел.get("заголовок") or "?"
        for поле in ("тело", "тело_en", "заголовок", "заголовок_en"):
            if not str(раздел.get(поле, "")).strip():
                беды.append(f"раздел {имя}: пустое поле «{поле}» — половина людей "
                            "увидит дыру")
        тело = str(раздел.get("тело", "")) + str(раздел.get("тело_en", ""))
        if 'class="copy"' in тело:
            коды = re.findall(r"<code>(.*?)</code>", тело, re.S)
            if not коды or not any(к.strip() for к in коды):
                беды.append(f"раздел {имя}: кнопка «Копировать» есть, а копировать нечего")
            if СОКРАЩЁННАЯ_ССЫЛКА.search("".join(коды)):
                беды.append(f"раздел {имя}: в копируемом тексте ссылка вида «.../main/» — "
                            "её нельзя вставить агенту, нужна полная")

    if читай_меня and листинг:
        объявлена = str(листинг.get("версия", "")).strip()
        руками = set(re.findall(r"версия\s*\|?\s*(\d+\.\d+\.\d+)", читай_меня))
        руками |= set(re.findall(r"[Рр]абочая публичная версия — (\d+\.\d+\.\d+)", читай_меня))
        чужие = {в for в in руками if в != объявлена}
        if чужие:
            беды.append(f"в store_app/README.md версия написана руками ({', '.join(sorted(чужие))}) "
                        f"и спорит с listing.json ({объявлена})")
    return беды


def предпросмотр() -> int:
    d, ж = данные(), журнал()
    записи = ж.get("выпуски", [])
    print(f"Версия содержимого: {d.get('версия_содержимого')}")
    print(f"Разделов: {len(d.get('разделы', []))}, отпечаток текста: {отпечаток(d)[:12]}")
    if not записи:
        print("Прошлых выпусков не записано — это будет первый.")
        return 0
    п = записи[-1]
    print(f"Последний записанный выпуск: {п['версия']} (отпечаток {п['отпечаток'][:12]})")
    if п["отпечаток"] == отпечаток(d):
        print("Текст НЕ менялся с прошлого выпуска — установленные ничего не заметят.")
    else:
        print("Текст ИЗМЕНИЛСЯ. После merge в main установленные приложения получат "
              "новый текст без отдельной выкладки — это и есть выпуск покупателю.")
        for з in d.get("что_нового", []):
            if str(з.get("версия")) == str(d.get("версия_содержимого")):
                print(f"  что увидит человек: {з.get('текст', '')[:300]}")
    return 0


def записать() -> int:
    d = данные()
    беды = разбор(d, журнал(), ЧИТАЙ_МЕНЯ.read_text(encoding="utf-8"),
                  json.loads(ЛИСТИНГ.read_text(encoding="utf-8")))
    if беды:
        for б in беды:
            print("  ✗ " + б)
        print("\nВыпуск не записан: сначала почините перечисленное.")
        return 1
    ж = журнал()
    записи = ж.setdefault("выпуски", [])
    новая = {"версия": str(d["версия_содержимого"]), "отпечаток": отпечаток(d)}
    # Повторная запись той же версии ОБНОВЛЯЕТ строку, а не плодит близнецов:
    # иначе журнал выпусков перестаёт быть журналом (я так и сделал дважды подряд).
    for i, з in enumerate(записи):
        if з.get("версия") == новая["версия"]:
            записи[i] = новая
            break
    else:
        записи.append(новая)
    ВЫПУСКИ.write_text(json.dumps(ж, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Выпуск записан: {d['версия_содержимого']} · {отпечаток(d)[:12]}")
    return 0


def прогон() -> int:
    беды = разбор(данные(), журнал(), ЧИТАЙ_МЕНЯ.read_text(encoding="utf-8"),
                  json.loads(ЛИСТИНГ.read_text(encoding="utf-8")))
    for б in беды:
        print("  ✗ " + б)
    if беды:
        print("\nНЕ УСПЕХ: содержимое приложения не готово уехать людям.")
        return 1
    d = данные()
    print(f"ПРОВЕРКА ИСХОДНИКОВ пройдена: содержимое {d['версия_содержимого']} готово к "
          f"выпуску (разделов {len(d['разделы'])}, оба языка заполнены, копируемые "
          "ссылки полные, версия строго новее прошлой).")
    print("Это не доказательство, что текст выглядит на экране как задумано, и не "
          "заменяет решения владельца: merge в main = выпуск покупателю.")
    return 0


def selftest() -> int:
    провалы = []
    d, ж = данные(), журнал()
    читай = ЧИТАЙ_МЕНЯ.read_text(encoding="utf-8")
    листинг = json.loads(ЛИСТИНГ.read_text(encoding="utf-8"))
    print("Самопроверка check_content_release:")

    if разбор(d, ж, читай, листинг):
        провалы.append("живое содержимое объявлено негодным — ложная тревога")
    print("  ✓ на живом содержимом тревоги нет")

    # Случаи про версию проверяются на ПОДСТАВНОМ журнале: иначе самопроверка
    # зависела бы от того, записан ли уже выпуск, и молчала бы на пустом журнале —
    # то есть ровно тогда, когда защита нужнее всего.
    подставной = {"выпуски": [{"версия": d["версия_содержимого"], "отпечаток": отпечаток(d)}]}

    # Главный случай: текст поменяли, версию не тронули.
    тот_же = json.loads(json.dumps(d, ensure_ascii=False))
    тот_же["разделы"][0]["тело"] += " правка без подъёма версии"
    беды = разбор(тот_же, подставной, читай, листинг)
    if not any("ВЕРСИЯ ТА ЖЕ" in б for б in беды):
        провалы.append("правка текста без подъёма версии не поймана — а это наш случай")
    print("  ✓ правка текста без подъёма версии ловится")

    # Версия ушла назад.
    назад = json.loads(json.dumps(d, ensure_ascii=False))
    назад["версия_содержимого"] = "2000-01-01.1"
    назад["что_нового"] = [{"версия": "2000-01-01.1", "текст": "проба"}]
    if not any("не новее" in б for б in разбор(назад, подставной, читай, листинг)):
        провалы.append("версия назад не поймана")
    print("  ✓ версия назад ловится")

    # Пустой язык.
    пустой = json.loads(json.dumps(d, ensure_ascii=False))
    пустой["разделы"][1]["тело_en"] = "   "
    if not any("пустое поле" in б for б in разбор(пустой, ж, читай, листинг)):
        провалы.append("пустой язык не пойман")
    print("  ✓ пустой язык раздела ловится")

    # Сокращённая ссылка в копируемом тексте.
    сокращ = json.loads(json.dumps(d, ensure_ascii=False))
    for раздел in сокращ["разделы"]:
        if 'class="copy"' in str(раздел.get("тело", "")):
            раздел["тело"] = раздел["тело"].replace(
                "<code>", "<code>смотри .../main/AGENT_START.md\n", 1)
            break
    if not any("main/" in б for б in разбор(сокращ, ж, читай, листинг)):
        провалы.append("сокращённая ссылка в копируемом тексте не поймана")
    print("  ✓ сокращённая ссылка в копируемом тексте ловится")

    # Рукописная версия спорит с листингом.
    if not any("написана руками" in б for б in
               разбор(d, ж, "| версия | 9.9.9, цена 0 |", листинг)):
        провалы.append("рукописная версия, спорящая с листингом, не поймана")
    print("  ✓ рукописная метка версии сверяется с листингом")

    # Отпечаток обязан быть про текст, а не про форматирование файла.
    иначе = json.loads(json.dumps(d, ensure_ascii=False))
    иначе["лишнее_поле"] = "не текст"
    if отпечаток(иначе) != отпечаток(d):
        провалы.append("отпечаток меняется от служебного поля — выпуски будут ложными")
    print("  ✓ отпечаток считается по тексту, а не по форматированию файла")

    if провалы:
        for п in провалы:
            print("  ✗ " + п)
        print("ИТОГ САМОПРОВЕРКИ: провалы есть")
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    if "--предпросмотр" in sys.argv:
        sys.exit(предпросмотр())
    if "--записать" in sys.argv:
        sys.exit(записать())
    sys.exit(прогон())
