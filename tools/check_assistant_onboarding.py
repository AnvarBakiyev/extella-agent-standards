#!/usr/bin/env python3
"""Подключение ассистента на новой машине закрыто продуктом, а не памяткой (H108).

ЗАЧЕМ. Приложение Extella не кладёт ключ на диск (замер 24.09.2026 на 1.3.0), и на
каждом новом компьютере ассистент остаётся без ключа. Пока это закрыто тремя
вещами — экспертом, который подключает сам; отказом установщика, который ведёт на
экран токенов; разделом в приложении «Разработка на Extella» — человек не упирается
в стену. Стоит любой из трёх исчезнуть, и мы вернёмся к переписке «а где взять
ключ», как было с коллегами на новых машинах.

ЧТО ПРОВЕРЯЕТСЯ (по файлам репозитория, без сети):

1. `experts/dev_connect_assistant.py` есть; пишет права 600; проверяет ключ живым
   вызовом; не возвращает значение ключа наружу; называет экран токенов.
2. `tools/connect_mcp.py` в отказе ведёт на экран токенов.
3. `store_app/content.json` содержит раздел про новую машину на двух языках.
4. (H110) Нигде в репозитории человеку не обещают, что ключ появится на диске сам. Запрет
   был только в самопроверке `connect_mcp.py` — и потому уцелел ещё в трёх файлах
   (`store_app/update.py`, `tools/new_product.py`, `INSTALLER_CANON.md`), которые
   продолжали звать «просто открой приложение». Цитировать неверный совет можно,
   но лишь рядом со словами, что он неверен.

    python3 tools/check_assistant_onboarding.py
    python3 tools/check_assistant_onboarding.py --selftest

Коды выхода: 0 — цело, 1 — что-то из трёх сломано или пропало.

ПРИЁМКА 25.09.2026: прогон по репозиторию зелёный, ложных тревог нет.
"""

from __future__ import annotations

import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ЭКСПЕРТ = КОРЕНЬ / "experts" / "dev_connect_assistant.py"
УСТАНОВЩИК = КОРЕНЬ / "tools" / "connect_mcp.py"
СОДЕРЖИМОЕ = КОРЕНЬ / "store_app" / "content.json"


def беды_эксперта(код: str) -> list[str]:
    беды = []
    if "0o600" not in код:
        беды.append("эксперт не ставит права 600 на файл ключа")
    if "api.extella.ai" not in код:
        беды.append("эксперт не проверяет ключ живым вызовом — наличие файла ничего не значит")
    if "Tokens" not in код:
        беды.append("эксперт не называет экран токенов, когда ключа нет")
    # Значение ключа наружу не уходит: в ответах допустим только отпечаток.
    if '"ключ"' in код or '"token":' in код:
        беды.append("эксперт возвращает значение ключа — наружу идёт только отпечаток")
    return беды


def беды_раздела(данные: dict) -> list[str]:
    разделы = данные.get("разделы") or []
    нужен = [р for р in разделы
             if "машин" in (р.get("заголовок") or "").lower()
             or "machine" in (р.get("заголовок_en") or "").lower()]
    if not нужен:
        return ["в приложении «Разработка на Extella» нет раздела про новую машину"]
    р = нужен[0]
    беды = []
    if "Tokens" not in (р.get("тело") or "") or "Tokens" not in (р.get("тело_en") or ""):
        беды.append("раздел не называет экран токенов на обоих языках")
    if "dev_connect_assistant" not in (р.get("тело") or ""):
        беды.append("раздел не называет эксперта, который подключает сам")
    return беды


ОБЕЩАНИЕ = ("появится сам", "появляется сам", "появится сама",
             "появляется при первом запуске", "appears the first time",
             "appears by itself")
# Обещание про ключ, а не про что угодно: «агент появляется сам после деплоя» —
# правда и к H108 отношения не имеет.
О_КЛЮЧЕ = ("ключ", "токен", "token", "api_token", "os_token")
# Цитата неверного совета законна рядом со словами, что он неверен.
ОПРОВЕРЖЕНИЕ = ("чего не происходит", "хотя", "неверн", "ложн", "не кладёт",
                "не появляется", "было —", "| Было", "раньше")
РАСШИРЕНИЯ = (".md", ".py", ".json", ".html", ".txt", ".sh")
# Свой файл мимо: в нём лежат сами образцы запрещённой фразы, иначе гейт падает
# на себе. Его охраняет собственная самопроверка.
МИМО = ("/.git/", "/dist/", "/node_modules/", "store_app/index.html",
        "/store_app/product/", "/store_app/migrations/",
        "/tools/check_assistant_onboarding.py")


def беды_обещания(корень: pathlib.Path) -> list[str]:
    """Обещание «ключ появится сам» ищется по всему репозиторию, а не в одном файле."""
    беды = []
    for ф in sorted(корень.rglob("*")):
        if not ф.is_file() or ф.suffix not in РАСШИРЕНИЯ:
            continue
        путь = "/" + str(ф.relative_to(корень))
        if any(м in путь for м in МИМО):
            continue
        try:
            строки = ф.read_text(encoding="utf-8").splitlines()
        except (UnicodeDecodeError, OSError):
            continue
        for н, строка in enumerate(строки, 1):
            низ = строка.lower()
            if not any(о in низ for о in ОБЕЩАНИЕ):
                continue
            if not any(к in низ for к in О_КЛЮЧЕ):
                continue
            if any(о in низ for о in ОПРОВЕРЖЕНИЕ):
                continue
            беды.append(f"{путь.lstrip('/')}:{н} обещает, что ключ появится сам (H108)")
    return беды


def проверить() -> int:
    беды: list[str] = []
    if not ЭКСПЕРТ.exists():
        беды.append("нет experts/dev_connect_assistant.py — подключение опять станет памяткой")
    else:
        беды += беды_эксперта(ЭКСПЕРТ.read_text(encoding="utf-8"))

    if not УСТАНОВЩИК.exists():
        беды.append("нет tools/connect_mcp.py")
    elif "Tokens" not in УСТАНОВЩИК.read_text(encoding="utf-8"):
        беды.append("отказ установщика не ведёт на экран токенов (H108)")

    if not СОДЕРЖИМОЕ.exists():
        беды.append("нет store_app/content.json")
    else:
        try:
            беды += беды_раздела(json.loads(СОДЕРЖИМОЕ.read_text(encoding="utf-8")))
        except json.JSONDecodeError as e:
            беды.append(f"content.json не разбирается: {e}")

    беды += беды_обещания(КОРЕНЬ)

    for б in беды:
        print("  ✗ " + б)
    if беды:
        print("\nНЕ УСПЕХ (H108): подключение ассистента на новой машине снова держится "
              "на памяти человека.")
        return 1
    print("H108 цел: эксперт подключает сам, установщик ведёт на экран токенов, "
          "раздел в приложении на месте, обещания «ключ появится сам» в репозитории нет.")
    return 0


def _selftest() -> int:
    провалы = []

    def проба(имя, условие):
        print(("  ✓ " if условие else "  ✗ ") + имя)
        if not условие:
            провалы.append(имя)

    print("Самопроверка check_assistant_onboarding:")
    хороший = 'os.chmod(ф, 0o600)\nurllib...api.extella.ai...\n"Library → System → Tokens"'
    проба("исправный эксперт претензий не вызывает", беды_эксперта(хороший) == [])
    проба("нет прав 600 — ловится",
          any("600" in б for б in беды_эксперта('api.extella.ai Tokens')))
    проба("нет рукопожатия — ловится",
          any("живым вызовом" in б for б in беды_эксперта('0o600 Tokens')))
    проба("возврат значения ключа — ловится",
          any("значение ключа" in б for б in беды_эксперта(хороший + '\n"token": ключ')))
    раздел = {"разделы": [{"заголовок": "Ассистент на новой машине",
                           "заголовок_en": "The assistant on a new machine",
                           "тело": "Tokens dev_connect_assistant", "тело_en": "Tokens"}]}
    проба("целый раздел претензий не вызывает", беды_раздела(раздел) == [])
    проба("раздел без английского текста — ловится",
          беды_раздела({"разделы": [{"заголовок": "новая машина",
                                     "тело": "Tokens dev_connect_assistant", "тело_en": ""}]}) != [])
    проба("раздела нет вовсе — ловится", беды_раздела({"разделы": []}) != [])
    проба("H108 упомянут в тексте проверки",
          "H108" in pathlib.Path(__file__).read_text(encoding="utf-8"))

    import tempfile
    with tempfile.TemporaryDirectory() as вр:
        д = pathlib.Path(вр)
        (д / "плохо.md").write_text(
            "Открой приложение — токен появится сам.", encoding="utf-8")
        (д / "цитата.md").write_text(
            "Совет «ключ появится сам» неверный: приложение его не кладёт.", encoding="utf-8")
        (д / "чужое.md").write_text(
            "Agent Cabinet появляется сам из Agent Passport.", encoding="utf-8")
        найдено = беды_обещания(д)
        проба("обещание про токен ловится",
              any("плохо.md" in б for б in найдено))
        проба("цитата рядом с опровержением пропускается",
              not any("цитата.md" in б for б in найдено))
        проба("обещание не про ключ пропускается",
              not any("чужое.md" in б for б in найдено))

    проба("в самом репозитории обещания нет", беды_обещания(КОРЕНЬ) == [])

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы — " + "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    sys.exit(_selftest() if "--selftest" in sys.argv else проверить())
