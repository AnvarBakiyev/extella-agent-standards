def fnd_journal(действие="список", текст="", тема="", перепроверить_через="", id=""):
    """Журнал решений основателя. Живёт ТОЛЬКО на машине владельца.

    Одно решение = одна запись: что решено, когда, по какой теме и когда это
    надо перепроверить. Последнее — главное: у нас факты о платформе протухали
    за сутки, и вчерашняя запись врала уже сегодня.

    Действия:
      список   — отдать всё одним снимком (страница дальше работает без сети)
      добавить — записать решение
      закрыть  — пометить решение неактуальным (не удаляя: след остаётся)

    Наружу не уходит ничего: файл лежит рядом с настройками Extella на этой машине.
    """
    import json, os, pathlib, datetime, hashlib

    def отдать(данные):
        """Возвращаем СТРОКУ JSON, а не словарь.

        Платформа сериализует словарь питоновским repr: одинарные кавычки и True/None.
        Это не JSON, и страница его не разберёт — а выглядит всё как успех.
        """
        return json.dumps(данные, ensure_ascii=False)

    ПАПКА = pathlib.Path.home() / ".extella" / "founder"
    ФАЙЛ = ПАПКА / "journal.json"
    ПАПКА.mkdir(parents=True, exist_ok=True)

    def прочитать():
        if not ФАЙЛ.exists():
            return {"версия": 1, "решения": []}
        try:
            return json.loads(ФАЙЛ.read_text(encoding="utf-8"))
        except Exception as e:
            # Битый файл не молчит и не затирается: рядом ложится копия.
            битый = ФАЙЛ.with_suffix(".битый")
            ФАЙЛ.replace(битый)
            return {"версия": 1, "решения": [],
                    "предупреждение": f"журнал был повреждён ({e}), прежний файл: {битый.name}"}

    def записать(д):
        врем = ФАЙЛ.with_suffix(".новый")
        врем.write_text(json.dumps(д, ensure_ascii=False, indent=1), encoding="utf-8")
        врем.replace(ФАЙЛ)          # замена целиком: половинчатого файла не бывает

    def сегодня():
        return datetime.date.today().isoformat()

    д = прочитать()
    решения = д.get("решения", [])

    if действие == "добавить":
        if not текст.strip():
            return отдать({"ошибка": "решение пустое — напиши, что именно решено"})
        через = 0
        try:
            через = int(перепроверить_через or 0)
        except ValueError:
            через = 0
        запись = {
            "id": hashlib.sha256((текст + сегодня()).encode()).hexdigest()[:12],
            "текст": текст.strip(),
            "тема": (тема or "без темы").strip(),
            "когда": сегодня(),
            "перепроверить": (datetime.date.today() + datetime.timedelta(days=через)).isoformat()
                             if через > 0 else "",
            "закрыто": False,
        }
        решения.insert(0, запись)
        д["решения"] = решения
        записать(д)
        return отдать({"добавлено": запись, "всего": len(решения)})

    if действие == "закрыть":
        нашлось = False
        for р in решения:
            if р.get("id") == id:
                р["закрыто"] = True
                р["закрыто_когда"] = сегодня()
                нашлось = True
        if not нашлось:
            return отдать({"ошибка": f"решения с id {id} нет — открой список и возьми id оттуда"})
        д["решения"] = решения
        записать(д)
        return отдать({"закрыто": id, "всего": len(решения)})

    # список — один снимок целиком, дальше страница работает мгновенно и без сети
    просрочены = [р for р in решения
                  if not р.get("закрыто") and р.get("перепроверить")
                  and р["перепроверить"] <= сегодня()]
    return отдать({
        "решения": решения,
        "всего": len(решения),
        "открытых": len([р for р in решения if not р.get("закрыто")]),
        "пора_перепроверить": просрочены,
        "файл": str(ФАЙЛ),
        "предупреждение": д.get("предупреждение", ""),
    })
