# description: Модуль «чтение договоров»: достаёт из файла договора стороны, срок, сумму, автопродление, срок уведомления и подсудность. Читает на устройстве локальной моделью — текст договора не покидает машину. Наружу отправляет только по явному разрешению человека.
def toolkit_contract_read(path: str = "", allow_cloud: str = "", max_chars: str = "") -> str:
    # ПРАВИЛО ЭТОГО МОДУЛЯ. Договор — данные клиента, и по канону они живут в
    # контуре клиента. Поэтому чтение идёт локальной моделью на этой машине, а
    # облако включается ТОЛЬКО явным allow_cloud="да-в-облако" от человека.
    # Молчаливая отправка договора наружу была бы худшим видом поломки: продукт
    # выглядит работающим, а данные уже ушли.
    import html, json, os, re, urllib.request, zipfile

    ПОЛЯ = ("стороны", "предмет", "срок", "сумма", "автопродление",
            "уведомление_о_расторжении", "подсудность")

    def отказ(сообщение, **ещё):
        д = {"status": "error", "message": сообщение}
        д.update(ещё)
        return json.dumps(д, ensure_ascii=False)

    файл = os.path.expanduser((path or "").strip())
    if not файл:
        return отказ("не сказано, какой файл читать")
    if not os.path.isfile(файл):
        return отказ("файла нет по этому пути: " + os.path.basename(файл))

    предел = 12000
    try:
        предел = max(2000, min(40000, int(str(max_chars).strip() or предел)))
    except ValueError:
        pass

    расш = os.path.splitext(файл)[1].lower()

    # Чем читаем — говорим честно. PDF без сторонней библиотеки не разбираем и
    # НЕ делаем вид, что разобрали: выдуманные поля дороже отказа.
    if расш in (".txt", ".md", ".rtf"):
        with open(файл, "r", encoding="utf-8", errors="replace") as f:
            текст = f.read()
        if расш == ".rtf":
            текст = re.sub(r"\\[a-z]+-?\d* ?|[{}]", "", текст)
    elif расш == ".docx":
        try:
            with zipfile.ZipFile(файл) as z:
                сырое = z.read("word/document.xml").decode("utf-8", "replace")
        except Exception as e:
            return отказ("не открыть .docx: " + str(e)[:90])
        сырое = re.sub(r"</w:(p|tr)>", "\n", сырое)
        сырое = re.sub(r"</w:tc>", "\t", сырое)
        текст = html.unescape(re.sub(r"<[^>]+>", "", сырое))
    elif расш == ".pdf":
        return отказ("PDF этот модуль не читает: без сторонней библиотеки текст "
                     "из него достаётся неверно, а выдуманные поля хуже отказа. "
                     "Сохрани договор как .docx или .txt и повтори.",
                     формат="pdf", что_умею=[".txt", ".md", ".rtf", ".docx"])
    else:
        return отказ("формат " + (расш or "без расширения") + " не читаю",
                     что_умею=[".txt", ".md", ".rtf", ".docx"])

    текст = re.sub(r"[ \t]+", " ", текст)
    текст = re.sub(r"\n{3,}", "\n\n", текст).strip()
    если_обрезан = len(текст) > предел
    текст = текст[:предел]
    if not текст:
        return отказ("в файле нет текста — возможно, это скан")

    задание = (
        "Ты читаешь договор и заполняешь карточку. Отвечай ТОЛЬКО одним объектом "
        "JSON с ключами: " + ", ".join(ПОЛЯ) + ". Значение — короткая строка из "
        "текста договора. Если в договоре этого нет — поставь строку \"не найдено\". "
        "Ничего не додумывай и не вычисляй.\n\nТЕКСТ ДОГОВОРА:\n" + текст)

    # ── чтение локальной моделью: текст остаётся на машине
    def местная_модель():
        try:
            with urllib.request.urlopen("http://127.0.0.1:1234/v1/models", timeout=6) as о:
                имена = [str(m.get("id", "")) for m in json.loads(о.read().decode()).get("data", [])]
        except Exception:
            return "", "локальная модель не отвечает на этой машине"
        годные = [и for и in имена if "embed" not in и.lower()]
        if not годные:
            return "", "на машине нет подходящей локальной модели"
        имя = годные[0]
        тело = json.dumps({"model": имя, "temperature": 0,
                           "messages": [{"role": "user", "content": задание}],
                           "max_tokens": 700}).encode()
        з = urllib.request.Request("http://127.0.0.1:1234/v1/chat/completions", data=тело,
                                   headers={"Content-Type": "application/json"}, method="POST")
        try:
            with urllib.request.urlopen(з, timeout=180) as о:
                д = json.loads(о.read().decode())
            return д["choices"][0]["message"]["content"], имя
        except Exception as e:
            return "", "локальная модель не ответила: " + str(e)[:90]

    ответ, чем = местная_модель()
    где = "на этом компьютере"

    if not ответ:
        # Облако — только по явному слову человека, и мы называем, что уйдёт.
        if str(allow_cloud).strip().lower() not in ("да-в-облако", "yes-cloud"):
            return отказ(
                "Читать нечем: " + чем + ". Текст договора наружу я сам не отправляю — "
                "это данные клиента. Если разрешаешь отправить его в облако Extella, "
                "повтори с allow_cloud=\"да-в-облако\".",
                нужно_разрешение=True, знаков_ушло_бы=len(текст))
        return отказ("облачное чтение этим модулем ещё не подключено — "
                     "разрешение получено, но канал не собран",
                     нужно_разрешение=False)

    # Модель обязана вернуть JSON; на свободный текст не гадаем.
    кусок = ответ[ответ.find("{"): ответ.rfind("}") + 1] if "{" in ответ else ""
    try:
        карточка = json.loads(кусок)
    except Exception:
        return отказ("модель ответила не карточкой, а свободным текстом — "
                     "поля не заполняю, чтобы не выдумать",
                     начало_ответа=ответ.strip()[:120])

    итог = {"status": "success", "file": os.path.basename(файл),
            "read_by": чем, "where": где, "truncated": если_обрезан,
            "chars_read": len(текст), "left_device": False}
    for поле in ПОЛЯ:
        итог[поле] = str(карточка.get(поле, "не найдено")).strip()[:400] or "не найдено"
    итог["found"] = sum(1 for п in ПОЛЯ if итог[п] != "не найдено")
    итог["of"] = len(ПОЛЯ)
    return json.dumps(итог, ensure_ascii=False)
