#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проверка модуля «чтение договоров» — та часть тулкита, которая умеет сказать «нет».

ЗАЧЕМ. Рецепт обещает способность, а доказывает её только проверка. Тулкит без
проверки — это лотерея: у одного собралось, у другого нет, и никто не знает,
у кого именно. Поэтому проверка обязана уметь ПРОВАЛИТЬСЯ, и это здесь
доказывается негативным контролем: слепок портится нарочно, и проверка обязана
покраснеть. Молчаливо зелёная проверка хуже её отсутствия.

    python3 проверка.py --selftest   # без модели: форма, границы, негативный контроль
    python3 проверка.py --живьём     # настоящий прогон на образце, нужна локальная модель

Коды выхода: 0 — прошло, 1 — есть провалы.
"""

import argparse
import importlib.util
import json
import pathlib
import re
import sys
import tempfile
import time

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
СЛЕПОК = ЗДЕСЬ / "слепок" / "toolkit_contract_read.py"
ОБРАЗЕЦ = ЗДЕСЬ / "образец" / "договор-образец.txt"
ПОЛЯ = ("стороны", "предмет", "срок", "сумма", "автопродление",
        "уведомление_о_расторжении", "подсудность")


def загрузить(путь: pathlib.Path):
    сп = importlib.util.spec_from_file_location("слепок_" + путь.stem, путь)
    м = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(м)
    return м.toolkit_contract_read


def форма(беды: list) -> None:
    """Тулкит — это три части. Нет любой из них — это не тулкит."""
    for имя, путь in (("рецепт", ЗДЕСЬ / "РЕЦЕПТ.md"),
                      ("паспорт", ЗДЕСЬ / "ПАСПОРТ.md"),
                      ("слепок", СЛЕПОК),
                      ("образец", ОБРАЗЕЦ)):
        if not путь.exists():
            беды.append(f"нет части «{имя}»: {путь.name}")
    if СЛЕПОК.exists():
        текст = СЛЕПОК.read_text(encoding="utf-8")
        if not текст.startswith("# description:"):
            беды.append("у слепка нет строки # description: — агент не поймёт, зачем он")
        if "import " in текст.split("def ", 1)[0]:
            беды.append("импорты вне функции: эксперт обязан быть самодостаточным")


def границы(зов, беды: list) -> None:
    """Отказы важнее успехов: модуль обязан отказывать словами, а не выдумывать."""
    случаи = (("пустой путь", {"path": ""}, "какой файл"),
              ("нет файла", {"path": "/tmp/нет-такого-договора.txt"}, "файла нет"),
              ("pdf", {"path": str(ЗДЕСЬ / "образец" / "мнимый.pdf")}, None))
    (ЗДЕСЬ / "образец" / "мнимый.pdf").write_bytes("%PDF-1.4 не настоящий".encode("utf-8"))
    try:
        for имя, параметры, ждём in случаи:
            о = json.loads(зов(**параметры))
            if о.get("status") != "error":
                беды.append(f"{имя}: обязан быть отказ, пришло {о.get('status')}")
                continue
            if ждём and ждём not in о.get("message", ""):
                беды.append(f"{имя}: отказ не называет причину")
            if имя == "pdf" and "PDF" not in о.get("message", ""):
                беды.append("pdf: модуль обязан отказаться, а не разбирать PDF наугад")
    finally:
        (ЗДЕСЬ / "образец" / "мнимый.pdf").unlink(missing_ok=True)


def приватность(беды: list) -> None:
    """Договор наружу по умолчанию не уходит. Проверяем поведением: подменяем
    модель на недоступную и смотрим, что модуль сделает без разрешения."""
    исходный = СЛЕПОК.read_text(encoding="utf-8")
    глухой = исходный.replace("http://127.0.0.1:1234", "http://127.0.0.1:9")
    with tempfile.TemporaryDirectory() as вр:
        копия = pathlib.Path(вр) / "глухая.py"
        копия.write_text(глухой, encoding="utf-8")
        зов = загрузить(копия)
        о = json.loads(зов(path=str(ОБРАЗЕЦ)))
        if о.get("status") != "error":
            беды.append("без локальной модели модуль обязан отказаться, а не отправить наружу")
        if not о.get("нужно_разрешение"):
            беды.append("отказ не просит разрешения на облако — человек не увидит границы")
        if "наружу" not in о.get("message", ""):
            беды.append("отказ не говорит про отправку наружу")


def негативный_контроль(беды: list) -> None:
    """Доказываем, что проверка умеет краснеть: ломаем слепок нарочно."""
    исходный = СЛЕПОК.read_text(encoding="utf-8")
    сломанный = исходный.replace(
        'if str(allow_cloud).strip().lower() not in ("да-в-облако", "yes-cloud"):',
        'if False:')
    if сломанный == исходный:
        беды.append("негативный контроль не сработал: не нашёл, что ломать")
        return
    with tempfile.TemporaryDirectory() as вр:
        копия = pathlib.Path(вр) / "сломанная.py"
        копия.write_text(сломанный.replace("http://127.0.0.1:1234", "http://127.0.0.1:9"),
                         encoding="utf-8")
        свои = []
        о = json.loads(загрузить(копия)(path=str(ОБРАЗЕЦ)))
        if о.get("нужно_разрешение"):
            свои.append("сломанный слепок всё ещё просит разрешения")
        if not свои:
            return          # проверка покраснела на сломанном — как и должна
        беды.extend("негативный контроль: " + с for с in свои)


# Форму ответа охраняем отдельно. Опыт 26.08.2026: две независимые сборки по
# одному рецепту дали ту же СПОСОБНОСТЬ, но разную форму ответа — 16, 19 и 22
# ключа, и у одной не было поля file. Приложение, написанное под одну сборку,
# на другой ломается. Значит рецепт воспроизводит умение, а контракт — нет, и
# пришпилить контракт обязана проверка.
ОБЯЗАТЕЛЬНЫЕ_КЛЮЧИ = set(ПОЛЯ) | {"status", "file", "read_by", "left_device",
                                   "found", "of"}


def форма_ответа(беды: list) -> None:
    if not ОБРАЗЕЦ.exists():
        return
    о = json.loads(загрузить(СЛЕПОК)(path=str(ОБРАЗЕЦ)))
    if о.get("status") != "success":
        return                       # это ловит живой прогон, здесь не дублируем
    нет = ОБЯЗАТЕЛЬНЫЕ_КЛЮЧИ - set(о)
    if нет:
        беды.append("в ответе нет обязательных ключей: " + ", ".join(sorted(нет)) +
                    " — приложение покупателя на такой сборке сломается")


def живьём(беды: list) -> None:
    """Настоящий прогон. Порог, а не идеал: модель находит не всё, и требовать
    семь из семи значило бы подогнать тест под удачный прогон."""
    зов = загрузить(СЛЕПОК)
    т0 = time.time()
    о = json.loads(зов(path=str(ОБРАЗЕЦ)))
    сек = time.time() - т0
    if о.get("status") != "success":
        беды.append("живой прогон не прошёл: " + str(о.get("message"))[:120])
        return
    print(f"    прочитано за {сек:.1f} с, читала {о.get('read_by')}, "
          f"наружу ушло: {о.get('left_device')}")
    print(f"    заполнено {о.get('found')} из {о.get('of')}")
    if о.get("left_device") is not False:
        беды.append("модуль сообщает, что текст покидал устройство")
    if (о.get("found") or 0) < 4:
        беды.append(f"заполнено всего {о.get('found')} полей из {о.get('of')} — "
                    "модуль не справляется даже с образцом")
    # Три факта заведомо есть в образце — их модуль обязан достать.
    обязаны = (("уведомление_о_расторжении", r"60"),
               ("сумма", r"18\s?400\s?000"),
               ("подсудность", r"[АA]лмат"))
    for поле, образ in обязаны:
        if not re.search(образ, str(о.get(поле, ""))):
            беды.append(f"поле «{поле}» не сошлось с образцом: {str(о.get(поле))[:60]}")


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--selftest", action="store_true")
    р.add_argument("--живьём", dest="живьём", action="store_true")
    о = р.parse_args()
    беды = []
    if о.живьём:
        print("  живой прогон модуля «чтение договоров»:")
        живьём(беды)
    else:
        форма(беды)
        print("  ✓ три части тулкита на месте")
        if СЛЕПОК.exists():
            границы(загрузить(СЛЕПОК), беды)
            print("  ✓ отказы называют причину, PDF не разбирается наугад")
            приватность(беды)
            print("  ✓ без локальной модели договор наружу не уходит")
            негативный_контроль(беды)
            print("  ✓ проверка умеет краснеть: сломанный слепок ловится")
            форма_ответа(беды)
            print("  ✓ форма ответа на месте: приложение покупателя не сломается")
    if беды:
        for б in беды:
            print("  ✗ " + б)
        print("ИТОГ САМОПРОВЕРКИ: провалы есть")
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    sys.exit(main())
