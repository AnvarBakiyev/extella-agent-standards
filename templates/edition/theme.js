// Тема издания — расширение Extella OS.
//
// ВАЖНО ПРО ГРАНИЦЫ. Расширение подмешивается во ВСЕ окна ОС. Поэтому тема обязана
// первым делом понять, где она оказалась, и в чужих окнах не делать НИЧЕГО. Тема,
// которая красит всё подряд, — не тема, а помеха, и её снимут в первый день.
(function () {
  var ИЗДАНИЕ = "edition-design";        // тег издания из edition.yaml
  // Версия в флаге обязательна: на столе могут ужиться ДВЕ копии темы — старая
  // и новая. Без версии первая занимает флаг и не пускает вторую, и обновление
  // темы тихо не применяется.
  var ВЕРСИЯ = "0.1.1";
  var ФЛАГ = "__тема_" + ИЗДАНИЕ + "_" + ВЕРСИЯ;
  if (window[ФЛАГ]) return;
  window[ФЛАГ] = true;

  // Тема применяется только к оболочке ОС и к окнам СВОИХ приложений.
  var СВОИ = [                            // listing_id приложений издания
    // "00000000-0000-0000-0000-000000000000",
  ];
  var это_оболочка = location.pathname.indexOf("/app-page/") !== 0;
  var это_своё = СВОИ.some(function (id) { return location.pathname.indexOf(id) >= 0; });
  if (!это_оболочка && !это_своё) return;  // чужое приложение — уходим молча

  // ВАЖНО: имена переменных у оболочки ОС СВОИ. Снято чтением 14.08.2026:
  //   --p акцент · --ph акцент при наведении · --ps подложка акцента
  //   --bg фон · --card карточка · --t текст · --tm приглушённый · --tb бледный
  //   --brd граница · --r и --rsm радиусы
  // Наши интерфейсные токены (--a, --s1, --tx…) оболочка НЕ знает: тема, которая
  // меняет их, не меняет ничего. Я на этом попался — тема «работала» и не красила.
  // Цвета — только из палитры (DESIGN_RULE_FOR_APPS); свой оттенок мимо неё — дефект.
  var стиль = document.createElement("style");
  стиль.setAttribute("data-издание", ИЗДАНИЕ);
  стиль.textContent = это_оболочка
    ? ":root{--p:#2F6B66;--ph:#24544F;}"     // оболочка ОС: акцент издания
    : ":root{--a:#2F6B66;}";                 // свои страницы: наш токен акцента
  document.head.appendChild(стиль);
})();
