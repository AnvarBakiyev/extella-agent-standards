#!/usr/bin/env python3
"""Правка большого артефакта: замена по уникальному якорю или отказ.

Правило из методики стройки КТ (AGENT_BUILD_GUIDE §5б): замена по тексту выполняется
**только при ровно одном вхождении** якоря. «Вхождений 18» — это стоп и переработка
якоря, а не «заменю первое». Молчаливая замена не в том месте хуже упавшего скрипта:
скрипт видно сразу, а неверную замену — через неделю у клиента.

Использование в скрипте-миграции:

    from safe_edit import правка

    правка("vitrina.html",
           якорь='<div class="median">78</div>',
           замена='<div class="median">81</div>',
           решение="Анвар 13.08: медиана считается по оплаченным, а не по всем")

Что делает: бэкап рядом, проверка единственности, замена, отчёт строкой.
Чего не делает: не правит по регулярному выражению (regex прячет неоднозначность),
не заменяет «первое вхождение», не работает без бэкапа.

Самопроверка: `python3 safe_edit.py --selftest`.
"""

import pathlib
import shutil
import sys
import tempfile


class Отказ(Exception):
    """Отказ, который называет причину и что делать."""


def сколько(текст: str, якорь: str) -> int:
    return текст.count(якорь)


def проверить_якорь(текст: str, якорь: str, где: str = "артефакт") -> None:
    if not якорь:
        raise Отказ("якорь пустой — заменять нечего")
    n = сколько(текст, якорь)
    if n == 0:
        raise Отказ(f"якорь не найден в {где}. Возможно, артефакт уже правился или "
                    f"якорь взят из другой версии. Найди фактический текст и повтори")
    if n > 1:
        raise Отказ(f"якорь встречается {n} раз в {где} — замена отменена. "
                    f"Расширь якорь соседними строками, чтобы он стал единственным")


def правка(файл, *, якорь: str, замена: str, решение: str = "",
           бэкап: bool = True, сообщить=print) -> dict:
    """Заменить единственное вхождение якоря. Иначе — отказ без изменений."""
    путь = pathlib.Path(файл)
    if not путь.exists():
        raise Отказ(f"нет файла {путь}")

    текст = путь.read_text()
    проверить_якорь(текст, якорь, путь.name)

    if замена == якорь:
        сообщить(f"{путь.name}: замена совпадает с якорем — файл не тронут")
        return {"изменено": False, "почему": "замена равна якорю"}

    копия = None
    if бэкап:
        копия = путь.with_suffix(путь.suffix + ".до_правки")
        shutil.copy2(путь, копия)

    новый = текст.replace(якорь, замена, 1)
    путь.write_text(новый)

    # Сверка после записи: читаем состояние, а не верим в успех записи.
    записано = путь.read_text()
    if замена not in записано:
        if копия:
            shutil.copy2(копия, путь)
        raise Отказ("после записи замены в файле нет — правка откачена. "
                    "Проверь права на файл и повтори")
    if сколько(записано, якорь) != 0:
        сообщить(f"{путь.name}: внимание — якорь остался в файле "
                 f"({сколько(записано, якорь)} раз). Это ожидаемо только если якорь "
                 f"входит в замену")

    сообщить(f"{путь.name}: заменено 1 вхождение"
             + (f" · решение: {решение}" if решение else "")
             + (f" · откат: {копия.name}" if копия else ""))
    return {"изменено": True, "было_байт": len(текст), "стало_байт": len(новый),
            "откат": str(копия) if копия else None, "решение": решение}


def _selftest() -> int:
    провалы = []

    def проверка(имя, функция):
        try:
            функция()
            print(f"  ✓ {имя}")
        except AssertionError as e:
            провалы.append(f"{имя}: {e}")
            print(f"  ✗ {имя}: {e}")

    def дубль_якоря_отвергается():
        with tempfile.TemporaryDirectory() as d:
            f = pathlib.Path(d) / "a.html"
            f.write_text("<b>78</b> и снова <b>78</b>")
            try:
                правка(f, якорь="<b>78</b>", замена="<b>81</b>", сообщить=lambda *_: None)
            except Отказ as e:
                assert "2 раз" in str(e), f"причина не названа: {e}"
                assert f.read_text() == "<b>78</b> и снова <b>78</b>", "файл всё же изменён"
                return
            raise AssertionError("дубль якоря прошёл, а не должен")

    def отсутствующий_якорь_отвергается():
        with tempfile.TemporaryDirectory() as d:
            f = pathlib.Path(d) / "a.html"
            f.write_text("ничего похожего")
            try:
                правка(f, якорь="<b>78</b>", замена="x", сообщить=lambda *_: None)
            except Отказ:
                return
            raise AssertionError("отсутствующий якорь прошёл, а не должен")

    def единственный_якорь_заменяется():
        with tempfile.TemporaryDirectory() as d:
            f = pathlib.Path(d) / "a.html"
            f.write_text("до <b>78</b> после")
            итог = правка(f, якорь="<b>78</b>", замена="<b>81</b>",
                          решение="проверка", сообщить=lambda *_: None)
            assert итог["изменено"], "замена не выполнена"
            assert f.read_text() == "до <b>81</b> после", "текст после замены неверный"
            assert (pathlib.Path(итог["откат"])).exists(), "бэкап не создан"
            assert pathlib.Path(итог["откат"]).read_text() == "до <b>78</b> после", \
                "бэкап содержит не прежний текст"

    def правка_не_ломает_соседей():
        with tempfile.TemporaryDirectory() as d:
            f = pathlib.Path(d) / "a.html"
            было = "<i>78</i> и <b>78</b>"
            f.write_text(было)
            правка(f, якорь="<b>78</b>", замена="<b>81</b>", сообщить=lambda *_: None)
            assert f.read_text() == "<i>78</i> и <b>81</b>", "затронуто лишнее"

    print("Самопроверка safe_edit:")
    проверка("дубль якоря отвергается", дубль_якоря_отвергается)
    проверка("отсутствующий якорь отвергается", отсутствующий_якорь_отвергается)
    проверка("единственный якорь заменяется с бэкапом", единственный_якорь_заменяется)
    проверка("соседнее похожее место не тронуто", правка_не_ломает_соседей)

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    print(__doc__)
