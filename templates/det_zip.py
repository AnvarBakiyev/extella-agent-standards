#!/usr/bin/env python3
"""Воспроизводимый zip: два прогона дают один хэш (AGENT_BUILD_GUIDE §5б).

Зачем: детерминированность содержимого — ещё не детерминированность артефакта.
Контейнер несёт метки времени и права файлов, и они утекают в хэш. Разобрано на живом
случае: 94 файла совпали пофайлово, а архивы двух прогонов разошлись.

Механика, замерено 13.08.2026 (формулировка «zipfile пишет текущее время» приводит не туда):

* `z.write(файл, имя)` берёт метку **из mtime файла** — при неизменных исходниках
  воспроизводимо;
* `z.writestr("имя", данные)` ставит метку **сейчас** — расходится;
* `z.write()` по **пересозданному** файлу расходится: генератор обновил mtime;
* фиксированная метка в `ZipInfo` воспроизводима всегда.

Отсюда правило: **метку фиксируют заранее**, а не после того, как хэши разошлись.

Использование:

    from det_zip import собрать_zip
    собрать_zip("dist/product.zip", корень="build", файлы=["index.html", "assets/app.js"])

Самопроверка: `python3 det_zip.py --selftest` — собирает дважды по пересоздаваемым файлам
и требует совпадения хэшей.
"""

import hashlib
import pathlib
import sys
import tempfile
import zipfile

# Любая константа; важно только, что она не зависит ни от часов, ни от файлов.
ЭПОХА = (2026, 1, 1, 0, 0, 0)
ПРАВА_ФАЙЛА = 0o644
ПРАВА_ИСПОЛНЯЕМОГО = 0o755


class Отказ(Exception):
    """Отказ, который называет причину и что делать."""


def _порядок(файлы) -> list:
    """Порядок записи тоже входит в хэш — сортируем, а не полагаемся на файловую систему."""
    return sorted(str(f) for f in файлы)


def собрать_zip(куда, *, корень, файлы, исполняемые=(), сообщить=print) -> str:
    """Собрать zip с фиксированными метками и правами. Вернуть sha256 архива."""
    корень = pathlib.Path(корень)
    if not корень.is_dir():
        raise Отказ(f"нет папки {корень} — собирать нечего")

    куда = pathlib.Path(куда)
    куда.parent.mkdir(parents=True, exist_ok=True)
    исполняемые = {str(x) for x in исполняемые}

    список = _порядок(файлы)
    if not список:
        raise Отказ("список файлов пуст — архив не собран")

    with zipfile.ZipFile(куда, "w", zipfile.ZIP_DEFLATED) as z:
        for имя in список:
            путь = корень / имя
            if not путь.is_file():
                raise Отказ(f"нет файла {имя} в {корень} — архив не собран, "
                            f"чтобы в него не уехала неполная сборка")
            инфо = zipfile.ZipInfo(имя, date_time=ЭПОХА)
            права = ПРАВА_ИСПОЛНЯЕМОГО if имя in исполняемые else ПРАВА_ФАЙЛА
            инфо.external_attr = права << 16
            инфо.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(инфо, путь.read_bytes())

    хэш = hashlib.sha256(куда.read_bytes()).hexdigest()
    сообщить(f"{куда.name}: {len(список)} файлов, {куда.stat().st_size} байт, sha256 {хэш[:16]}…")
    return хэш


def _selftest() -> int:
    провалы = []

    def проверка(имя, функция):
        try:
            функция()
            print(f"  ✓ {имя}")
        except AssertionError as e:
            провалы.append(f"{имя}: {e}")
            print(f"  ✗ {имя}: {e}")

    def два_прогона_совпадают_на_пересоздаваемых():
        """Главный случай: генератор пересоздаёт файлы, mtime новый — хэш обязан совпасть."""
        with tempfile.TemporaryDirectory() as d:
            d = pathlib.Path(d)
            корень = d / "build"; корень.mkdir()
            (корень / "assets").mkdir()
            хэши = []
            for _ in range(2):
                # имитируем генератор: файлы создаются заново каждый прогон
                (корень / "index.html").write_text("<h1>одно и то же</h1>")
                (корень / "assets" / "app.js").write_text("console.log(1)")
                хэши.append(собрать_zip(
                    d / "out.zip", корень=корень,
                    файлы=["index.html", "assets/app.js"], сообщить=lambda *_: None))
            assert хэши[0] == хэши[1], f"хэши разошлись: {хэши[0][:12]} против {хэши[1][:12]}"

    def обычный_zipfile_на_том_же_расходится():
        """Контроль: доказываем, что проверка выше не тривиальна."""
        with tempfile.TemporaryDirectory() as d:
            d = pathlib.Path(d)
            хэши = []
            for _ in range(2):
                архив = d / "naive.zip"
                with zipfile.ZipFile(архив, "w", zipfile.ZIP_DEFLATED) as z:
                    z.writestr("index.html", "<h1>одно и то же</h1>")
                хэши.append(hashlib.sha256(архив.read_bytes()).hexdigest())
                import time; time.sleep(2.5)   # DOS-время в zip кратно двум секундам
            assert хэши[0] != хэши[1], \
                "наивная сборка совпала — значит проверка ничего не доказывает"

    def метка_и_права_действительно_зафиксированы():
        """Без этой проверки самопроверка проходит даже со снятой фиксацией: у ZipInfo
        умолчание — константа 1980 года, и «два прогона совпали» ничего не доказывает."""
        with tempfile.TemporaryDirectory() as d:
            d = pathlib.Path(d)
            корень = d / "build"; корень.mkdir()
            (корень / "f.txt").write_text("данные")
            (корень / "run.sh").write_text("#!/bin/sh\necho 1\n")
            собрать_zip(d / "m.zip", корень=корень, файлы=["f.txt", "run.sh"],
                        исполняемые=["run.sh"], сообщить=lambda *_: None)
            with zipfile.ZipFile(d / "m.zip") as z:
                for инфо in z.infolist():
                    assert инфо.date_time == ЭПОХА, \
                        f"{инфо.filename}: метка {инфо.date_time}, а не {ЭПОХА}"
                права = {и.filename: (и.external_attr >> 16) & 0o777 for и in z.infolist()}
            assert права["f.txt"] == ПРАВА_ФАЙЛА, f"права файла {oct(права['f.txt'])}"
            assert права["run.sh"] == ПРАВА_ИСПОЛНЯЕМОГО, f"права скрипта {oct(права['run.sh'])}"

    def порядок_файлов_не_влияет():
        with tempfile.TemporaryDirectory() as d:
            d = pathlib.Path(d)
            корень = d / "build"; корень.mkdir()
            (корень / "a.txt").write_text("a")
            (корень / "b.txt").write_text("b")
            один = собрать_zip(d / "1.zip", корень=корень, файлы=["a.txt", "b.txt"],
                               сообщить=lambda *_: None)
            два = собрать_zip(d / "2.zip", корень=корень, файлы=["b.txt", "a.txt"],
                              сообщить=lambda *_: None)
            assert один == два, "порядок в списке изменил хэш — сортировка не работает"

    def пропавший_файл_роняет_сборку():
        with tempfile.TemporaryDirectory() as d:
            d = pathlib.Path(d)
            корень = d / "build"; корень.mkdir()
            (корень / "есть.txt").write_text("тут")
            try:
                собрать_zip(d / "x.zip", корень=корень, файлы=["есть.txt", "нету.txt"],
                            сообщить=lambda *_: None)
            except Отказ:
                return
            raise AssertionError("неполная сборка прошла, а не должна")

    print("Самопроверка det_zip:")
    проверка("два прогона по пересоздаваемым файлам совпадают", два_прогона_совпадают_на_пересоздаваемых)
    проверка("метка и права зафиксированы", метка_и_права_действительно_зафиксированы)
    проверка("наивная сборка расходится (проверка не тривиальна)", обычный_zipfile_на_том_же_расходится)
    проверка("порядок в списке не влияет на хэш", порядок_файлов_не_влияет)
    проверка("пропавший файл роняет сборку", пропавший_файл_роняет_сборку)

    if провалы:
        print("ИТОГ САМОПРОВЕРКИ: провалы —", "; ".join(провалы))
        return 1
    print("ИТОГ САМОПРОВЕРКИ: все проверки прошли")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    print(__doc__)
